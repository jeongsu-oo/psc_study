#   [역전파 = 연쇄법칙 한 줄 정리]
#     큰 미분(∂L/∂W1) 하나를, 사슬 각 마디의 작은 지역 기울기들의 '곱' 으로 쪼갠다.
#     순전파로 값 먼저 → 출력 오차(∂L/∂ŷ)에서 출발 → 거꾸로 곱하며 앞으로.
#
#   [일곱 기울기 요약 (이 망 기준)]
#     ∂L/∂ŷ  = 2(ŷ - y)                    ← 씨앗
#     ∂L/∂Vj = ∂L/∂ŷ · aj ,   ∂L/∂c  = ∂L/∂ŷ
#     ∂L/∂aj = ∂L/∂ŷ · Vj
#     ∂L/∂zj = ∂L/∂aj · aj(1 - aj)         ← sigmoid 도함수
#     ∂L/∂Wj = ∂L/∂zj · x ,   ∂L/∂bj = ∂L/∂zj
#
#   [기억할 것]
#     · 역전파는 마법이 아니라 연쇄법칙(곱하기)을 뒤에서 앞으로 돌린 것
#     · 각 마디에서 하는 일 = '넘어온 값 × 그 마디의 지역 기울기'
#     · 순전파로 구한 값(a, x)이 지역 기울기 식에 그대로 쓰인다 → 순전파 먼저
#     · 수치미분과 대조하면 역전파가 맞는지 눈으로 검산할 수 있다
#     · 구한 기울기로 param ← param - lr·grad → 이게 신경망 학습의 한 스텝
#     · 다음 4편 : 이 사슬을 numpy로 벡터화해 여러 샘플·층을 한 번에 학습
