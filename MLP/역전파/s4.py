# ----------------------------------------
# 직선 vs MLP - 손실을 숫자로 대조
# ----------------------------------------

# "정말 직선보다 나은 거 맞아?" — 손실 숫자로 못 박습니다.
# 1편의 선형회귀(직선)로 같은 데이터를 맞춰 손실을 재 봅니다.

기울기, 절편 = np.polyfit(온도, 불량, 1)   # 최적 직선 (1편 선형회귀)
직선예측 = 기울기 * 온도 + 절편
직선손실 = np.mean((직선예측 - 불량) ** 2)
mlp손실 = 손실(예측.reshape(-1, 1), 불량.reshape(-1, 1))

print("\n[직선 vs MLP · 손실 대조]")
print("  직선(선형회귀) 손실:", round(직선손실, 4))    # → 직선(선형회귀) 손실: 9.3469
print("  MLP 손실          :", round(mlp손실, 4))      # → MLP 손실          : 0.0006
print("  MLP 가 직선보다 손실 작다?", bool(mlp손실 < 직선손실))   # → MLP 가 직선보다 손실 작다? True

# 직선 손실 9.35 vs MLP 손실 0.0006. 1만 배 이상 작습니다.
# U자처럼 '올라갔다 내려갔다' 하는 패턴은 직선이 원리적으로 못 잡아요.
# (직선은 한 방향으로만 기울죠. 양 끝을 동시에 올릴 수가 없습니다.)
# 층을 쌓아 곡선을 만들 수 있게 된 것 — 이게 딥러닝의 핵심 능력입니다.

assert mlp손실 < 직선손실, "MLP 가 직선보다 못하면 학습이 잘못된 것!"
assert mlp손실 < 0.01, "손실이 충분히 줄지 않았다 = 학습 실패!"


