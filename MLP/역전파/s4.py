# ----------------------------------------
# [실습] 하이퍼파라미터 실험
# ----------------------------------------

# 오늘 만든 fit / predict 를 그대로 써서, 설정을 바꾸며 성능이 어떻게 변하는지 봅니다.
# '하이퍼파라미터'(뉴런 수·epochs·lr)는 정답 공식이 없어요. 실험으로 감을 잡습니다.
#
#   케이스 A : 은닉 뉴런 수를 2, 4, 8, 16 으로 바꿔 최종 손실 비교   ← 아래 정답 예시
#   케이스 B : epochs 를 300, 1000, 3000 으로 바꿔 손실 비교        ← 직접 해보기
#
#   Step 1) for 로 설정을 바꿔 가며 fit
#   Step 2) predict 로 예측 → 손실 계산
#   Step 3) 표로 나란히 비교, "뉴런 많을수록 / 오래 돌릴수록 손실이 주는가?" 관찰
#
#   완료 기준 : 설정별 손실이 화면에 표로 나오고, 경향(많을수록·오래일수록 감소)이 보이면 성공.

print("\n[실습 예시 · 은닉 뉴런 수 바꿔 보기]")
print("  뉴런수   최종손실")
for 뉴런수 in [2, 4, 8, 16]:
    m = fit(온도, 불량, 은닉수=뉴런수, lr=0.1, epochs=3000)   # 로그 없이 학습만
    L = 손실(predict(온도, m).reshape(-1, 1), 불량.reshape(-1, 1))
    print(f"  {뉴런수:4d}    {L:8.4f}")
# → [실습 예시 · 은닉 뉴런 수 바꿔 보기]
# →   뉴런수   최종손실
# →     2      0.0139
# →     4      0.0072
# →     8      0.0006
# →    16      0.0009

# 뉴런 2개는 손실 0.014 — U자를 겨우 흉내만 냅니다. 표현력이 부족해요.
# 4개부터 좋아지고, 8개에서 거의 완벽. 뉴런이 많을수록 복잡한 곡선을 그립니다.
# (단, 무작정 늘리면 데이터를 '외워버리는' 과적합 위험 — 그건 과정5에서 다룹니다.)
#
#   [기억할 것]
#     · 학습 = 순전파 → 역전파 → 갱신 을 for 로 반복 (경사하강 루프)
#     · 가중치를 행렬로 두면 뉴런 많아도 순전파는 세 줄 (Z=XW+b, A=σ(Z), ŷ=AV+c)
#     · sigmoid 신경망엔 입력 표준화 필수 (안 하면 포화로 학습 멈춤)
#     · 직선이 못 잡는 U자를 MLP 는 잡는다 (곡선을 그리는 능력)
#     · 이 세 부품이 딥러닝의 심장 — 층·뉴런 늘리면 그대로 깊은 신경망
