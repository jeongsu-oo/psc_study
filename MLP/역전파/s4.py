# ----------------------------------------
# MLPRegressor - 둘 다 U자를 잡는다
# ----------------------------------------

# 우리가 손으로 만든 게 진짜 신경망이 맞는지, 세계 표준 도구로 대조합니다.
# sklearn 의 MLPRegressor — 은닉 8개, 활성화 sigmoid(logistic). 우리와 같은 구조.
# 값 완전 일치는 어렵습니다(초기화·최적화 방식이 달라서). 핵심은 '둘 다 U자를 잡느냐'.

from sklearn.neural_network import MLPRegressor

z = ((온도 - 온도.mean()) / 온도.std()).reshape(-1, 1)   # sklearn 에도 표준화 입력
sk = MLPRegressor(hidden_layer_sizes=(8,), activation='logistic',
                  solver='lbfgs', max_iter=5000, random_state=0)
sk.fit(z, 불량)
sk예측 = sk.predict(z)

print("\n[sklearn MLPRegressor 대조]")
print("  온도  실제  우리MLP  sklearn")
for t, 실, 우, 스 in zip(온도, 불량, 예측, sk예측):
    print(f"  {int(t):3d}   {int(실):2d}    {우:5.2f}    {스:5.2f}")
# → [sklearn MLPRegressor 대조]
# →   온도  실제  우리MLP  sklearn
# →   10    9     8.99     9.00
# →   15    5     5.01     5.00
# →   20    2     1.97     2.00
# →   25    1     1.05     1.00
# →   30    2     1.97     2.00
# →   35    5     5.02     5.00
# →   40    9     8.99     9.00

# 우리 MLP 와 sklearn 이 나란히 같은 U자를 그립니다. 값도 거의 붙어요.
# 우리가 손으로 짠 순전파+역전파+경사하강이, 세계 표준 도구 속 원리와 같다는 증거입니다.
