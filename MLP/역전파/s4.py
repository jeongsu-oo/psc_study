# ----------------------------------------
# 4부작을 관통한 세 부품
# ----------------------------------------

#   [MLP 4부작 한 줄 정리]
#     1편  왜 신경망?  → 직선으로 못 잡는 U자, 층을 쌓으면 잡힌다
#     2편  순전파      → 입력 → 은닉(sigmoid) → 출력, 예측 한 번
#     3편  역전파      → 연쇄법칙으로 각 가중치의 기울기 되짚기 + 한 스텝
#     4편  완성(오늘)  → 그 한 바퀴를 반복해 U자를 학습
#
# 우리가 손으로 만든 것을 딱 세 부품으로 요약하면:
#
#   ① 순전파     : 지금 가중치로 예측한다            (Z=XW+b, A=σ(Z), ŷ=AV+c)
#   ② 역전파     : 틀린 만큼 각 가중치의 기울기를 구한다  (연쇄법칙, 뒤→앞)
#   ③ 경사하강   : 그 기울기 방향으로 조금 갱신한다       (w ← w - lr·∂L/∂w)
#
#   이 세 부품을 for 로 반복 = 학습 = 딥러닝의 심장.
#
# 놀라운 건, 층을 더 쌓고 뉴런을 더 늘려도 이 세 부품은 '그대로' 라는 겁니다.
#   은닉층 1개 → 10개?   역전파 체인이 길어질 뿐, 원리는 동일.
#   뉴런 8개 → 8억 개?   W, V 행렬이 커질 뿐, 곱셈 세 줄은 동일.
# ChatGPT 같은 거대 모델도 이 세 부품을 어마어마하게 키운 것일 뿐입니다.
#
# 여러분은 오늘, 그 심장을 numpy 몇 줄로 직접 뛰게 만들었습니다.

