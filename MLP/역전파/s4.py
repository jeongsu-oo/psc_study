"""[한 바퀴는 돌려 봤는데, 그럼 언제 '똑똑' 해지나요?]
MLP 4부작의 마지막, 클라이맥스입니다.

3편에서 우리는 신경망의 '한 바퀴'를 손으로 짰습니다.
   순전파(예측 한 번) → 역전파(연쇄법칙으로 기울기) → 한 스텝(갱신)
딱 한 바퀴요. 예측이 아직 엉망인 채로 조금 고쳐진 정도였죠.

오늘 할 일은 과정3(경사하강)에서 이미 배운 그 수법입니다 —
그 한 바퀴를 for 루프로 감싸 수백 번 반복합니다.
한 바퀴는 조금 고칠 뿐이지만, 수백 번 돌리면 예측이 점점 정답에 붙습니다.
그게 '학습' 입니다. 경사하강 루프를, 이번엔 신경망 위에서 돌리는 거예요.

오늘의 성취를 미리 말해 둡니다.
1편에서 직선(선형회귀)으로는 '절대' 못 맞췄던 U자 불량 패턴을 —
   온도가 너무 낮아도(춥다) 불량, 너무 높아도(과열) 불량, 가운데가 최적
오늘 우리가 만든 MLP는 맞춥니다. 직선이 못 그리는 곡선을 그려 냅니다.
그게 층을 쌓는 이유이고, 이게 딥러닝의 첫 성공 체험입니다.

이 파일은 전환 → 행렬로 벡터화 → fit 완성 → 표준화 →
U자 학습 성취 → sklearn 대조 → 큰 그림 → 실습 순으로 위에서 아래로 쌓습니다.
"""

# 오늘은 뉴런을 여러 개 두려고 가중치를 '행렬' 로 다룹니다. numpy가 주인공이에요.
import numpy as np


# ========================================================
#  PART 1 : 전환 - 한 바퀴를 '반복' 하면 학습이 된다
# ========================================================

# ----------------------------------------
# 3편의 한 바퀴 = 오늘 for 로 감쌀 재료
# ----------------------------------------

# 3편에서 만든 신경망 한 바퀴를 떠올려 봅시다. 세 단계였죠.
#
#   ① 순전파 : 지금 가중치로 예측을 한 번 해 본다        (ŷ 를 구함)
#   ② 역전파 : 예측이 틀린 만큼, 각 가중치를 어느 쪽으로   (기울기 ∂L/∂w)
#              고쳐야 할지 연쇄법칙으로 되짚어 구한다
#   ③ 한 스텝: 그 방향으로 가중치를 조금 갱신한다          (w ← w - lr·∂L/∂w)
#
# 이 한 바퀴가 손실을 '조금' 줄입니다. 과정3 경사하강의 한 걸음과 똑같아요.
# 그래서 오늘의 전략도 똑같습니다 — for 루프로 이 한 바퀴를 수백 번 반복.
#
#   for epoch in range(epochs):
#       순전파 → 역전파 → 한 스텝      ← 3편에서 만든 그 한 바퀴 그대로
#
# 딱 하나 3편과 달라지는 것: 은닉 뉴런을 여러 개로 늘립니다.
# 그러려면 가중치를 숫자 하나가 아니라 '행렬' 로 다뤄야 해요. 그게 PART 2.


# ----------------------------------------
# 준비물 - 데이터와 sigmoid
# ----------------------------------------

# 4부작 내내 쓴 그 온도-불량 데이터입니다. (외부 파일 없이 인라인)
# 핵심은 모양이 'U자' 라는 것 — 양 끝(춥다/과열)이 높고 가운데가 낮습니다.

온도 = np.array([10, 15, 20, 25, 30, 35, 40], dtype=float)
불량 = np.array([ 9,  5,  2,  1,  2,  5,  9], dtype=float)

#   불량
#    9 |●                       ●     ← 양 끝이 높다 (춥다 / 과열)
#      | \                     /
#    5 |  ●                   ●
#      |   \                 /
#    2 |    ●               ●
#    1 |         ●·······●            ← 가운데가 최적 (불량 최소)
#      +--------------------------→ 온도
#       10  15  20  25  30  35  40
#
# 직선 하나로는 이 U자를 절대 못 그립니다. (1편에서 확인했죠.)
# 곡선을 그리려면 '휘는 능력' 이 필요한데, 그게 sigmoid 입니다.

def sigmoid(z):
    return 1 / (1 + np.exp(-z))   # S자 곡선. 신경망에 '휘는 능력' 을 준다

# sigmoid 는 입력을 0~1 사이 S자로 눌러 담는 함수입니다.
# 이 S자들을 여러 개 겹치고 더하면 U자 같은 복잡한 곡선도 만들어져요.
# 그래서 '휘는 부품' 이라고 생각하면 됩니다.


# ========================================================
#  PART 2 : numpy 행렬로 벡터화 - 뉴런을 여러 개로
# ========================================================

# ----------------------------------------
# 왜 행렬인가 - 뉴런이 많아도 한 줄
# ----------------------------------------

# 3편은 은닉 뉴런이 몇 개 안 됐고, 가중치를 하나씩 이름 붙여 다뤘습니다.
# 그런데 U자처럼 여러 번 휘는 곡선을 그리려면 뉴런이 많아야 해요(오늘은 8개).
# 뉴런마다 가중치를 w1, w2, ... w8 이렇게 따로 쓰면 코드가 지옥이 됩니다.
#
# 그래서 D파트에서 배운 '행렬곱' 을 씁니다. 뉴런 8개의 가중치를 행렬 하나로
# 묶으면, 8개를 한꺼번에 계산하는 게 '곱셈 한 줄' 로 끝납니다.
#
#   망의 구조 (입력 1개 → 은닉 8개 → 출력 1개):
#
#      온도 x ──┬─→ [은닉1] ─┐
#     (표준화)  ├─→ [은닉2] ─┤
#               ├─→   ...    ├─→ (합쳐서) ─→ ŷ 예측
#               └─→ [은닉8] ─┘
#               └── W (1×8) ──┘   └─ V (8×1) ─┘
#
# 순전파를 행렬로 쓰면 이렇게 딱 세 줄입니다 (D파트 행렬곱 @ 회수):
#
#   Z = X · W + b       (n×1)·(1×8) → (n×8)   은닉층에 들어가는 값
#   A = sigmoid(Z)                             은닉층 출력 (휘어짐)
#   ŷ = A · V + c       (n×8)·(8×1) → (n×1)   최종 예측
#
# 뉴런이 8개든 800개든 이 세 줄은 안 바뀝니다. W, V 의 크기만 커질 뿐이죠.
# '뉴런 많아도 한 줄' — 이게 행렬로 쓰는 이유입니다.


# ----------------------------------------
# 순전파를 함수로 - Z, A, ŷ
# ----------------------------------------

# 위 세 줄을 그대로 함수로 옮깁니다. 파라미터(W, b, V, c)를 받아 예측을 냅니다.
# 나중에 역전파에서 A 도 필요하므로 같이 돌려줍니다.

def 순전파(X, W, b, V, c):
    Z = X @ W + b          # (n×1)·(1×8) + (1×8) = (n×8)   은닉 입력
    A = sigmoid(Z)         # (n×8)                          은닉 출력(휘어짐)
    ŷ = A @ V + c          # (n×8)·(8×1) + (1×1) = (n×1)   최종 예측
    return ŷ, A            # A 는 역전파에서 재사용

def 손실(ŷ, Y):
    return np.mean((ŷ - Y) ** 2)   # MSE = (1/n)Σ(ŷ-y)²  (3편과 동일)


# ========================================================
#  PART 3 : 학습 함수 완성 - fit
# ========================================================

# ----------------------------------------
# 역전파식(행렬판) - 3편 체인을 행렬로
# ----------------------------------------

# 3편에서 손으로 유도한 연쇄법칙 기울기를, 이번엔 행렬로 씁니다.
# 유도는 3편에서 끝냈으니 오늘은 결과 식만 회수합니다. 뒤(출력)에서 앞으로:
#
#   ∂L/∂ŷ = 2(ŷ - y)/n                    출력 오차 (n×1)          … dŷ
#   ∂L/∂V = Aᵀ · dŷ            (8×n)·(n×1) = (8×1)                 … dV
#   ∂L/∂c = Σ dŷ                                                    … dc
#   ∂L/∂A = dŷ · Vᵀ           (n×1)·(1×8) = (n×8)                  … dA
#   ∂L/∂Z = dA ⊙ A(1-A)        sigmoid 미분 = a(1-a), 자리끼리 곱   … dZ
#   ∂L/∂W = Xᵀ · dZ           (1×n)·(n×8) = (1×8)                  … dW
#   ∂L/∂b = Σ dZ                                                    … db
#
# ⊙ 는 '같은 자리끼리 곱'(성분별 곱, D파트). @ 는 행렬곱. 헷갈리지 마세요.
# 갱신식은 과정3·3편 그대로:  파라미터 ← 파라미터 - lr·(그 기울기)

def 역전파(X, Y, A, ŷ, W, b, V, c):
    n = len(X)
    dŷ = 2 * (ŷ - Y) / n           # (n×1) 출력 오차
    dV = A.T @ dŷ                  # (8×1)
    dc = dŷ.sum(axis=0, keepdims=True)          # (1×1)
    dA = dŷ @ V.T                  # (n×8)
    dZ = dA * A * (1 - A)          # (n×8)  ⊙ sigmoid'=a(1-a)
    dW = X.T @ dZ                  # (1×8)
    db = dZ.sum(axis=0, keepdims=True)          # (1×8)
    return dW, db, dV, dc


# ----------------------------------------
# 표준화 - 학습이 되게 하는 준비물
# ----------------------------------------

# 잠깐 준비물 하나. 온도는 10~40 으로 값이 큽니다.
# sigmoid 는 입력이 크면(±5만 넘어도) 0이나 1에 딱 붙어 '포화' 됩니다.
# 포화되면 기울기가 0에 가까워져 가중치가 안 움직여요 = 학습이 멈춤.
# 그래서 온도를 '평균 0, 퍼짐 1' 로 눈금을 바꿔 줍니다 = 표준화 (과정2·과정3 회수).
#
#   z = (x - 평균) / 표준편차       입력을 sigmoid 가 잘 반응하는 구간으로
#
# 표준화 안 하면 학습이 아예 안 된다는 걸 PART 4 끝에서 숫자로 보여 드립니다.

def 표준화(x):
    m, s = x.mean(), x.std()
    return (x - m) / s, m, s        # 되돌릴 일은 없지만 관례상 m, s 도 반환


# ----------------------------------------
# fit - 랜덤 초기화 → 반복 → 갱신
# ----------------------------------------

# 드디어 학습 본체입니다. 하는 일은 경사하강 루프 그대로예요.
#   1) 가중치를 랜덤으로 초기화 (시드 고정 → 매번 같은 결과)
#   2) epochs 번 반복: 순전파 → 역전파 → 갱신
#   3) 몇 epoch마다 손실을 print 해서 '점점 주는 것' 을 눈으로 확인
# 은닉 뉴런이 서로 다른 곡선을 배우려면 처음 값이 서로 달라야 해서 '랜덤' 입니다.
# (전부 0으로 시작하면 8개가 똑같이 움직여 뉴런 1개나 마찬가지가 됩니다.)

def fit(x, y, 은닉수=8, lr=0.1, epochs=3000, 로그=False):
    z, m, s = 표준화(x)               # 입력 표준화 (필수!)
    X = z.reshape(-1, 1)              # (n×1) 세로 표로
    Y = y.reshape(-1, 1)             # (n×1)

    np.random.seed(0)                # 시드 고정 → 재현성 (출력이 매번 동일)
    W = np.random.randn(1, 은닉수) * 0.5     # (1×은닉) 입력→은닉 가중치
    b = np.zeros((1, 은닉수))               # (1×은닉) 은닉 편향
    V = np.random.randn(은닉수, 1) * 0.5     # (은닉×1) 은닉→출력 가중치
    c = np.zeros((1, 1))                    # (1×1)   출력 편향

    for epoch in range(epochs):
        ŷ, A = 순전파(X, W, b, V, c)                 # 예측 한 번
        dW, db, dV, dc = 역전파(X, Y, A, ŷ, W, b, V, c)  # 기울기 되짚기
        W -= lr * dW                                 # ← 갱신 (한 스텝)
        b -= lr * db
        V -= lr * dV
        c -= lr * dc
        if 로그 and epoch % 500 == 0:
            print(f"  epoch {epoch:5d}   손실 {손실(순전파(X,W,b,V,c)[0], Y):.4f}")

    if 로그:
        print(f"  epoch {epochs:5d}   손실 {손실(순전파(X,W,b,V,c)[0], Y):.4f}")
    return (W, b, V, c, m, s)          # 학습된 파라미터 묶음 = '학습된 모델'


# ----------------------------------------
# predict - 학습된 모델로 예측
# ----------------------------------------

# fit 이 돌려준 모델(가중치 묶음)로 새 온도의 불량을 예측합니다.
# 학습 때 표준화했으니, 예측할 때도 같은 m, s 로 표준화해서 넣어야 합니다.

def predict(x, 모델):
    W, b, V, c, m, s = 모델
    z = (np.asarray(x, dtype=float) - m) / s   # 학습 때와 같은 눈금으로
    X = z.reshape(-1, 1)
    ŷ, _ = 순전파(X, W, b, V, c)
    return ŷ.ravel()                            # 세로 표 → 평평한 배열


# ========================================================
#  PART 4 : 학습 실행 - 손실이 줄어드는 걸 눈으로
# ========================================================

# ----------------------------------------
# 온도-불량 데이터로 fit - 로그 확인
# ----------------------------------------

# 이제 진짜로 학습시켜 봅니다. 8개 뉴런, lr=0.1, 3000 epoch.
# 손실이 처음(엉망)에서 점점 0에 붙는 걸 로그로 확인하세요.

print("[MLP 학습 로그]")
모델 = fit(온도, 불량, 은닉수=8, lr=0.1, epochs=3000, 로그=True)
# → [MLP 학습 로그]
# →   epoch     0   손실 11.9755
# →   epoch   500   손실 0.0070
# →   epoch  1000   손실 0.0047
# →   epoch  1500   손실 0.0030
# →   epoch  2000   손실 0.0019
# →   epoch  2500   손실 0.0011
# →   epoch  3000   손실 0.0006

# 손실이 12 에서 시작해 0.0006 까지 뚝 떨어집니다.
# 처음 500걸음에 12 → 0.007 로 확 줄고, 그 뒤론 미세하게 다듬는 과정이에요.
#
#   손실
#    12 |●
#       | \
#     6 |  \
#       |   \
#     0 |    ●●●●●●●●●●●●●●●●●●●●●   ← 금세 바닥에 붙어 다듬기만
#       +---------------------------→ epoch
#        0   500  1000  ...   3000
#
# 이게 과정3에서 본 그 '수렴' 곡선입니다. 신경망도 결국 걸어서 내려가요.


# ----------------------------------------
# 표준화가 왜 필수인지 - 숫자로 증명
# ----------------------------------------

# "표준화 그거 꼭 해야 하나요?" — 안 하면 어떻게 되는지 직접 보여 드립니다.
# 표준화 없이(온도 10~40 원값 그대로) 똑같이 학습시켜 보면:

def fit_표준화없이(x, y, 은닉수=8, lr=0.1, epochs=3000):
    X = x.reshape(-1, 1)             # 표준화 '안 함' — 값이 큰 채로
    Y = y.reshape(-1, 1)
    np.random.seed(0)
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))
    for _ in range(epochs):
        ŷ, A = 순전파(X, W, b, V, c)
        dW, db, dV, dc = 역전파(X, Y, A, ŷ, W, b, V, c)
        W -= lr*dW; b -= lr*db; V -= lr*dV; c -= lr*dc
    return 손실(순전파(X, W, b, V, c)[0], Y)

손실_표준화O = 손실(predict(온도, 모델).reshape(-1, 1), 불량.reshape(-1, 1))
print("\n[표준화 효과]")
print("  표준화 O 최종 손실:", round(손실_표준화O, 4))                     # → 표준화 O 최종 손실: 0.0006
print("  표준화 X 최종 손실:", round(fit_표준화없이(온도, 불량), 4))       # → 표준화 X 최종 손실: 9.3471

# 표준화 O 는 0.0006, X 는 9.3471. 무려 1만 배 차이입니다.
# 표준화를 안 하면 온도 값이 커서 sigmoid 가 포화 → 기울기가 죽어 학습이 멈춤.
# 손실 9.3 은 사실상 '평평한 직선' 수준 — 아무것도 못 배운 거예요.
# 한 줄 정리: sigmoid 신경망에 큰 입력을 넣으려면 반드시 표준화부터.


