"""[층을 쌓아도 선이면, 뭘 더 넣어야 곡선이 되나요?]
1편에서 우리가 직접 확인한 게 있죠.
은닉층을 아무리 쌓아도, 그냥 '가중합' 만 반복하면 결과는 여전히 직선입니다.
   층 → 층 → 층  =  결국 하나의 직선 (선형 붕괴)

그런데 세상 데이터는 직선이 아니에요.
1편의 불량 데이터도 온도가 낮으면 불량 많고, 중간이면 적고, 높으면 다시 많은
'U자' 모양이었습니다. 직선으로는 절대 못 그립니다.

그래서 필요한 게 오늘의 주인공 - '활성화 함수' 입니다.
각 뉴런이 가중합을 구한 '뒤에' 슬쩍 씌우는 장치예요.
이 장치가 직선을 살짝 구부려 줍니다. 여러 개가 합쳐지면 곡선이 되죠.

오늘 할 일:
   1) 활성화가 대체 뭔지 (가중합 뒤에 씌우는 것)
   2) sigmoid - S자로 눌러 주는 대표 활성화
   3) ReLU - 요즘 제일 많이 쓰는 간단한 활성화
   4) 왜 비선형이 필요한지 다시 확인 (활성화 넣으면 곡선이 생긴다)
   5) 활성화의 '도함수(미분)' - 3편 역전파에서 쓸 핵심 준비물
   6) 1편 아키텍처에 sigmoid 끼워 순전파 한 번 완주
   7) 실습 - 활성화 바꿔 보기

위에서 아래로 한 줄씩 쌓아 갑니다.
"""

# e^(-z) 를 계산하려면 지수함수가 필요합니다. 표준 math 모듈에 들어 있어요.
import math


# ========================================================
#  PART 1 : 전환 - '활성화' 가 곡선을 만든다
# ========================================================

# ----------------------------------------
# 뉴런 하나가 하는 일 - 가중합 다음에 한 단계 더
# ----------------------------------------

# 1편에서 뉴런 하나는 이렇게 계산했습니다.
#   z = W·x + b      ← 입력에 가중치 곱하고 편향 더함 = 가중합
#
# 이게 전부면 아무리 층을 쌓아도 직선입니다.
# 그래서 z 를 그대로 다음 층에 넘기지 않고, 한 단계를 더 거칩니다.
#
#   z = W·x + b          (가중합)      ← 여기까지가 1편
#   a = 활성화(z)         (곡선 장치)   ← 오늘 새로 넣는 단계
#
# z 를 활성화 함수에 통과시킨 결과 a 를 다음 층에 넘깁니다.
# 이 '활성화(z)' 한 단계가 직선을 구부리는 장치예요.
#
#      입력 x
#        │
#        ▼
#   ┌─────────┐
#   │ z=W·x+b │   가중합 (직선)
#   └────┬────┘
#        ▼
#   ┌─────────┐
#   │ a=활성화(z)│  ← 여기서 곡선이 생긴다 (오늘의 주제)
#   └────┬────┘
#        ▼
#      다음 층으로
#
# 그럼 이 '활성화' 자리에 뭘 넣느냐 - 대표 선수 둘을 만나 봅시다.


# ========================================================
#  PART 2 : sigmoid - 어떤 값이든 0~1 로 눌러 주는 S자
# ========================================================

# ----------------------------------------
# sigmoid 식과 구현
# ----------------------------------------

# sigmoid(z) = 1 / (1 + e^(-z))
#
# 식은 이거 하나뿐입니다. e 는 자연상수(약 2.718), e^(-z) 는 math.exp(-z).
# 하는 일은 딱 하나 - 들어온 값을 무조건 0 과 1 사이로 눌러 줍니다.

def sigmoid(z):
    return 1 / (1 + math.exp(-z))    # 1 / (1 + e^(-z))

# 정말 0~1 사이로 눌러 주는지, 여러 z 를 넣어 표로 확인해 봅시다.

print("[sigmoid - 여러 값을 넣어 보기]")
print("     z  →  sigmoid(z)")
for z in [-3, -1, 0, 1, 3]:
    print(f"  {z:4}  →  {sigmoid(z):.4f}")
# → [sigmoid - 여러 값을 넣어 보기]
# →      z  →  sigmoid(z)
# →    -3  →  0.0474
# →    -1  →  0.2689
# →     0  →  0.5000
# →     1  →  0.7311
# →     3  →  0.9526

# 읽는 법:
#   · 큰 음수(-3) → 0 에 가까움 (0.05)
#   · 0        → 정확히 한가운데 0.5
#   · 큰 양수(3)  → 1 에 가까움 (0.95)
# 아무리 큰 값이 들어와도 1 을 넘지 않고, 아무리 작아도 0 밑으로 안 갑니다.
# '납작하게 눌러 주는' 장치라고 생각하면 됩니다.


# ----------------------------------------
# sigmoid 의 S자 모양 - 눈으로
# ----------------------------------------

# 위 숫자들을 곡선으로 이으면 부드러운 'S자' 가 됩니다.
# 이 S 커브가 바로 직선을 구부리는 정체예요.
#
#   sigmoid(z)
#     1.0 |               ________●●●●●●   ← 큰 양수는 1 에 붙음
#         |            ●●●
#     0.5 |─ ─ ─ ─ ─ ●─ ─ ─ ─ ─ ─ ─ ─ ─    ← z=0 에서 딱 0.5
#         |       ●●
#     0.0 |●●●●●●●____________________     ← 큰 음수는 0 에 붙음
#         +-----------------------------→ z
#            -3   -1   0   1   3
#
# 가운데(z=0 근처)는 비스듬한 직선처럼 보이지만,
# 양 끝으로 갈수록 눕습니다. 이 '휘어짐' 이 곡선의 씨앗이에요.
# 직선(가중합)을 S자에 통과시키면 더 이상 직선이 아니게 됩니다.


# ========================================================
#  PART 3 : ReLU - 음수는 0, 양수는 그대로 (요즘 대세)
# ========================================================

# ----------------------------------------
# ReLU 식과 구현
# ----------------------------------------

# relu(z) = max(0, z)
#
# 훨씬 간단합니다. 규칙 하나예요.
#   · z 가 음수면 → 0 으로 잘라 버림
#   · z 가 양수면 → 그대로 통과
# 이름은 거창하지만(Rectified Linear Unit) 하는 일은 '음수 자르기' 입니다.

def relu(z):
    return max(0, z)    # 음수는 0, 양수는 그대로

print("\n[ReLU - 여러 값을 넣어 보기]")
print("     z  →  relu(z)")
for z in [-3, -1, 0, 1, 3]:
    print(f"  {z:4}  →  {relu(z)}")
# → [ReLU - 여러 값을 넣어 보기]
# →      z  →  relu(z)
# →    -3  →  0
# →    -1  →  0
# →     0  →  0
# →     1  →  1
# →     3  →  3


# ----------------------------------------
# ReLU 의 꺾은선 모양
# ----------------------------------------

# ReLU 는 곡선이 아니라 '꺾은선' 입니다. 0 에서 한 번 꺾입니다.
#
#   relu(z)
#      3 |                    ●   ← 양수는 z 그대로 (45도 직선)
#        |                  ／
#      2 |                ／
#        |              ／
#      1 |            ●
#        |          ／
#      0 |●●●●●●●●●●●              ← 음수는 전부 0 (바닥에 붙음)
#        +------------------------→ z
#         -3   -2   -1   0   1  2  3
#
# 왼쪽 절반(음수)은 바닥에 눌러 붙어 있고, 0 을 지나면 45도로 솟습니다.
# 이 '꺾임' 하나가 sigmoid 의 S자처럼 비선형을 만들어 줍니다.
#
# 왜 요즘 ReLU 를 더 많이 쓸까?
#   · 계산이 간단(max 하나)해서 빠릅니다.
#   · sigmoid 는 양 끝이 너무 납작해서 학습이 굼떠지는 문제가 있는데,
#     ReLU 는 양수 쪽이 쭉 뻗어 있어 그 문제가 덜합니다.
# 그래서 실무 신경망 은닉층은 대부분 ReLU 를 씁니다.
# (다만 오늘 아키텍처 설명은 값이 0~1 로 예쁘게 눌리는 sigmoid 로 합니다.)


# ========================================================
#  PART 4 : 왜 비선형이 필요한가 - 활성화 없으면 선형 붕괴
# ========================================================

# ----------------------------------------
# 활성화 빼면 다시 직선이 된다 (1편 회수)
# ----------------------------------------

# 1편의 핵심을 코드로 다시 확인합니다.
# 은닉 뉴런 둘을 거쳐도, 활성화를 '안' 씌우면 결과가 직선이라는 것.
#
# 망 구조(1편 그대로):
#   입력 x → 은닉 2뉴런(W1,W2 / b1,b2) → 출력(V1,V2 / c)
#   zj = Wj·x + bj,   aj = 활성화(zj),   ŷ = V1·a1 + V2·a2 + c

# 아무 가중치나 정해 둡니다 (오늘은 학습이 아니라 '모양' 확인이 목적).
W1, b1 = 0.3, -6.0
W2, b2 = -0.2, 5.0
V1, V2, c = 4.0, -3.0, 1.0

# (A) 활성화를 '안' 씌운 순전파 - aj = zj 를 그대로 씀
def 순전파_활성화없음(x):
    z1 = W1 * x + b1
    z2 = W2 * x + b2
    a1, a2 = z1, z2                 # ← 활성화 생략 (그냥 통과)
    return V1 * a1 + V2 * a2 + c

# 여러 x 에 대해 출력을 뽑아, 이웃한 값의 '차이' 가 일정한지 봅니다.
# 차이가 일정하면 = 일정한 기울기 = 직선이라는 증거예요.
xs = [10, 15, 20, 25, 30, 35, 40]
ys_lin = [순전파_활성화없음(x) for x in xs]
print("\n[활성화 없음 → 출력이 직선인가?]")
print("  x별 출력:", [round(y, 2) for y in ys_lin])
차이 = [round(ys_lin[i+1] - ys_lin[i], 2) for i in range(len(xs) - 1)]
print("  이웃 차이:", 차이, " ← 모두 같으면 직선")
# → [활성화 없음 → 출력이 직선인가?]
# →   x별 출력: [-20.0, -11.0, -2.0, 7.0, 16.0, 25.0, 34.0]
# →   이웃 차이: [9.0, 9.0, 9.0, 9.0, 9.0, 9.0]  ← 모두 같으면 직선

# 이웃 차이가 전부 9.0 으로 똑같습니다. 완벽한 직선이에요.
# 뉴런을 둘이나 거쳤는데도 활성화가 없으니 그냥 하나의 직선으로 붕괴했습니다.


# ----------------------------------------
# sigmoid 를 끼우면 곡선이 생긴다
# ----------------------------------------

# 이번엔 같은 망에 sigmoid 만 끼워 봅니다. aj = sigmoid(zj).
def 순전파_시그모이드(x):
    z1 = W1 * x + b1
    z2 = W2 * x + b2
    a1, a2 = sigmoid(z1), sigmoid(z2)   # ← 여기 한 줄만 바뀜
    return V1 * a1 + V2 * a2 + c

ys_sig = [순전파_시그모이드(x) for x in xs]
print("\n[sigmoid 있음 → 출력이 곡선인가?]")
print("  x별 출력:", [round(y, 2) for y in ys_sig])
차이2 = [round(ys_sig[i+1] - ys_sig[i], 2) for i in range(len(xs) - 1)]
print("  이웃 차이:", 차이2, " ← 들쭉날쭉하면 곡선")
# → [sigmoid 있음 → 출력이 곡선인가?]
# →   x별 출력: [-1.67, -0.91, 0.81, 2.77, 4.0, 4.6, 4.85]
# →   이웃 차이: [0.76, 1.72, 1.96, 1.23, 0.59, 0.25]  ← 들쭉날쭉하면 곡선

# 이번엔 이웃 차이가 0.76, 1.72, 1.96... 로 제각각입니다.
# 기울기가 계속 바뀐다 = 직선이 아니다 = 곡선이라는 뜻이죠.
# 코드에서 바뀐 건 딱 한 줄(aj = sigmoid(zj)) 인데 직선이 곡선이 됐습니다.
# 이게 활성화 함수가 하는 일의 전부이자 핵심입니다.


# ========================================================
#  PART 5 : 활성화의 도함수 - 3편 역전파의 핵심 준비물
# ========================================================

# ----------------------------------------
# 왜 미분(도함수) 이 필요한가
# ----------------------------------------

# 여기가 오늘 가장 중요한 부분입니다. 미리 못 박아 둡니다.
#
# 다음 편(3편) 역전파에서는 '손실을 줄이려면 각 가중치를 어느 쪽으로
# 움직여야 하나' 를 구합니다. 그 방향을 층 뒤에서 앞으로 되짚어 갈 때,
# 각 층의 활성화가 '얼마나 민감하게 반응하는지' = 도함수(기울기)를 곱해
# 나갑니다.
#
#   3편 미리보기(느낌만):  출력 오차 × V × [활성화의 도함수] × x  ...
#                                          └── 오늘 만들어 둘 것
#
# 즉 활성화 함수의 '도함수' 는 역전파의 필수 부품입니다.
# 오늘은 이 부품을 만들어 두고, 수치미분으로 맞는지 검증만 합니다.
# (미분을 극한으로 유도하진 않습니다. 식을 쓰고, 맞는지 대조만.)


# ----------------------------------------
# sigmoid 의 도함수
# ----------------------------------------

# sigmoid'(z) = sigmoid(z) · (1 - sigmoid(z))
#
# 아주 예쁜 성질입니다. a = sigmoid(z) 라고 두면
#   sigmoid'(z) = a · (1 - a)
# 즉 sigmoid 값만 알면 도함수가 바로 나옵니다. e 를 다시 계산할 필요 없어요.

def sigmoid_도함수(z):
    a = sigmoid(z)
    return a * (1 - a)             # a·(1-a)


# ----------------------------------------
# ReLU 의 도함수
# ----------------------------------------

# relu'(z) = 1 (z > 0),  0 (z ≤ 0)
#
# 꺾은선이라 도함수도 간단합니다.
#   · 양수 구간은 기울기 45도(=1)
#   · 음수 구간은 바닥이라 기울기 0
# (z=0 딱 그 점은 수학적으로 애매하지만, 실무에선 그냥 0 으로 둡니다.)

def relu_도함수(z):
    return 1.0 if z > 0 else 0.0   # 양수면 1, 아니면 0


# ----------------------------------------
# 수치미분으로 맞는지 대조 - 검증
# ----------------------------------------

# 우리가 쓴 도함수 식이 정말 맞을까요? '수치미분' 으로 채점합니다.
# 수치미분 = 아주 작은 h 만큼 양옆으로 움직여 실제 기울기를 근사로 재는 것.
#   기울기 ≈ ( f(z+h) - f(z-h) ) / (2h)      (h 는 아주 작은 수)
# 식으로 구한 도함수와 이 수치미분이 같으면, 우리 식이 맞다는 증거예요.

def 수치미분(f, z, h=1e-6):
    return (f(z + h) - f(z - h)) / (2 * h)

print("\n[sigmoid 도함수 vs 수치미분 대조]")
print("      z   식으로   수치미분   일치?")
for z in [-2, -0.5, 0, 0.5, 2]:
    식값 = sigmoid_도함수(z)
    수치 = 수치미분(sigmoid, z)
    일치 = abs(식값 - 수치) < 1e-6
    print(f"  {z:5}   {식값:.5f}   {수치:.5f}    {일치}")
# → [sigmoid 도함수 vs 수치미분 대조]
# →       z   식으로   수치미분   일치?
# →     -2   0.10499   0.10499    True
# →   -0.5   0.23500   0.23500    True
# →      0   0.25000   0.25000    True
# →    0.5   0.23500   0.23500    True
# →      2   0.10499   0.10499    True

# 전부 True. sigmoid'(z)=a(1-a) 식이 실제 기울기와 일치합니다.
# 참고로 z=0 에서 도함수가 0.25 로 가장 큽니다 = S자 가운데가 가장 가파름.
# 양 끝(±2)으로 가면 0.1 로 작아져요 = S자 끝이 납작 = 기울기 완만.

print("\n[ReLU 도함수 vs 수치미분 대조]")
print("      z   식으로   수치미분   일치?")
for z in [-2, 2]:                  # 꺾이는 0 은 애매하니 양·음 대표만
    식값 = relu_도함수(z)
    수치 = 수치미분(relu, z)
    일치 = abs(식값 - 수치) < 1e-6
    print(f"  {z:5}    {식값:.1f}      {수치:.1f}      {일치}")
# → [ReLU 도함수 vs 수치미분 대조]
# →       z   식으로   수치미분   일치?
# →     -2    0.0      0.0      True
# →      2    1.0      1.0      True

# ReLU 도 맞습니다. 음수 쪽 기울기 0, 양수 쪽 기울기 1.
