# 활성화를 인자로 받는 순전파를 만들어, sigmoid 와 ReLU 를 각각 넣어 봅니다.

def 순전파(x, 활성화):
    z1 = W1 * x + b1
    z2 = W2 * x + b2
    a1, a2 = 활성화(z1), 활성화(z2)   # ← 여기에 sigmoid 든 relu 든 끼움
    return V1 * a1 + V2 * a2 + c

