"""[직선으로 못 푸는 문제가 있다고요?]
과정3에서 우리는 직선 하나로 예측했습니다.
   ŷ = w·x + b       (온도가 오르면 불량이 는다, 같은 '일직선' 관계)
경사하강으로 그 직선의 w, b 를 걸어서 찾기까지 했죠.

그런데 세상에는 직선으로 도저히 못 그리는 관계가 있습니다.
온도가 '너무 낮아도' 불량이 늘고, '너무 높아도' 불량이 늘고,
중간이 가장 좋은 U자 관계 — 이건 어떤 직선을 갖다 대도 안 맞습니다.

이 파일에서 할 일:
  1) U자 데이터에 직선을 맞춰 보고, 얼마나 안 맞는지 '숫자로' 확인 (선형의 벽)
  2) 해법 아이디어 : 뉴런을 층으로 쌓아 '휘어지는' 함수를 만든다 = MLP
  3) 뉴런 하나가 하는 계산, 그리고 층을 타고 흐르는 계산 = 순전파(forward)
  4) 순전파를 손으로 한 번, 코드로 한 번
  5) '활성화가 없으면 층을 쌓아도 그냥 직선' 임을 코드로 확인 (다음 편 동기)

역전파(학습)·미분은 3편, 활성화 함수의 속내는 2편에서 합니다.
오늘은 '입력이 앞으로 흘러 답이 나오는' 순전파까지만, 위에서 아래로 갑니다.
"""

# 순전파는 곱하고 더하는 게 전부라 순수 파이썬으로 보여줍니다.
# math 는 활성화 함수 g(시그모이드) 계산에만, numpy 는 맨 끝 대조용으로만 씁니다.
import math
import numpy as np


# ========================================================
#  PART 1 : 선형의 벽 - 직선으로 U자를 못 그린다
# ========================================================

# ----------------------------------------
# U자 불량 데이터 - 중간이 최선
# ----------------------------------------

# 제조 현장의 실제 감각 그대로입니다.
# 온도가 너무 낮으면 재료가 덜 녹아 불량, 너무 높으면 타서 불량.
# 딱 중간 온도(25도 근처)가 불량이 가장 적습니다.
#
#   불량
#    9 |●                       ●     ← 양 끝(저온·고온)에서 불량 많음
#      | \                     /
#    5 |  ●                   ●
#      |   \                 /
#    2 |    ●               ●
#    1 |          ● (바닥)          ← 가운데가 최선
#      +----------------------------→ 온도
#       10  15  20  25  30  35  40
#
# 이게 U자(아래로 볼록) 패턴입니다. 직선 한 개로는 이 골짜기를 못 그려요.

온도 = [10, 15, 20, 25, 30, 35, 40]
불량 = [9, 5, 2, 1, 2, 5, 9]


# ----------------------------------------
# 직선을 맞춰 본다 - 최소제곱 공식 (과정3 그대로)
# ----------------------------------------

# 과정3에서 만든 도구를 그대로 가져옵니다. 직선 ŷ = w·x + b 의
# 가장 잘 맞는 w, b 를 공식으로 단번에 구합니다. (경사하강으로 걸어가도
# 결과는 같으니, 여기선 빠른 공식으로.)

def 평균(xs):
    return sum(xs) / len(xs)

def 예측하기(xs, w, b):
    return [w * x + b for x in xs]            # 각 x 마다 ŷ = w·x + b

x̄, ȳ = 평균(온도), 평균(불량)
w = sum((x - x̄) * (y - ȳ) for x, y in zip(온도, 불량)) / sum((x - x̄) ** 2 for x in 온도)
b = ȳ - w * x̄

print("[U자 데이터에 직선 맞추기]")
print("  기울기 w:", round(w, 4))        # → 기울기 w: 0.0
print("  절편   b:", round(b, 4))        # → 절편   b: 4.7143

# 기울기가 정확히 0 입니다. 무슨 뜻일까요?
# 온도가 오르든 내리든 '불량은 그대로' 라고 직선이 판단했다는 겁니다.
# 실제로는 양 끝에서 불량이 확 느는데, 직선은 그걸 하나도 못 봤어요.
# 절편 4.71 은 그냥 불량의 평균값입니다 — 직선이 포기하고 평균만 그은 거죠.


# ----------------------------------------
# 얼마나 안 맞나 - R²로 점수 매기기
# ----------------------------------------

# R²(설명력)는 '이 직선이 데이터를 얼마나 설명하나' 점수입니다.
#   1에 가까우면 잘 맞음, 0이면 '평균만 찍는 것과 다를 바 없음'.

def R2(xs, ys, w, b):
    ȳ = 평균(ys)
    preds = 예측하기(xs, w, b)
    SSE = sum((y - p) ** 2 for y, p in zip(ys, preds))   # 직선이 못 맞힌 오차
    SST = sum((y - ȳ) ** 2 for y in ys)                  # 평균으로 찍기의 오차
    return 1 - SSE / SST

print("  R² (설명력):", round(R2(온도, 불량, w, b), 4))   # → R² (설명력): 0.0

# R²=0.0. 바닥입니다. 이 직선은 불량을 '전혀' 설명하지 못합니다.
# 과정3에서 온도-불량이 일직선이던 데이터는 R²≈0.98 이었죠.
# 같은 도구, 같은 최선의 직선인데 이번엔 0 점.
# 데이터 잘못이 아니라 '직선이라는 도구' 자체의 한계입니다.
#
#   불량        직선이 맞추려 하면...
#    9 |●                       ●
#      |
#    5 |- - - - - - - - - - - - - -  ← 직선이 할 수 있는 최선은
#      |                              그냥 평균에 수평선 긋기
#    1 |          ●
#      +----------------------------→ 온도
#   어느 쪽으로 기울여도 한쪽 끝이 더 틀어집니다. 그래서 기울기 0.
#
# 이게 '선형의 벽' 입니다. 직선은 한 번 꺾일 줄을 모릅니다.
# 우리에겐 '휘어지는' 함수가 필요합니다.


# ========================================================
#  PART 2 : 해법 - 뉴런을 층으로 쌓는다 (MLP)
# ========================================================

# ----------------------------------------
# 아이디어 - 휘는 조각을 여럿 합친다
# ----------------------------------------

# 직선 하나는 못 꺾입니다. 그럼 어떻게 U자를 그릴까요?
# 발상은 이렇습니다 — '살짝 휘는 조각' 을 여러 개 만들어 겹쳐 더하면,
# 그 합이 U자처럼 굽은 모양이 될 수 있습니다.
#
# 그 '휘는 조각' 하나를 만드는 게 뉴런이고,
# 뉴런 여러 개를 한 줄(층)로 세워 결과를 합치는 구조가
# MLP(Multi-Layer Perceptron, 다층 퍼셉트론) 입니다.
#
#   직선 하나 :  ─────      (한 방향, 못 꺾임)
#   뉴런 여럿  :  ╲   ╱      (각자 다르게 휜 조각을)
#                  ╲ ╱
#   합치면     :   ╲╱  →  U자 같은 굽은 모양도 표현 가능
#
# 핵심 단어 두 개만 잡고 갑니다 : '뉴런' 과 '층'. 하나씩 봅니다.


# ----------------------------------------
# 뉴런 하나 = 가중합 + 활성화
# ----------------------------------------

# 뉴런 하나가 하는 일은 딱 두 단계입니다.
#   1단계 가중합 : 입력에 가중치를 곱하고 편향을 더한다  →  z = W·x + b
#                  (이거, 과정3의 직선 w·x+b 와 똑같은 모양이죠!)
#   2단계 활성화 : 그 z 를 활성화 함수 g 에 통과시킨다   →  a = g(z)
#                  이 g 가 값을 '휘게' 만드는 장본인입니다.
#
#            W (가중치)
#             \
#   입력 x ────●────  z = W·x + b  ──[ g ]──  a = g(z)  → 출력
#             /          (가중합)    (활성화)
#            b (편향)
#
# 1단계까지는 직선과 같습니다. 다른 건 2단계 활성화 g 하나뿐이에요.
# 이 g 가 있고 없고가 오늘 마지막에 걸릴 결정적 차이입니다. 기억해 두세요.
#
# 활성화 함수 g 는 여러 종류가 있는데, 오늘은 대표선수 시그모이드를 씁니다.
# 속내(왜 이 모양인지, 도함수는 뭔지)는 2편에서 파고, 오늘은 'S자로 눌러 주는
# 함수 g' 정도로만 쓰겠습니다. 계산 흐름에 집중하려고요.

def g(z):
    # 시그모이드 : 어떤 값이든 0~1 사이로 'S자' 로 눌러 준다.
    return 1 / (1 + math.exp(-z))             # 자세한 건 2편에서

print("\n[활성화 함수 g 맛보기 - S자로 눌러 준다]")
print("  g(-2) =", round(g(-2), 4))   # → g(-2) = 0.1192
print("  g( 0) =", round(g(0), 4))    # → g( 0) = 0.5
print("  g( 2) =", round(g(2), 4))    # → g( 2) = 0.8808

# 큰 음수는 0쪽, 0은 딱 0.5, 큰 양수는 1쪽. 직선이 아니라 살짝 휘죠?
# 이 '휨' 이 층을 쌓았을 때 U자 같은 곡선을 만들어 내는 재료입니다.


# ========================================================
#  PART 3 : 아키텍처 - 4부작 내내 쓸 우리 망
# ========================================================

# ----------------------------------------
# 입력 → 은닉층(뉴런 2개) → 출력
# ----------------------------------------

# 이 4부작 내내 쓸 아주 작은 신경망을 소개합니다. 딱 이 구조로 고정입니다.
#   · 입력 : 온도 x (숫자 하나, 스칼라)
#   · 은닉층 : 뉴런 2개. 각자 가중합 + 활성화 g. (여기가 '휘는' 부분)
#   · 출력 : 은닉층 두 값을 가중합. 활성화 없이 그냥 선형 (예측값을 뽑음)
#
#                  은닉층 (활성화 g 있음)
#                  ┌─────────────┐
#                  │   ● 뉴런1    │
#          W1,b1  ╱│  a1=g(z1)   │╲  V1
#   입력 x ●─────╱ │             │ ╲───● 출력  ŷ = V1·a1 + V2·a2 + c
#          W2,b2 ╲ │   ● 뉴런2    │ ╱  V2      (여긴 활성화 없이 선형)
#                 ╲│  a2=g(z2)   │╱
#                  └─────────────┘
#
# 이름표(4부작 공통 - 계속 이 기호를 씁니다):
#   은닉 뉴런1 : 가중치 W1, 편향 b1  →  z1 = W1·x + b1,  a1 = g(z1)
#   은닉 뉴런2 : 가중치 W2, 편향 b2  →  z2 = W2·x + b2,  a2 = g(z2)
#   출력      : 가중치 V1, V2, 편향 c →  ŷ = V1·a1 + V2·a2 + c
#
# '순전파(forward)' 는 이 그림에서 입력 x 가 왼쪽에서 출발해
# 화살표를 타고 오른쪽 출력 ŷ 까지 '앞으로 흘러가는' 계산 전부를 말합니다.
# 딱 이 순서예요 :  x → (z1,z2) → (a1,a2) → ŷ.


# ========================================================
#  PART 4 : 순전파 - 손으로 한 번, 코드로 한 번
# ========================================================

# ----------------------------------------
# 손계산 - 작은 값으로 흐름 따라가기
# ----------------------------------------

# 아주 작은 값으로 한 번 손으로 흘려 봅니다. 숫자는 아무거나 잡았습니다
# (이 가중치들은 아직 '학습' 한 게 아니라 그냥 예시값이에요. 학습은 3편).
#
#   가중치 : W1=0.5, b1=-1.0 / W2=-0.3, b2=2.0 / V1=1.5, V2=-1.0, c=0.4
#   입력   : x = 2.0
#
#   [1단계] 은닉층 가중합
#     z1 = W1·x + b1 = 0.5·2.0 + (-1.0) =  0.0
#     z2 = W2·x + b2 = -0.3·2.0 + 2.0   =  1.4
#   [2단계] 은닉층 활성화
#     a1 = g(z1) = g(0.0) = 0.5
#     a2 = g(z2) = g(1.4) ≈ 0.8022
#   [3단계] 출력 (선형)
#     ŷ = V1·a1 + V2·a2 + c
#        = 1.5·0.5 + (-1.0)·0.8022 + 0.4 ≈ 0.3478
#
# 이게 순전파 전부입니다. 곱하고 더하고, 중간에 g 한 번 씌우고, 또 곱하고 더함.
# 이제 이 손계산을 코드로 그대로 옮겨 값이 맞는지 확인합니다.

# 이 가중치들은 아래 여러 곳에서 재사용하니 변수로 잡아 둡니다.
W1, b1 = 0.5, -1.0        # 은닉 뉴런1
W2, b2 = -0.3, 2.0        # 은닉 뉴런2
V1, V2, c = 1.5, -1.0, 0.4  # 출력층

def 순전파(x):
    # x 하나가 들어와 ŷ 하나가 나오기까지, 위 그림 그대로 앞으로 흐른다.
    z1 = W1 * x + b1          # 뉴런1 가중합
    z2 = W2 * x + b2          # 뉴런2 가중합
    a1 = g(z1)                # 뉴런1 활성화
    a2 = g(z2)                # 뉴런2 활성화
    ŷ = V1 * a1 + V2 * a2 + c  # 출력 (선형)
    return ŷ, z1, z2, a1, a2   # 중간값도 같이 돌려줘 눈으로 확인

ŷ, z1, z2, a1, a2 = 순전파(2.0)
print("\n[순전파 손계산 대조 · x=2.0]")
print("  z1 =", round(z1, 4), " a1 = g(z1) =", round(a1, 4))   # → z1 = 0.0  a1 = g(z1) = 0.5
print("  z2 =", round(z2, 4), " a2 = g(z2) =", round(a2, 4))   # → z2 = 1.4  a2 = g(z2) = 0.8022
print("  ŷ  =", round(ŷ, 4))                                    # → ŷ  = 0.3478

# 손으로 구한 0.3478 과 코드가 딱 맞습니다.
# 층이 여러 개여도 이 흐름의 반복일 뿐이에요 — 가중합, 활성화, 다시 가중합.
# 이 '앞으로 흐르기' 가 순전파고, 신경망이 예측을 뽑는 방식입니다.


# ========================================================
#  PART 5 : 활성화가 없으면? - 층을 쌓아도 그냥 직선
# ========================================================

# ----------------------------------------
# g 를 빼 보면 - 두 층이 하나로 붕괴한다
# ----------------------------------------

# 여기가 오늘의 핵심 반전이자, 2편으로 넘어가는 이유입니다.
# 질문 : "활성화 g 가 그렇게 중요해? 빼면 안 돼?"
# 빼 봅시다. 활성화 없이(a = z 그대로) 똑같이 두 층을 통과시켜 봅니다.

def 순전파_활성화없음(x):
    # g 를 안 씌우고 z 를 그대로 다음 층에 넘긴다 (a1=z1, a2=z2).
    z1 = W1 * x + b1
    z2 = W2 * x + b2
    return V1 * z1 + V2 * z2 + c     # 활성화 없이 바로 출력 가중합

# 그런데 이 식을 손으로 풀어 정리해 보면 (x 로 묶으면) :
#   ŷ = V1·(W1·x+b1) + V2·(W2·x+b2) + c
#     = (V1·W1 + V2·W2)·x  +  (V1·b1 + V2·b2 + c)
#     =        W_eff       ·x  +        b_eff
# 즉 '뉴런 2개짜리 은닉층' 이 그냥 직선 하나(ŷ = W_eff·x + b_eff)로 쪼그라듭니다.

W_eff = V1 * W1 + V2 * W2          # = 1.5·0.5 + (-1.0)·(-0.3) = 1.05
b_eff = V1 * b1 + V2 * b2 + c      # = 1.5·(-1.0) + (-1.0)·2.0 + 0.4 = -3.1

print("\n[활성화 없이 두 층 통과 vs 직선 하나]")
print(f"  붕괴된 직선 : ŷ = {W_eff}·x + ({b_eff})")   # → 붕괴된 직선 : ŷ = 1.05·x + (-3.1)
for x in [0.0, 1.0, 2.0, 3.0]:
    쌓은망 = 순전파_활성화없음(x)
    직선 = W_eff * x + b_eff
    print(f"  x={x}  두 층 통과={쌓은망:+.4f}   직선 하나={직선:+.4f}   같나? {abs(쌓은망-직선)<1e-9}")
# → 붕괴된 직선 : ŷ = 1.05·x + (-3.1)
# →   x=0.0  두 층 통과=-3.1000   직선 하나=-3.1000   같나? True
# →   x=1.0  두 층 통과=-2.0500   직선 하나=-2.0500   같나? True
# →   x=2.0  두 층 통과=-1.0000   직선 하나=-1.0000   같나? True
# →   x=3.0  두 층 통과=+0.0500   직선 하나=+0.0500   같나? True

