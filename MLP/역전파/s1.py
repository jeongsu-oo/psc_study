# 위 순전파를 numpy 로 짜도 값은 똑같습니다. (은닉층을 배열 한 번에 계산)
# 4부작 뒤로 갈수록 numpy 가 편하지만, 오늘은 '무슨 계산인지' 를 순수
# 파이썬으로 다 봤으니, numpy 는 같은 답이 나오는지 대조만 합니다.

def 순전파_numpy(x):
    W = np.array([W1, W2])                 # 은닉층 가중치 두 개를 배열로
    bh = np.array([b1, b2])                # 은닉층 편향 두 개
    z = W * x + bh                         # 가중합 두 개를 한 번에
    a = 1 / (1 + np.exp(-z))               # 활성화 g 도 한 번에
    return float(np.array([V1, V2]) @ a + c)  # 출력 가중합 (@ 는 내적)

print("\n[순수 파이썬 vs numpy · x=2.0]")
순수, *_ = 순전파(2.0)
print("  순수 파이썬 ŷ:", round(순수, 4))            # → 순수 파이썬 ŷ: 0.3478
print("  numpy      ŷ:", round(순전파_numpy(2.0), 4))  # → numpy      ŷ: 0.3478
print("  같나?", abs(순수 - 순전파_numpy(2.0)) < 1e-9)  # → 같나? True


