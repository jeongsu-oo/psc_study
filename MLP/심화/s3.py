# 처음 손실과 끝 손실, 그리고 정확도를 나란히 보면 초기화의 힘이 드러나요.

print("[초기화 비교 · 활성화=ReLU · 150스텝]")
print("  방식      시작손실   끝손실   정확도")
for 초기화 in ["zero", "small", "he"]:
    손실, 정확도 = mlp_학습(relu, relu_도함수, 초기화)
