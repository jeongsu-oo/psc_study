# 말로만 말고, He 로 초기화한 층을 여러 개 통과시켜 신호(활성화)의 표준편차가
# 유지되는지 재 봅시다. '너무 큰 std' 초기화와 나란히 놓고요.
# 신호 std 가 1 근처로 유지되면 좋은 것, 폭발하거나 0으로 죽으면 나쁜 겁니다.

def 신호_흐르기(초기화방식):
    a = np.random.randn(200)                 # 입력 200개, std≈1 로 출발
    stds = []
    for _ in range(5):                       # 은닉층 5개를 통과
        n_in = a.shape[0]
        if 초기화방식 == "he":
            W = np.random.randn(200, n_in) * np.sqrt(2 / n_in)
        else:  # 너무 큰 초기화
            W = np.random.randn(200, n_in) * 1.0
        a = relu(W @ a)                       # ReLU 은닉층
        stds.append(a.std())
    return stds

