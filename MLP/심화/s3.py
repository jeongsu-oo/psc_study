# 0 초기화(zero) : 손실이 0.6931 에서 '한 발도' 안 움직입니다. 정확도 0.51 =찍기.
#                  대칭이 안 깨져 모든 은닉 뉴런이 똑같이 굴어 학습이 아예 안 돼요.
