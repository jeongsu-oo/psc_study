# ----------------------------------------
# 제조 데이터 - 비선형(직선으로 못 가르는) 이진 분류
# ----------------------------------------

# 이제 진짜 MLP 를 학습시켜, 초기화·활성화가 학습 속도를 바꾸는 걸 봅니다.
# 데이터는 제조 센서 2개(온도·진동)로 '불량 여부(0/1)'를 맞히는 문제로 만들죠.
# 불량이 '온도와 진동이 둘 다 높거나 둘 다 낮을 때' 나온다고 하면, 이건
# 직선 하나로 못 가르는 비선형 문제라 은닉층이 꼭 필요합니다(XOR 같은 모양).

def 제조데이터(n=400):
    np.random.seed(0)
    온도 = np.random.randn(n)                 # 표준화된 온도 (평균0·std1)
    진동 = np.random.randn(n)                 # 표준화된 진동
    # 부호가 같으면(둘 다 +거나 둘 다 -) 불량(1), 다르면 정상(0) → 비선형
    y = ((온도 * 진동) > 0).astype(float)
    X = np.stack([온도, 진동], axis=1)         # (n, 2)
    return X, y.reshape(-1, 1)

X, y = 제조데이터()
print("[제조 데이터]")
print("  모양 X:", X.shape, " y:", y.shape)   # → 모양 X: (400, 2)  y: (400, 1)
print("  불량 비율:", f"{y.mean():.2f}")        # → 불량 비율: 0.51


# ----------------------------------------
# 작은 MLP 하나 - 2 → 16 → 1 (은닉층 하나)
# ----------------------------------------

# 망 구조 : 입력 2 → 은닉 16(활성화) → 출력 1(sigmoid, 이진이니까).
# 순전파·역전파를 손으로 짜되, '은닉층 활성화'와 '초기화'만 인자로 바꿔 끼웁니다.
# 그래야 그 둘의 영향만 딱 떼어 비교할 수 있어요.

def mlp_학습(활성화, 활성화도함수, 초기화, 스텝=150, lr=0.5, seed=1):
    np.random.seed(seed)
    n_in, n_hid = 2, 16

    # --- 초기화 방식만 바꿔 가중치 세팅 ---
    if 초기화 == "he":
        W1 = np.random.randn(n_in, n_hid) * np.sqrt(2 / n_in)
    elif 초기화 == "xavier":
        W1 = np.random.randn(n_in, n_hid) * np.sqrt(1 / n_in)
    elif 초기화 == "zero":
        W1 = np.zeros((n_in, n_hid))               # 대칭 안 깨짐(나쁨)
    elif 초기화 == "small":
        W1 = np.random.randn(n_in, n_hid) * 0.01   # 너무 작음(신호 쪼그라듦)
    b1 = np.zeros(n_hid)
    W2 = np.random.randn(n_hid, 1) * np.sqrt(2 / n_hid)
    b2 = np.zeros(1)

    손실기록 = []
    for _ in range(스텝):
        # --- 순전파 ---
        z1 = X @ W1 + b1
        a1 = 활성화(z1)                # 은닉층 활성화 (여기를 바꿔 끼움)
        z2 = a1 @ W2 + b2
        y_hat = sigmoid(z2)            # 출력은 항상 sigmoid (이진 분류)

        # 이진 교차엔트로피 손실 (log(0) 막으려 살짝 클립)
        p = np.clip(y_hat, 1e-7, 1 - 1e-7)
        손실 = -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))
        손실기록.append(손실)

        # --- 역전파 ---
        d_z2 = (y_hat - y) / len(X)               # sigmoid+BCE 는 이 형태로 깔끔
        d_W2 = a1.T @ d_z2
        d_b2 = d_z2.sum(axis=0)
        d_a1 = d_z2 @ W2.T
        d_z1 = d_a1 * 활성화도함수(z1)             # 은닉 활성화 도함수 곱하기
        d_W1 = X.T @ d_z1
        d_b1 = d_z1.sum(axis=0)

        # --- 갱신 (경사하강) ---
        W2 -= lr * d_W2; b2 -= lr * d_b2
        W1 -= lr * d_W1; b1 -= lr * d_b1

    # 최종 정확도도 같이 반환
    정확도 = np.mean((y_hat > 0.5) == y)
    return 손실기록, 정확도


