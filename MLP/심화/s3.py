# -------------------------------
# 활성화 함수와 가중치 초기화 - 기울기 소실을 푸는 두 손잡이 (과정4 심화 3편)
# -------------------------------


"""[기울기 소실을 봤는데, 그럼 뭘 어떻게 바꿔야 하죠?]
심화 2편에서 기울기 소실을 손으로 만졌습니다. 결론은 한 문장이었죠.
   역전파는 층마다 '지역 기울기'를 곱해 뒤→앞으로 가는데,
   sigmoid 지역 기울기가 ≤0.25 라 층을 지날수록 0으로 사라진다.

그럼 앞층까지 기울기를 살려 보내려면 뭘 바꿔야 할까요? 손잡이가 둘 있습니다.

   손잡이 1 = 활성화 함수 (층마다 곱해지는 그 지역 기울기를 뭘로 만들지)
   손잡이 2 = 가중치 초기화 (학습을 어떤 값에서 출발시킬지)

이 파일은 그 둘을 위에서 아래로 훑습니다.
   활성화 4종의 값·도함수를 표로 재고 (곱해지는 게 얼마나 큰지)
   → 은닉층엔 ReLU·출력층은 목적따라 → 죽은 ReLU 와 LeakyReLU
   → 왜 0으로도, 너무 크게도, 너무 작게도 초기화하면 안 되는지
   → He·Xavier 초기화 (팬-인 n_in 에 분산을 맞추는 처방)
   → 마지막엔 제조 데이터로 진짜 MLP 를 학습시켜, 나쁜 초기화 vs He,
     sigmoid vs ReLU 의 손실 감소 차이를 '숫자로' 봅니다.

수식은 주석에 적되 유도는 안 합니다. 도함수는 수치로 검증해 보고요.
numpy 만 씁니다. 시드를 고정해 매번 같은 결과가 나오게 합니다.
"""

import numpy as np

# 이 파일 전체에서 난수를 쓰는 곳(초기화·데이터)이 여럿입니다.
# 시드를 한 번 고정해 두면, 몇 번을 돌려도 아래 print 가 똑같이 나옵니다.
np.random.seed(42)


# ========================================================
#  PART 1 : 활성화 함수 4종 - 값과 도함수를 표로 재기
# ========================================================

# ----------------------------------------
# 네 함수와 그 도함수를 코드로
# ----------------------------------------

# 활성화 함수는 z(가중합)를 받아 '이 뉴런이 얼마나 켜질지'를 정하는 문지기입니다.
# 역전파에서 중요한 건 그 도함수예요. 층을 지날 때 곱해지는 '지역 기울기'니까요.
# 네 후보의 정의와 도함수를 나란히 적습니다. (수식은 주석, 유도는 생략)
#
#   sigmoid(z)  = 1 / (1 + e^-z)          출력 0~1     도함수 = a(1-a) ≤ 0.25
#   tanh(z)     = (e^z - e^-z)/(e^z+e^-z) 출력 -1~1    도함수 = 1 - a²  ≤ 1
#   relu(z)     = max(0, z)               출력 0~∞     도함수 = 1(z>0), 0(z<0)
#   leaky(z)    = z(z>0), 0.01·z(z<0)     음수도 조금  도함수 = 1(z>0), 0.01(z<0)

def sigmoid(z):
    return 1 / (1 + np.exp(-z))

def sigmoid_도함수(z):
    a = sigmoid(z)
    return a * (1 - a)          # a(1-a)

def tanh(z):
    return np.tanh(z)

def tanh_도함수(z):
    a = np.tanh(z)
    return 1 - a ** 2           # 1 - tanh²

def relu(z):
    return np.maximum(0.0, z)

def relu_도함수(z):
    return np.where(z > 0, 1.0, 0.0)

def leaky(z, 기울기=0.01):
    return np.where(z > 0, z, 기울기 * z)

def leaky_도함수(z, 기울기=0.01):
    return np.where(z > 0, 1.0, 기울기)


# ----------------------------------------
# 여러 z 에서 값·도함수를 한 표로
# ----------------------------------------

# z 를 -2 부터 +2 까지 훑으며 네 함수의 '값'과 '도함수'를 나란히 찍습니다.
# 보고 싶은 건 두 가지 — 값이 어느 범위에 갇히는지, 도함수가 얼마나 큰지.

zs = [-2.0, -1.0, 0.0, 1.0, 2.0]

print("[활성화 값 f(z)]")
print("     z   sigmoid    tanh    relu   leaky")
for z in zs:
    print(f"  {z:+.1f}   {sigmoid(z):.3f}  {tanh(z):+.3f}  {relu(z):.3f}  {leaky(z):+.3f}")
# → [활성화 값 f(z)]
# →      z   sigmoid    tanh    relu   leaky
# →   -2.0   0.119  -0.964  0.000  -0.020
# →   -1.0   0.269  -0.762  0.000  -0.010
# →   +0.0   0.500  +0.000  0.000  +0.000
# →   +1.0   0.731  +0.762  1.000  +1.000
# →   +2.0   0.881  +0.964  2.000  +2.000

print("\n[도함수 f'(z) - 역전파에서 층마다 곱해지는 값]")
print("     z   sigmoid    tanh    relu   leaky")
for z in zs:
    print(f"  {z:+.1f}    {sigmoid_도함수(z):.3f}   {tanh_도함수(z):.3f}   {relu_도함수(z):.3f}   {leaky_도함수(z):.3f}")
# → [도함수 f'(z) - 역전파에서 층마다 곱해지는 값]
# →      z   sigmoid    tanh    relu   leaky
# →   -2.0    0.105   0.071   0.000   0.010
# →   -1.0    0.197   0.420   0.000   0.010
# →   +0.0    0.250   1.000   0.000   0.010
# →   +1.0    0.197   0.420   1.000   1.000
# →   +2.0    0.105   0.071   1.000   1.000

# 도함수 표가 핵심입니다. 이게 '한 층 지날 때 기울기가 몇 배 되나'예요.
#   sigmoid : 아무리 커야 0.25. 양옆으로 가면 뚝 떨어짐 → 곱하면 소실
#   tanh    : 중심에서 1까지 감. sigmoid 보단 낫지만 역시 양끝은 0에 붙음
#   relu    : 양수 구간에서 딱 1. 곱해도 1은 안 줄어듦 → 소실 안 함
#   leaky   : relu 와 같되, 음수 구간도 0 이 아니라 0.01 (죽지 않게)


# ----------------------------------------
# 도함수를 수치로 검증 - 정의대로 맞나
# ----------------------------------------

# 위 도함수 공식을 그냥 믿지 말고, 도함수의 정의로 직접 검산해 봅시다.
#   f'(z) ≈ (f(z+h) - f(z-h)) / (2h)   (h 아주 작게)
# 공식으로 구한 값과 이 수치미분이 같으면, 우리 도함수가 맞다는 뜻이죠.

h = 1e-6
z0 = 0.7
for 이름, f, df in [("sigmoid", sigmoid, sigmoid_도함수),
                     ("tanh", tanh, tanh_도함수),
                     ("relu", relu, relu_도함수)]:
    수치 = (f(z0 + h) - f(z0 - h)) / (2 * h)
    공식 = df(z0)
    print(f"  {이름:8s} z=0.7 : 공식={공식:.5f}  수치미분={수치:.5f}")
# →   sigmoid  z=0.7 : 공식=0.22171  수치미분=0.22171
# →   tanh     z=0.7 : 공식=0.63474  수치미분=0.63474
# →   relu     z=0.7 : 공식=1.00000  수치미분=1.00000

# 공식과 수치미분이 소수점 다섯 자리까지 같습니다. 우리 도함수가 맞아요.
# (relu 는 z=0 딱 그 점만 안 미분되지, z=0.7 처럼 양수면 도함수 1 로 멀쩡)


# ========================================================
#  PART 2 : 어디에 뭘 쓰나 - 은닉층 vs 출력층
# ========================================================

# ----------------------------------------
# 자리마다 역할이 다르다
# ----------------------------------------

# 활성화는 아무 데나 아무거나 쓰는 게 아닙니다. 자리마다 목적이 달라요.
#
#   [은닉층] - 기울기를 앞층까지 살려 보내는 게 목적
#       기본은 ReLU. 이유는 2편에서 봤죠 — 도함수가 1이라 곱해도 안 줄어듦.
#       빠르기도 하고요(exp 계산 없이 max 하나). 죽는 게 걱정되면 LeakyReLU.
#
#   [출력층] - 문제의 '정답 모양'에 맞추는 게 목적
#       회귀(연속값 예측)  → 활성화 없음(선형). 온도 87.3도 같은 실수 그대로
#       이진 분류(0/1)     → sigmoid. 출력이 0~1 이라 '확률'로 읽힘
#       다중 분류(N개 중 1) → softmax. N개 확률의 합이 1이 되게
#
# 한 줄 요령: 은닉층은 '기울기 잘 흐르나', 출력층은 '정답 모양 맞나'로 고른다.

print("[활성화 선택 - 자리와 목적]")
print("  은닉층      : ReLU (기본), 죽으면 LeakyReLU")
print("  출력·회귀   : 선형(없음)")
print("  출력·이진   : sigmoid")
print("  출력·다중   : softmax")
# → [활성화 선택 - 자리와 목적]
# →   은닉층      : ReLU (기본), 죽으면 LeakyReLU
# →   출력·회귀   : 선형(없음)
# →   출력·이진   : sigmoid
# →   출력·다중   : softmax

# 여기서 딱 잡을 것 : sigmoid 는 '은닉층엔 안 쓰지만(소실), 이진 출력엔 쓴다'.
# 같은 함수라도 어느 자리에 놓느냐로 좋고 나쁨이 갈리는 거예요.


# ========================================================
#  PART 3 : ReLU 의 함정 - 죽은 ReLU 와 LeakyReLU
# ========================================================

# ----------------------------------------
# 죽은 ReLU - 음수만 들어오면 영영 0
# ----------------------------------------

# ReLU 가 소실을 풀지만, 대신 다른 함정이 하나 있습니다. '죽은 ReLU'예요.
# relu 도함수는 z>0 이면 1, z≤0 이면 0 이죠. 그런데 어쩌다 어떤 뉴런의 z 가
# 늘 음수만 나오게 되면? 도함수가 계속 0 → 기울기 0 → 그 뉴런은 학습이 멈춥니다.
# 한 번 죽으면 가중치가 안 움직이니 다시 못 살아나요. 그래서 '죽었다'고 합니다.
#
# ASCII 로 두 곡선을 겹쳐 보면 차이가 한눈에 옵니다.
#
#          ReLU                     LeakyReLU
#            |    /                    |    /
#            |   /                     |   /
#   ─────────┼──────           ───────┼──────
#         ___|                      ／ |            음수 쪽이
#            |                    ／   |            0 이 아니라
#      (음수=0, 평평)          (음수도 살짝 기울어짐)  살짝 흐름

# 음수 입력만 잔뜩 들어온 뉴런을 흉내 내 봅시다.
음수입력 = np.array([-3.0, -1.5, -0.5, -2.0])

print("[죽은 ReLU - 음수만 들어온 뉴런의 도함수]")
print("  relu  도함수:", relu_도함수(음수입력))    # → relu  도함수: [0. 0. 0. 0.]
print("  leaky 도함수:", leaky_도함수(음수입력))   # → leaky 도함수: [0.01 0.01 0.01 0.01]

# relu 는 도함수가 전부 0 — 이 뉴런은 죽었습니다. 기울기가 0이라 안 배워요.
# leaky 는 0.01 — 작지만 0은 아니죠. 기울기가 조금이라도 흐르니 되살아날 길이 있습니다.
# LeakyReLU 는 음수 구간에 '0.01 기울기'를 줘서 뉴런이 죽는 걸 막는 처방입니다.


# ========================================================
#  PART 4 : 가중치 초기화 - 왜 0도, 큰 것도, 작은 것도 안 되나
# ========================================================

# ----------------------------------------
# 0으로 초기화하면? - 대칭이 안 깨진다
# ----------------------------------------

# 활성화를 잘 골랐어도, 학습의 '출발점'인 초기 가중치가 나쁘면 망합니다.
# 첫 번째 금기 : 모든 가중치를 0(또는 같은 값)으로 두는 것.
#
# 왜 안 되냐 — 한 층의 뉴런들이 전부 똑같은 값(0)에서 출발하면,
# 같은 입력에 같은 출력, 역전파로 오는 기울기도 같습니다. 그래서 갱신 후에도
# 여전히 서로 똑같아요. 뉴런이 열 개든 백 개든 전부 '한 뉴런의 복사본'이 됩니다.
# 이걸 '대칭이 안 깨졌다'고 합니다. 뉴런을 여러 개 둔 의미가 사라지죠.

# 뉴런 3개짜리 층에, 입력 하나가 들어온다고 하고 한 스텝만 흉내 내 봅시다.
입력 = np.array([1.0, 2.0])          # 입력 2개
W0 = np.zeros((3, 2))                # 뉴런3 x 입력2, 전부 0 으로 초기화
z = W0 @ 입력                        # 세 뉴런의 가중합
print("[0 초기화 - 세 뉴런이 완전히 똑같음]")
print("  세 뉴런 z:", z)             # → 세 뉴런 z: [0. 0. 0.]
# 세 뉴런이 전부 0 으로 똑같습니다. 역전파 기울기도 똑같이 올 테니
# 갱신해도 셋이 나란히 같은 값으로 움직여요. 영원히 한 뉴런처럼 굽니다.
# 그래서 초기 가중치는 '서로 다른 랜덤값'이어야 대칭이 깨집니다.


# ----------------------------------------
# 랜덤이면 됐지 - 크기가 또 문제다
# ----------------------------------------

# 그럼 랜덤이면 끝? 아뇨. 랜덤값의 '크기(분산)'가 또 사고를 칩니다.
#   너무 크면  → z 가 커짐 → sigmoid/tanh 는 양끝(도함수≈0)으로 포화 → 소실
#                (ReLU 는 z 가 폭주 → 값이 발산)
#   너무 작으면 → 신호가 층을 지날수록 쪼그라듦 → 역시 앞층에서 소실
# 즉 크지도 작지도 않은 '딱 맞는 크기'가 필요합니다. 그걸 재 봅시다.

# 입력 100개짜리 층을, 가중치 표준편차를 바꿔 가며 z 의 퍼짐(표준편차)을 봅니다.
n_in = 100
x = np.random.randn(n_in)            # 입력 100개 (평균0·분산1 근처)
for 표준편차 in [0.01, 1.0, 10.0]:
    W = np.random.randn(n_in) * 표준편차     # 이 크기로 가중치 랜덤
    z = W @ x
    print(f"  가중치 std={표준편차:5.2f} → z={z:+8.2f},  sigmoid'(z)={sigmoid_도함수(z):.6f}")
# →   가중치 std= 0.01 → z=   -0.12,  sigmoid'(z)=0.249113
# →   가중치 std= 1.00 → z=  +17.93,  sigmoid'(z)=0.000000
# →   가중치 std=10.00 → z= -146.41,  sigmoid'(z)=0.000000

# 보이시나요. 가중치가 크면(std=1,10) z 가 +18, -146 으로 커지고,
# 그러면 sigmoid 도함수가 0.000000 으로 죽습니다(포화 = 소실).
# 너무 작으면(std=0.01) z 가 거의 0 이라 도함수는 0.25 로 살지만, 이번엔
# 신호 자체가 너무 약해 층을 여러 개 지나면 사라지죠. 어느 쪽도 답이 아닙니다.
# 입력 개수 n_in 에 맞춰 딱 좋은 std 를 정해 주는 게 다음의 He·Xavier 입니다.


# ========================================================
#  PART 5 : He / Xavier 초기화 - 팬-인에 분산을 맞춘다
# ========================================================

# ----------------------------------------
# 공식 - n_in(팬-인)에 std 를 맞춘다
# ----------------------------------------

# 딱 좋은 크기는 '입력 개수 n_in(팬-인, 그 뉴런에 들어오는 선의 수)'로 정합니다.
# 입력이 많을수록 가중합이 커지니, 입력이 많으면 가중치를 작게 줘서 균형을 맞춰요.
#
#   He 초기화     : std = √(2 / n_in)      ← ReLU 계열에 (음수 절반이 0 되는 걸 보정)
#   Xavier 초기화 : std = √(1 / n_in)      ← sigmoid / tanh 에
#
# 규칙은 '팬-인이 클수록 std 를 줄여, 층을 지나도 신호 크기가 유지되게'입니다.

def he_초기화(n_out, n_in):
    return np.random.randn(n_out, n_in) * np.sqrt(2 / n_in)      # ReLU 용

def xavier_초기화(n_out, n_in):
    return np.random.randn(n_out, n_in) * np.sqrt(1 / n_in)      # sigmoid/tanh 용

for n_in in [10, 100, 1000]:
    print(f"  n_in={n_in:4d} :  He std=√(2/{n_in})={np.sqrt(2/n_in):.4f}   "
          f"Xavier std=√(1/{n_in})={np.sqrt(1/n_in):.4f}")
# →   n_in=  10 :  He std=√(2/10)=0.4472   Xavier std=√(1/10)=0.3162
# →   n_in= 100 :  He std=√(2/100)=0.1414   Xavier std=√(1/100)=0.1000
# →   n_in=1000 :  He std=√(2/1000)=0.0447   Xavier std=√(1/1000)=0.0316

# 입력이 10개면 std≈0.45, 1000개면 std≈0.045 로 확 작아집니다.
# 입력이 많을수록 가중치를 작게 — 그래야 가중합(z)이 안 커지고 포화도 안 나요.


