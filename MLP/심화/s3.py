# ----------------------------------------
# 3편 마무리 - 오늘 손에 넣은 것
# ----------------------------------------

#   [활성화 4종 한 줄 정리]
#     sigmoid  : 출력 0~1, 도함수 ≤0.25 → 은닉층엔 X(소실), 이진 출력엔 O
#     tanh     : 출력 -1~1, 중심 0, 도함수 ≤1 → sigmoid 보단 나음
#     ReLU     : max(0,z), 도함수 0/1 → 은닉층 기본(소실 안 함·빠름)
#     LeakyReLU: 음수도 0.01 통과 → 죽은 ReLU 방지
#
#   [어디에 뭘]
#     은닉층 = ReLU(기본)/LeakyReLU     출력층 = 회귀·선형, 이진·sigmoid, 다중·softmax
#
#   [초기화 3금기]
#     0 으로   → 대칭 안 깨짐(모든 뉴런 똑같아짐) → 학습 자체가 안 됨
#     너무 큼  → z 포화/발산 → 도함수 0 → 소실
#     너무 작음 → 신호가 층마다 쪼그라듦 → 소실
#
#   [처방 = He / Xavier]
#     He     std=√(2/n_in)  ← ReLU 계열
#     Xavier std=√(1/n_in)  ← sigmoid/tanh
#     팬-인 n_in 이 클수록 std 를 줄여, 층을 지나도 신호 크기를 유지
#
#   [숫자로 본 것]
#     0 초기화는 손실이 0.6929 에서 안 움직임(대칭), He 는 0.11 까지 내려감
#     은닉층 sigmoid 는 0.641(굼뜸), ReLU 는 0.107(빠름) — 소실의 실전 여파
#
#   [기억할 것]
#     · 2편의 기울기 소실을 푸는 두 손잡이 = 활성화(ReLU) + 초기화(He)
#     · 활성화는 '은닉=기울기, 출력=정답모양' 기준으로 고른다
#     · 초기화는 랜덤이되 팬-인에 맞춘 '딱 좋은 크기'여야 한다
#     · 심화 3부작(역전파 → 소실 → 활성화·초기화) 여기서 마무리
