"""[은닉층 1개짜리를 배웠는데, 층을 더 쌓으면 뭐가 달라지나요?]
과정4 심화의 첫 편입니다.

역전파 편(4부작)에서 우리가 만든 신경망은 은닉층이 '1개' 였습니다.
   입력 → 은닉(sigmoid) → 출력
이 한 층짜리도 직선이 못 잡는 U자 불량을 훌륭히 잡았죠.

그런데 진짜 딥러닝(deep learning)은 '깊다(deep)' 가 이름에 붙어 있습니다.
은닉층을 하나가 아니라 여러 개 쌓는다는 뜻이에요.
   입력 → 은닉1 → 은닉2 → 출력      ← 은닉층 2개
층을 쌓으면 더 복잡한 패턴을 표현할 수 있습니다. 왜, 어떻게 되는지
오늘 밑바닥부터 손으로 만들어 봅니다.

핵심 아이디어 딱 하나: 층이 몇 개든 '똑같은 일의 반복' 이라는 것.
   순전파 = 층을 앞에서 뒤로 하나씩 통과 (for 루프)
   역전파 = 오차를 뒤에서 앞으로 하나씩 되돌림 (거꾸로 for 루프)
층마다 하는 계산은 역전파 편에서 배운 그 패턴 그대로입니다.
달라지는 건 '몇 번 반복하느냐' 뿐이에요. 그래서 층을 '리스트' 로 일반화합니다.

이 파일 순서:
  전환(리스트로 일반화) → 순전파 일반화 → 역전파 일반화(핵심) →
  수치미분 킬러 검증 → 2층으로 U자 학습 → 왜 깊게? → 실습.
전부 numpy 몇 줄입니다. 역전파 편이 '1층 특수판' 이었다면, 오늘은 그 '일반판' 이에요.
"""

# 오늘도 numpy 가 주인공입니다. 층을 리스트로 다루며 행렬곱을 돌립니다.
import numpy as np


# ========================================================
#  PART 1 : 전환 - 층을 '리스트' 로 일반화
# ========================================================

# ----------------------------------------
# 은닉층 1개 → 여러 개, 뭐가 바뀌나
# ----------------------------------------

# 역전파 편의 망은 층이 딱 두 덩어리였습니다 (입력→은닉, 은닉→출력).
# 그래서 W, b, V, c 처럼 가중치에 '이름' 을 하나씩 붙여 다뤘죠.
#
# 그런데 은닉층을 3개, 5개 쌓으면 W1,b1,W2,b2,W3,b3,... 끝이 없습니다.
# 이름을 계속 늘리는 대신, 층을 '리스트' 에 담아 for 로 훑기로 합니다.
#
#   망 구조 (은닉층 2개짜리 예):
#
#      입력 X ──►[은닉1]──►[은닉2]──►[출력]──► ŷ
#              W[0],b[0]  W[1],b[1]  W[2],b[2]
#              sigmoid    sigmoid    (선형)
#
#   층 = [ (W[0],b[0]), (W[1],b[1]), (W[2],b[2]) ]   ← 리스트로 일반화
#
# 이렇게 리스트에 담으면, 층이 2개든 10개든 코드는 안 바뀝니다.
# for 로 리스트 길이만큼 돌면 되니까요. 이게 오늘의 전부입니다.


# ----------------------------------------
# 준비물 - 데이터, 활성화 함수, 층 만들기
# ----------------------------------------

# 역전파 편에서 쓴 그 온도-불량 데이터입니다. (외부 파일 없이 인라인)
# 모양이 'U자' — 양 끝(춥다/과열)이 높고 가운데(최적)가 낮습니다.

온도 = np.array([10, 15, 20, 25, 30, 35, 40], dtype=float)
불량 = np.array([ 9,  5,  2,  1,  2,  5,  9], dtype=float)

#   불량
#    9 |●                       ●     ← 양 끝이 높다 (춥다 / 과열)
#      | \                     /
#    5 |  ●                   ●
#    2 |    ●               ●
#    1 |         ●·······●            ← 가운데가 최적 (불량 최소)
#      +--------------------------→ 온도
#       10  15  20  25  30  35  40


def sigmoid(z):
    return 1 / (1 + np.exp(-z))       # S자 곡선 = '휘는 능력'

def sigmoid_도함수(a):
    # 역전파 편에서 본 그 식. 출력값 a 로 바로 구해진다: σ'(z) = a(1-a)
    return a * (1 - a)


# 층을 만드는 함수. 각 층의 뉴런 수를 리스트로 주면, 층마다 (W, b) 를 만듭니다.
#   구조=[1, 6, 6, 1]  →  입력1 → 은닉6 → 은닉6 → 출력1  (은닉층 2개)
# 이웃한 두 숫자가 한 층의 (입력 수, 출력 수) 가 됩니다.

def 층만들기(구조, seed=0):
    np.random.seed(seed)                       # 시드 고정 → 매번 같은 결과
    층 = []
    for 들어옴, 나감 in zip(구조[:-1], 구조[1:]):
        W = np.random.randn(들어옴, 나감) * 0.5    # (들어옴×나감) 가중치 행렬
        b = np.zeros((1, 나감))                    # (1×나감) 편향
        층.append([W, b])
    return 층

# 예: 은닉층 2개짜리 망을 만들어 확인합니다.
망 = 층만들기([1, 6, 6, 1])
print("[층 리스트로 만든 망]")
print(f"  층 개수: {len(망)}")                              # → 층 개수: 3
for i, (W, b) in enumerate(망):
    print(f"  층{i}: W {W.shape}  b {b.shape}")
# → [층 리스트로 만든 망]
# →   층 개수: 3
# →   층0: W (1, 6)  b (1, 6)
# →   층1: W (6, 6)  b (1, 6)
# →   층2: W (6, 1)  b (1, 1)

# 층 3개(은닉2 + 출력1)가 리스트에 담겼습니다. 이제 이 리스트를 for 로 통과시킵니다.


# ========================================================
#  PART 2 : 순전파 일반화 - 층 리스트를 for 로 통과
# ========================================================

# ----------------------------------------
# A0=X, 각 층: Z=A@W+b, A=활성화(Z)
# ----------------------------------------

# 역전파 편 순전파는 두 줄이었습니다 (은닉 한 번, 출력 한 번).
# 층이 여러 개면? '같은 두 줄' 을 층마다 반복하면 됩니다. for 로요.
#
#   A0 = X                          입력을 0번째 활성화로 둔다
#   각 층 l 에 대해:
#       Z = A @ W[l] + b[l]         선형 (앞 층 출력에 이번 층 가중치)
#       A = 활성화(Z)               활성화 통과 → 다음 층 입력이 됨
#   마지막 층만 활성화 없이 선형     (회귀니까 출력은 그대로 씀)
#
# 앞 층의 출력 A 가 다음 층의 입력이 되어 '릴레이' 처럼 흐릅니다.
# 역전파 때 각 층의 A 값이 필요하므로, 지나온 A 들을 리스트에 저장해 둡니다.

def 순전파(X, 층):
    A = X
    활성화들 = [X]           # A0=X 부터 저장 (역전파에서 각 층 입력으로 씀)
    마지막 = len(층) - 1
    for l, (W, b) in enumerate(층):
        Z = A @ W + b       # 선형: 앞 층 출력 @ 이번 층 가중치
        if l == 마지막:
            A = Z           # 출력층은 선형 그대로 (회귀)
        else:
            A = sigmoid(Z)  # 은닉층은 활성화 통과 (휘는 능력)
        활성화들.append(A)
    return A, 활성화들        # A=최종예측 ŷ, 활성화들=각 층 출력 모음

# 한 번 흘려보내 봅니다. 표준화한 온도를 넣어 예측 모양을 확인.
z = ((온도 - 온도.mean()) / 온도.std()).reshape(-1, 1)   # 표준화 (뒤에서 설명)
ŷ0, _ = 순전파(z, 망)
print("\n[순전파 한 번 · 학습 전]")
print(f"  입력 shape {z.shape} → 예측 shape {ŷ0.shape}")   # → 입력 shape (7, 1) → 예측 shape (7, 1)
print(f"  예측 앞 3개: {np.round(ŷ0.ravel()[:3], 4)}")      # → 예측 앞 3개: [-0.4572 -0.5042 -0.5593]

# 아직 학습 전이라 예측은 엉망입니다(다 비슷한 값). 하지만 층 3개를
# for 로 무사히 통과했어요. 층이 10개여도 이 함수는 그대로 돕니다.


# ========================================================
#  PART 3 : 역전파 일반화 (핵심) - 오차를 뒤에서 앞으로
# ========================================================

# ----------------------------------------
# delta 를 뒤 층부터 앞 층으로 전달
# ----------------------------------------

# 오늘의 심장입니다. 역전파 편에서 '한 층' 을 거슬러 오는 걸 손으로 짰죠.
# 층이 여러 개면, 그 '거슬러 오기' 를 층마다 반복하면 됩니다. 거꾸로 for 로요.
#
# 핵심 도구는 delta = ∂L/∂z (그 층 선형출력에 대한 손실 기울기).
# delta 만 손에 쥐면 그 층의 가중치 기울기가 바로 나옵니다:
#
#   출력층에서 출발:
#       delta = ∂L/∂z_출력 = 2(ŷ - y)/n          ← 씨앗 (출력은 선형)
#
#   각 층을 거꾸로 (l = 마지막-1, ..., 0):
#       delta^(l) = (delta^(l+1) @ W^(l+1)ᵀ) ⊙ 활성화'(z^(l))
#                    └ 뒤 층 오차를 가중치로 되돌림 ┘ └ 이 층 활성화 미분 ┘
#
#   각 층의 가중치 기울기 (delta 만 있으면 즉시):
#       ∂L/∂W^(l) = A^(l-1)ᵀ @ delta^(l)         (앞 층 출력)ᵀ @ (이 층 delta)
#       ∂L/∂b^(l) = Σ delta^(l)                  delta 를 세로로 합
#
# ⊙ 는 '같은 자리끼리 곱'(성분별). @ 는 행렬곱. 층마다 '똑같은 패턴' 이
# 반복될 뿐입니다 — 이게 연쇄법칙(역전파 편)을 층 개수만큼 이어 붙인 거예요.

def 역전파(Y, 활성화들, 층):
    n = len(Y)
    기울기들 = [None] * len(층)              # 층마다 (dW, db) 채울 자리
    ŷ = 활성화들[-1]

    # 출력층 delta = 씨앗 (출력은 선형이라 활성화 미분 없음)
    delta = 2 * (ŷ - Y) / n                 # ∂L/∂z_출력   (n×출력수)

    # 마지막 층부터 0번 층까지 거꾸로
    for l in reversed(range(len(층))):
        A_이전 = 활성화들[l]                 # 이 층의 입력 = 앞 층 출력 A^(l-1)
        dW = A_이전.T @ delta               # ∂L/∂W^(l) = A^(l-1)ᵀ @ delta
        db = delta.sum(axis=0, keepdims=True)   # ∂L/∂b^(l) = Σ delta
        기울기들[l] = [dW, db]

        # 다음(앞) 층으로 넘길 delta 를 미리 계산 (0번 층이면 필요 없음)
        if l > 0:
            W = 층[l][0]
            A_이번 = 활성화들[l]             # 이 층 출력 (sigmoid 통과값) = a^(l-1)
            # delta^(l-1) = (delta^(l) @ W^(l)ᵀ) ⊙ σ'(z^(l-1))
            delta = (delta @ W.T) * sigmoid_도함수(A_이번)
    return 기울기들

# 방금 순전파한 결과로 기울기를 한 번 구해 모양만 확인합니다.
Y = 불량.reshape(-1, 1)
_, 활성화들0 = 순전파(z, 망)
기울기들0 = 역전파(Y, 활성화들0, 망)
print("\n[역전파 한 번 · 기울기 모양]")
for l, (dW, db) in enumerate(기울기들0):
    print(f"  층{l}: dW {dW.shape}  db {db.shape}")
# → [역전파 한 번 · 기울기 모양]
# →   층0: dW (1, 6)  db (1, 6)
# →   층1: dW (6, 6)  db (1, 6)
# →   층2: dW (6, 1)  db (1, 1)

# 각 층 가중치와 '똑같은 모양' 의 기울기가 나왔습니다.
# (W 와 dW 모양이 같아야 W ← W - lr·dW 로 갱신할 수 있으니까요.)
# 층이 몇 개든 이 for 하나로 전부 거슬러 옵니다. 이게 역전파 일반화입니다.


# ========================================================
#  PART 4 : 킬러 검증 - 다층 전체 기울기 vs 수치미분
# ========================================================

# ----------------------------------------
# 손으로 짠 역전파가 정말 맞을까 (다층 전체 대조)
# ----------------------------------------

# 역전파 편에서 했던 '킬러 검증' 을, 이번엔 은닉층 2개짜리 망 '전체' 에 겁니다.
# 방법은 그대로예요. 완전히 다른 방법(수치미분)으로 재서 같으면 '맞다' 는 증거.
#
#   수치미분: 가중치 하나를 아주 조금(h) 흔들어 손실 변화를 잰다.
#     ∂L/∂param ≈ ( L(param+h) - L(param-h) ) / (2h)     (중앙차분)
#   미분 공식 없이, 손실을 두 번 계산해 빼기만 하면 됩니다. 느리지만 정직해요.
#
# 은닉2층 망의 '모든 가중치' 기울기가 수치미분과 소수점까지 맞으면,
# 역전파 일반화(delta 전파 for 루프)가 옳다는 강력한 증거입니다.

def 손실(ŷ, Y):
    return np.mean((ŷ - Y) ** 2)          # MSE

def 손실만_계산(X, Y, 층):
    ŷ, _ = 순전파(X, 층)
    return 손실(ŷ, Y)

def 수치미분_기울기(X, Y, 층, h=1e-5):
    # 층의 모든 W, b 원소를 하나씩 흔들어 수치 기울기를 구한다 (층별 리스트로).
    수치들 = []
    for l in range(len(층)):
        dW = np.zeros_like(층[l][0])
        db = np.zeros_like(층[l][1])
        for 파라, d파라 in ((층[l][0], dW), (층[l][1], db)):
            it = np.nditer(파라, flags=["multi_index"])
            while not it.finished:
                idx = it.multi_index
                원래 = 파라[idx]
                파라[idx] = 원래 + h;  L_plus = 손실만_계산(X, Y, 층)
                파라[idx] = 원래 - h;  L_minus = 손실만_계산(X, Y, 층)
                파라[idx] = 원래                      # 원상복구
                d파라[idx] = (L_plus - L_minus) / (2 * h)
                it.iternext()
        수치들.append([dW, db])
    return 수치들

# 은닉2층 망을 다시 만들어(같은 시드) 역전파 기울기와 수치미분을 대조합니다.
검증망 = 층만들기([1, 6, 6, 1])
ŷ, 활성화들 = 순전파(z, 검증망)
역전파_기울기 = 역전파(Y, 활성화들, 검증망)
수치_기울기 = 수치미분_기울기(z, Y, 검증망)

print("\n[킬러 검증 · 역전파 vs 수치미분 (은닉2층 전체)]")
print(f"  {'층':4}{'파라':6}{'최대 오차':>14}   일치?")
모두일치 = True
for l in range(len(검증망)):
    for j, 이름 in enumerate(["W", "b"]):
        차 = np.abs(역전파_기울기[l][j] - 수치_기울기[l][j]).max()
        일치 = 차 < 1e-7
        모두일치 = 모두일치 and 일치
        print(f"  {l:<4}{이름:6}{차:14.2e}   {일치}")
print("  → 모든 층의 모든 가중치가 일치?", 모두일치)
# → [킬러 검증 · 역전파 vs 수치미분 (은닉2층 전체)]
# →   층   파라             최대 오차   일치?
# →   0   W           6.43e-10   True
# →   0   b           5.81e-10   True
# →   1   W           8.05e-10   True
# →   1   b           2.24e-10   True
# →   2   W           4.79e-10   True
# →   2   b           9.40e-11   True
# →   → 모든 층의 모든 가중치가 일치? True

assert 모두일치, "역전파 일반화가 수치미분과 안 맞으면 delta 전파가 틀린 것!"

# 은닉2층 망의 모든 가중치가 소수점 깊숙이까지 수치미분과 일치합니다.
# 손으로 짠 delta 전파 for 루프가, 완전히 다른 방법과 같은 값에 닿았어요.
# 이게 '역전파 일반화가 맞다' 는 눈으로 보는 증거입니다.
# (수치미분은 원소마다 순전파를 두 번 돌려 느립니다. 그래서 검산용으로만 써요.)


# ========================================================
#  PART 5 : 학습 - 은닉2층으로 U자 불량 잡기
# ========================================================

# ----------------------------------------
# fit - 순전파 → 역전파 → 갱신 을 반복
# ----------------------------------------

# 기울기가 맞다는 걸 확인했으니, 경사하강 루프로 학습합니다.
# 역전파 편 4편과 똑같아요. 딱 하나 달라진 건 '층이 리스트' 라는 것뿐.
#   1) 층을 랜덤 초기화 (시드 고정)
#   2) epochs 번 반복: 순전파 → 역전파 → 층마다 갱신 (W ← W - lr·dW)
#   3) 몇 번마다 손실 출력

def 표준화(x):
    m, s = x.mean(), x.std()
    return (x - m) / s, m, s

def fit(x, y, 구조, lr=0.1, epochs=1500, seed=0, 로그=False):
    z, m, s = 표준화(x)
    X = z.reshape(-1, 1)
    Y = y.reshape(-1, 1)
    층 = 층만들기(구조, seed=seed)
    for epoch in range(epochs):
        ŷ, 활성화들 = 순전파(X, 층)              # 예측
        기울기들 = 역전파(Y, 활성화들, 층)         # 기울기 되짚기 (뒤→앞)
        for l in range(len(층)):                 # 층마다 갱신
            층[l][0] -= lr * 기울기들[l][0]        # W ← W - lr·dW
            층[l][1] -= lr * 기울기들[l][1]        # b ← b - lr·db
        if 로그 and epoch % 300 == 0:
            print(f"  epoch {epoch:5d}   손실 {손실(순전파(X, 층)[0], Y):.4f}")
    if 로그:
        print(f"  epoch {epochs:5d}   손실 {손실(순전파(X, 층)[0], Y):.4f}")
    return 층, m, s

def predict(x, 모델):
    층, m, s = 모델
    X = ((np.asarray(x, dtype=float) - m) / s).reshape(-1, 1)
    ŷ, _ = 순전파(X, 층)
    return ŷ.ravel()

# 은닉층 2개(6,6)로 U자 데이터를 학습시킵니다.
print("\n[은닉2층 MLP 학습 로그]  구조 [1, 6, 6, 1]")
모델2층 = fit(온도, 불량, [1, 6, 6, 1], lr=0.1, epochs=1500, 로그=True)
층2, m2, s2 = 모델2층
# → [은닉2층 MLP 학습 로그]  구조 [1, 6, 6, 1]
