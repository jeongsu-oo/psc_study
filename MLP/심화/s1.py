# ========================================================
#  PART 6 : 왜 깊게? - 표현력과 그 대가
# ========================================================

# ----------------------------------------
# 층을 쌓으면 표현력이 올라간다
# ----------------------------------------

# 왜 굳이 층을 쌓을까요? 한 층은 sigmoid 로 '한 번 휘는' 곡선을 만듭니다.
# 층을 쌓으면 그 휘어진 결과를 '다시 휘게' 합니다. 휨 위에 휨을 얹는 거예요.
#
#   은닉1층:  입력 → (한 번 휨) → 출력            비교적 단순한 곡선
#   은닉2층:  입력 → (휨) → (휨 위에 또 휨) → 출력  훨씬 복잡한 곡선
#
# 그래서 깊은 망은 더 복잡한 패턴(여러 번 꺾이는 관계)을 적은 뉴런으로 표현합니다.
# 이게 딥러닝이 '깊이(depth)' 를 택한 이유입니다. 넓게(뉴런 많이)보다
# 깊게(층 많이) 가 복잡한 함수를 더 효율적으로 담을 때가 많거든요.

# ----------------------------------------
# 대가 - 깊으면 생기는 문제 (다음 편 예고)
# ----------------------------------------

#   [깊게 쌓으면 공짜가 아니다 — 다음 편들에서 다룰 위험]
#     · 기울기 소실 : delta 를 뒤에서 앞으로 곱하며 전달하는데(PART 3),
#                     sigmoid 미분 a(1-a) 은 최대 0.25. 층을 많이 지나면
#                     0.25 를 계속 곱해 delta 가 0 에 수렴 → 앞 층이 안 배움.
#                     (해법: ReLU 활성화 — 다음 편)
#     · 과적합       : 표현력이 너무 세면 데이터를 '외워버려' 새 값에 약해짐.
#                     (해법: 정규화·드롭아웃 — 다음 편)
#
# 오늘 우리가 만든 '층 리스트 + for 순전파 + 거꾸로 for 역전파' 는
# 이 문제들을 다룰 다음 편들의 뼈대입니다. 활성화만 바꾸면 ReLU 망이 되고,
# 층만 늘리면 더 깊은 망이 돼요. 뼈대는 오늘 완성했습니다.


# ========================================================
#  PART 7 : 실습 - 층 구성을 바꿔 성능 비교
# ========================================================

# ----------------------------------------
# [실습] 뉴런 수·층 수를 바꿔 최종 손실 관찰
# ----------------------------------------

# 오늘 만든 fit / predict 를 그대로 써서, 층 구조만 바꿔 성능을 비교합니다.
# 구조 리스트만 갈아 끼우면 되니, 층·뉴런 실험이 한 줄로 끝나요.
#
#   Step 1) for 로 여러 구조를 돌려 가며 fit
#   Step 2) predict 로 예측 → 손실 계산
#   Step 3) 표로 나란히 비교, "깊게/넓게 하면 손실이 주는가?" 관찰
#
#   완료 기준 : 구조별 손실이 표로 나오고, 경향이 보이면 성공.

실험구조 = {
    "[1,4,1]  얕고 좁게": [1, 4, 1],
    "[1,12,1] 얕고 넓게": [1, 12, 1],
    "[1,6,6,1] 깊게(2층)": [1, 6, 6, 1],
    "[1,4,4,4,1] 더 깊게(3층)": [1, 4, 4, 4, 1],
}

print("\n[실습 · 층 구성별 손실 비교]")
print(f"  {'구조':24}{'최종손실':>10}")
for 설명, 구조 in 실험구조.items():
    m = fit(온도, 불량, 구조, lr=0.1, epochs=1500, seed=0)
    L = 손실(predict(온도, m).reshape(-1, 1), Y)
    print(f"  {설명:24}{L:10.4f}")
# → [실습 · 층 구성별 손실 비교]
# →   구조                       최종손실
# →   [1,4,1]  얕고 좁게            0.0108
# →   [1,12,1] 얕고 넓게           0.0030
# →   [1,6,6,1] 깊게(2층)          0.0085
# →   [1,4,4,4,1] 더 깊게(3층)     0.1200

# 얕고 좁은 [1,4,1] 은 뉴런이 부족해 U자를 겨우 흉내(0.011).
# 넓히거나(12뉴런) 깊게(6,6) 하면 다 잘 잡습니다(0.003~0.009).
# 그런데 3층 [1,4,4,4,1] 은 확 나빠졌죠(0.12) — 층이 깊어질수록 sigmoid 미분
# a(1-a)≤0.25 를 여러 번 곱하며 delta 가 죽는 '기울기 소실' 이 실제로 나타난 겁니다.
# '깊다고 무조건 좋은 게 아니다' 를 숫자로 본 거예요. 이 소실을 잡는 게 다음 편의
# ReLU 이고, 적절한 깊이·너비를 찾는 게 실무의 감각입니다.
#
#   [기억할 것]
#     · 층을 '리스트' 로 두면 은닉층이 몇 개든 코드가 안 바뀐다
#     · 순전파 = 층 리스트를 앞→뒤로 for 통과 (A@W+b, 활성화)
#     · 역전파 = delta 를 뒤→앞으로 for 전달
#          delta^(l) = (delta^(l+1) @ W^(l+1)ᵀ) ⊙ σ'(z^(l))
#          ∂L/∂W^(l) = A^(l-1)ᵀ @ delta^(l),   ∂L/∂b^(l) = Σ delta^(l)
#     · 층마다 '똑같은 패턴' 의 반복 = 역전파 편 연쇄법칙의 일반화
#     · 다층 전체 기울기가 수치미분과 일치 → 역전파 일반화가 맞다는 증거
#     · 깊으면 표현력↑ 이지만 기울기 소실·과적합 위험 → 다음 편 (ReLU·정규화)
