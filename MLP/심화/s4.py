# ----------------------------------------
# 심화 4편 마무리 - 오늘 손에 넣은 것
# ----------------------------------------

#   [MLP 실전 학습 도구 한 줄 정리]
#     미니배치   전체 대신 몇 개씩 → 딥러닝 학습의 사실상 표준
#     학습곡선   train vs val 을 에폭마다 → 두 곡선 벌어지면 과적합
#     조기 종료  val 최저에서 멈춤 → 잡음 외우기 전에 건짐
#     L2 정규화  L = 손실 + λΣw², 기울기에 +2λw → 큰 가중치 억제
#     드롭아웃   학습 때 뉴런 무작위로 끔 → 과의존 방지 (추론 땐 다 켬)
#
#   [기억할 것]
#     · 진짜 실력은 '안 본 val' 로 잰다. train 손실만 보고 좋아하지 마라
#     · train ≪ val (격차 큼) = 과적합 신호
#     · 정규화의 거래: train 을 조금 내주고 val(일반화)을 얻는다
#     · 이 미니배치·정규화가 실제 딥러닝 프레임워크의 batch_size,
#       weight_decay, dropout, early stopping 설정 그대로다
