# ========================================================
#  PART 4 : L2 정규화 - 큰 가중치에 벌점 (weight decay)
# ========================================================

# ----------------------------------------
# 수식 - L = 손실 + λΣw², 기울기에 +2λw
# ----------------------------------------

# 과정3 정규화 편에서 배운 걸 '신경망 버전' 으로 회수합니다.
# 과적합은 가중치가 커지면서 곡선이 미친 듯이 출렁일 때 생깁니다.
# 그러니 '가중치가 커지는 것 자체에 벌금' 을 물리면 됩니다.
#
#   손실에 벌점 항을 더한다:
#       L = 손실 + λ·Σw²          ← 가중치 제곱합에 비례한 벌금
#
#   λ(람다) = 벌점 세기. 크면 가중치를 더 세게 억누름.
#   Σw² = 모든 가중치를 제곱해 더한 값. w 가 크면 이 항이 커져 손실 ↑.
#
#   이 벌점을 미분하면 기울기에 한 항이 더 붙습니다:
#       ∂(λΣw²)/∂w = 2λw
#   즉 갱신할 때 원래 기울기에 '+2λw' 를 더하면 끝입니다.
#   w -= lr·(원래기울기 + 2λw)  →  매 스텝 w 를 조금씩 0 쪽으로 끌어당김.
#   그래서 이걸 'weight decay(가중치 감쇠)' 라고도 불러요.
#
# fit 안에서 이미 dW += 2λW, dV += 2λV 로 넣어 뒀습니다(위 PART 1 코드).
# λ 만 0 에서 키우면 정규화가 켜집니다.

# 정규화 세기 λ 를 바꿔 가며 train·val 격차가 어떻게 변하나 봅니다.
print("\n[L2 정규화 · λ 별 train/val (배치6, 1500에폭)]")
print(f"  {'λ':>7} | {'train':>8} | {'val':>8} | {'격차':>8}")
for lam in [0.0, 0.001, 0.002, 0.01]:
    _, tr, val = fit(X_tr, Y_tr, X_val, Y_val, lam=lam, 드롭율=0.0)
    print(f"  {lam:7.3f} | {tr[-1]:8.4f} | {val[-1]:8.4f} | {val[-1]-tr[-1]:8.4f}")
# → [L2 정규화 · λ 별 train/val (배치6, 1500에폭)]
# →       λ |    train |      val |     격차
# →   0.000 |   0.0252 |   0.0555 |   0.0302
# →   0.001 |   0.0214 |   0.0398 |   0.0184
# →   0.002 |   0.0198 |   0.0304 |   0.0106
# →   0.010 |   0.0486 |   0.0326 |  -0.0160

# λ 를 키울수록 val 격차가 확 줄어듭니다(0.0302→0.0106). λ=0.002 쯤이
# val 손실 자체도 최저(0.0304)로, 정규화 없음(0.0555) 대비 거의 절반이에요.
# 다만 너무 크면(0.01) 벌점이 세서 train 까지 나빠지죠(0.0486) — 과소적합
# 쪽으로 넘어간 겁니다. 적당한 λ 를 고르는 게 핵심.


# ========================================================
#  PART 5 : 드롭아웃 - 학습 때 뉴런 일부를 끈다
# ========================================================

# ----------------------------------------
# 개념 - 무작위로 꺼서 '과의존' 방지
# ----------------------------------------

# 드롭아웃(dropout)은 발상이 재밌습니다. 학습하는 동안 은닉 뉴런 일부를
# '무작위로 꺼' 버립니다(출력을 0으로). 매 스텝 켜지는 뉴런이 달라져요.
#
#   [드롭아웃 켬 · 학습 때]        [드롭아웃 끔 · 추론 때]
#     은닉1 ●                       은닉1 ●
#     은닉2 ✗ (이번엔 꺼짐)          은닉2 ●   ← 다 켬
#     은닉3 ●                       은닉3 ●
#     은닉4 ✗                       은닉4 ●
#
# 왜 이게 과적합을 줄이나?
#   특정 뉴런 몇 개에만 의존하면, 그 뉴런들이 학습 데이터를 통째로 외워
#   버립니다. 그런데 매번 무작위로 꺼지면 "누가 꺼질지 모르니" 어느 한
#   뉴런에 몰빵할 수 없어요. 뉴런들이 골고루, 견고하게 배우게 됩니다.
#
# 구현(마스크):
#   마스크 = (rand > 드롭율)        ← 드롭율 확률로 False(꺼짐), 나머지 True
#   A = A * 마스크 / (1 - 드롭율)   ← 켜진 것만 남기고, 꺼진 몫만큼 키워 보정
#   (÷(1-드롭율) 은 '역스케일링'. 학습 때 평균 출력 크기를 추론 때와 맞춰,
#    추론 땐 아무것도 안 하고 그냥 다 켜도 되게 만드는 관례입니다.)
#
# 핵심 규칙: 드롭아웃은 '학습 때만'. 추론(예측·손실 측정) 땐 뉴런을 다 켭니다.
# 위 fit 은 이미 이렇게 짜여 있어요 — 배치 학습 안에서만 마스크를 씌우고,
# 손실 기록은 순전파(마스크 없음)로 재니까요.

print("\n[드롭아웃 · 드롭율 별 train/val (배치6, 1500에폭)]")
print(f"  {'드롭율':>7} | {'train':>8} | {'val':>8} | {'격차':>8}")
for 드롭율 in [0.0, 0.1, 0.2, 0.3]:
    _, tr, val = fit(X_tr, Y_tr, X_val, Y_val, lam=0.0, 드롭율=드롭율)
    print(f"  {드롭율:7.1f} | {tr[-1]:8.4f} | {val[-1]:8.4f} | {val[-1]-tr[-1]:8.4f}")
# → [드롭아웃 · 드롭율 별 train/val (배치6, 1500에폭)]
# →     드롭율 |    train |      val |     격차
# →     0.0 |   0.0252 |   0.0555 |   0.0302
# →     0.1 |   0.0313 |   0.0218 |  -0.0094
# →     0.2 |   0.0340 |   0.0226 |  -0.0114
# →     0.3 |   0.0543 |   0.0419 |  -0.0124

# L2 와 비슷한 그림입니다. 드롭율을 켜면 train 은 조금 나빠지지만(외우기
# 어려워짐) val 이 확 내려가요(0.0555→0.0218). 0.1~0.2 쯤이 val 도 낮고
# 좋습니다. 너무 세게 끄면(0.3) 남은 뉴런이 적어 train 이 흔들리죠(0.0543).
# (데이터가 적을수록 드롭아웃은 출렁임이 커, L2 보다 값이 덜 매끄럽습니다.)


