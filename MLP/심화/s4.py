# →    500 |   0.0185 |   0.0330 |         0.0144
# →   1500 |   0.0252 |   0.0555 |         0.0302

# 격차 열이 오늘의 이야기입니다. 에폭 100쯤엔 val 이 train 만큼(오히려 더)
# 낮아 건강합니다 — val 손실 0.0328 로 여기가 사실상 최저예요. 그런데 그 뒤로
# train 은 계속 내려가는데(0.0479→0.0185→...) val 은 되레 올라 격차가
# 벌어집니다(0.0330→0.0555). 100 에폭 넘어서부터 '규칙'이 아니라 '잡음'을
# 외우기 시작한 거죠. 전형적인 과적합 진행입니다.


# ----------------------------------------
# 학습곡선 ASCII 그림 - 벌어지는 모양
# ----------------------------------------

# 위 숫자를 그림으로 새깁니다. 세로축이 손실, 가로축이 에폭이에요.
# train 은 쭉 내려가고, val 은 내려가다 U자로 다시 벌어집니다.
#
#   손실
#    ↑
#    |＼
#    | ＼＿ val   ＿＿＿＿＿＿／‾‾‾‾   ← 내려가다가 어느 지점부터 다시 ↗ (과적합)
#    |    ＼    ／
#    |     ＼＿／                     ← 이 '최저점' = 조기종료 하기 좋은 곳
#    |       ＼train ＿＿＿＿＿＿＿＿＿  ← train 은 끝까지 내려가기만 함
#    +-------------------------------→ 에폭
#         (건강)  ↑ 여기(약 100)부터 과적합
#
# 기억할 한 줄: "train 은 내려가는데 val 이 올라가기 시작하면, 거기서부터
# 모델이 규칙이 아니라 잡음을 외우기 시작한 것이다."
# val 이 최저인 그 순간이 일반화가 가장 좋은 순간이고,
# 그 순간에 멈추는 게 바로 다음의 조기 종료입니다.


# ========================================================
#  PART 3 : 조기 종료 - val 이 나빠지면 멈춘다
# ========================================================

# ----------------------------------------
# 개념 - val 최저점을 지나면 그만
# ----------------------------------------

# 학습곡선에서 봤듯, val 손실은 어느 지점에서 최저를 찍고 다시 오릅니다.
# 그 최저점 이후는 '과적합만 쌓이는' 구간이에요. 그러니 거기서 멈추면 됩니다.
# 이게 조기 종료(early stopping)입니다 — 아주 싸고 효과 좋은 과적합 처방.
#
# 구현 아이디어(간단판):
#   · 지금까지 본 val 손실 중 '최저값' 과 그때의 모델을 기억해 둔다.
#   · val 이 최저를 갱신하면 → 기록 갱신 + 그 모델을 저장.
#   · val 이 최저보다 나빠진 채로 'patience(참을성) 에폭' 이 지나면 → 멈춤.
#   · 최종적으로 '멈춘 시점' 이 아니라 '저장해 둔 최저 val 모델' 을 쓴다.

def fit_조기종료(X_tr, Y_tr, X_val, Y_val, 은닉수=24, lr=0.1,
                epochs=1500, 배치크기=6, patience=50, seed=0):
    np.random.seed(seed)
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))

    n = len(X_tr)
    최저val = float("inf")
    최고모델 = None
    최고에폭 = 0
    나빠진횟수 = 0
    for epoch in range(epochs):
        순서 = np.random.permutation(n)
        for 시작 in range(0, n, 배치크기):
            골라낸 = 순서[시작:시작 + 배치크기]
            Xb, Yb = X_tr[골라낸], Y_tr[골라낸]
            ŷ, A = 순전파(Xb, W, b, V, c)
            dW, db, dV, dc = 역전파(Xb, Yb, A, ŷ, V)
            W -= lr * dW;  b -= lr * db
            V -= lr * dV;  c -= lr * dc

        ŷ_val, _ = 순전파(X_val, W, b, V, c)
        현재val = 손실(ŷ_val, Y_val)
        if 현재val < 최저val:                     # 최저 갱신 → 저장
            최저val = 현재val
            최고모델 = (W.copy(), b.copy(), V.copy(), c.copy())
            최고에폭 = epoch + 1
            나빠진횟수 = 0
        else:                                     # 안 좋아짐 → 참을성 소진
            나빠진횟수 += 1
            if 나빠진횟수 >= patience:
                break                             # patience 넘으면 멈춤
    return 최고모델, 최저val, 최고에폭, epoch + 1


모델_es, 최저val, 멈춘_최저, 실제돈에폭 = fit_조기종료(X_tr, Y_tr, X_val, Y_val)
print("\n[조기 종료 · patience 50]")
print("  val 이 최저였던 에폭:", 멈춘_최저)          # → val 이 최저였던 에폭: 146
print("  그때 val 손실:", round(최저val, 4))          # → 그때 val 손실: 0.016
print("  실제로 돌다 멈춘 에폭:", 실제돈에폭)          # → 실제로 돌다 멈춘 에폭: 196
print("  (1500 에폭 끝까지 안 가고 일찍 멈췄고, 저장된 건 최저 val 모델)")

# 1500 에폭을 다 돌면 val 0.0555(PART 1)까지 나빠졌는데, 조기 종료는
# val 최저(에폭 146, 손실 0.016)에서 멈춰 그 모델을 건졌습니다.
# 끝까지 학습한 것보다 val 손실이 3배 넘게 낮죠 — 잡음을 외우기 전에 멈춘 겁니다.
