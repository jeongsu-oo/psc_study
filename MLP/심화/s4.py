"""[학습 데이터엔 잘 맞는데, 새 데이터엔 왜 엉망이죠?]
지금까지 우리는 MLP 를 '전체 데이터로 한 발씩' 걸어 학습시켰습니다.
그리고 손실이 쭉 내려가는 걸 보며 "잘 배웠다" 고 좋아했죠.

그런데 그건 '학습에 쓴 데이터' 로 잰 손실이었습니다.
진짜 실력은 '안 본 데이터' 에서 나옵니다. 학습 데이터만 달달 외운
모델은 새 측정값 앞에서 무너져요 — 이게 과적합(overfitting)입니다.
(과정3 분류·평가 4편에서 다항회귀로 이미 겪었죠. 오늘은 신경망 버전.)

이 파일은 MLP 를 '실전처럼' 학습시키는 도구들을 위에서 아래로 쌓습니다.
  1) 미니배치 학습   - 전체 대신 몇 개씩 (과정3 경사하강 변형 회수)
  2) 학습곡선        - train 손실 vs 검증(val) 손실을 에폭마다 기록·그림
  3) 조기 종료       - val 이 안 좋아지면 멈춤
  4) L2 정규화       - 큰 가중치에 벌점 (L = 손실 + λΣw²)
  5) 드롭아웃        - 학습 때 뉴런 일부를 무작위로 끔
  6) 실측 비교       - 정규화 없음 vs L2 vs 드롭아웃, train/val 격차 표
  7) 실습           - 배치크기·λ·드롭아웃율 바꿔 비교

밑바닥 넘파이로, 과적합이 '실제 숫자'로 줄어드는 걸 눈으로 봅니다.
"""

# 재현성을 위해 시드를 고정합니다. 데이터 생성·셔플·랜덤 초기화·드롭아웃
# 마스크가 매번 같아야 아래 '# →' 출력이 돌릴 때마다 똑같이 나옵니다.
import numpy as np
np.random.seed(42)


# ========================================================
#  준비 : 과적합이 나게 '적은' 데이터 + 은닉층 MLP
# ========================================================

# ----------------------------------------
# 데이터 - 적게, 잡음 섞어 (과적합이 나게)
# ----------------------------------------

# 과적합을 '보이게' 하려면 데이터가 적어야 합니다. 많으면 모델이 외울
# 틈이 없거든요. 그래서 제조 센서값을 36개만 만듭니다.
#
# 상황: 설비 온도(x)에 따른 미세 품질편차(y). 진짜 규칙은 완만한 곡선인데
# 측정에는 늘 잡음이 섞입니다. 모델이 이 '잡음까지 외우면' 과적합이에요.

n_data = 36
온도 = np.linspace(0, 10, n_data)                 # 온도 0~10
진짜곡선 = lambda t: 0.05 * (t - 5) ** 2 + 0.3    # 완만한 U자 (진짜 규칙)
잡음 = np.random.randn(n_data) * 0.15             # 시드 고정 잡음
y = 진짜곡선(온도) + 잡음                          # 관측된 품질편차

# train / val 분리 — 진짜 실력은 '안 본' val 로 잰다 (과정3 회수).
# 인덱스를 섞어 앞 24개는 학습, 뒤 12개는 검증으로 씁니다.
idx = np.random.permutation(n_data)
train_idx, val_idx = idx[:24], idx[24:]

# sigmoid 는 큰 입력에서 포화되므로 온도를 표준화합니다(4부작 회수).
# 표준화 기준(평균·표준편차)은 반드시 'train 만' 으로 잡습니다 —
# val 값을 미리 쓰면 그건 시험문제를 훔쳐보는 셈이니까요.
m, s = 온도[train_idx].mean(), 온도[train_idx].std()
X_all = ((온도 - m) / s).reshape(-1, 1)           # (36×1) 표준화 입력
Y_all = y.reshape(-1, 1)                          # (36×1)
X_tr, Y_tr = X_all[train_idx], Y_all[train_idx]   # (24×1)
X_val, Y_val = X_all[val_idx], Y_all[val_idx]     # (12×1)

print("[데이터 준비]")
print("  전체:", n_data, "개  ->  학습:", len(X_tr), "개 / 검증:", len(X_val), "개")
# → [데이터 준비]
# →   전체: 36 개  ->  학습: 24 개 / 검증: 12 개
print("  표준화 X_tr 앞 3개:", np.round(X_tr[:3].ravel(), 3))
# → 표준화 X_tr 앞 3개: [ 0.983  1.707 -1.604]


# ----------------------------------------
# MLP 부품 - 4부작에서 만든 것 그대로 회수
# ----------------------------------------

# 순전파·역전파·sigmoid 는 MLP 4부작(역전파 편)에서 손으로 만든 것과
# '똑같습니다'. 오늘은 이걸 새로 만드는 게 아니라, 이 위에 미니배치와
# 정규화라는 '실전 장치'를 얹는 겁니다. 부품 설명은 회수만 합니다.
#
#   망 구조 (입력 1 → 은닉 24 → 출력 1):
#     Z = X·W + b     (n×1)·(1×24) → (n×24)   은닉 입력
#     A = sigmoid(Z)                          은닉 출력 (휘어짐)
#     ŷ = A·V + c     (n×24)·(24×1) → (n×1)   최종 예측

def sigmoid(z):
    # clip: 표준화·랜덤 초기화 조합에서 z 가 아주 커지면 exp 가 넘칠 수
    # 있어, ±30 으로 잘라 둡니다. sigmoid 는 그 밖에선 어차피 0/1 이라 결과 동일.
    return 1 / (1 + np.exp(-np.clip(z, -30, 30)))

def 순전파(X, W, b, V, c):
    Z = X @ W + b
    A = sigmoid(Z)
    ŷ = A @ V + c
    return ŷ, A               # A 는 역전파에서 재사용

def 손실(ŷ, Y):
    return np.mean((ŷ - Y) ** 2)   # MSE = (1/n)Σ(ŷ-y)²


# ========================================================
#  PART 1 : 미니배치 학습 - MLP 도 전체 대신 배치씩
# ========================================================

# ----------------------------------------
# 회수 - 에폭 / 배치 / 셔플
# ----------------------------------------

# 과정3 경사하강 변형 편에서 배웠죠. 데이터가 크면 매 스텝 전체를 훑는 건
# 무겁습니다. 그래서 '한 번에 몇 개(배치)씩' 봅니다 = 미니배치.
# 신경망도 똑같아요. 사실 딥러닝 학습은 사실상 전부 미니배치입니다.
#
#   에폭(epoch) : 전체 데이터를 한 바퀴 다 도는 것
#   배치(batch) : 한 스텝에 보는 몇 개 (예: 6개)
#   셔플(shuffle): 매 에폭 순서를 섞음 — 같은 순서로만 보면 편향돼서
#
#   한 에폭의 스텝 수 = 데이터수 ÷ 배치크기.  24개 / 배치6 → 4 스텝.
#
# 역전파식은 4부작 그대로, 넘겨준 배치 개수만큼만 계산하면 됩니다.
# n 자리에 '이번 배치 크기' 가 들어갈 뿐이에요.

# L2 정규화 항(+2λw)은 이 함수가 아니라 아래 fit 의 갱신 직전에 dW, dV 에
# 더합니다 — 그래야 W, V 를 여기 안 넘겨도 되고 코드가 깔끔하거든요(PART 4).

def 역전파(Xb, Yb, A, ŷ, V):
    n = len(Xb)
    dŷ = 2 * (ŷ - Yb) / n          # (n×1) 출력 오차
    dV = A.T @ dŷ                  # (은닉×1)
    dc = dŷ.sum(axis=0, keepdims=True)
    dA = dŷ @ V.T                  # (n×은닉)
    dZ = dA * A * (1 - A)          # ⊙ sigmoid'=a(1-a)
    dW = Xb.T @ dZ                 # (1×은닉)
    db = dZ.sum(axis=0, keepdims=True)
    return dW, db, dV, dc


# ----------------------------------------
# 미니배치 fit - 학습곡선까지 함께 기록
# ----------------------------------------

# 학습 본체입니다. 하는 일은 경사하강 루프 그대로예요.
#   1) 가중치 랜덤 초기화 (시드 고정 → 재현성)
#   2) epochs 번 반복: 매 에폭 셔플 → 배치크기씩 잘라 순전파·역전파·갱신
#   3) 에폭 끝마다 train 손실과 val 손실을 둘 다 기록  ← 학습곡선의 재료
#
# 여기에 lam(L2), 드롭율(드롭아웃)까지 손잡이로 달아 둡니다. 기본값 0 이면
# 정규화가 꺼진 '맨 모델' 입니다. PART 4·5에서 이 손잡이를 켭니다.

def fit(X_tr, Y_tr, X_val, Y_val, 은닉수=24, lr=0.1, epochs=1500,
        배치크기=6, lam=0.0, 드롭율=0.0, seed=0):
    np.random.seed(seed)                         # 초기화·셔플·드롭 재현성
    W = np.random.randn(1, 은닉수) * 0.5          # (1×은닉) 입력→은닉
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5          # (은닉×1) 은닉→출력
    c = np.zeros((1, 1))

    n = len(X_tr)
    train_기록, val_기록 = [], []
    for epoch in range(epochs):
        순서 = np.random.permutation(n)          # 매 에폭 셔플
        for 시작 in range(0, n, 배치크기):        # 배치크기씩 잘라
            골라낸 = 순서[시작:시작 + 배치크기]
            Xb, Yb = X_tr[골라낸], Y_tr[골라낸]

            Z = Xb @ W + b
            A = sigmoid(Z)
            # 드롭아웃: 학습 때만, 은닉 출력 일부를 무작위로 0으로 (PART 5)
            if 드롭율 > 0:
                마스크 = (np.random.rand(*A.shape) > 드롭율) / (1 - 드롭율)
                A = A * 마스크
            ŷ = A @ V + c

            dW, db, dV, dc = 역전파(Xb, Yb, A, ŷ, V)
            # L2 정규화: 손실에 λΣw² 를 더한 효과 = 기울기에 +2λw (PART 4)
            dW += 2 * lam * W
            dV += 2 * lam * V

            W -= lr * dW;  b -= lr * db           # 한 스텝 갱신
            V -= lr * dV;  c -= lr * dc

        # 에폭 끝: 전체 train·val 손실 기록 (추론이므로 드롭아웃 끔 → A 그대로)
        ŷ_tr, _ = 순전파(X_tr, W, b, V, c)
        ŷ_val, _ = 순전파(X_val, W, b, V, c)
        train_기록.append(손실(ŷ_tr, Y_tr))
        val_기록.append(손실(ŷ_val, Y_val))

    모델 = (W, b, V, c)
    return 모델, train_기록, val_기록


모델0, tr0, val0 = fit(X_tr, Y_tr, X_val, Y_val, lam=0.0, 드롭율=0.0)
print("\n[미니배치 학습 · 배치크기 6 · 1500 에폭 · 정규화 없음]")
print("  에폭당 스텝 수 =", len(X_tr), "÷ 6 =", len(X_tr) // 6)   # → 에폭당 스텝 수 = 24 ÷ 6 = 4
print("  최종 train 손실:", round(tr0[-1], 4))    # → 최종 train 손실: 0.0252
print("  최종 val   손실:", round(val0[-1], 4))   # → 최종 val   손실: 0.0555

# train 손실은 낮은데(0.0252) val 손실은 그 두 배가 넘습니다(0.0555).
# 이 '격차' 가 바로 과적합 신호예요. 학습 점은 잘 맞추는데 안 본 점엔 약한 거죠.


# ========================================================
#  PART 2 : 학습곡선 - train vs val 을 에폭마다 그림
# ========================================================

# ----------------------------------------
# 두 곡선이 벌어지면 과적합 신호
# ----------------------------------------

# 과적합을 '한 시점'이 아니라 '학습 내내' 지켜보는 도구가 학습곡선입니다.
# 에폭마다 train 손실과 val 손실을 둘 다 찍어 나란히 그려요.
#
#   · train 손실 : 계속 내려감 (모델이 학습 점을 점점 잘 외움)
#   · val   손실 : 처음엔 같이 내려가다가, 어느 순간부터 다시 '올라감'
#     ← 이 갈라지는 지점이 "이제부터 외우기 시작했다" 는 과적합 시작점
#
# 몇 에폭만 찍어 숫자로 먼저 봅니다. 이미 위에서 tr0, val0 를 받아 뒀어요.

찍을에폭 = [1, 5, 20, 100, 500, 1500]
print("\n[학습곡선 · 에폭별 손실]")
print(f"  {'에폭':>4} | {'train':>8} | {'val':>8} | {'격차(val-train)':>14}")
for e in 찍을에폭:
    i = e - 1
    print(f"  {e:4d} | {tr0[i]:8.4f} | {val0[i]:8.4f} | {val0[i]-tr0[i]:14.4f}")
# → [학습곡선 · 에폭별 손실]
