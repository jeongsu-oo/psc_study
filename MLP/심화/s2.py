# -------------------------------
# 다중 분류 - softmax 로 여러 등급을 가른다 (과정4 심화 2편)
# -------------------------------


"""[양품이냐 불량이냐 둘 중 하나가 아니라, 등급이 셋이면 어떻게 하나요?]
심화 1편에서 우리 MLP 는 '양품이냐 불량이냐' 를 갈랐습니다. 둘 중 하나, 이진 분류였죠.
출력 뉴런 하나에 sigmoid 를 씌워 '불량일 확률(0~1)' 하나만 뽑고 0.5 로 갈랐어요.

그런데 현장 판정이 늘 둘로만 갈리지는 않습니다.
  "이 제품, 양품이야? 경미 불량이야? 심각 불량이야?"
셋(혹은 그 이상) 중 하나로 판정해야 할 때가 많아요. 이게 다중 분류입니다.

오늘 손에 넣을 부품은 딱 세 개, 그리고 놀라운 결말 하나입니다.
  ① softmax    : 여러 점수를 '합이 1인 확률분포' 로 바꾼다 (sigmoid 의 여러 개 버전)
  ② 원-핫      : 정답 '2' 를 [0,0,1] 처럼 클래스 수만큼의 자리로 편다 (과정2 인코딩 회수)
  ③ 교차엔트로피: 다중 분류의 손실 (BCE 의 여러 개 버전)
  ④ 놀라운 결말 : softmax+교차엔트로피의 출력 기울기 = p - y. 이진의 (p-y) 그대로!

이진에서 배운 게 하나도 안 버려집니다. 전부 '여러 개로 편' 것뿐이에요.
이 파일은 전환 → softmax → 원-핫 → 교차엔트로피 → 기울기 p-y →
MLP 3클래스 학습(정확도·혼동행렬) → sklearn 대조 → 실습 순으로 쌓습니다.
"""

# 이진 편처럼 가중치를 '행렬' 로 다룹니다. numpy 가 주인공이에요.
import numpy as np


# ========================================================
#  PART 1 : 전환 - 출력이 '하나' 에서 '클래스 수만큼' 으로
# ========================================================

# ----------------------------------------
# 이진과 다중, 무엇이 바뀌나
# ----------------------------------------

# 이진(1편)     :  출력 뉴런 1개 → sigmoid → '불량일 확률' 하나 → 0.5 로 판정
# 다중(오늘)    :  출력 뉴런 K개 → softmax → K개 확률(합=1) → 가장 큰 게 예측 클래스
#
# 즉 달라지는 건 '출력층의 너비' 와 '마지막 변환' 뿐입니다.
#   · 3등급이면 출력 뉴런이 3개. 각 뉴런은 그 클래스의 '점수(로짓)' 를 냅니다.
#   · 그 세 점수를 softmax 로 '합이 1인 확률' 로 바꿔요. 예: [0.1, 0.7, 0.2]
#   · 가장 큰 확률의 자리(위 예에선 1번)가 예측 클래스입니다. (argmax)
#
#        입력           은닉(sigmoid)          출력 3개 → softmax
#      온도·압력  →   ○ ○ ○ ○ ○ ○   →   [점수0 점수1 점수2] → [p0 p1 p2] 합=1
#                                                                  ↑ 가장 큰 자리가 예측
#
# 은닉층·역전파의 뼈대는 1편과 똑같습니다. 출력 하나를 셋으로 넓혔을 뿐이에요.

def sigmoid(z):
    return 1 / (1 + np.exp(-z))   # 0~1 S자. 은닉층의 '휘는 부품' (1편 그대로)


# ----------------------------------------
# 제조 3등급 품질 데이터 - 온도·압력으로 3클래스
# ----------------------------------------

# 온도와 압력, 두 특징으로 품질 등급을 셋으로 가릅니다.
#   0 = 양품        (온도 낮고 압력 적당)
#   1 = 경미 불량   (온도 중간)
#   2 = 심각 불량   (온도 높음)
# 클래스마다 중심 구간이 다르되, 경계는 살짝 겹칩니다 — 현실 데이터가 원래 그래요.
# 외부 파일 없이 인라인으로 만듭니다. 시드 고정(재현성).

np.random.seed(0)

def _make_class(n, 온도중심, 압력중심):
    온도 = np.random.randn(n) * 2.2 + 온도중심     # 중심 주위로 퍼진 온도
    압력 = np.random.randn(n) * 1.5 + 압력중심     # 중심 주위로 퍼진 압력
    return np.column_stack([온도, 압력])

X0 = _make_class(40, 온도중심=22, 압력중심=5)   # 양품:      저온
X1 = _make_class(40, 온도중심=30, 압력중심=6)   # 경미 불량: 중온
X2 = _make_class(40, 온도중심=38, 압력중심=7)   # 심각 불량: 고온
X_raw = np.vstack([X0, X1, X2])                 # (120×2)  온도·압력
y = np.array([0]*40 + [1]*40 + [2]*40)          # (120,)   정답 등급 0/1/2

#   압력
#     |        ● ● ●              ▲ ▲ ▲     ● = 양품(0)  저온
#     |     ● ● ● ●  ■ ■ ■ ■   ▲ ▲ ▲ ▲    ■ = 경미(1)  중온
#     |   ● ● ●    ■ ■ ■ ■ ■   ▲ ▲ ▲      ▲ = 심각(2)  고온
#     +----------------------------------→ 온도
#      저온(22)      중온(30)      고온(38)
#
# 온도가 오를수록 0 → 1 → 2 로 등급이 나빠지는 흐름. 경계는 겹칩니다.

K = 3   # 클래스 수 (양품/경미/심각). 이 값만 바꾸면 4등급, 5등급도 됨


# ----------------------------------------
# 표준화 - 1편과 같은 이유로 필수
# ----------------------------------------

# 온도(20~40)와 압력(5~7)은 스케일이 제각각입니다. 그대로 넣으면
# 온도가 압력을 압도하고, sigmoid 도 포화돼 학습이 죽어요.
# 그래서 각 열(특징)을 '평균 0, 퍼짐 1' 로 눈금 맞춥니다. (과정2·3·1편 회수)

특징평균 = X_raw.mean(axis=0)          # 열별(특징별) 평균 [온도평균, 압력평균]
특징표준 = X_raw.std(axis=0)           # 열별 표준편차
X = (X_raw - 특징평균) / 특징표준       # (120×2) 표준화 완료

print("[데이터 준비]")
print("  전체 shape:", X.shape, " 클래스 수:", K)   # → 전체 shape: (120, 2)  클래스 수: 3
print("  클래스별 개수:", [int(np.sum(y == k)) for k in range(K)])  # → 클래스별 개수: [40, 40, 40]


# ========================================================
#  PART 2 : softmax - 여러 점수를 '합이 1인 확률' 로
# ========================================================

# ----------------------------------------
# sigmoid 의 여러 개 버전
# ----------------------------------------

# 이진에선 sigmoid 로 점수 하나를 '불량일 확률' 하나로 눌렀죠.
# 다중에선 점수가 K개(클래스마다 하나)입니다. 이걸 한꺼번에 '합이 1인 확률' 로
# 바꿔 주는 게 softmax 예요.
#
#   수식 :  p_k = e^(z_k) / Σ_j e^(z_j)
#
#   · 분자 e^(z_k) : 각 점수를 지수로 키운다 (큰 점수는 더 크게 벌어짐)
#   · 분모 Σ_j e^(z_j) : 그 지수들의 총합으로 나눈다 → 전부 더하면 정확히 1
#
# 그래서 결과는 '확률분포' 가 됩니다. 예: 점수 [1, 3, 0] → 확률 [0.11, 0.84, 0.05], 합=1.
# 가장 큰 점수의 자리가 가장 큰 확률을 갖고, 그 자리가 곧 예측 클래스입니다.
#
#   점수 z      softmax         확률 p (합=1)
#   [1,3,0]  ─────────────→  [0.11, 0.84, 0.05]
#                                    ↑ 가장 큼 = 1번 클래스로 예측

def softmax(Z):
    # 오버플로 방지: 각 행의 최댓값을 빼도 결과는 같다 (분자·분모에서 상쇄됨).
    # 안 빼면 e^(큰 점수) 가 무한대로 터질 수 있어요. 이 한 줄이 안전장치입니다.
    Z = Z - Z.max(axis=1, keepdims=True)          # 행별 최댓값 빼기 (핵심 한 줄)
    exp = np.exp(Z)                               # e^(z_k)
    return exp / exp.sum(axis=1, keepdims=True)   # Σ_j e^(z_j) 로 나눔 → 합=1

# 정말 합이 1인지, 큰 점수가 큰 확률이 되는지 눈으로 봅시다.
예시점수 = np.array([[1.0, 3.0, 0.0]])
예시확률 = softmax(예시점수)
print("\n[softmax 맛보기]")
print("  점수:", 예시점수[0].tolist())                        # → 점수: [1.0, 3.0, 0.0]
print("  확률:", np.round(예시확률[0], 3).tolist())            # → 확률: [0.114, 0.844, 0.042]
print("  확률 합:", round(float(예시확률.sum()), 6))            # → 확률 합: 1.0

# 점수 3.0 이 가장 커서 확률 0.844 로 몰렸고, 셋을 더하면 정확히 1.
# 오버플로 방지도 확인 — 아주 큰 점수를 넣어도 안 터집니다.
print("  큰 점수[1000, 1001, 999] 확률:", np.round(softmax(np.array([[1000., 1001., 999.]]))[0], 3).tolist())
# → 큰 점수[1000, 1001, 999] 확률: [0.245, 0.665, 0.09]


# ========================================================
#  PART 3 : 원-핫 인코딩 - 정답을 클래스 수만큼의 자리로 편다
# ========================================================

# ----------------------------------------
# 정답 '2' 를 [0, 0, 1] 로
# ----------------------------------------

# 예측은 K개 확률로 나오는데, 정답은 '2' 같은 숫자 하나입니다. 짝이 안 맞죠.
# 그래서 정답도 K개 자리로 폅니다 — 정답 클래스 자리만 1, 나머지는 0.
# 이걸 원-핫 인코딩이라 합니다. (과정2 범주형 인코딩에서 배운 그것, 회수)
#
#   정답 0  →  [1, 0, 0]
#   정답 1  →  [0, 1, 0]
#   정답 2  →  [0, 0, 1]
#
# 이러면 예측확률 [0.1, 0.7, 0.2] 와 정답 [0, 1, 0] 이 같은 모양(K개)이 되어
# 자리끼리 바로 비교·계산할 수 있습니다.

def 원핫(y, K):
    Y = np.zeros((len(y), K))     # (n×K) 전부 0으로
    Y[np.arange(len(y)), y] = 1   # 각 행에서 정답 클래스 자리만 1
    return Y

Y = 원핫(y, K)   # (120×3) 정답을 원-핫으로
print("\n[원-핫 인코딩]")
print("  정답 라벨 앞 3개:", y[:3].tolist())          # → 정답 라벨 앞 3개: [0, 0, 0]
print("  원-핫 앞 3개:\n", Y[:3].astype(int))
# → 원-핫 앞 3개:
# →  [[1 0 0]
# →  [1 0 0]
# →  [1 0 0]]
print("  경계에서 하나(60번, 클래스", y[60], "):", Y[60].astype(int).tolist())  # → 경계에서 하나(60번, 클래스 1 ): [0, 1, 0]


# ========================================================
#  PART 4 : 교차엔트로피 손실 - BCE 의 여러 개 버전
# ========================================================

# ----------------------------------------
# 정답 클래스 확률의 -log
# ----------------------------------------

# 이진에서 BCE(로그손실)를 썼죠. 다중에선 그 일반화인 교차엔트로피를 씁니다.
#
#   수식 :  L = -Σ_k y_k · log(p_k)
#
# 정답 y 는 원-핫이라 정답 클래스 자리만 1, 나머지는 0. 그래서 합 Σ_k 에서
# 0인 항은 다 사라지고, 딱 '정답 클래스의 확률에 -log' 만 남습니다.
#
#   정답이 2번인데 p = [0.1, 0.2, 0.7] 이면  →  L = -log(0.7) = 0.357  (잘 맞힘, 손실 작음)
#   정답이 2번인데 p = [0.6, 0.3, 0.1] 이면  →  L = -log(0.1) = 2.303  (틀림, 손실 큼)
#
# 즉 '정답 클래스에 확률을 얼마나 몰아줬나' 를 재는 자예요.
# 정답에 확률을 크게 주면 손실↓, 엉뚱한 데 주면 손실↑. BCE 와 성격이 똑같습니다.

def 교차엔트로피(P, Y):
    eps = 1e-9   # log(0) = -무한대 방지용 아주 작은 값
    return -np.mean(np.sum(Y * np.log(P + eps), axis=1))
    # 행마다 Σ_k y_k·log(p_k) 구하고(정답 자리만 남음), 그 -평균

# 숫자로 확인: 정답에 확률을 몰아줄수록 손실이 작아지는지.
정답원핫 = np.array([[0.0, 0.0, 1.0]])   # 정답은 2번
print("\n[교차엔트로피 맛보기 · 정답은 2번]")
for p2 in [0.7, 0.4, 0.1]:
    나머지 = (1 - p2) / 2
    P = np.array([[나머지, 나머지, p2]])
    print(f"  정답확률 p2={p2} → 손실 {교차엔트로피(P, 정답원핫):.4f}")
# → [교차엔트로피 맛보기 · 정답은 2번]
# →   정답확률 p2=0.7 → 손실 0.3567
# →   정답확률 p2=0.4 → 손실 0.9163
# →   정답확률 p2=0.1 → 손실 2.3026

# 정답 클래스에 0.7 을 주면 손실 0.36, 0.1 밖에 안 주면 2.30 으로 폭증.
# BCE 때 봤던 '확신 틀림을 크게 벌한다' 가 클래스 여러 개로 그대로 확장된 겁니다.


# ========================================================
#  PART 5 : 놀라운 단순함 - 출력 기울기가 그냥 p - y
# ========================================================

# ----------------------------------------
# 이진 (p-y) 의 일반화
# ----------------------------------------

# 여기가 오늘의 하이라이트입니다. softmax 와 교차엔트로피를 짝지으면
# 그 미분(출력층 기울기)이 거짓말처럼 깔끔해집니다.
#
#   ∂L/∂z = p - y        ← p 는 softmax 확률(K개), y 는 원-핫 정답(K개)
#
# 1편 이진에선 출력 오차가 (p - y) 였죠(sigmoid+BCE). 다중도 똑같습니다 —
# 단지 p 와 y 가 '스칼라 하나' 에서 'K개 벡터' 로 넓어졌을 뿐이에요.
# (유도는 생략, 결과만 씁니다. softmax 미분과 log 미분이 서로 상쇄돼 이렇게 됩니다.)
#
#   이진(1편)  :  출력 오차 = p - y        (숫자 하나)
#   다중(오늘)  :  출력 오차 = p - y        (K개 벡터)   ← 똑같은 얼굴!
#
# 이게 뭘 뜻하냐면 — 이 한 줄(dlogit = p - y)만 넣으면, 그 뒤 역전파
# (dV, dc, dA, dZ, dW, db)는 1편과 완전히 똑같이 흘러갑니다. 아무것도 새로 안 배워요.
#
#   ∂L/∂Z_out = (P - Y)/n              출력 오차 (n×K)              … dlogit
#   ∂L/∂V = Aᵀ · dlogit                                            … dV   (은닉×K)
#   ∂L/∂c = Σ dlogit                                               … dc   (1×K)
#   ∂L/∂A = dlogit · Vᵀ                                            … dA
#   ∂L/∂Z = dA ⊙ A(1-A)        sigmoid 미분 = a(1-a) (1편 그대로)   … dZ
#   ∂L/∂W = Xᵀ · dZ                                                … dW
#   ∂L/∂b = Σ dZ                                                   … db


# ----------------------------------------
# 순전파 - 마지막에 softmax
# ----------------------------------------

# 1편 순전파(A=σ(XW+b), 출력=AV+c)에서 마지막 한 줄만 바뀝니다.
# 출력을 sigmoid 하나가 아니라 softmax 로 눌러 'K개 확률' 을 만들어요.
# 그리고 V·c 의 너비가 1 → K 로 넓어진 것뿐입니다.

def 순전파(X, W, b, V, c):
    A = sigmoid(X @ W + b)   # (n×은닉)  은닉층 출력 (휘어짐, 1편 그대로)
    P = softmax(A @ V + c)   # (n×K)     최종 K개 확률(합=1)  ← 여기가 이진과 다른 점
    return P, A              # A 는 역전파에서 재사용


# ----------------------------------------
# 역전파 - dlogit = p - y 만 넣으면 1편과 동일
# ----------------------------------------

def 역전파(X, Y, A, P, W, b, V, c):
    n = len(X)
    dlogit = (P - Y) / n           # (n×K)  ← 이진의 (p-y) 그대로, 벡터로만 넓어짐
    dV = A.T @ dlogit              # (은닉×K)
    dc = dlogit.sum(axis=0, keepdims=True)      # (1×K)
    dA = dlogit @ V.T              # (n×은닉)
    dZ = dA * A * (1 - A)          # (n×은닉)  ⊙ sigmoid'=a(1-a) (1편 그대로)
    dW = X.T @ dZ                  # (특징×은닉)
    db = dZ.sum(axis=0, keepdims=True)          # (1×은닉)
    return dW, db, dV, dc


# ========================================================
#  PART 6 : MLP 로 3클래스 학습 - 정확도·혼동행렬
# ========================================================

# ----------------------------------------
# fit - 경사하강 루프 (1편과 판박이, 출력만 K개)
# ----------------------------------------

# 학습 본체는 1편과 똑같습니다. 랜덤 초기화 → epochs 번 (순전파→역전파→갱신).
# 딱 달라진 것: 출력 가중치 V·c 의 너비가 1 → K, 손실이 교차엔트로피.

def fit(X, y, K, 은닉수=8, lr=0.5, epochs=3000, 로그=False):
    n, 특징수 = X.shape
    Y = 원핫(y, K)                        # 정답을 원-핫으로 (n×K)

    np.random.seed(0)                     # 시드 고정 → 재현성 (출력 매번 동일)
    W = np.random.randn(특징수, 은닉수) * 0.5   # (특징×은닉)
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, K) * 0.5        # (은닉×K)   ← 출력이 K개
    c = np.zeros((1, K))

    for epoch in range(epochs):
        P, A = 순전파(X, W, b, V, c)                    # K개 확률 예측 한 번
        dW, db, dV, dc = 역전파(X, Y, A, P, W, b, V, c)  # 기울기 되짚기 (dlogit=P-Y)
        W -= lr * dW                                    # ← 갱신 (한 스텝)
        b -= lr * db
        V -= lr * dV
        c -= lr * dc
        if 로그 and epoch % 600 == 0:
            손실 = 교차엔트로피(순전파(X, W, b, V, c)[0], Y)
            print(f"  epoch {epoch:5d}   교차엔트로피 {손실:.4f}")

    if 로그:
        손실 = 교차엔트로피(순전파(X, W, b, V, c)[0], Y)
        print(f"  epoch {epochs:5d}   교차엔트로피 {손실:.4f}")
    return (W, b, V, c)


# ----------------------------------------
# predict - 확률과 argmax 판정
# ----------------------------------------

# 이진은 0.5 로 갈랐죠. 다중은 K개 확률 중 '가장 큰 자리' 가 예측 클래스입니다(argmax).

def 예측확률(X, 모델):
    P, _ = 순전파(X, *모델)
    return P                                  # (n×K) 각 클래스 확률

def 예측(X, 모델):
    return 예측확률(X, 모델).argmax(axis=1)    # 가장 큰 확률의 자리 = 예측 클래스

def 정확도(X, y, 모델):
    return np.mean(예측(X, 모델) == y)


