#     · 이진 → 다중 : 출력 K개 + softmax(합=1) + 원핫 정답 + 교차엔트로피
#     · softmax : p_k = e^(z_k)/Σe^(z_j). 오버플로는 max 빼기 한 줄로 방지
#     · 교차엔트로피 L = -Σ y·log p 는 '정답 클래스 확률의 -log' — BCE 의 일반화
