# 이진의 혼동행렬은 2×2 였죠. 클래스가 셋이면 3×3 이 됩니다.
# 행 = 실제 클래스, 열 = 예측 클래스. 대각선이 정답, 대각선 밖이 오분류입니다.

def 혼동행렬(y_true, y_pred, K):
    M = np.zeros((K, K), dtype=int)
    for t, p in zip(y_true, y_pred):
        M[t, p] += 1          # 실제 t 를 p 로 예측한 횟수
    return M

