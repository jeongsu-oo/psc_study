"""[뉴런 하나로 뭘 할 수 있나요?]
앞서 MLP 편에서 뉴런을 '층으로 쌓은' 신경망을 배웠습니다.
그런데 애초에 왜 층을 쌓아야 했을까요? 뉴런 하나로는 안 됐을까요?

이 파일은 그 뿌리로 거슬러 올라갑니다.
신경망의 가장 단순한 조상 = '퍼셉트론(perceptron)' = 뉴런 딱 하나.
1958년에 나온 이 뉴런 한 개짜리 기계가 무엇을 할 수 있고,
무엇을 '못 하는지' 를 직접 학습시켜 눈으로 봅니다.

바로 그 '못 하는 것' 에서 "그래서 층을 쌓아야 했다" 는
MLP 의 존재 이유가 튀어나옵니다. 위에서 아래로 갑니다.
"""

# 퍼셉트론은 곱하고 더하고 크기 비교하는 게 전부라 순수 파이썬으로 짭니다.
# 외부 파일도, numpy 도 안 씁니다. 데이터도 코드 안에 직접 적어 둡니다.
import random


# ========================================================
#  PART 1 : 퍼셉트론 = 뉴런 하나
# ========================================================

# ----------------------------------------
# 뉴런 하나가 하는 일
# ----------------------------------------

# 퍼셉트론은 입력 몇 개를 받아 0 또는 1, 딱 한 가지를 답하는 기계입니다.
# 하는 일은 두 단계뿐이에요.
#   1단계 가중합 : 입력마다 가중치를 곱해 다 더하고, 편향을 하나 더한다
#                  z = w1·x1 + w2·x2 + b
#   2단계 계단 활성화 : 그 z 가 0 이상이면 1, 아니면 0 을 뱉는다
#                  출력 = 1 (z ≥ 0),  0 (z < 0)
#
#            w1
#   x1 ●────╲
#            ╲
#             ●──  z = w1·x1 + w2·x2 + b  ──[ 계단 ]──  0 또는 1
#            ╱          (가중합)              (활성화)
#   x2 ●────╱
#            w2          ↑
#                        b (편향, 입력 없이 늘 더해지는 값)
#
# MLP 편의 뉴런과 거의 같죠? 1단계 가중합은 똑같습니다(z = W·x + b).
# 다른 건 2단계 활성화뿐이에요. MLP 에선 S자로 눌러 주는 시그모이드였지만,
# 퍼셉트론은 그냥 '0 이상이냐 아니냐' 로 뚝 잘라 0/1 을 내는 '계단' 입니다.

def 계단(z):
    # 계단 활성화 : 문턱(0)을 넘으면 1, 못 넘으면 0. S자가 아니라 딱 끊김.
    return 1 if z >= 0 else 0

print("[계단 활성화 - 0 에서 뚝 끊긴다]")
print("  계단(-2.0) =", 계단(-2.0))   # → 계단(-2.0) = 0
print("  계단( 0.0) =", 계단(0.0))    # → 계단( 0.0) = 1
print("  계단( 1.5) =", 계단(1.5))    # → 계단( 1.5) = 1

# 시그모이드가 0~1 사이를 부드럽게 오갔다면, 계단은 0 아니면 1, 중간이 없습니다.
# 퍼셉트론은 이 '예/아니오' 를 답하는 아주 단호한 뉴런입니다.


# ----------------------------------------
# 예측하기 - 가중합 + 계단
# ----------------------------------------

# 입력 x(값 두 개), 가중치 w(값 두 개), 편향 b 를 받아
# 위 그림 그대로 z 를 구하고 계단에 통과시켜 0/1 을 돌려줍니다.

def 예측(x, w, b):
    z = w[0] * x[0] + w[1] * x[1] + b     # 1단계 가중합
    return 계단(z)                         # 2단계 계단 활성화

# 가중치를 아무 값이나 손으로 잡아 한 번 굴려 봅니다 (아직 학습 전, 예시값).
w예시 = [0.5, 0.5]
b예시 = -0.7
print("\n[예측 맛보기 · w=[0.5, 0.5], b=-0.7]")
print("  입력 [1, 1] →", 예측([1, 1], w예시, b예시))   # → 입력 [1, 1] → 1
print("  입력 [1, 0] →", 예측([1, 0], w예시, b예시))   # → 입력 [1, 0] → 0
print("  입력 [0, 0] →", 예측([0, 0], w예시, b예시))   # → 입력 [0, 0] → 0

# [1,1] 은 0.5+0.5-0.7 = 0.3 ≥ 0 이라 1,
# [1,0] 은 0.5-0.7 = -0.2 < 0 이라 0.
# 가중치와 편향을 어떻게 잡느냐에 따라 답이 갈립니다.
# 그럼 이 w, b 를 '사람이 손으로 맞추지 않고' 데이터로 찾게 하는 게 학습입니다.


# ========================================================
#  PART 2 : 퍼셉트론 학습 규칙 - 틀리면 정답 쪽으로 민다
# ========================================================

# ----------------------------------------
# 학습 규칙의 직관
# ----------------------------------------

# 학습이란 결국 '틀린 만큼 고치기' 입니다. 규칙은 놀랄 만큼 단순해요.
#
#   예측이 맞았으면  → 아무것도 안 한다 (건드릴 이유가 없음)
#   예측이 틀렸으면  → 가중치를 정답 쪽으로 '조금' 민다
#
# 식으로는 이렇습니다 (오차 = 정답 - 예측):
#   w ← w + lr · (정답 - 예측) · x
#   b ← b + lr · (정답 - 예측)
#
# 여기서 lr(learning rate, 학습률)은 '한 번에 얼마나 밀지' 를 정하는 보폭입니다.
#
# 오차가 이 규칙의 핵심이에요. 셋 중 하나입니다.
#   정답 1, 예측 0 → 오차 +1 → w 를 x 쪽으로 키운다 (z 를 올려 1 이 나오게)
#   정답 0, 예측 1 → 오차 -1 → w 를 x 쪽으로 줄인다 (z 를 내려 0 이 나오게)
#   정답 = 예측    → 오차  0 → 아무 변화 없음 (곱하면 0 이라 그대로)
#
# 방향(+1/-1)과 크기(입력 x)를 오차 하나가 동시에 정해 줍니다.
# 이 규칙을 데이터 위로 여러 번 돌리면 w, b 가 점점 정답에 맞게 자리를 잡아요.


# ----------------------------------------
# 학습 함수 - 규칙을 여러 번 반복
# ----------------------------------------

# 전체 데이터를 한 바퀴 도는 것을 1 에폭(epoch)이라 부릅니다.
# 에폭을 여러 번 돌리며, 각 데이터마다 위 규칙으로 w, b 를 조금씩 밉니다.

def 학습(X, Y, lr=0.1, 에폭=20, seed=0):
    random.seed(seed)                         # 시드 고정 - 매번 같은 결과
    w = [random.uniform(-1, 1), random.uniform(-1, 1)]  # 가중치 무작위 시작
    b = random.uniform(-1, 1)                  # 편향도 무작위 시작
    for _ in range(에폭):
        for x, 정답 in zip(X, Y):
            예측값 = 예측(x, w, b)
            오차 = 정답 - 예측값               # +1, -1, 또는 0
            w[0] += lr * 오차 * x[0]           # 틀린 만큼, x 쪽으로 민다
            w[1] += lr * 오차 * x[1]
            b += lr * 오차                     # 편향은 입력 없이 오차만큼
    return w, b

# 채점 도우미 : 학습된 w, b 로 네 입력을 다 맞히는지 세어 준다.
def 채점(X, Y, w, b):
    예측들 = [예측(x, w, b) for x in X]
    맞은수 = sum(p == t for p, t in zip(예측들, Y))
    return 예측들, 맞은수


# ========================================================
#  PART 3 : AND 게이트 학습 - 직선 하나로 가른다
# ========================================================

# ----------------------------------------
# 논리 게이트 데이터 (고전 문제)
# ----------------------------------------

# 퍼셉트론의 실력을 재는 고전 시험지가 '논리 게이트' 입니다.
# 입력 두 개(각각 0 또는 1)를 받아 정해진 규칙대로 0/1 을 내는 문제죠.
#
#   AND : 둘 다 1 일 때만 1        (그리고)
#   OR  : 하나라도 1 이면 1        (또는)
#   XOR : 둘이 서로 다를 때만 1    (같으면 0, 다르면 1)

입력 = [[0, 0], [0, 1], [1, 0], [1, 1]]   # 네 가지 입력 조합
AND = [0, 0, 0, 1]     # 둘 다 1 일 때만 1
OR  = [0, 1, 1, 1]     # 하나라도 1 이면 1
XOR = [0, 1, 1, 0]     # 서로 다를 때만 1


# ----------------------------------------
# AND 를 학습시켜 본다
# ----------------------------------------

# 퍼셉트론에게 AND 정답을 주고 학습 규칙으로 w, b 를 스스로 찾게 합니다.

w_and, b_and = 학습(입력, AND)
예측_and, 맞은_and = 채점(입력, AND, w_and, b_and)

print("\n[AND 게이트 학습 결과]")
print("  학습된 w:", [round(v, 4) for v in w_and])   # → 학습된 w: [0.4888, 0.3159]
print("  학습된 b:", round(b_and, 4))                # → 학습된 b: -0.5589
for x, 정답 in zip(입력, AND):
    print(f"  입력 {x} → 예측 {예측(x, w_and, b_and)} (정답 {정답})")
# → 입력 [0, 0] → 예측 0 (정답 0)
# → 입력 [0, 1] → 예측 0 (정답 0)
# → 입력 [1, 0] → 예측 0 (정답 0)
# → 입력 [1, 1] → 예측 1 (정답 1)
print("  맞은 개수:", f"{맞은_and}/4")               # → 맞은 개수: 4/4

# 네 개 다 맞혔습니다. 퍼셉트론이 AND 를 완벽히 배웠어요.


# ----------------------------------------
# 왜 됐나 - 직선 하나로 갈랐기 때문
# ----------------------------------------

# 퍼셉트론이 하는 일을 그림으로 보면 '직선 하나 긋기' 입니다.
# 입력 네 점을 평면에 찍고, 정답 0 인 점과 1 인 점을 직선 하나로 가르는 거죠.
# (z = w1·x1 + w2·x2 + b = 0 이 바로 그 경계 직선입니다.)
#
#   x2                    AND: (1,1) 만 1, 나머지는 0
#    1 | ○           ●     ○ = 정답 0,  ● = 정답 1
#      |        ╱          비스듬한 직선 하나로
#      |     ╱             (1,1) 만 쏙 갈라낼 수 있음
#    0 | ○ ╱       ○
#      +----------------→ x1
#        0           1
#
# 한쪽에 ● 하나, 반대쪽에 ○ 셋. 직선 하나면 충분히 나뉩니다.
# 이렇게 '직선 하나로 두 무리를 가를 수 있는' 문제를 선형 분리 가능하다고 해요.
# 퍼셉트론은 딱 이런 문제만 풀 수 있습니다. 그 이유는 곧 XOR 에서 드러납니다.


# ========================================================
#  PART 4 : OR 게이트 학습 - 이것도 직선으로 된다
# ========================================================

# OR 도 같은 방식으로 학습됩니다. AND 와 정답만 다를 뿐, 코드는 그대로예요.

w_or, b_or = 학습(입력, OR)
예측_or, 맞은_or = 채점(입력, OR, w_or, b_or)

print("\n[OR 게이트 학습 결과]")
print("  학습된 w:", [round(v, 4) for v in w_or])    # → 학습된 w: [0.6888, 0.5159]
print("  학습된 b:", round(b_or, 4))                 # → 학습된 b: -0.1589
for x, 정답 in zip(입력, OR):
    print(f"  입력 {x} → 예측 {예측(x, w_or, b_or)} (정답 {정답})")
# → 입력 [0, 0] → 예측 0 (정답 0)
# → 입력 [0, 1] → 예측 1 (정답 1)
# → 입력 [1, 0] → 예측 1 (정답 1)
# → 입력 [1, 1] → 예측 1 (정답 1)
print("  맞은 개수:", f"{맞은_or}/4")                # → 맞은 개수: 4/4

# 또 4/4. OR 도 직선 하나로 갈립니다.
#
#   x2                    OR: (0,0) 만 0, 나머지는 1
#    1 | ●           ●     직선 하나로 (0,0) 만
#      |   ╲                반대쪽으로 떼어낼 수 있음
#      |     ╲
#    0 | ○     ╲     ●
#      +----------------→ x1
#        0           1
#
# ○ 하나(0,0) 만 한쪽으로, ● 셋을 반대쪽으로. 역시 직선 하나로 충분하죠.
# 여기까지 보면 퍼셉트론이 꽤 똑똑해 보입니다. 그런데...


# ========================================================
#  PART 5 : XOR 의 벽 - 직선 하나로는 절대 못 가른다
# ========================================================

# ----------------------------------------
# XOR 점을 찍어 보면
# ----------------------------------------

# XOR 는 '서로 다를 때만 1' 입니다. 네 점을 찍어 보면 사정이 완전히 달라져요.
#
#   x2                    XOR: 대각선끼리 같은 편
#    1 | ●           ○     (0,1)·(1,0) 은 1 (●)
#      |                    (0,0)·(1,1) 은 0 (○)
#      |
#    0 | ○           ●
#      +----------------→ x1
#        0           1
#
# ● 두 개가 왼쪽위·오른쪽아래(대각선),
# ○ 두 개가 왼쪽아래·오른쪽위(반대 대각선)에 X 자로 엇갈려 있습니다.
# 여기에 직선 '하나' 를 그어서 ● 둘만 한쪽에, ○ 둘만 반대쪽에 놓을 수 있나요?
# 아무리 그어 봐도 안 됩니다. 어떤 직선을 갖다 대도 한 편에 ● 와 ○ 가 섞여요.
# 이걸 선형 분리 불가능하다고 합니다. 직선 한 개로는 못 가르는 배치입니다.


# ----------------------------------------
# 그래도 학습시켜 본다 - 4개를 다 못 맞힌다
# ----------------------------------------

# 그림으로는 안 될 것 같지만, 백문이 불여일견. 똑같이 학습시켜 결과를 봅니다.

w_xor, b_xor = 학습(입력, XOR)
예측_xor, 맞은_xor = 채점(입력, XOR, w_xor, b_xor)

print("\n[XOR 게이트 학습 결과 - 실패를 눈으로]")
print("  학습된 w:", [round(v, 4) for v in w_xor])   # → 학습된 w: [-0.1112, 0.0159]
print("  학습된 b:", round(b_xor, 4))                # → 학습된 b: 0.0411
for x, 정답 in zip(입력, XOR):
    예측값 = 예측(x, w_xor, b_xor)
    표시 = "O" if 예측값 == 정답 else "X 틀림"
    print(f"  입력 {x} → 예측 {예측값} (정답 {정답})  {표시}")
# → 입력 [0, 0] → 예측 1 (정답 0)  X 틀림
# → 입력 [0, 1] → 예측 1 (정답 1)  O
# → 입력 [1, 0] → 예측 0 (정답 1)  X 틀림
# → 입력 [1, 1] → 예측 0 (정답 0)  O
print("  맞은 개수:", f"{맞은_xor}/4")               # → 맞은 개수: 2/4

# 2/4. 절반밖에 못 맞혔습니다. 에폭을 아무리 늘려도, 시드를 바꿔도,
# 학습률을 조정해도 4/4 는 나오지 않습니다. 퍼셉트론이 게을러서가 아니라
# '직선 하나' 라는 도구 자체의 한계라서 그래요. XOR 는 직선으로 못 가르니까.
#
# 이게 1969년에 밝혀진 그 유명한 '퍼셉트론의 한계' 입니다.
# 이 한 방에 신경망 연구가 한동안 겨울을 맞았을 정도로 뼈아픈 벽이었어요.


# ========================================================
#  PART 6 : 해법 - 뉴런을 층으로 쌓으면 XOR 도 된다
# ========================================================

# ----------------------------------------
# 큰 그림 연결 - 그래서 MLP 였다
# ----------------------------------------

# 직선 하나로 안 되면? 답은 단순합니다 — '선(뉴런)을 여러 개 쓰면' 됩니다.
# XOR 은 직선 하나로는 못 갈라도, 직선 두 개를 조합하면 갈라낼 수 있어요.
#
#   x2      직선 1 ╲   ╱ 직선 2       두 직선 사이의 '띠' 안쪽만 1,
#    1 | ●    ╲ ○ ╱                  바깥은 0 으로 잡으면 XOR 이 갈림
#      |       ╲ ╱                    (● 둘은 띠 안, ○ 둘은 띠 밖)
#      |       ╱ ╲
#    0 | ○    ╱ ● ╲
#      +----------------→ x1
#
# 직선 하나 = 퍼셉트론 하나(뉴런 하나) 였죠.
# 그러니 '직선 여러 개' 는 곧 '뉴런 여러 개' 입니다.
# 뉴런을 한 줄(은닉층)로 세워 각자 직선을 긋게 하고, 그 결과를 다음 뉴런이
# 다시 조합하게 하면 — 직선 하나로는 못 긋던 경계도 그려집니다.
#
#   퍼셉트론 1개  :  직선 1개        → AND, OR (O)  /  XOR (X)
#   뉴런을 층으로  :  직선 여러 개 조합 → XOR 도 (O)
#
# 바로 이 '뉴런을 층으로 쌓은' 구조가 다층 퍼셉트론(MLP)입니다.
# 여러분이 MLP 편에서 배운 그 은닉층이, 사실 이 XOR 의 벽을 넘으려고
# 태어난 겁니다. 그리고 그 층들의 가중치를 실제로 학습시키는 방법이
# 바로 MLP 편의 주인공 '역전파' 였고요.
#
# 정리하면 이야기가 한 줄로 이어집니다.
#   퍼셉트론(뉴런 하나) → 직선의 벽(XOR) → 층을 쌓음(MLP) → 학습법(역전파)
# 오늘 우리는 이 이야기의 맨 처음, '왜 층이 필요했나' 의 뿌리를 본 셈입니다.


