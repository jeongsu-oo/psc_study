"""[값은 맞췄는데, 그럼 '양품/불량'은 어떻게 가려내나요?]
과정4 보충의 마지막 편입니다. 두 가지를 손에 넣고 딥러닝 실전을 마무리해요.

지난 편(역전파)에서 우리 MLP 는 온도로 '불량 개수(값)' 를 예측했습니다. 회귀였죠.
그런데 현장에서 더 자주 필요한 건 '이 제품 양품이냐 불량이냐' 를 딱 가르는 일입니다.
그게 분류예요. 오늘 첫째 할 일: 지난 편 그 망을 거의 그대로 두고,
출력에 sigmoid 하나만 씌워 '불량일 확률(0~1)' 을 뽑고 0.5 를 넘으면 불량으로 판정합니다.

둘째 할 일이 오늘의 진짜 주제 — 하이퍼파라미터 튜닝입니다.
신경망에는 '스스로 학습되는' 가중치 말고, 우리가 손으로 정해 줘야 하는 손잡이들이 있어요.
학습률(lr), 은닉 뉴런 수, epochs(반복 횟수) 같은 것들이요.
이 손잡이를 어떻게 돌리냐에 따라 같은 데이터·같은 코드인데 성능이 확 달라집니다.
정답 공식이 없어서, 하나씩 바꿔 돌려 보고 '감' 을 잡는 수밖에 없어요. 오늘 그 감을 만듭니다.

이 파일은 회귀→분류 전환 → 학습·평가(정확도·혼동행렬) →
lr·은닉수·epochs 를 하나씩 튜닝 → 과적합(train/test) →
sklearn 대조 → 큰 그림(과정5 예고) → 실습 순으로 위에서 아래로 쌓습니다.
"""

# 지난 편처럼 가중치를 '행렬' 로 다룹니다. numpy 가 주인공이에요.
import numpy as np


# ========================================================
#  PART 1 : 회귀 → 분류 - 출력에 sigmoid 하나만 씌운다
# ========================================================

# ----------------------------------------
# 무엇이 바뀌나 - 딱 두 군데
# ----------------------------------------

# 지난 편 MLP 의 뼈대(입력 → 은닉 8개(sigmoid) → 출력)는 그대로 씁니다.
# 회귀를 분류로 바꾸는 데 손대는 곳은 정확히 두 군데뿐이에요.
#
#   ① 출력에 sigmoid 를 한 번 더 씌운다
#       회귀 출력은 ŷ = A·V + c 로 끝나 아무 값(2.7, -3 …)이나 나왔습니다.
#       분류는 '확률' 이 필요하니 그 값을 sigmoid 로 0~1 사이로 눌러 담아요.
#           p = sigmoid(A·V + c)     ← p 는 '불량일 확률'
#       그리고 p ≥ 0.5 면 불량(1), 아니면 양품(0). 이 0.5 가 '결정경계' 입니다.
#
#   ② 손실을 MSE 대신 BCE(로그손실)로 바꾼다
#       회귀는 (예측-정답)² 인 MSE 를 썼죠. 분류는 확률을 다루므로
#       과정3 로지스틱 회귀에서 본 그 BCE(이진 교차엔트로피) 를 씁니다.
#           BCE = -(1/n) Σ [ y·log(p) + (1-y)·log(1-p) ]
#       정답이 1인데 p 를 0 가까이 예측하면 -log(p) 가 폭발 → 크게 혼납니다.
#       '확률을 얼마나 자신 있게, 맞는 쪽으로 찍었나' 를 재는 손실이에요.
#
# 놀라운 사실 하나: 이렇게 바꿔도 역전파 체인은 거의 안 변합니다. (PART 3에서 확인)

def sigmoid(z):
    return 1 / (1 + np.exp(-z))   # 0~1 S자. 은닉층의 '휘는 부품' 이자 출력의 '확률 변환기'


# ----------------------------------------
# 제조 양품/불량 데이터 - 과정3 분류와 같은 세계관
# ----------------------------------------

# 온도가 높을수록 대체로 불량이 늘어나는, 과정3에서 쓴 그 온도-불량 데이터입니다.
# 불량=1(불량), 0(양품). 외부 파일 없이 인라인으로 둡니다.
# 완벽히 딱 갈리지 않고 경계(26~34도) 근처가 살짝 겹칩니다 — 현실 데이터가 원래 그래요.

온도 = np.array([18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40], dtype=float)
불량 = np.array([ 0,  0,  0,  0,  1,  0,  1,  1,  0,  1,  1,  1], dtype=float)

#  불량?
#   1 |                 ●     ● ●     ● ● ●    ← 고온 쪽에 불량(1)이 몰림
#     |                 :                        (단 28=양품, 34=양품 처럼 살짝 섞임)
#   0 | ● ● ● ●     ●             ●             ← 저온 쪽은 대체로 양품(0)
#     +--------------------------------------→ 온도
#      18 20 22 24 26 28 30 32 34 36 38 40
#
# 저온=양품 / 고온=불량 으로 '가르는 선' 을 MLP 가 배우게 하는 게 목표입니다.


# ----------------------------------------
# 표준화 - 지난 편과 같은 이유로 필수
# ----------------------------------------

# 온도는 18~40 으로 값이 큽니다. sigmoid 는 입력이 크면 0/1 에 딱 붙어 '포화' 되고,
# 포화되면 기울기가 죽어 학습이 멈춰요. 그래서 '평균 0, 퍼짐 1' 로 눈금을 바꿉니다.
# (과정2·3·지난 편 회수. 분류에서도 이유는 똑같습니다.)

def 표준화(x):
    m, s = x.mean(), x.std()
    return (x - m) / s, m, s        # 예측할 때도 같은 m, s 를 써야 함


# ========================================================
#  PART 2 : 순전파·손실 - 확률을 내고 로그손실을 잰다
# ========================================================

# ----------------------------------------
# 순전파 - 마지막에 sigmoid 한 번 더
# ----------------------------------------

# 지난 편 순전파(Z=XW+b, A=σ(Z), 출력=AV+c)에서 마지막 한 줄만 바뀝니다.
# 출력을 그냥 두지 않고 sigmoid 로 눌러 '확률 p' 를 만들어요.

def 순전파(X, W, b, V, c):
    A = sigmoid(X @ W + b)   # (n×은닉)  은닉층 출력 (휘어짐)
    p = sigmoid(A @ V + c)   # (n×1)     최종 '불량일 확률' 0~1  ← 여기가 회귀와 다른 점
    return p, A              # A 는 역전파에서 재사용

def BCE손실(p, Y):
    eps = 1e-9   # log(0) = -무한대 방지용 아주 작은 값
    return -np.mean(Y * np.log(p + eps) + (1 - Y) * np.log(1 - p + eps))
    # BCE = -(1/n)Σ[y·log p + (1-y)·log(1-p)]  (과정3 로지스틱 회수)


# ========================================================
#  PART 3 : 역전파 - 체인은 거의 그대로, 출력 미분만 p-y
# ========================================================

# ----------------------------------------
# '기적의 단순화' - sigmoid + BCE 의 출력 오차
# ----------------------------------------

# 지난 편 역전파 체인을 그대로 가져옵니다. 딱 한 곳만 달라져요 — 맨 앞(출력 오차).
#
#   회귀(MSE)  였을 때:  출력 오차 = 2(ŷ - y)/n
#   분류(BCE)  일 때  :  출력 오차 =  (p - y)/n      ← 더 깔끔!
#
# 신기하게도, sigmoid 와 BCE 를 짝지으면 미분이 서로 상쇄돼
# 출력 오차가 그냥 '예측확률 - 정답' 이 됩니다. (유도는 생략, 결과만 씁니다.)
# 이 한 줄만 바꾸면 나머지 되짚기(dV, dA, dZ, dW …)는 지난 편과 완전히 똑같아요.
#
#   ∂L/∂출력 = (p - y)/n                  출력 오차 (n×1)          … dlogit  ← 유일한 변경점
#   ∂L/∂V = Aᵀ · dlogit                                            … dV
#   ∂L/∂c = Σ dlogit                                               … dc
#   ∂L/∂A = dlogit · Vᵀ                                            … dA
#   ∂L/∂Z = dA ⊙ A(1-A)        sigmoid 미분 = a(1-a), 자리끼리 곱   … dZ
#   ∂L/∂W = Xᵀ · dZ                                                … dW
#   ∂L/∂b = Σ dZ                                                   … db

def 역전파(X, Y, A, p, W, b, V, c):
    n = len(X)
    dlogit = (p - Y) / n           # (n×1)  ← 회귀의 2(ŷ-y)/n 자리. p-y 로 바뀐 것뿐!
    dV = A.T @ dlogit              # (은닉×1)
    dc = dlogit.sum(axis=0, keepdims=True)
    dA = dlogit @ V.T              # (n×은닉)
    dZ = dA * A * (1 - A)          # (n×은닉)  ⊙ sigmoid'=a(1-a)
    dW = X.T @ dZ                  # (1×은닉)
    db = dZ.sum(axis=0, keepdims=True)
    return dW, db, dV, dc


# ----------------------------------------
# fit - 경사하강 루프 (지난 편 그대로)
# ----------------------------------------

# 학습 본체는 지난 편과 판박이입니다. 랜덤 초기화 → epochs 번 (순전파→역전파→갱신).
# 은닉수·lr·epochs 를 인자로 받게 해 뒀어요 — 이게 곧 '튜닝할 손잡이' 들입니다.

def fit(x, y, 은닉수=6, lr=1.0, epochs=2000, 로그=False):
    z, m, s = 표준화(x)                # 입력 표준화 (필수!)
    X = z.reshape(-1, 1)              # (n×1)
    Y = y.reshape(-1, 1)             # (n×1)

    np.random.seed(0)                # 시드 고정 → 재현성 (출력이 매번 동일)
    W = np.random.randn(1, 은닉수) * 0.5     # (1×은닉)
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5     # (은닉×1)
    c = np.zeros((1, 1))

    for epoch in range(epochs):
        p, A = 순전파(X, W, b, V, c)                    # 확률 예측 한 번
        dW, db, dV, dc = 역전파(X, Y, A, p, W, b, V, c)  # 기울기 되짚기
        W -= lr * dW                                    # ← 갱신 (한 스텝)
        b -= lr * db
        V -= lr * dV
        c -= lr * dc
        if 로그 and epoch % 400 == 0:
            print(f"  epoch {epoch:5d}   BCE손실 {BCE손실(순전파(X,W,b,V,c)[0], Y):.4f}")

    if 로그:
        print(f"  epoch {epochs:5d}   BCE손실 {BCE손실(순전파(X,W,b,V,c)[0], Y):.4f}")
    return (W, b, V, c, m, s)          # 학습된 모델


# ----------------------------------------
# predict - 확률과 0/1 판정
# ----------------------------------------

# 회귀의 predict 는 값을 바로 돌려줬죠. 분류는 두 가지를 씁니다.
#   · 확률(0~1) : sigmoid 출력 그대로
#   · 판정(0/1) : 확률 ≥ 0.5 면 불량(1), 아니면 양품(0)  ← 결정경계 0.5

def 예측확률(x, 모델):
    W, b, V, c, m, s = 모델
    z = (np.asarray(x, dtype=float) - m) / s   # 학습 때와 같은 눈금으로
    X = z.reshape(-1, 1)
    p, _ = 순전파(X, W, b, V, c)
    return p.ravel()

def 예측(x, 모델, 경계=0.5):
    return (예측확률(x, 모델) >= 경계).astype(int)   # 확률 → 0/1 판정

def 정확도(x, y, 모델):
    return np.mean(예측(x, 모델) == y.astype(int))   # 맞춘 비율


# ========================================================
#  PART 4 : 학습·평가 - 정확도와 혼동행렬
# ========================================================

# ----------------------------------------
# 학습 로그 - BCE 손실이 줄어드는 걸 눈으로
# ----------------------------------------

# 은닉 6개, lr=1.0, 2000 epoch 로 학습시켜 봅니다. BCE 손실이 줄어드는지 보세요.
# (이 데이터는 경계가 겹쳐 손실이 0까지는 안 내려갑니다 — 원래 그런 데이터예요.)

print("[MLP 분류 학습 로그]")
모델 = fit(온도, 불량, 은닉수=6, lr=1.0, epochs=2000, 로그=True)
# → [MLP 분류 학습 로그]
