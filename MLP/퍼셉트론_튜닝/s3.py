# →   80.0    6.1228   0.500

# lr 0.01 은 손실 0.51 — 덜 내려갔어요(느림). 1.0 이 손실 0.37 로 가장 잘 수렴.
# 그런데 20 을 넘기면 손실이 되레 커지고, 80 에선 6.1 로 폭발합니다 = '발산'.
