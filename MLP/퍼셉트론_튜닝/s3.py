# ----------------------------------------
# 왜 나눠서 재나 - '외운 것' 과 '배운 것'
# ----------------------------------------

# 지금까지는 12개 전부로 학습하고 그 12개로 정확도를 쟀습니다. 이건 시험문제를
# 미리 보고 시험 보는 격이에요. 뉴런을 잔뜩 늘리면 데이터를 통째로 '외워' 버려서
# 학습 데이터 정확도는 100% 가 되지만, 처음 보는 데이터엔 엉망일 수 있습니다.
# 이게 과적합(overfitting)입니다 (과정3 회수).
#
# 그래서 데이터를 둘로 나눕니다.
#   · train(8개) : 학습에만 사용
#   · test (4개) : 학습에 안 쓰고, '처음 보는 데이터' 로 성능을 정직하게 채점
# 시드를 고정해 매번 같은 분할이 나오게 합니다(재현성).

np.random.seed(4)
섞은순서 = np.random.permutation(len(온도))
train_idx, test_idx = 섞은순서[:8], 섞은순서[8:]
온도_tr, 불량_tr = 온도[train_idx], 불량[train_idx]
온도_te, 불량_te = 온도[test_idx], 불량[test_idx]
print("\n[train/test 분리]")
print("  train 온도:", 온도_tr.astype(int).tolist())   # → train 온도: [24, 26, 30, 36, 34, 22, 40, 18]
print("  test  온도:", 온도_te.astype(int).tolist())   # → test  온도: [20, 28, 32, 38]


# ----------------------------------------
# 은닉수를 키우며 - test 성능이 꺾이는 지점
# ----------------------------------------

# train 으로만 학습하고, train 정확도와 test 정확도를 나란히 봅니다.
# 은닉수를 1 → 32 로 키우며 두 정확도가 어떻게 갈라지는지가 핵심이에요.

# test 는 학습 안 쓴 데이터라 학습 때 본 평균·표준편차(train 기준)로 표준화해야 함
tr_m, tr_s = 온도_tr.mean(), 온도_tr.std()
def 정확도_고정눈금(x, y, 모델):
    W, b, V, c, _, _ = 모델
    z = (x - tr_m) / tr_s
    p, _ = 순전파(z.reshape(-1, 1), W, b, V, c)
    return np.mean((p.ravel() >= 0.5).astype(int) == y.astype(int))

def fit_고정눈금(x, y, 은닉수):
    z = (x - tr_m) / tr_s   # train 기준 눈금 (test 와 공유)
    X = z.reshape(-1, 1); Y = y.reshape(-1, 1)
    np.random.seed(0)
    W = np.random.randn(1, 은닉수) * 0.5; b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5; c = np.zeros((1, 1))
    for _ in range(2000):
        p, A = 순전파(X, W, b, V, c)
        dW, db, dV, dc = 역전파(X, Y, A, p, W, b, V, c)
        W -= 1.0*dW; b -= 1.0*db; V -= 1.0*dV; c -= 1.0*dc
    return (W, b, V, c, tr_m, tr_s)

print("\n[과적합 관찰 · 은닉수 ↑]")
print("   은닉수   train정확도   test정확도")
for h in [1, 2, 4, 8, 32]:
    m = fit_고정눈금(온도_tr, 불량_tr, h)
    tr_acc = 정확도_고정눈금(온도_tr, 불량_tr, m)
    te_acc = 정확도_고정눈금(온도_te, 불량_te, m)
    print(f"    {h:3d}       {tr_acc:.3f}        {te_acc:.3f}")
# → [과적합 관찰 · 은닉수 ↑]
# →    은닉수   train정확도   test정확도
# →      1       0.875        0.750
# →      2       0.875        0.750
# →      4       1.000        0.500
# →      8       1.000        0.500
# →     32       1.000        0.500

# 바로 이게 과적합의 교과서적 그림입니다.
#   은닉수를 키우면 train 정확도는 0.875 → 1.000 으로 올라(데이터를 외움),
#   하지만 test 정확도는 0.750 → 0.500 으로 되레 '꺾입니다'.
# 처음 보는 데이터엔 오히려 못하게 된 거예요 — 외웠지 배운 게 아닙니다.
#
#   정확도
#    1.0 |        ●━━━━━●━━━━━●   ← train (외울수록 오름)
#    0.75|●━━━━━●        ·
#    0.5 |         ●━━━━━●━━━━━●  ← test (어느 순간부터 꺾여 내려감)
#        +-----------------------→ 은닉수  1  2  4  8  32
#
# 교훈: 모델을 무작정 키우지 말 것. test 성능이 최고인 지점(여기선 작은 은닉수)이 정답.
# '얼마나 복잡하게 할까' 를 test 로 정하는 것 — 이게 튜닝의 핵심 감각입니다.


