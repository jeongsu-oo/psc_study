# 손실이 0.66 에서 0.37 로 줄었습니다. 확률 예측이 점점 정답 쪽으로 붙는다는 뜻이에요.


# ----------------------------------------
# 확률 → 판정 → 실제 - 한 줄씩 비교
# ----------------------------------------

# 학습된 모델이 각 온도를 어떻게 보는지 확률·판정·실제를 나란히 봅니다.

확률 = 예측확률(온도, 모델)
