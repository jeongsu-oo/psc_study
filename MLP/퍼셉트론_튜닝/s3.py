# 여기가 오늘의 핵심입니다. 결과에 영향 주는 손잡이(하이퍼파라미터)를
# '하나만 바꾸고 나머지는 고정' 해서 돌려 보고, 손실·정확도가 어떻게 변하는지 표로 봅니다.
# 정답 공식은 없어요. 이렇게 실험해 '감' 을 잡는 게 튜닝입니다.

def 손실계산(모델):
    return BCE손실(예측확률(온도, 모델).reshape(-1, 1), 불량.reshape(-1, 1))


# ----------------------------------------
