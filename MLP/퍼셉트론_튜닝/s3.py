# ----------------------------------------

# lr 은 '한 걸음의 보폭' 입니다(과정3 경사하강 회수).
#   · 너무 작으면(0.01): 보폭이 좁아 2000번 걸어도 덜 내려감 = 느림
#   · 알맞으면(1.0)    : 잘 수렴
#   · 너무 크면(80)    : 보폭이 커 골짜기를 건너뛰어 튕겨나감 = '발산'(손실이 되레 커짐)

print("\n[튜닝 ① 학습률 lr]  (은닉6·epochs2000 고정)")
print("    lr     BCE손실   정확도")
for lr in [0.01, 0.1, 1.0, 20.0, 80.0]:
    m = fit(온도, 불량, 은닉수=6, lr=lr, epochs=2000)
    print(f"  {lr:5}    {손실계산(m):.4f}   {정확도(온도,불량,m):.3f}")
# → [튜닝 ① 학습률 lr]  (은닉6·epochs2000 고정)
# →     lr     BCE손실   정확도
