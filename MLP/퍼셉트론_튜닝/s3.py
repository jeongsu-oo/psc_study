print("\n[온도별 확률·판정·실제]")
print("  온도   불량확률   판정   실제")
for t, pr, pd, y in zip(온도, 확률, 판정, 불량):
    맞음 = "O" if pd == int(y) else "X"
    print(f"  {int(t):3d}     {pr:.3f}     {pd}     {int(y)}  {맞음}")
# → [온도별 확률·판정·실제]
# →   온도   불량확률   판정   실제
