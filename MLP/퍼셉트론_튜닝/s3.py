# ========================================================

#   [과정4 보충 3부작 한 줄 정리]
#     1편  순전파      → 입력 → 은닉(sigmoid) → 출력, 예측 한 번
#     2편  역전파      → 연쇄법칙으로 각 가중치의 기울기 되짚기 + 갱신
#     3편  튜닝·분류   → 그 망을 분류로 쓰고, 손잡이를 돌려 성능을 끌어올림 (오늘)
#
# 오늘로 딥러닝 실전에 필요한 조각이 다 모였습니다. 딱 이겁니다:
#
#   ① 순전파     : 지금 가중치로 예측(확률)을 낸다      (A=σ(XW+b), p=σ(AV+c))
#   ② 역전파     : 틀린 만큼 각 가중치 기울기를 구한다   (출력오차 p-y 로 시작, 뒤→앞)
#   ③ 경사하강   : 그 기울기 방향으로 조금 갱신한다       (w ← w - lr·∂L/∂w)
#   ④ 튜닝       : lr·은닉수·epochs 를 돌려 최고 성능을 찾는다 (test 로 과적합 감시)
#
#   ①②③ 을 for 로 반복 = 학습.  거기에 ④ 튜닝을 얹으면 = 딥러닝 실전.
#
