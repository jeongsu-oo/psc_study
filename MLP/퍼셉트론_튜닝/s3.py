# ----------------------------------------
# [실습] 조합을 바꿔 최고 정확도 찾기
# ----------------------------------------

# 오늘 만든 fit / 정확도 를 그대로 써서, lr·은닉수·epochs 조합을 바꿔 가며
# 가장 정확도가 높은 설정을 직접 찾아봅니다. 이게 실전 튜닝이에요.
#
#   Step 1) 후보 조합을 몇 개 정한다 (아래는 정답 예시)
#   Step 2) for 로 조합마다 fit → 정확도 계산
#   Step 3) 표로 나란히 보고 최고 조합을 고른다
#   완료 기준 : 조합별 정확도가 표로 나오고, 최고 조합이 무엇인지 말할 수 있으면 성공.

print("\n[실습 예시 · 조합 탐색]")
print("     lr   은닉수   epochs   정확도")
후보 = [
    (0.1, 4, 2000),
    (1.0, 4, 2000),
    (1.0, 4, 5000),
    (1.0, 6, 5000),
]
최고 = None
for lr, h, e in 후보:
    m = fit(온도, 불량, 은닉수=h, lr=lr, epochs=e)
    acc = 정확도(온도, 불량, m)
    print(f"   {lr:4}    {h:3d}    {e:5d}    {acc:.3f}")
    if 최고 is None or acc > 최고[0]:
        최고 = (acc, lr, h, e)
print(f"  → 최고: 정확도 {최고[0]:.3f}  (lr={최고[1]}, 은닉={최고[2]}, epochs={최고[3]})")
# → [실습 예시 · 조합 탐색]
# →      lr   은닉수   epochs   정확도
# →    0.1      4     2000    0.833
# →    1.0      4     2000    0.833
# →    1.0      4     5000    0.917
# →    1.0      6     5000    0.917
# →   → 최고: 정확도 0.917  (lr=1.0, 은닉=4, epochs=5000)

# 같은 데이터·같은 코드인데 조합만 바꿔 정확도가 0.75 → 0.917 로 올랐습니다.
# 이게 튜닝의 힘이에요. 정답 공식은 없고, 이렇게 돌려 보며 감으로 최고를 찾습니다.
#
#   [기억할 것]
#     · 회귀 → 분류 : 출력에 sigmoid + 손실 BCE, 경계 0.5. 역전파는 출력오차만 p-y 로
