# →   40     0.946     1     1  O

# 저온은 확률이 0에 가깝고(양품), 고온은 1에 가까워(불량) '가르는 선' 을 배웠습니다.
# 다만 경계인 26·28·34 는 데이터가 겹쳐서 틀립니다 — 완벽히는 못 갈라요. 그게 정상.


# ----------------------------------------
# 정확도와 혼동행렬 - 과정3 평가지표 회수
# ----------------------------------------

# 분류는 '손실' 만으론 감이 안 와요. 과정3에서 배운 평가지표로 봅니다.
#   · 정확도 = 맞춘 개수 / 전체
#   · 혼동행렬 = 맞고 틀림을 네 칸으로 쪼갠 표 (어떻게 틀렸는지가 보임)

def 혼동행렬(y_true, y_pred):
    y_true = y_true.astype(int)
    TP = int(np.sum((y_pred == 1) & (y_true == 1)))   # 불량을 불량이라 함 (정답)
    TN = int(np.sum((y_pred == 0) & (y_true == 0)))   # 양품을 양품이라 함 (정답)
    FP = int(np.sum((y_pred == 1) & (y_true == 0)))   # 양품인데 불량이라 함 (오검)
    FN = int(np.sum((y_pred == 0) & (y_true == 1)))   # 불량인데 양품이라 함 (놓침 - 위험!)
    return TP, TN, FP, FN

TP, TN, FP, FN = 혼동행렬(불량, 판정)
print("\n[평가]")
print("  정확도:", round(정확도(온도, 불량, 모델), 4))   # → 정확도: 0.75
print("  혼동행렬            예측:양품  예측:불량")
print(f"    실제 양품(0)        {TN:3d}        {FP:3d}")   # → 실제 양품(0)          4          2
print(f"    실제 불량(1)        {FN:3d}        {TP:3d}")   # → 실제 불량(1)          1          5
# → [평가]
# →   정확도: 0.75
# →   혼동행렬            예측:양품  예측:불량
# →     실제 양품(0)          4          2
# →     실제 불량(1)          1          5

# 12개 중 9개 맞아 정확도 0.75. 혼동행렬을 보면 '어떻게' 틀렸는지가 보입니다.
#   · FN(놓침)=1 : 불량인데 양품이라 흘려보낸 것 → 현장에선 이게 제일 위험(불량 출하)
#   · FP(오검)=2 : 양품인데 불량이라 붙잡은 것 → 멀쩡한 걸 버려 손해
# 정확도 하나보다 이 네 칸이 훨씬 많은 걸 말해 줍니다. (과정3 회수)


# ========================================================
#  PART 5 : 하이퍼파라미터 튜닝 - 손잡이를 하나씩 돌린다
