"""[과정3에선 직선으로 풀었죠. 신경망은 얼마나 더 잘 풀까요?]
과정4를 여기까지 오느라 고생 많으셨습니다. 우리는 조각조각 배웠어요.
  · 순전파   : 입력 → 은닉(sigmoid) → 출력, 예측을 한 번 낸다
  · 역전파   : 연쇄법칙으로 각 가중치의 기울기를 뒤에서 앞으로 되짚는다
  · 경사하강 : 그 기울기 방향으로 조금씩 갱신, for 로 반복 = 학습
  · 튜닝     : lr·은닉수·epochs 손잡이를 돌려 성능을 끌어올린다

오늘은 이 조각들을 하나로 잇습니다. 제조 현장에 데이터가 딱 떨어졌다고
치고, 문제 정의부터 결과 해석까지 '처음부터 끝까지(end-to-end)' 관통해요.
새 이론은 없습니다. 배운 걸 순서대로 꿰는 게 오늘의 전부.

오늘의 핵심 질문 하나: "MLP가 과정3의 선형모델보다 정말 나은가?"
그래서 오늘은 꼭 순서를 지킵니다.
  먼저 로지스틱(과정3)으로 성능 '기준선(베이스라인)' 을 세우고,
  그 다음 MLP로 같은 문제를 풀어 "베이스라인을 이겼나" 를 숫자로 확인.
이겨야 신경망을 쓸 이유가 있는 거예요. 안 이기면 굳이 복잡한 걸 쓸 필요 없죠.

중요한 약속 하나. 오늘은 강사가 먼저 시범을 보이고,
중간중간 [실습 지점] 에서 "이제 여러분 차례" 하고 넘깁니다.
그 자리엔 정답 예시도 실행되게 넣어 뒀으니, 먼저 스스로 해보고 비교하세요.

  [오늘의 흐름]
    1. 문제 정의   - 뭘 풀 건가, 목표·흐름도
    2. 데이터 이해 - 센서 데이터 살펴보기 (요약·불량비율=불균형 점검)
    3. 전처리      - 표준화·train/val/test 3분할 (누출 방지)         [실습]
    4. 베이스라인  - 로지스틱(과정3)으로 성능 기준선부터
    5. MLP 학습    - 은닉층 MLP로 분류, 베이스라인과 비교 (MLP 우세)  [실습]
    6. 하이퍼튜닝  - 은닉수·lr·정규화를 val 로 최적 찾기 (과적합 주의) [실습]
    7. 최종 평가   - 손 안 댄 test 로 채점 + 현장 언어로 해석
    8. 마무리      - 과정5 통합 프로젝트 예고
"""

# 오늘도 numpy 밑바닥으로 갑니다. 순전파·역전파·경사하강 전부 우리 손으로 짠 것 그대로.
# 데이터는 외부 파일 없이 '시드 고정' 으로 이 안에서 만듭니다(자족).
# 맨 끝 선택 파트에서만, 우리가 구한 값이 맞는지 sklearn 으로 대조합니다.
import numpy as np


# ========================================================
#  PART 1 : 문제 정의 - 무엇을 풀 것인가
# ========================================================

# ----------------------------------------
# 목표 - '이 배치, 불량이냐' 를 가른다
# ----------------------------------------

# 제조 라인에서 센서가 온도·압력을 계속 찍고 있습니다.
# 현장이 알고 싶은 건 딱 하나 — "이번 배치, 불량 배치야 아니야?"
# 값(개수)이 아니라 '이냐 아니냐' 니까 분류 문제입니다.
#
#   불량여부 : 1(불량 배치) / 0(양품 배치)   ← 오늘의 타깃
#
# 그런데 오늘 데이터엔 함정이 하나 있어요. 온도가 '너무 낮아도(냉각 불량)'
# '너무 높아도(과열 불량)' 불량이 나고, 가운데 온도대(정상 공정창)에서만
# 양품이 나옵니다. 즉 불량이 온도의 '양 끝' 에 몰려요 — U자/띠(band) 모양.
#
#   [오늘의 end-to-end 흐름도]
#
#     센서 데이터(온도·압력)
#            │
#       표준화 · train/val/test 3분할
#            │
#      ┌─────┴──────┐
#      ▼            ▼
#   베이스라인     MLP
#   로지스틱      은닉층 신경망
#   (직선 한 겹)  (곡선을 그림)
#      │            │
#      └─────┬──────┘
#            ▼
#     "MLP가 베이스라인을 이겼나?"  → val 로 튜닝 → test 로 최종 채점
#            ▼
#      현장 언어로 해석 → 조치
#
# 왼쪽(로지스틱)은 '직선 하나' 로 가릅니다. 그런데 불량이 양 끝에 몰린
# 이 패턴은 직선 하나로는 절대 못 갈라요(양 끝을 동시에 '불량' 편에 둘 수가 없음).
# 여기서 MLP(곡선)가 빛을 봅니다 — 그걸 오늘 숫자로 확인하는 게 목표입니다.


# ========================================================
#  PART 2 : 데이터 이해 - 센서 데이터를 살펴본다
# ========================================================

# ----------------------------------------
# 데이터 만들기 - 인라인, 시드 고정
# ----------------------------------------

# 외부 csv 없이 이 안에서 데이터를 만듭니다(자족 원칙). 시드를 고정해서
# 몇 번을 돌려도 똑같은 데이터가 나오게 합니다 — 그래야 결과가 재현됩니다.
# 실제 라인에서는 pd.read_csv 로 파일을 읽겠지만, 그 뒤 과정은 오늘과 똑같아요.

SEED = 42
rng = np.random.RandomState(SEED)        # 시드 고정 = 항상 같은 난수

N = 300                                   # 제조 배치 300건
온도 = rng.uniform(180, 260, N)           # 성형 온도 (도)
압력 = rng.uniform(90, 135, N)            # 주입 압력 (bar)

# 불량여부(타깃)를 '숨은 규칙 + 약간의 잡음' 으로 만듭니다.
# 핵심 규칙 : 온도가 정상 공정창(약 210~230도)에서 벗어날수록 불량↑ (양 끝이 위험).
#   → 이건 온도의 '거리' 로 정해지는 U자 패턴 — 직선 하나로 못 가르는 모양입니다.
# 압력도 거들어요(너무 높으면 불량↑). 여기에 현실의 잡음을 살짝 섞습니다.
# (이 규칙은 데이터 생성용일 뿐. 모델은 이걸 모른 채 데이터만 보고 배웁니다.)
정상온도 = 220.0                          # 이 근처가 양품 공정창의 중심
온도벗어남 = np.abs(온도 - 정상온도) / 20.0   # 중심에서 멀수록 커지는 값(0~2)
압력벗어남 = np.clip((압력 - 122) / 15.0, 0, None)   # 압력이 아주 높을 때만 살짝 거듦
잡음 = rng.normal(0, 0.18, N)             # 현실의 들쭉날쭉함 (약간)
위험도 = 온도벗어남 + 0.25 * 압력벗어남 + 잡음
불량여부 = (위험도 >= 1.05).astype(int)   # 위험도가 문턱을 넘으면 불량(1)

특징원본 = np.column_stack([온도, 압력])   # (300, 2) 특징 행렬


# ----------------------------------------
# 살펴보기 - 요약통계 (과정2 회수)
# ----------------------------------------

# 데이터를 받으면 제일 먼저 '어떻게 생겼나' 를 봅니다. 최소·최대·평균.
# 과정2 numpy 에서 배운 .min() .max() .mean() 을 그대로 씁니다.

print("[센서 데이터 요약 · 배치", N, "건]")
for 이름, 열 in [("온도", 온도), ("압력", 압력)]:
    print(f"  {이름}: 최소 {열.min():6.1f}   최대 {열.max():6.1f}   평균 {열.mean():6.1f}")
# → [센서 데이터 요약 · 배치 300 건]
# →   온도: 최소  180.4   최대  259.2   평균  219.6
# →   압력: 최소   90.5   최대  135.0   평균  113.0

# 온도 180~260, 압력 90~135 … 열마다 값의 크기(스케일)가 다르죠?
# 이게 나중에 표준화가 필요한 이유입니다. 지금은 눈도장만 찍어 둡니다.


# ----------------------------------------
# 불량이 온도 '양 끝' 에 몰렸나 - 패턴 확인
# ----------------------------------------

# 오늘 데이터의 핵심은 '불량이 양 끝(저온·고온)에 몰린다' 는 것.
# 온도를 세 구간(저온/정상/고온)으로 나눠 각 구간의 불량비율을 봅니다.

print("\n[온도 구간별 불량비율 · U자 패턴 확인]")
for 이름, 조건 in [("저온(<205)", 온도 < 205),
                  ("정상(205~235)", (온도 >= 205) & (온도 <= 235)),
                  ("고온(>235)", 온도 > 235)]:
    print(f"  {이름:14s}: 불량비율 {불량여부[조건].mean():.2f}  ({조건.sum()}건)")
# → [온도 구간별 불량비율 · U자 패턴 확인]
# →   저온(<205)      : 불량비율 0.83  (100건)
# →   정상(205~235)   : 불량비율 0.00  (105건)
# →   고온(>235)      : 불량비율 0.78  (95건)

# 보이시죠? 저온 0.83, 고온 0.78 로 양 끝이 불량투성이인데 가운데(정상)는 0.00.
# 이게 '직선으로 못 가르는' 패턴입니다 — 온도 축 위에서 불량이 양쪽에 몰려서,
# 직선 하나로는 "이쪽은 불량, 저쪽은 양품" 식으로 한 번밖에 못 자르거든요.
# 딱 MLP(곡선)가 필요한 상황. 이걸 뒤에서 직접 확인합니다.


# ----------------------------------------
# 불량 비율 - 클래스 불균형 점검 (분류 전 필수)
# ----------------------------------------

# 분류를 하기 전, 반드시 볼 게 하나 있어요 — '불량이 전체의 몇 %냐'.
# 이걸 모르고 정확도만 보면 나중에 크게 속습니다(과정3 평가지표 편의 그 함정).

불량건수 = int(불량여부.sum())
불량비율 = 불량여부.mean()
print("\n[클래스 불균형 점검]")
print(f"  양품 배치: {N - 불량건수}건 / 불량 배치: {불량건수}건")
print(f"  불량 비율: {불량비율:.3f}  (전체의 약 {불량비율*100:.0f}%)")
# → [클래스 불균형 점검]
# →   양품 배치: 143건 / 불량 배치: 157건
# →   불량 비율: 0.523  (전체의 약 52%)

# 불량이 약 52% — 이번엔 양품/불량이 반반이라 심한 불균형은 아니에요.
# 그래도 습관으로 항상 이걸 먼저 봅니다. 반반이라 정확도를 봐도 크게 안 속지만,
# 그래도 재현율(불량을 얼마나 잡나)은 오늘도 꼭 함께 볼 겁니다.


# ========================================================
#  PART 3 : 전처리 - 표준화 + train/val/test 3분할
# ========================================================

# ----------------------------------------
# 왜 3분할인가 - train·val·test 역할 분담
# ----------------------------------------

# 과정3에선 train/test 둘로만 나눴죠. 오늘은 튜닝(PART 6)이 있어서 셋으로 나눕니다.
#   · train(60%) : 가중치를 배운다 (학습)
#   · val  (20%) : 튜닝용 채점표. 손잡이(은닉수·lr…) 고를 때 이걸로 비교
#   · test (20%) : 맨 마지막 딱 한 번만. 진짜 실력을 정직하게 채점
#
#   ★ 왜 val 을 따로 두나? 튜닝하면서 test 를 계속 보면, test 에 맞춰 손잡이를
#     고르게 돼 test 가 '오염' 됩니다(사실상 훔쳐본 셈). 그래서 튜닝은 val 로 하고,
#     test 는 다 끝난 뒤 한 번만 엽니다. 이게 정직한 평가의 핵심이에요.
#   ★ 누출 방지 : 표준화 평균·표준편차도 'train 것만' 으로 구해 val·test 에 적용.

idx = np.arange(N)
np.random.RandomState(0).shuffle(idx)     # 순서 섞기(시드 고정) — 편향 방지
n_tr, n_val = 180, 60                      # 300건 → train 180 / val 60 / test 60
tr, va, te = idx[:n_tr], idx[n_tr:n_tr+n_val], idx[n_tr+n_val:]

X_tr, X_va, X_te = 특징원본[tr], 특징원본[va], 특징원본[te]
y_tr, y_va, y_te = 불량여부[tr], 불량여부[va], 불량여부[te]

print("[train/val/test 3분할]")
print(f"  train {len(tr)}건 (불량비율 {y_tr.mean():.3f})  "
      f"val {len(va)}건 (불량비율 {y_va.mean():.3f})  "
      f"test {len(te)}건 (불량비율 {y_te.mean():.3f})")
# → [train/val/test 3분할]
# →   train 180건 (불량비율 0.567)  val 60건 (불량비율 0.450)  test 60건 (불량비율 0.467)

# 세 덩어리 모두 불량비율이 50% 안팎 — 한쪽에 불량이 몰리지 않게 잘 섞였습니다.


# ----------------------------------------
# 표준화 - train 기준으로만 (누출 방지)
# ----------------------------------------

# 온도(180~260)와 압력(90~135)은 크기가 다릅니다. 게다가 sigmoid 신경망은
# 입력이 크면 '포화' 돼 학습이 멈춰요(과정4 내내 강조한 그 이유). 그래서
# 모든 특징을 '평균 0, 퍼짐 1' 로 눈금을 통일합니다 = 표준화.  z = (x - 평균)/표준편차
#
# ★ 누출 방지 핵심 : 평균·표준편차를 train 에서만 구하고, 그 값으로 val·test 도 변환.

평균 = X_tr.mean(axis=0)                   # train 각 특징의 평균 (2개)
표준편차 = X_tr.std(axis=0)                # train 각 특징의 표준편차 (2개)
Z_tr = (X_tr - 평균) / 표준편차            # train 표준화
Z_va = (X_va - 평균) / 표준편차            # val 도 'train 기준' 으로
Z_te = (X_te - 평균) / 표준편차            # test 도 'train 기준' 으로

print("\n[표준화 확인 · train 은 평균≈0, 퍼짐≈1]")
print("  train 각 특징 평균:", np.round(Z_tr.mean(axis=0), 3))
print("  train 각 특징 퍼짐:", np.round(Z_tr.std(axis=0), 3))
# → [표준화 확인 · train 은 평균≈0, 퍼짐≈1]
# →   train 각 특징 평균: [-0.  0.]
# →   train 각 특징 퍼짐: [1. 1.]


# ----------------------------------------
# [실습 지점] val 도 같은 자로 쟀는지 확인해 보세요
# ----------------------------------------

# 강사가 train 기준으로 표준화했습니다. 이제 여러분 차례 —
# val 을 'train 기준' 으로 변환한 게 맞는지 눈으로 확인해 봅니다.
# val 은 평균이 정확히 0은 아니어야 정상이에요(train 눈금을 빌려 쓴 거니까).
# 만약 val 평균이 딱 0 이 나오면? val 제 통계로 표준화한 것 = 누출 사고입니다!
#
#   Step 1) Z_va 의 각 특징 평균을 np.round 로 찍어 본다
#   Step 2) 0 에 '가깝지만 딱 0은 아닌지' 확인 (0.1~0.3 정도면 정상)
#   Step 3) 만약 딱 0.000 이 나온다면 train 기준이 아니라 val 기준으로 잰 것 → 누출!
#   완료 기준 : val 평균이 0 근처지만 딱 0은 아님을 확인하면 성공(= 누출 없음).

