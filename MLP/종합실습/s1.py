#     · 3분할 규율      : val 로 튜닝, test 는 마지막 한 번. 표준화 통계도 train 만.
#     · 지표는 재료      : 숫자를 현장이 조치할 수 있는 말로 번역해야 일이 끝난다.
#
#   [왜 MLP 가 이겼나 — 한 줄]
#     불량이 온도 '양 끝' 에 몰린 U자 패턴은 직선 한 겹(로지스틱)으론 못 가른다.
