#  PART 4 : 베이스라인 - 로지스틱(과정3)으로 기준선부터
# ========================================================

# ----------------------------------------
# 왜 베이스라인부터 - "MLP가 이걸 이겨야 의미"
# ----------------------------------------

# 신경망부터 덤비고 싶겠지만, 실무의 철칙은 '단순한 것부터'.
# 먼저 과정3의 로지스틱(직선 한 겹)으로 성능 기준선을 세웁니다.
# 그래야 나중에 MLP 점수가 나왔을 때 "이게 좋은 거야?" 를 판단할 수 있어요.
# MLP가 이 기준선을 못 이기면? 굳이 복잡한 신경망 쓸 이유가 없는 겁니다.
#
# 로지스틱은 과정3 그대로 : 직선값을 sigmoid 로 눌러 확률로, 손실은 BCE.
#   p = sigmoid(Zw + b),   ∂L/∂w = (1/n) Zᵀ(p - y)   ← 갱신은 경사하강

def sigmoid(z):
    return 1 / (1 + np.exp(-z))           # 아무 값이나 0~1 로 눌러 주는 S자

def 로지스틱학습(Z, y, lr=0.3, epochs=4000):
    n, d = Z.shape
    w = np.zeros(d)                        # 가중치, 0 에서 출발
    b = 0.0
    for _ in range(epochs):
        오차 = sigmoid(Z @ w + b) - y      # p - y  (과정3 그대로)
        w -= lr * (Z.T @ 오차) / n         # ∂L/∂w = (1/n)Zᵀ(p-y)
        b -= lr * 오차.sum() / n
    return w, b

def 로지스틱확률(Z, w, b):
    return sigmoid(Z @ w + b)


# ----------------------------------------
# 공용 평가 도구 - 정확도·재현율·혼동행렬
# ----------------------------------------

# 베이스라인과 MLP 를 같은 자로 재려고, 평가 함수를 먼저 만들어 공용으로 씁니다.
# 확률 → 0.5 넘으면 불량(1) 판정 → 실제와 대조.

def 판정(확률, 경계=0.5):
    return (확률 >= 경계).astype(int)

def 혼동행렬(y, pred):
    tp = int(((y == 1) & (pred == 1)).sum())   # 불량을 불량이라 맞힘
    fp = int(((y == 0) & (pred == 1)).sum())   # 양품을 불량이라 오판(헛경보)
    fn = int(((y == 1) & (pred == 0)).sum())   # 불량을 양품이라 놓침! (위험)
    tn = int(((y == 0) & (pred == 0)).sum())   # 양품을 양품이라 맞힘
    return tp, fp, fn, tn

def 정확도(y, 확률):
    return np.mean(판정(확률) == y)

def 재현율(y, 확률):
    tp, fp, fn, tn = 혼동행렬(y, 판정(확률))
    return tp / (tp + fn) if (tp + fn) else 0.0


