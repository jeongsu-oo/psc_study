# ----------------------------------------
# MLP 순전파·역전파 - 과정4 회수
# ----------------------------------------

# 과정4에서 손으로 짠 그 MLP 를 그대로 가져옵니다. 은닉층을 하나 두면
# sigmoid 곡선들이 겹쳐 '휘는 경계' 를 그릴 수 있어요 — 직선이 못 하던 그 일.
#
#   순전파 :  A = sigmoid(X·W + b)      은닉층 출력 (n×은닉)
#             p = sigmoid(A·V + c)      최종 '불량일 확률' (n×1)
#   손실   :  BCE = -(1/n)Σ[y·log p + (1-y)·log(1-p)]   (분류 손실)
#   역전파(과정4 결과, 뒤→앞) :
#             출력오차 dlogit = (p - y)/n     ← sigmoid+BCE 라 이렇게 깔끔
#             dV = Aᵀ·dlogit,  dA = dlogit·Vᵀ,  dZ = dA ⊙ A(1-A)
#             dW = Xᵀ·dZ                       (⊙ 은 자리끼리 곱)

def 순전파(X, W, b, V, c):
    A = sigmoid(X @ W + b)   # (n×은닉)  은닉층 출력 (휘어짐)
    p = sigmoid(A @ V + c)   # (n×1)     최종 불량 확률
    return p, A              # A 는 역전파에서 재사용

def BCE손실(p, Y):
    eps = 1e-9               # log(0) 방지용 아주 작은 값
    return -np.mean(Y * np.log(p + eps) + (1 - Y) * np.log(1 - p + eps))

# 역전파는 학습 루프(MLP학습) 안에 인라인으로 두겠습니다 — 한자리에서 흐름을
# 보는 게 배우기 쉬워서예요. 정규화(가중치 벌점)는 dW, dV 에 lam·(가중치) 를
# 더해 처리합니다(가중치가 크면 그만큼 더 깎여 = 과하게 매달리는 걸 누름).

def MLP학습(Z, y, 은닉수=8, lr=0.5, epochs=3000, lam=0.0, 로그=False):
    Y = y.reshape(-1, 1).astype(float)
    n, d = Z.shape

    np.random.seed(0)                  # 시드 고정 → 재현성 (출력이 매번 동일)
    W = np.random.randn(d, 은닉수) * 0.5    # (입력×은닉) 입력→은닉
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5    # (은닉×1) 은닉→출력
    c = np.zeros((1, 1))

    for epoch in range(epochs):
        p, A = 순전파(Z, W, b, V, c)               # 확률 예측 한 번
        dlogit = (p - Y) / n
        dV = A.T @ dlogit + lam * V                # ← 정규화: 가중치 벌점
        dc = dlogit.sum(axis=0, keepdims=True)
        dZ = (dlogit @ V.T) * A * (1 - A)
        dW = Z.T @ dZ + lam * W                    # ← 정규화: 가중치 벌점
        db = dZ.sum(axis=0, keepdims=True)
        W -= lr * dW; b -= lr * db                 # 갱신 (한 스텝)
        V -= lr * dV; c -= lr * dc
        if 로그 and epoch % 500 == 0:
            print(f"  epoch {epoch:5d}   BCE손실 {BCE손실(순전파(Z,W,b,V,c)[0], Y):.4f}")
    if 로그:
        print(f"  epoch {epochs:5d}   BCE손실 {BCE손실(순전파(Z,W,b,V,c)[0], Y):.4f}")
    return (W, b, V, c)

def MLP확률(Z, 모델):
    W, b, V, c = 모델
    p, _ = 순전파(Z, W, b, V, c)
    return p.ravel()


