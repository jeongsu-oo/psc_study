# 강사가 몇 개 조합을 봤습니다. 이제 여러분 차례 —
# lr 이나 lam 을 더 넓게 흔들어 보고, val 이 어떻게 반응하는지 관찰하세요.
# 특히 lr 을 아주 크게(예: 5.0) 주면 발산해서 되레 나빠지는 걸 볼 수 있어요.
#
#   Step 1) lr 후보를 넓게 정한다 (예: 0.1, 0.5, 2.0, 5.0)  ← 아래 정답 예시
#   Step 2) for 로 각 lr 에서 MLP학습 → val 정확도
#   Step 3) 표로 보고 "너무 작으면 느리고, 너무 크면 발산" 을 확인
#   완료 기준 : lr 별 val 정확도가 표로 나오고, 적당한 lr 이 최고임을 확인하면 성공.

# (실습 정답 예시)
print("\n[실습 · lr 을 넓게 흔들기]  (은닉8·epochs3000 고정)")
print("     lr    val정확도")
for lr in [0.1, 0.5, 2.0, 5.0]:
    m = MLP학습(Z_tr, y_tr, 은닉수=8, lr=lr, epochs=3000)
    print(f"   {lr:4}    {정확도(y_va, MLP확률(Z_va, m)):.3f}")
# → [실습 · lr 을 넓게 흔들기]  (은닉8·epochs3000 고정)
# →      lr    val정확도
# →     0.1    0.917
# →     0.5    0.917
# →     2.0    0.917
# →     5.0    0.950

# 0.1~2.0 은 다 0.917 로 잘 수렴합니다. 이 데이터에선 lr 에 크게 안 민감했어요.
# 5.0 에서 0.950 이 나오긴 하지만, 이렇게 큰 보폭은 데이터가 조금만 달라도 튀기
# 쉬워요(발산 위험) — 운 좋게 잘 맞은 것에 가깝습니다. 보통은 적당한 값(0.5~2.0)에서
# 안정적으로 고릅니다. 교훈: lr 은 '적당히'. 작으면 느리고 너무 크면 튄다.


