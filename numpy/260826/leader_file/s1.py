"""[수백 개의 값을, 왜 몇 개 숫자로 줄일까요?]
설비 한 대에서 하루 온도를 재면 값이 수백 개, 여러 설비를 며칠
돌리면 수천 수만 개로 불어납니다. 이 숫자를 그대로 늘어놓아서는
설비 상태를 알 수 없어요. 사람 눈은 수백 개 숫자를 한 번에 못 읽으니까요.

그래서 많은 값을 몇 개의 '대표 숫자'로 압축합니다. 이걸 요약이라고 해요.
요약은 딱 세 물음에 답하는 일입니다.
  - 중심   : 값들이 대개 어디쯤 모여 있나?      (평균, 중앙값)
  - 흩어짐 : 중심 주위에 촘촘한가 넓게 퍼졌나?  (범위, IQR, 표준편차)
  - 이상치 : 유난히 튀는 값은 없나?             (z-score)

요약이 없으면 비교도 판단도 없습니다. 두 설비를 견주려면 원본 수천 개가
아니라 대표 숫자 몇 개를 나란히 놓아야 하죠.
이 파일은 그 요약 도구들을 위에서 아래로 훑으며 하나씩 익힙니다.

이번 단원은 '수학이 실제로 있는' 구간입니다. 겁내지 마세요.
직관을 먼저 잡고, 그다음 공식은 참고용 한 줄만 주석에 남깁니다.
값은 전부 numpy 함수가 계산해 주니, 우리는 결과를 '읽는' 데 집중합니다.
(공식을 밑바닥부터 손으로 재구현하는 건 뒤의 파트13에서 다룹니다.)
"""

# numpy는 np 라는 별칭으로 부르는 것이 전 세계 관례입니다.
# 다르게 쓰지 마세요. 남의 코드를 읽을 때 소통이 안 됩니다.
import numpy as np


# ----------------------------------------
# 중앙값 - 크기순으로 놓았을 때 '한가운데' 값
# ----------------------------------------

"""[중심을 재는 방법이 평균 하나뿐일까요?]
데이터의 중심을 말할 때 가장 먼저 떠올리는 건 평균입니다.
그런데 중심을 짚는 방법이 평균 하나만은 아니에요.
값을 크기순으로 줄 세웠을 때 딱 한가운데에 오는 값,
이것도 훌륭한 중심입니다. 이 값이 '중앙값'(median)이죠.

평균은 배열에 점을 찍어 temps.mean() 으로 불렀지만,
median 은 np.median(temps) 형태로 씁니다. (np. 뒤에 배열을 넣기)
"""

temps = np.array([82, 85, 84, 86, 83, 88])
print("중앙값(짝수 개):", np.median(temps))   # → 중앙값(짝수 개): 84.5
# 크기순으로 놓으면 82, 83, 84, 85, 86, 88.
# 값이 '짝수 개'라 딱 가운데가 없으니, 가운데 두 값(84와 85)의 평균 84.5.

odd = np.array([75, 82, 88, 91, 95])
print("중앙값(홀수 개):", np.median(odd))     # → 중앙값(홀수 개): 88.0
# 값이 '홀수 개'면 딱 가운데 하나가 그대로 나옵니다. 세 번째 값 88.


# ----------------------------------------
# 평균 vs 중앙값 - 이상치가 하나 섞이면?
# ----------------------------------------

"""[왜 중심을 재는 대표값이 두 개나 필요할까요?]
평균과 중앙값이 크게 갈라지는 상황을 직접 만들어,
각각이 언제 쓸모 있는지 눈으로 확인해 보겠습니다.
핵심은 '이상치'(튀는 값 하나)에 두 값이 어떻게 반응하는가입니다.
"""

# 깨끗한 온도 여섯 값 - 평균과 중앙값이 거의 겹칩니다.
clean = np.array([82, 85, 84, 86, 83, 88])
print("깨끗한 값 - 평균:", clean.mean())        # → 깨끗한 값 - 평균: 84.66666666666667
print("깨끗한 값 - 중앙값:", np.median(clean))   # → 깨끗한 값 - 중앙값: 84.5
# 둘이 84.7 근처로 가까워요. 데이터가 고르게 퍼져 있다는 뜻이죠.

# 마지막 값을 999로 바꿔 '이상치'를 하나 심어 봅니다. (센서 접촉 불량 같은 상황)
bad = np.array([82, 85, 84, 86, 83, 999])
print("999 섞임 - 평균:", bad.mean())        # → 999 섞임 - 평균: 236.5
print("999 섞임 - 중앙값:", np.median(bad))   # → 999 섞임 - 중앙값: 84.5

# 여기가 핵심입니다.
#   평균은 84.7 → 236.5 로 크게 튀어 올랐습니다.
#     999가 합에 통째로 더해지니 평균이 그쪽으로 '끌려간' 거죠.
#   중앙값은 84.5 그대로입니다.
#     크기순으로 세우면 999는 맨 끝으로 밀릴 뿐, 한가운데를 차지하지 못하니까요.
#
# 정리:
#   - 평균   : 모든 값을 계산에 넣음  → 이상치에 '민감'(약함)
#   - 중앙값 : 순서만 봄             → 이상치에 '강함'
#   두 값이 크게 벌어지면 = 데이터 어딘가에 이상치가 숨어 있다는 '신호'!


# ----------------------------------------
# 분위수 - '하위 몇 퍼센트' 지점의 값
# ----------------------------------------

"""[알고 싶은 지점이 꼭 한가운데만은 아닙니다]
중앙값은 데이터를 정확히 반으로 가르는 '하위 50% 지점'이었죠.
그런데 하위 25%는 어디인지, 상위 10%에 드는 값은 얼마부터인지가
궁금할 때가 있습니다. 이렇게 하위 몇 퍼센트 지점의 값을 뽑는 것이
'분위수'(percentile)입니다.

값을 작은 것부터 큰 것까지 줄 세운 뒤 100 등분한다고 상상하세요.
np.percentile(배열, 백분위숫자) 로 그 지점 값을 뽑습니다.
"""

scores = np.array([70, 74, 78, 80, 82, 86, 90, 96])
print("50% 지점:", np.percentile(scores, 50))   # → 50% 지점: 81.0
# 50을 넣으면 한가운데 지점 → 중앙값과 같은 뜻입니다.

print("90% 지점:", np.percentile(scores, 90))   # → 90% 지점: 91.8
# 하위 90% 지점 = 상위 10%가 시작되는 경계.
# 이 값(91.8)보다 큰 값은 전체의 10%뿐이라는 뜻이죠.
#
# 평균·중앙값이 '중심 한 점'을 말한다면,
# 분위수는 데이터를 따라 '원하는 위치'의 값을 자유롭게 뽑아냅니다.


# ----------------------------------------
# 사분위수 Q1·Q3 와 IQR
# ----------------------------------------

"""[분위수 중 실무가 가장 자주 쓰는 것]
데이터를 넷으로 나누는 사분위수입니다. 크기순 줄을 사등분하면
세 경계가 생기죠.
  - 하위 25% 지점 = 1사분위수 Q1
  - 하위 50% 지점 = 중앙값
  - 하위 75% 지점 = 3사분위수 Q3
Q3에서 Q1을 뺀 폭을 IQR(사분위 범위)이라 부릅니다.
  수식(참고): IQR = Q3 - Q1
"""

q1 = np.percentile(scores, 25)
q3 = np.percentile(scores, 75)
print("Q1(하위 25%):", q1)     # → Q1(하위 25%): 77.0
print("Q3(하위 75%):", q3)     # → Q3(하위 75%): 87.0
print("IQR = Q3 - Q1:", q3 - q1)   # → IQR = Q3 - Q1: 10.0

# IQR이 뜻하는 것 = '가운데 50%'의 값들이 흩어진 폭.
# 양 끝 극단을 뺀 중간 절반이 얼마나 넓게 퍼졌는지를 한 숫자로 말해 줍니다.
#
# 중요: IQR은 Q1·Q3라는 '순서상 위치'로만 계산됩니다.
#       그래서 양 끝 이상치에 흔들리지 않아요.
#       이상치가 섞인 데이터의 흩어짐은 표준편차보다 IQR이 더 믿을 만합니다.


# ----------------------------------------
# 데이터 범위 - max에서 min까지 '전체 폭'
# ----------------------------------------

# 데이터가 얼마나 흩어졌는지를 재는 가장 단순한 방법은 양 끝을 보는 겁니다.
# 가장 큰 값 - 가장 작은 값 = 전체 범위. 앞서 익힌 max, min을 그냥 빼면 끝.
#   수식(참고): 범위 = max - min

print("범위(전체 폭):", scores.max() - scores.min())   # → 범위(전체 폭): 26
# max는 96, min은 70이니 범위는 26. 이 데이터가 70~96 사이, 폭 26 안에 흩어짐.
#
# 주의: 범위는 양 끝 값 딱 '두 개'에만 의존해 이상치에 약합니다.
#       999가 섞이면 범위가 900대로 튀어, 촘촘한 데이터를 넓게 퍼진 것처럼 보이게 하죠.
#       그래서 전체 폭(범위)과 가운데 절반 폭(IQR)을 '함께' 봅니다.
#       범위가 IQR보다 유난히 크면 = 양 끝에 극단값이 있다는 신호.


# ----------------------------------------
# 여기까지 대표값 지도 - 세 갈래로 정리
# ----------------------------------------

# 지금까지 본 도구들을 한 장의 지도 위에 올려 봅니다.
# 이 지도가 앞으로 데이터를 만날 때마다 꺼내 쓸 판단표가 됩니다.
#
#   대표값 지도
#     ├─ 중심 : 평균, 중앙값     → 데이터가 대개 어디에 모였나
#     │          (평균=이상치 약함 / 중앙값=이상치 강함)
#     ├─ 위치 : 분위수 Q1, Q3    → 사분면 경계가 어디부터인가
#     └─ 폭   : 범위, IQR        → 전체와 가운데 절반이 얼마나 퍼졌나
#                (범위=이상치 약함 / IQR=이상치 강함)
#
# 이 지도를 관통하는 하나의 축 = '이상치에 강한가 약한가'.
# 실무에선 대개 두 종류(약한 것·강한 것)를 나란히 구해 갈라짐을 살핍니다.


# ----------------------------------------
# 표준편차의 의미 - 평균에서 '퍼진 정도'
# ----------------------------------------

"""[표준편차, 이 숫자가 정확히 무슨 뜻일까요?]
범위와 IQR이 '양 끝·사분면'으로 흩어짐을 쟀다면,
표준편차(std)는 '평균을 기준'으로 흩어짐을 잽니다.
각 값이 평균에서 평균적으로 얼마나 떨어졌는지의 크기죠.

  직관 : 표준편차 = 평균에서 데이터가 '평균적으로 떨어진 정도'
  수식(참고) : σ = √( Σ(x - 평균)² / n )
        각 값에서 평균을 빼고(떨어진 거리), 제곱해 더하고, 개수로 나눈 뒤,
        제곱근을 씌운 것. 손으로 하면 길지만 std 한 줄이면 끝입니다.
        (밑바닥 재구현은 파트13에서 직접 만듭니다. 여기선 도구를 씁니다.)
"""

print("표준편차 std:", scores.std())   # → 표준편차 std: 7.937253933193772
print("분산 var:", scores.var())       # → 분산 var: 63.0
# 값들이 평균에서 평균적으로 약 7.94만큼 떨어져 있다는 뜻.
#   std가 작으면 → 평균 근처에 모여 안정적
#   std가 크면   → 넓게 퍼져 불안정
# 분산 var(=63)는 표준편차를 '제곱'한 값이라 더 큽니다.
#
# 표준편차가 특별한 이유: 원래 값과 '같은 단위'를 씁니다.
#   온도의 표준편차는 '도' 단위로 나와 "평균에서 약 8도쯤 흩어졌다"처럼 곧바로 이해돼요.
# 이 표준편차가 곧 나올 정규분포에서 '폭을 나누는 눈금'이 되고, z-score의 바탕이 됩니다.


# ----------------------------------------
# 정규분포 - 자연에서 가장 흔한 '종모양'
# ----------------------------------------

"""[측정 데이터는 대개 어떤 '모양'으로 퍼질까요?]
값들을 크기별로 나눠 각 구간에 몇 개씩 있는지 세어 그리면
데이터의 '모양'이 드러납니다. 그런데 측정 데이터의 상당수가
하나의 공통된 모양을 보여요.
가운데가 가장 높고 양옆으로 갈수록 낮아지는 좌우 대칭 '종모양'.
이게 정규분포입니다.

왜 종모양일까요? 대부분의 측정값은 '평균적인 상태' 근처에서
자잘하게 변동하기 때문입니다. 설비 온도를 여러 번 재면 평균 근처에
값이 몰리고, 아주 높거나 낮은 값은 드물게만 나오죠.
사람 키, 시험 점수, 제품 치수 오차도 이 종모양을 따릅니다.

    빈도
     │        ▁▄█▄▁
     │      ▁█████████▁
     │    ▁███████████████▁
     └──────────┼──────────── 값
             평균(꼭대기)

정규분포가 특별한 이유: 평균과 표준편차 '두 숫자'만으로 모양이 완전히 정해집니다.
  - 평균     → 종의 꼭대기 '위치'
  - 표준편차 → 종의 '폭' (작으면 좁고 뾰족, 크면 넓고 완만)

평균이 같아도 표준편차가 다르면 전혀 다른 종이 됩니다.

    표준편차 작음(안정)          표준편차 큼(불안정)
           ▁█▁                      ▁▄▄▁
          ▁███▁                  ▁▄██████▄▁
        ▁███████▁            ▁▄██████████████▄▁
      ─────┼─────           ────────┼────────
         평균 85도                평균 85도
      값이 82~88도에         값이 70~100도까지
      촘촘히 모임             넓게 퍼짐

둘 다 "평균 85도"인 설비지만 상태는 전혀 다르죠.
왼쪽은 늘 85도 언저리인 안정된 설비, 오른쪽은 오르내림이 심한 설비입니다.
평균만 보면 이 차이가 안 보입니다. 표준편차를 '함께' 봐야 하는 이유예요.
"""

# 주의: 모든 데이터가 종모양인 건 아닙니다.
#   한쪽으로 꼬리가 길게 늘어진 데이터도 흔해요.
#   (고장까지 걸린 시간, 대기 시간, 소득처럼 '대부분 작고 가끔 아주 큰' 값들)
#   종모양에서 멀어지면 바로 아래 68-95-99.7 규칙과 z-score의 정확도도 떨어집니다.
#
#   간단한 확인법 - 앞에서 배운 도구를 그대로 씁니다.
#     평균과 중앙값이 비슷하다  → 좌우 대칭에 가깝다 (종모양일 가능성 높음)
#     크게 벌어졌다             → 한쪽으로 치우쳤거나 이상치가 있다
#   그래서 mean과 median을 늘 함께 구하는 습관이 여기서도 쓸모가 있어요.


# ----------------------------------------
# 68-95-99.7 규칙 - 종 아래 값이 얼마씩 나뉘나
# ----------------------------------------

# 정규분포는 평균과 표준편차로 정해진다고 했죠.
# 그렇다면 '평균에서 표준편차 몇 칸 떨어진 구간'에 값이 얼마나 들어 있는지도 정해집니다.
# 이걸 알려 주는 게 68-95-99.7 규칙이에요. (σ = 표준편차 한 칸)
#
#   ±1σ 안 (좌우 한 칸)   → 약 68%  가 들어옴
#   ±2σ 안 (좌우 두 칸)   → 약 95%  가 들어옴
#   ±3σ 안 (좌우 세 칸)   → 약 99.7% 가 들어옴
#
# 예) 평균 85도, 표준편차 5도인 설비라면
#   80~90도 사이  = ±1σ = 약 68%
#   75~95도 사이  = ±2σ = 약 95%
#   70~100도 사이 = ±3σ = 약 99.7%
#
# 이 규칙이 강력한 이유: 어떤 값이 얼마나 '이례적'인지 판단하는 기준을 줍니다.
#   표준편차 3배(3σ) 밖의 값은 0.3%뿐 → 그런 값이 나오면 정상 변동이 아니라
#   '이상값'일 가능성이 높다고 볼 수 있죠. 이 발상이 곧 나올 z-score의 핵심입니다.


# ----------------------------------------
# 표준화(z-score) - 값을 '평균에서 몇 σ 떨어졌나'로 바꾸기
# ----------------------------------------

"""[종모양 눈금에서 값이 '몇 칸'에 놓이나 - 그걸 숫자로]
앞의 종모양에서 값이 눈금 몇 칸에 놓이는지가 이례성을 말해 준다고 했죠.
이 '몇 칸'을 그대로 숫자로 만든 것이 z-score, 곧 표준화입니다.

  직관 : z-score = 이 값이 평균에서 '표준편차 몇 배(몇 칸)' 떨어졌나
  수식(참고) : z = (x - 평균) / 표준편차
        평균을 빼면 '얼마나 떨어졌나'가 나오고,
        표준편차로 나누면 그게 '표준편차 몇 배'인지로 바뀝니다.

읽는 법:
  z = 0   → 정확히 평균
  z = +1  → 표준편차 한 칸 '위',   z = -1 → 한 칸 '아래'
  부호 = 평균보다 위/아래,  크기 = 몇 칸 떨어졌나
68-95-99.7과 이어져: |z| 1 안이면 흔한 값, 2 넘으면 드문 값, 3 넘으면 아주 이례적.
"""

t = np.array([80, 84, 88, 92, 96])
z = (t - t.mean()) / t.std()   # 벡터 연산 한 줄로 배열 전체가 표준화됨 (for 없이!)
print("z-score:", z)           # → z-score: [-1.41421356 -0.70710678  0.          0.70710678  1.41421356]
# 평균값 88이 정확히 0, 작은 값은 음수, 큰 값은 양수.
# 가장 작은 80은 -1.41, 가장 큰 96은 +1.41.

print("z의 평균, 표준편차:", z.mean(), z.std())   # → z의 평균, 표준편차: 0.0 0.9999999999999999
# 표준화가 제대로 됐는지 확인 → 평균 0, 표준편차 1(부동소수라 0.9999...로 보임).
# 어떤 배열이든 표준화하면 '평균 0, 표준편차 1'이라는 같은 눈금으로 통일됩니다.
# (이 뺄셈·나눗셈이 왜 이례성 눈금이 되는지, 밑바닥 원리는 파트13에서 손으로 만듭니다.)


# ----------------------------------------
# 표준화의 쓸모 - 단위가 다른 센서 '비교하기'
# ----------------------------------------

"""[92도와 34mm/s 중 어느 쪽이 더 이상할까요?]
z-score의 진짜 쓸모는 '단위가 다른' 데이터를 비교할 수 있게 해 준다는 겁니다.
설비에는 온도(도), 진동(mm/s)처럼 단위가 제각각인 센서가 여럿 붙어 있죠.
"지금 어느 센서가 가장 이상한가?"를 물으면, 단위가 달라 원래 값으로는 비교가 안 됩니다.
온도 92도와 진동 34mm/s는 92와 34만 봐서는 우열을 알 수 없어요.

각각 자기 기준으로 표준화하면 둘 다 "자기 평균에서 표준편차 몇 배"라는
'같은 눈금' 위의 숫자가 됩니다. 그제야 비교가 됩니다.
"""

temp = np.array([80, 84, 88, 92, 96])   # 온도 (도)
vib = np.array([28, 30, 32, 34, 36])    # 진동 (mm/s)
zt = (temp - temp.mean()) / temp.std()
zv = (vib - vib.mean()) / vib.std()
print("네 번째 시점 - 온도 z, 진동 z:", zt[3], zv[3])   # → 네 번째 시점 - 온도 z, 진동 z: 0.7071067811865475 0.7071067811865475
# 원래 값은 92와 34로 전혀 다르지만, 각자의 분포에서 차지하는 위치는
# 똑같이 "평균보다 표준편차 0.71배 위". 표준화가 '단위를 지우고' 이례성만 남긴 거죠.
#
# 여러 센서를 모두 z-score로 바꾸면 그 시점에 '어느 센서가 가장 튀는지' 곧바로 비교됩니다.
# 온도 z가 +0.5인데 진동 z가 +2.8이면 → 문제는 진동 쪽이라는 게 한눈에 보이죠.


# ----------------------------------------
# 배열의 형상(shape) - 이 배열은 몇 행 몇 열인가
# ----------------------------------------

"""[센서가 열 개, 백 개라면 눈으로 비교할 수 있을까요?]
방금은 온도 z와 진동 z를 따로 구해 눈으로 견줬습니다.
센서가 둘이라 가능했지, 열 개 백 개면 그렇게 못 하죠.
여러 센서의 z를 '한 덩어리'로 쌓아 한 번에 다뤄야 합니다.

배열을 쌓는 순간 늘 따라붙는 물음이 '이건 몇 줄 몇 칸짜리인가'입니다.
그 크기를 알려 주는 것이 형상(shape)이에요.
  - shape : (행 개수, 열 개수) 를 알려 줌
  - ndim  : 몇 차원인가 (한 줄이면 1, 표면 2)
형상은 계산의 '치수'입니다. 치수가 안 맞으면 계산 자체가 거부돼요.
"""

temp2 = np.array([84, 85, 86, 92, 85])   # 온도(도)   - 네 번째 시점만 급등
vib2 = np.array([31, 30, 32, 31, 33])    # 진동(mm/s) - 대체로 잔잔

print("한 줄 배열의 형상:", temp2.shape)   # → 한 줄 배열의 형상: (5,)
# (5,) 는 "값 다섯 개가 한 줄"이라는 뜻. 쉼표 뒤가 비어 있는 게 1차원의 표시입니다.

# 각 센서를 자기 기준으로 표준화한 뒤 두 줄로 쌓습니다.
zt2 = (temp2 - temp2.mean()) / temp2.std()
zv2 = (vib2 - vib2.mean()) / vib2.std()
zs = np.array([zt2, zv2])                 # 첫 행 = 온도 z, 둘째 행 = 진동 z

print("쌓은 배열의 형상:", zs.shape)   # → 쌓은 배열의 형상: (2, 5)
print("차원 ndim:", zs.ndim)           # → 차원 ndim: 2

# np.round(배열, 자릿수) = 소수점을 잘라 보기 좋게. 값 자체를 바꾸는 게 아니라
# '보여 줄 때만' 줄이는 용도예요. z-score는 소수가 길어 이걸 자주 씁니다.
print("온도 z:", np.round(zt2, 2))   # → 온도 z: [-0.84 -0.49 -0.14  1.95 -0.49]
print("진동 z:", np.round(zv2, 2))   # → 진동 z: [-0.39 -1.37  0.59 -0.39  1.57]
#
# 이 두 줄을 쌓은 zs 의 형상이 (2, 5) 입니다.
#   (2, 5) = 센서 2개(행) × 시점 5개(열). 항상 (행, 열) 순서로 읽습니다.
#
#            시점0    1     2     3     4
#   온도z [ -0.84 -0.49 -0.14  1.95 -0.49 ]   ← 행 0
#   진동z [ -0.39 -1.37  0.59 -0.39  1.57 ]   ← 행 1
#
# 네 번째 시점(자리 3)에서 온도 z가 1.95로 홀로 솟았죠. 온도만 급등한 시점입니다.
#
# 주의: (5,) 와 (1, 5) 는 다른 형상입니다.
#       앞은 '한 줄', 뒤는 '1행 5열짜리 표'. 값은 같아도 모양이 달라
#       뒤에 나올 행렬곱에서 결과 형상이 갈립니다.


# ----------------------------------------
# 가중치와 가중합 - 센서마다 '몫'을 다르게 주기
# ----------------------------------------

"""[센서 둘의 점수를 하나로 합칠 때, 그냥 평균이면 될까요?]
표를 만들었으니 "지금 이 설비, 얼마나 이상한가"를 시점마다 숫자 하나로
말하고 싶습니다. 가장 쉬운 방법은 두 z의 평균이겠죠.
그런데 평균은 온도와 진동을 '똑같이 중요하다'고 취급하는 셈입니다.

베어링이 먼저 망가지는 설비라면 진동이 더 결정적이고,
과열이 먼저 터지는 설비라면 온도가 더 결정적이죠.
중요도가 다른데 똑같이 세면 정작 중요한 신호가 묻힙니다.

그래서 센서마다 '몫'을 다르게 줍니다. 이 몫이 가중치(weight)예요.
  - 가중치 : 각 값을 얼마나 무겁게 칠지 정한 숫자
  - 가중합 : 각 값에 자기 가중치를 곱해서 전부 더한 것

  가중합 = (가중치1 × 값1) + (가중치2 × 값2) + ...

관례상 가중치의 합은 1로 맞춥니다. 그래야 '전체 100%를 어떻게 나눠 줬나'로
읽히고, 결과도 원래 값들과 비슷한 크기로 나와 비교하기 편해요.
  온도 0.7 + 진동 0.3 = 1  → "온도에 70%, 진동에 30%의 비중"
"""

# 네 번째 시점(자리 3) 하나만 손으로 해 봅니다.
print("자리 3의 온도 z, 진동 z:", round(zt2[3], 3), round(zv2[3], 3))
# → 자리 3의 온도 z, 진동 z: 1.951 -0.392
print("가중합(0.7, 0.3):", round(0.7 * zt2[3] + 0.3 * zv2[3], 3))
# → 가중합(0.7, 0.3): 1.248
#   0.7 × 1.951 = 1.366
#   0.3 × (-0.392) = -0.118
#   1.366 + (-0.118) = 1.248
# 온도가 크게 튀었고 그 온도에 70%를 줬으니 종합 점수도 높게 나왔죠.
#
# 가중치를 똑같이(0.5, 0.5) 주면 어떻게 될까요?
print("가중합(0.5, 0.5):", round(0.5 * zt2[3] + 0.5 * zv2[3], 3))
# → 가중합(0.5, 0.5): 0.779
print("두 z의 그냥 평균:", round((zt2[3] + zv2[3]) / 2, 3))
# → 두 z의 그냥 평균: 0.779
# 둘이 똑같습니다. 즉 '그냥 평균'은 가중치를 균등하게 준 가중합의 한 경우예요.
# 가중합은 평균을 포함하면서, 중요도를 조절할 수 있게 넓힌 것입니다.
#
# 가중치는 데이터가 정해 주지 않습니다. 현장이 정합니다.
# 어느 센서가 고장을 먼저 알리는지 아는 사람이 몫을 나눠 주는 자리예요.

# 문제: 시점이 다섯 개니 위 손계산을 다섯 번 되풀이해야 합니다.
#       센서 열 개, 시점 천 개면? 이 되풀이를 없애는 게 다음의 행렬곱입니다.


# ----------------------------------------
# 행렬곱(@) - 가중합을 한 줄로
# ----------------------------------------

"""[가중합을 모든 시점에 한꺼번에 걸 수 없을까요?]
방금 한 손계산 - '짝지어 곱해서 전부 더하기'.
이것을 모든 시점에 대해 한 번에 해 주는 연산이 행렬곱입니다.

  직관 : 행렬곱 = '한 줄과 한 줄을 짝지어 곱해 더하기'를 모든 조합에 한꺼번에
  기호 : @   (파이썬의 행렬곱 전용 기호. np.matmul(a, b) 라고 써도 같습니다)
  주의 : *  는 행렬곱이 아니라 '같은 자리끼리 곱셈'입니다. 완전히 다른 연산이에요.

행렬곱이 왜 가중합인지는 그림으로 보면 바로 보입니다.

   가중치        센서 점수표(zs)                 결과
  [0.7 0.3]  @  [ -0.84 -0.49 -0.14  1.95 -0.49 ]  =  [ ... ... ... 1.248 ... ]
                [ -0.39 -1.37  0.59 -0.39  1.57 ]
                                └── 자리 3 열 ──┘        └─ 자리 3 결과 ─┘

  가중치 한 줄이 표의 각 '열'과 짝을 지어, 0.7×(윗값) + 0.3×(아랫값) 을 합니다.
  열이 다섯 개니 그 계산이 다섯 번 일어나고, 결과도 다섯 개가 나옵니다.
"""

w = np.array([0.7, 0.3])   # 온도에 0.7, 진동에 0.3 - 몫의 합은 1
score = w @ zs             # 가중치 한 줄 @ 센서 점수표
print("시점별 종합 이상 점수:", np.round(score, 3))
# → 시점별 종합 이상 점수: [-0.703 -0.753  0.079  1.248  0.129]
# 자리 3의 값 1.248 - 위에서 손으로 구한 그 숫자와 정확히 같습니다.
# 손계산 다섯 번이 @ 한 글자로 끝난 거죠.

# np.argmax(배열) = 가장 큰 값이 '몇 번째 자리'에 있는지 알려 줍니다.
#   (값 자체가 아니라 '위치'를 준다는 점에 주의. 값은 배열[그 위치]로 꺼냅니다.)
print("가장 이상한 시점:", np.argmax(score))   # → 가장 이상한 시점: 3
# 자리 3(네 번째 시점)이 1.248로 홀로 높습니다.
# 센서 두 줄짜리 표가 시점 다섯 개의 점수 한 줄로 압축돼, 한눈에 답이 나왔어요.


# ----------------------------------------
# 행렬곱의 형상 규칙 - 안쪽 숫자가 같아야 한다
# ----------------------------------------

# 행렬곱은 아무 두 배열에나 되는 게 아닙니다. 형상이 맞아야 해요.
#
#   (m, n) @ (n, p)  →  (m, p)
#        └───┬───┘
#       안쪽 두 숫자가 같아야 계산됨. 결과는 바깥 두 숫자.
#
# 왜 안쪽이 같아야 할까요? '짝지어 곱해 더하기'를 하려면
# 왼쪽이 내놓는 값의 개수와 오른쪽이 받는 값의 개수가 맞아야 하기 때문입니다.
# 가중치가 둘인데 센서가 셋이면 짝이 하나 남아 계산이 성립하지 않죠.
#
# 위 예로 확인하면
#   w 는 (2,)     ← 값 두 개 (센서 두 개의 몫)
#   zs 는 (2, 5)  ← 센서 2 × 시점 5
#   안쪽이 2와 2로 같으니 계산됨 → 결과는 남은 5, 즉 (5,)
print("w 형상:", w.shape, " zs 형상:", zs.shape, " 결과 형상:", score.shape)
# → w 형상: (2,)  zs 형상: (2, 5)  결과 형상: (5,)
# 맞물린 2가 사라지고 시점 5만 남았습니다. 형상만 봐도 무슨 일이 났는지 읽히죠.
#
# 형상이 안 맞으면? 가중치를 셋으로 주면 (3,) @ (2, 5) 가 되어
# 안쪽이 3과 2로 어긋납니다. 이때 numpy는 계산을 멈추고 ValueError를 냅니다.
#   ValueError: matmul: Input operand 1 has a mismatch in its core dimension ...
# 조용히 틀린 답을 내지 않고 오류로 알려 주는 것 - 그래서 형상 확인이 안전장치예요.
# 행렬곱이 안 될 땐 늘 양쪽 shape부터 찍어 보세요. 원인의 대부분이 여기 있습니다.


# ----------------------------------------
# 흔한 실수 - @ 와 * 를 헷갈리기
# ----------------------------------------

# 두 기호는 생김새만 비슷할 뿐 하는 일이 전혀 다릅니다.
a = np.array([[1, 2], [3, 4]])
b = np.array([[10, 0], [0, 10]])

print("a @ b (행렬곱):")
print(a @ b)
# → [[10 20]
# →  [30 40]]
#   왼쪽 첫 행 [1, 2] 와 오른쪽 첫 열 [10, 0] 을 짝지어: 1×10 + 2×0 = 10
#   왼쪽 첫 행 [1, 2] 와 오른쪽 둘째 열 [0, 10] 을 짝지어: 1×0 + 2×10 = 20
#   이렇게 '곱해서 더하기'가 모든 행×열 조합에서 일어납니다.

print("a * b (자리별 곱):")
print(a * b)
# → [[10  0]
# →  [ 0 40]]
#   같은 자리끼리만 곱합니다. 1×10=10, 2×0=0, 3×0=0, 4×10=40. 더하기는 없어요.
#
#   @  : 행과 열을 짝지어 '곱해서 더함' → 여러 값을 하나로 합칠 때 (가중합·집계)
#   *  : 같은 자리끼리만 곱함, 형상 그대로 유지 → 값마다 배율을 걸 때
# 통계에서 '여러 지표를 가중치로 묶어 한 점수로' 만드는 자리엔 언제나 @ 입니다.


# ----------------------------------------
# 센서 데이터 요약 통계 - 재는 대상별로 한눈에
# ----------------------------------------

# 이번 시간에 배운 도구를 한 센서 데이터에 '모두' 걸어 보면
# 이들이 어떻게 협력하는지 드러납니다.
#
#   재는 대상 |  함수            |  알려 주는 것
#  ----------+------------------+------------------
#   중심     |  mean, median    |  어디에 모였나
#   위치     |  percentile      |  사분면 경계
#   폭       |  범위, IQR       |  얼마나 퍼졌나
#   흩어짐   |  std             |  평균에서 떨어짐
#   표준화   |  z-score         |  튀는 값 유무
#   형상     |  shape, ndim     |  배열이 몇 행 몇 열인가
#   종합     |  행렬곱 @        |  여러 센서 점수를 한 점수로

sensor = np.array([82, 86, 84, 88, 83, 90, 85, 87])   # 설비 M-101 온도 여덟 값
print("[센서 요약]")
print("  평균:", sensor.mean())                       # → 평균: 85.625
print("  중앙값:", np.median(sensor))                 # → 중앙값: 85.5
#   평균과 중앙값을 나란히 → 둘이 가까우면 고르고, 벌어지면 이상치 의심.
print("  Q1:", np.percentile(sensor, 25))             # → Q1: 83.75
print("  Q3:", np.percentile(sensor, 75))             # → Q3: 87.25
print("  IQR:", np.percentile(sensor, 75) - np.percentile(sensor, 25))   # → IQR: 3.5
print("  범위:", sensor.max() - sensor.min())         # → 범위: 8
#   범위가 IQR보다 유난히 크면 극단값 신호. (여기선 8 vs 3.5, 무난)
print("  표준편차:", sensor.std())                    # → 표준편차: 2.496873044429772
# 이 몇 개의 숫자만으로 "평균 85.6도 근처, 83~90 사이, 촘촘히 모임"이라는 그림이 그려집니다.


# ----------------------------------------
# 흔한 실수 - 이상치를 둔 채 '평균만' 믿기
# ----------------------------------------

# 노베이스가 가장 자주 저지르는 실수: 평균 하나만 믿는 것.
# 평균은 가장 익숙한 대표값이라 무심코 평균만 구해 데이터를 대표시키기 쉽죠.
# 그런데 평균은 이상치에 크게 끌려갑니다.

raw = np.array([82, 85, 84, 86, 83, 999])   # 접촉 불량으로 999가 하나 찍힌 온도 배열
print("[흔한 실수]")
print("  평균:", raw.mean())        # → 평균: 236.5
print("  중앙값:", np.median(raw))  # → 중앙값: 84.5
# 나머지 다섯 값은 모두 82~86 사이인데 평균은 236.5.
#   "이 설비 평균 온도는 236.5도"라고 보고하면 완전히 틀린 요약입니다.
#   이상치 하나가 평균을 엉뚱한 곳으로 끌고 간 거예요.
# 같은 데이터의 중앙값 84.5는 실제를 훨씬 잘 대표합니다.
#   평균 236.5와 중앙값 84.5가 크게 벌어진 것 자체가 이상치가 숨었다는 강력한 신호죠.
#
# 실무의 순서: 평균과 중앙값을 함께 구한다 → 크게 벌어지면 이상치를 의심한다
#            → 찾으면 걸러 내거나 따로 처리한 뒤 다시 요약한다.
# (이상치를 걸러 다루는 본격적인 이상 탐지는 이 파트 뒤쪽에서 z-score·IQR로 다룹니다.)


# ----------------------------------------
# 통계 요약 절차 - 낯선 데이터를 밟아 가는 다섯 단계
# ----------------------------------------

# 함수를 하나씩 아는 것과, 어떤 '순서'로 꺼내 쓸지 아는 것은 다릅니다.
# 낯선 센서 데이터를 만나면 이 다섯 단계로 훑으세요. (넓게 → 점점 가까이)
#
#   1) 배열 만들기   : np.array 로 배열부터 만든다 (통계 도구의 출발점)
#   2) 중심 보기     : mean + median 을 함께 → 벌어지면 이상치 냄새
#   3) 흩어짐 보기   : 범위(전체 폭) + IQR(가운데 절반) + std(평균 기준)
#   4) 분포 그리기   : 평균·표준편차를 종모양에 얹어 68-95-99.7로 정상 범위 가늠
#   5) 표준화        : z-score 로 각 값이 몇 σ 떨어졌나 → 튀는 값 찾기
#
# 마지막 5번 칸이 곧 '이상 감지'의 시작입니다.


# ----------------------------------------
# [실습] 센서 통계 요약
# ----------------------------------------

# 한 설비의 측정값 배열을 만들고, 위 다섯 단계를 차례로 적용해
# median·사분위수·z-score 로 데이터 성격을 요약해 봅니다.
#   케이스 A(온도) / 케이스 B(진동) - 하는 일은 같습니다.
#   케이스 B에는 유난히 튄 값이 하나 있으니 z-score로 찾아내 보세요.

# 케이스 B: 설비 M-102 진동 여덟 값 (mm/s) - 하나가 튐
vib_raw = np.array([30, 32, 31, 33, 30, 55, 32, 31])

print("[실습 - 진동 요약]")
# Step 1: 배열은 위에서 이미 만들었습니다.
# Step 2: 중심 + 흩어짐
print("  평균:", vib_raw.mean())            # → 평균: 34.25
print("  중앙값:", np.median(vib_raw))      # → 중앙값: 31.5
#   평균 34.25 vs 중앙값 31.5 → 벌어졌으니 이상치 의심!
print("  Q1:", np.percentile(vib_raw, 25))  # → Q1: 30.75
print("  Q3:", np.percentile(vib_raw, 75))  # → Q3: 32.25
print("  IQR:", np.percentile(vib_raw, 75) - np.percentile(vib_raw, 25))   # → IQR: 1.5
print("  범위:", vib_raw.max() - vib_raw.min())   # → 범위: 25
#   범위 25가 IQR 1.5보다 압도적으로 큼 → 양 끝에 극단값이 있다는 신호.

# Step 3: z-score로 가장 튀는 값 찾기
zv_raw = (vib_raw - vib_raw.mean()) / vib_raw.std()
print("  z-score:", zv_raw)
# → z-score: [-0.5378562  -0.2847474  -0.4113018  -0.158193   -0.5378562   2.62600379
# →  -0.2847474  -0.4113018 ]
print("  가장 튀는 값:", vib_raw[np.argmax(np.abs(zv_raw))])   # → 가장 튀는 값: 55
#   z가 +2.63으로 홀로 튄 값 = 55. |z|가 2를 훌쩍 넘으니 명백한 이상값이죠.
#   (np.argmax(np.abs(z)) = |z|가 가장 큰 값의 '위치'를 알려 줍니다.)

