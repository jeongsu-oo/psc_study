# NumPy 통계와 센서 데이터 - 이상 탐지와 종합
# -------------------------------


"""[무리 밖으로 튄 값, 어떻게 잡아내나요?]
지난 시간까지 배열을 통계로 요약하고(평균·표준편차),
두 센서가 함께 움직이는 관계까지 재는 데 왔습니다.

그런데 그 데이터 안에는 종종 '혼자 튀는 값'이 숨어 있어요.
온도가 하루 종일 83~86도를 오가는데 딱 하나가 125도라면,
그 하나가 평균을 끌어올려 요약을 뒤틀고,
동시에 냉각 장치 고장 같은 '신호'일 수도 있습니다.

이 파일은 그 튀는 값(이상값)을 규칙으로 자동으로 찾아내는
두 가지 방법(z-score, IQR)을 위에서 아래로 훑으며 익히고,
마지막에 여러 센서를 한 번에 보는 종합 분석까지 갑니다.
"""

# numpy는 np 라는 별칭으로 부르는 것이 전 세계 관례입니다.
# 다르게 쓰지 마세요. 남의 코드를 읽을 때 소통이 안 됩니다.
import numpy as np


# ----------------------------------------
# 이상값이란 - 무리 밖으로 튄 값
# ----------------------------------------

# 측정값 대부분은 서로 비슷한 범위에 모여 있습니다.
# 온도가 하루 종일 83~86도 사이를 오간다면 그 값들은 한 무리를 이루죠.
# 그 무리 속에 혼자 125도로 튀거나 30도로 뚝 떨어진 값 —
# 그게 '이상값' 입니다. 영어로 outlier, '무리 바깥으로 나간 값'이에요.
#
#   정상 무리                        이상값
#   83 84 85 86 85 84 ... 85 86      125   ← 혼자 저 위로 튐
#   └───── 좁은 띠에 옹기종기 ─────┘

# 이 파일 전체에서 쓸 온도 배열입니다. 설비 M-101의 온도 스무 값.
# 열아홉 개는 83~86도 무리에 모여 있고, 맨 끝 하나만 125도로 튀어 있어요.
temps = np.array([84, 86, 85, 83, 86, 85, 84, 86, 85, 83,
                  86, 84, 85, 86, 84, 86, 85, 83, 86, 125])
print("측정값 개수:", temps.size)   # → 측정값 개수: 20


# ----------------------------------------
# 이상값이 문제인 두 가지 이유
# ----------------------------------------

# 왜 굳이 이상값을 찾아야 할까요? 두 가지 이유가 있습니다.
#
#   1) 요약 왜곡 : 이상값 하나가 평균과 표준편차를 통째로 끌어당깁니다.
#                 대부분 85도인데 하나가 125도면 평균이 위로 끌려 올라가
#                 실제보다 높게 나오죠. 평균은 이상값에 약합니다.
#
#   2) 이상 신호 : 더 중요하게, 튀는 값 자체가 신호일 때가 많습니다.
#                 125도로 튀었다면 냉각 장치 고장·과부하·센서 접촉 불량 —
#                 어느 쪽이든 사람이 확인해야 할 사건이죠.
#                 이상값을 찾는다는 건 곧 설비 이상 징후를 찾는 일입니다.
#
#   3) 탐지 필요 : 값이 수백 개면 눈으로 하나씩 못 봅니다.
#                 '튀었다'를 숫자로, 규칙으로 정해 자동으로 골라내야 하죠.

# 이상값이 평균을 얼마나 끌어당기는지 눈으로 확인해 봅시다.
print("전체 평균:", round(temps.mean(), 2))          # → 전체 평균: 86.85
print("125 뺀 평균:", round(temps[:-1].mean(), 2))    # → 125 뺀 평균: 84.84
# 값 하나 차이로 평균이 2도나 움직입니다. 하나가 이렇게 셉니다.


# ==========================================================
#  방법 1 : z-score 기반 이상 탐지
# ==========================================================

# ----------------------------------------
# z-score - '평균에서 몇 σ 떨어졌나'
# ----------------------------------------

# '튀었다'를 숫자로 재려면 기준이 필요합니다.
# 지난 통계 심화에서 익힌 z-score가 그 기준이에요.
# z-score는 한 값이 '평균에서 표준편차 몇 배만큼' 떨어졌는지를 나타냅니다.
#
#   z = (x - 평균) / 표준편차       ← 참고용 수식 한 줄. 외우진 마세요.
#
# 0이면 딱 평균, 2면 표준편차 두 배만큼 위, -1이면 한 배만큼 아래죠.
# 배열 전체에 이 한 줄을 걸면 모든 값의 z-score가 한꺼번에 나옵니다.

z = (temps - temps.mean()) / temps.std()
print("z-score:", np.round(z, 2))
# → z-score: [-0.32 -0.1  -0.21 -0.44 -0.1  -0.21 -0.32 -0.1  -0.21 -0.44 -0.1  -0.32
# →  -0.21 -0.1  -0.32 -0.1  -0.21 -0.44 -0.1   4.33]

# 이게 이상 탐지에 딱 맞는 이유:
# 대부분의 값은 평균 근처라 z-score가 0 언저리에 모입니다.
# 그런데 혼자 크게 튄 이상값(125)은 평균에서 멀리 떨어져 z=4.33으로 홀로 솟죠.
# 'z-score의 절댓값이 크다' = '튀었다'의 숫자 표현입니다.


# ----------------------------------------
# z-score로 단위 다른 센서를 한 잣대로
# ----------------------------------------

# z-score를 쓰는 진짜 편함이 여기 있습니다.
# 원래 값은 센서마다 단위가 다르죠 — 온도 85 근처, 진동 35 근처, 압력 56 근처.
# '튀었다' 기준을 원래 값으로 정하면 센서마다 다르게 정해야 합니다.
#
# 그런데 z-score로 바꾸면 모두 '평균 0, 표준편차 1'이라는 같은 잣대 위에 놓여요.
# 어느 센서든 z-score가 3을 넘으면 '튀었다'고 똑같이 판단할 수 있죠.
# 단위가 다른 여러 센서를 하나의 규칙으로 검사하는 힘이 여기서 나옵니다.

# (평균을 빼고 표준편차로 나누는 그 셈을 손으로 직접 만드는 일은
#  이어지는 단락 C에서 다룹니다. 여기선 numpy가 내주는 z-score를 씁니다.)
demo = np.array([82, 91, 75, 88, 79, 95])
print("표준화 결과:", np.round((demo - demo.mean()) / demo.std(), 2))
# → 표준화 결과: [-0.43  0.86 -1.44  0.43 -0.86  1.44]
# 원래 값이 75~95든 무엇이든, 표준화하면 -1.44~1.44 같은 공통 눈금으로 바뀝니다.


# ----------------------------------------
# 임계값 설정 - 보통 ±3
# ----------------------------------------

# z-score가 크면 '튀었다'는 알았죠. 어디까지가 정상이고 어디부터 이상일까요?
# 이 경계선을 정하는 숫자가 '임계값' 입니다.
# z-score 절댓값이 임계값을 넘으면 이상값, 넘지 않으면 정상값으로 판정하죠.
#
# 가장 흔히 쓰는 임계값이 ±3 입니다. 왜 하필 3일까요?
# 지난 시간의 정규분포와 68-95-99.7 규칙이 근거입니다.
#   - 데이터가 정규분포를 따르면 z가 -3 ~ 3 사이에 전체의 약 99.7%가 들어감
#   - 뒤집으면 ±3을 벗어나는 값은 약 0.3%, 천 개 중 세 개 정도로 극히 드묾
# 이렇게 드물어야 할 값이 실제로 나타났다면 '뭔가 이상'으로 보는 게 합리적이죠.

# [임계값은 절대 법칙이 아니라 상황에 따라 조절하는 손잡이]
#
#   Q. 임계값을 ±2로 낮추면?   → 기준이 느슨해져 더 많은 값이 걸림(예민하게)
#   Q. ±3.5로 높이면?          → 정말 크게 튄 확실한 값만 걸림(둔감하게)
#   Q. 언제 낮추고 언제 높이나? → 놓치면 안 되는 중대 설비는 낮게,
#                                변동 잦은 곳은 높게. 특별한 이유 없으면 ±3.


# ----------------------------------------
# 이상값 위치 찾기 - 불리언 인덱싱
# ----------------------------------------

# 임계값을 정했으니 실제로 골라낼 차례입니다.
# 앞서 배운 불리언 인덱싱이 그대로 쓰여요.

# np.abs 는 절댓값 — 음수든 양수든 부호를 떼고 크기만 남깁니다.
# z가 -3.2든 3.2든 절댓값은 3.2가 되어 3을 넘으니, '위아래로' 튄 값을 한 번에 잡죠.
mask = np.abs(z) > 3      # 이상 자리만 True 인 불리언 배열
print("이상 위치 mask:", mask)
# → 이상 위치 mask: [False False False False False False False False False False False False
# →  False False False False False False False  True]

# 이 불리언 배열로 원래 배열을 인덱싱하면 이상값 '자체'가 나옵니다.
print("이상값:", temps[mask])           # → 이상값: [125]

# 값만이 아니라 '몇 번째 자리'인지도 알아야 할 때가 많습니다(몇 시에 이상이 났나).
# 이때는 np.where 를 씁니다.
print("이상 위치:", np.where(mask)[0])   # → 이상 위치: [19]
# 19 = 스무 번째 측정값이 이상값이라는 뜻이죠.
#
# 정리: 불리언 배열[mask]은 '값'을 골라낼 때, np.where는 '자리'를 짚을 때.


# ----------------------------------------
# 이상값 개수와 비율
# ----------------------------------------

# 이상값을 찾았으면 다음은 '몇 개인가'입니다.
# 하나뿐이면 잠깐 튄 정도지만, 절반이 이상값이면 센서 자체가 고장 난 거죠.

# 개수 세기는 조건 통계에서 배운 그대로예요.
# 불리언 배열은 True=1, False=0 으로 세어지니, sum 을 걸면 '참의 개수' = 이상값 개수.
print("이상값 개수:", mask.sum())               # → 이상값 개수: 1

# 비율은 개수를 전체 개수(size)로 나누기만 하면 됩니다.
print("이상값 비율:", mask.sum() / temps.size)   # → 이상값 비율: 0.05
# 스무 개 중 하나 = 0.05 = 5%.
#
# 왜 비율이 중요할까요? 이상값 다섯 개는
#   - 전체가 열 개일 때 → 절반이 오염(심각)
#   - 전체가 만 개일 때 → 거의 깨끗
# 완전히 다른 이야기죠. 그래서 이상 탐지 결과는 '개수와 비율'을 함께 말합니다.


# ----------------------------------------
# z-score 이상 탐지 흐름 - 네 단계
# ----------------------------------------

# 조각조각 배운 걸 하나의 흐름으로 이어 붙여 둡니다.
# 이 흐름 하나면 낯선 센서 데이터 앞에서도 어디서부터 손댈지 곧바로 잡혀요.
#
#   ① 표준화     원래 값 → z-score          (공통 잣대 위에 올림)
#       ↓
#   ② 임계값     abs(z) > 3 조건            (이상 자리만 True)
#       ↓
#   ③ 골라내기   temps[mask], np.where      (값과 위치 추출)
#       ↓
#   ④ 세기       mask.sum(), / size         (개수와 비율)
#
# 각 단계가 앞 단계 없이는 못 갑니다(조건은 z가 있어야, 골라내기는 조건이 있어야).
# 이 의존 관계가 순서를 강제하니 한 번 흐름을 잡으면 헷갈릴 일이 없어요.


# ----------------------------------------
# [실습 재료] 이상값 탐지기
# ----------------------------------------

# 위 네 단계를 함수 하나로 묶어 봅니다. 배열만 넣으면 값·위치·개수·비율이 나오게.
# (케이스 A 온도 / 케이스 B 진동 — 값과 상황만 다르고 하는 일은 같습니다.)

def detect_zscore(arr, thr=3):
    z = (arr - arr.mean()) / arr.std()      # ① 표준화
    m = np.abs(z) > thr                      # ② 임계값
    return {                                 # ③ 골라내기 + ④ 세기
        "값": arr[m],
        "위치": np.where(m)[0],
        "개수": int(m.sum()),
        "비율": m.sum() / arr.size,
    }

vibs = np.array([30, 32, 31, 29, 33, 30, 31, 32, 30, 29,
                 33, 31, 30, 32, 29, 33, 31, 65, 32, 70])  # 설비 M-102 진동
print("[온도 탐지]", detect_zscore(temps))
# → [온도 탐지] {'값': array([125]), '위치': array([19]), '개수': 1, '비율': np.float64(0.05)}
print("[진동 탐지]", detect_zscore(vibs))
# → [진동 탐지] {'값': array([70]), '위치': array([19]), '개수': 1, '비율': np.float64(0.05)}
# (진동에도 65가 튀었는데 왜 70만 잡혔을까요? 두 스파이크가 표준편차를 부풀려
#  65의 z가 3을 못 넘긴 겁니다 — 바로 아래 IQR에서 다룰 z-score의 약점이에요.)


# ==========================================================
#  방법 2 : IQR 기반 이상 탐지
# ==========================================================

# ----------------------------------------
# z-score의 약점과 IQR의 등장
# ----------------------------------------

# z-score에는 숨은 약점이 있습니다.
# z-score는 '평균과 표준편차'로 계산되는데, 그 평균·표준편차 자체가 이상값에 휘둘려요.
# 이상값이 여러 개 섞이면 표준편차가 커지고 → 분모가 커지니 z-score는 오히려 작아지죠.
# 그래서 이상값이 서로가 서로를 가려 '놓치기'도 합니다.
#
# 이걸 보완하는 게 IQR 방법입니다. 평균 대신 '사분위수'를 써요.
#   IQR = Q3 - Q1                          ← 데이터 가운데 절반이 놓인 범위
#   이상 경계 = Q1 - 1.5·IQR  ~  Q3 + 1.5·IQR   ← 이 울타리 바깥이 이상값

# 이상값 두 개(120, 125)가 섞인 배열로 z-score의 약점을 직접 봅시다.
temps2 = np.array([84, 86, 85, 83, 86, 85, 84, 86, 85, 83,
                   86, 84, 85, 86, 84, 86, 85, 120, 86, 125])

q1, q3 = np.percentile(temps2, 25), np.percentile(temps2, 75)
iqr = q3 - q1
low, high = q1 - 1.5 * iqr, q3 + 1.5 * iqr
print("Q1, Q3:", q1, q3, "  IQR:", iqr)      # → Q1, Q3: 84.0 86.0   IQR: 2.0
print("울타리:", low, "~", high)             # → 울타리: 81.0 ~ 89.0

# 그 울타리 바깥 값을 골라냅니다. | 는 '또는'이라 아래보다 작거나 위보다 큰 값을 한 번에.
print("IQR 이상값:", temps2[(temps2 < low) | (temps2 > high)])
# → IQR 이상값: [120 125]


# ----------------------------------------
# 같은 배열, 다른 결과 - z-score vs IQR
# ----------------------------------------

# 똑같은 temps2 배열에 z-score를 걸어 보면 결과가 다릅니다.
z2 = (temps2 - temps2.mean()) / temps2.std()
print("z-score 이상값:", temps2[np.abs(z2) > 3])   # → z-score 이상값: [125]
print("120의 z-score:", round(z2[17], 2))          # → 120의 z-score: 2.76

# z-score는 125 '하나'만 잡았습니다. 왜?
#   이상값 120과 125가 둘 다 섞여 표준편차를 크게 부풀렸거든요.
#   표준편차가 커지자 120의 z-score가 2.76으로 3을 못 넘겨 놓친 겁니다.
#   → '이상값이 이상값을 숨긴' 셈이죠.
#
# 반면 IQR은 120, 125 '둘 다' 잡았습니다.
#   사분위수는 크기순 위치라, 이상값이 아무리 커도 가운데 값들의 위치는 안 흔들려요.
#   그래서 이상값에 '덜 휘둘립니다(강건함)'.
#
#   [비교]           z-score          IQR
#   ---------------+----------------+----------------
#    잣대          | 평균에서 거리   | 가운데서 거리
#    전제          | 정규분포        | 분포 무관
#    이상값 영향   | 휘둘림          | 강건함
#    센서 비교     | 쉬움(표준화)    | 어려움
#
# 정규분포에 가깝고 여러 센서를 함께 볼 땐 z-score,
# 분포를 확신 못 하거나 이상값이 여럿이면 IQR이 안전합니다. 둘을 함께 써도 좋고요.


# ----------------------------------------
# 두 방법의 탐지 절차 - 앞은 다르고 뒤는 같다
# ----------------------------------------

#   단계 |  z-score            |  IQR
#  ------+---------------------+---------------------
#    1   |  평균·std 구하기     |  Q1·Q3 구하기
#    2   |  z-score 표준화      |  IQR 계산
#    3   |  abs(z)>3 조건       |  울타리 바깥 조건
#    4   |  뽑고 세기           |  뽑고 세기          ← 여기는 완전히 같음
#
# 잣대를 만드는 앞부분만 다를 뿐, 이상값을 '뽑고 세는' 뒷부분은 같은 손동작입니다.
# 조건 만들고 → 인덱싱으로 뽑고 → np.where로 위치 짚고 → sum으로 세기.
# 이 마무리 하나를 익히면 앞부분 잣대만 갈아 끼우면 돼요.


# ----------------------------------------
# 이상 탐지의 한계 - 맹신 금지
# ----------------------------------------

# 이상 탐지가 완벽하게 걸러 준다고 믿기 쉽지만, 분명한 한계가 있습니다.
#
#   1) 정상 오인 : z가 3을 넘었다고 반드시 고장은 아닙니다.
#                 정상적으로 잠깐 높은 부하를 받아 살짝 튄 것일 수도 있죠.
#                 통계는 '무리에서 벗어났다'고만 말할 뿐입니다.
#
#   2) 고장 놓침 : 반대로 서서히 나빠지는 '느린 고장'은 값이 조금씩만 변해
#                 임계값을 안 넘습니다. 각 시점은 정상 범위라 안 걸리지만,
#                 며칠에 걸쳐 보면 분명한 고장 징후예요.
#
#   3) 후보일 뿐 : 그래서 걸린 값은 '최종 판정'이 아니라 '사람이 확인할 후보'입니다.
#                 통계가 수백 개 중 살펴볼 것 몇 개로 좁혀 주고, 사람이 확인하는 협업.
#
# 원칙: '도구가 골라 준 것을 사람이 다시 본다.'
# 맹신하면 정상을 버리거나 고장을 놓치는 실수를 합니다.


# ==========================================================
#  다중 센서와 종합 분석 : 여러 센서를 한 번에
# ==========================================================

# ----------------------------------------
# 다중 센서 이상 탐지 - 센서를 행으로 쌓기
# ----------------------------------------

# 지금까진 온도 하나만 봤습니다. 실제 설비엔 온도·진동·압력이 여럿 달려 있죠.
# 여러 센서를 한 번에 검사하려면 앞서 배운 2차원 배열을 씁니다.
# 각 센서의 측정값을 한 '행'으로 두고 여러 행을 쌓으면 하나의 표가 되죠.
#
#         시간대 →
#   온도 [ 84 86 85 ... 120 ]   ← 행 0
#   진동 [ 30 32 31 ...  65 ]   ← 행 1
#   압력 [ 55 56 54 ...  56 ]   ← 행 2

sensors = np.array([
    [84, 86, 85, 83, 86, 85, 84, 86, 85, 120],   # 온도
    [30, 32, 31, 29, 33, 30, 31, 65, 30,  29],   # 진동
    [55, 56, 54, 57, 55, 56, 54, 57, 55,  56],   # 압력(정상)
])

# 센서마다 단위가 다르니 이상 탐지도 센서별로 따로 해야죠.
# 여기서 axis가 그대로 쓰입니다. 센서를 '행'으로 쌓았으니
# 각 행을 요약하는 axis=1 을 주면, percentile이 세 센서의 사분위수를 한 줄에 동시에 구해요.
q1 = np.percentile(sensors, 25, axis=1)
q3 = np.percentile(sensors, 75, axis=1)
high = q3 + 1.5 * (q3 - q1)
low = q1 - 1.5 * (q3 - q1)

# 각 센서의 울타리를 세우고, reshape로 열로 세워(3,1) 행마다 비교해 걸러냅니다.
mask3 = (sensors > high.reshape(3, 1)) | (sensors < low.reshape(3, 1))
print("센서별 이상 개수:", mask3.sum(axis=1))   # → 센서별 이상 개수: [1 1 0]
# 온도 하나, 진동 하나, 압력은 없다는 뜻입니다.
# mask.sum(axis=1) 로 센서마다 이상이 몇 개인지 한 줄로 나와요.


# ----------------------------------------
# 센서 표의 형상(shape) 확인 - 계산 전 치수 재기
# ----------------------------------------

# 2차원 배열을 다룰 땐 계산에 들어가기 전에 '몇 행 몇 열인가'부터 확인합니다.
# 그 치수를 알려 주는 것이 형상(shape)이에요. (행, 열) 순서로 알려 줍니다.
print("센서 표의 형상:", sensors.shape)   # → 센서 표의 형상: (3, 10)
print("차원 ndim:", sensors.ndim)         # → 차원 ndim: 2
# (3, 10) = 센서 3개(행) × 시점 10개(열).
# 형상을 모른 채 axis를 고르면 행을 누를지 열을 누를지부터 헷갈립니다.
# 앞으로 나올 axis도, 곧 볼 행렬곱도 전부 이 형상 위에서 움직여요.


# ----------------------------------------
# 종합 이상 점수 ① - 센서마다 몫을 주는 가중합
# ----------------------------------------

# 지금까지는 센서마다 따로 이상을 셌습니다(센서별 이상 개수 [1 1 0]).
# 그런데 현장이 진짜 알고 싶은 건 "몇 시에 설비가 위험했나"입니다.
# 센서별이 아니라 '시점별'로 하나의 점수가 필요하죠.
#
# 세 센서 점수를 하나로 합칠 때, 그냥 평균을 내면 셋을 똑같이 중요하다고 치는 셈입니다.
# 하지만 이 설비에선 온도가 가장 결정적이고 압력은 거의 변하지 않죠.
# 그래서 센서마다 '몫'을 다르게 줍니다. 이 몫이 가중치입니다.
#
#   가중치 : 각 센서를 얼마나 무겁게 칠지 정한 숫자 (합을 1로 맞추는 게 관례)
#   가중합 : 각 값에 자기 가중치를 곱해 전부 더한 것
#
#   종합점수 = 0.5 × 온도z + 0.3 × 진동z + 0.2 × 압력z
#              └─ 온도 50%, 진동 30%, 압력 20% 의 비중 (합 = 1)
#
# 가중치는 데이터가 정해 주지 않습니다. 어느 센서가 고장을 먼저 알리는지
# 아는 사람 - 현장이 정합니다. 값을 바꾸면 판단 기준 자체가 바뀝니다.
#
# 가중합을 하려면 먼저 세 센서가 '같은 눈금' 위에 있어야 합니다.
# 온도 85, 진동 30, 압력 55는 단위가 달라 그냥 더할 수 없으니까요.
# 그래서 센서마다 z-score로 표준화하는 게 첫 단계입니다.

# ① 센서별 표준화 - 평균·표준편차를 행마다 구해 (3,1)로 세워 나눕니다.
#    앞의 IQR 울타리에서 high.reshape(3, 1) 로 했던 것과 똑같은 손동작이에요.
mu = sensors.mean(axis=1).reshape(3, 1)   # 센서별 평균  (3, 1)
sd = sensors.std(axis=1).reshape(3, 1)    # 센서별 표준편차 (3, 1)
zmat = (sensors - mu) / sd
print("z 점수표 형상:", zmat.shape)   # → z 점수표 형상: (3, 10)
print("z 점수표:")
print(np.round(zmat, 2))
# → [[-0.42 -0.23 -0.32 -0.51 -0.23 -0.32 -0.42 -0.23 -0.32  2.99]
# →  [-0.38 -0.19 -0.29 -0.48 -0.1  -0.38 -0.29  2.98 -0.38 -0.48]
# →  [-0.49  0.49 -1.46  1.46 -0.49  0.49 -1.46  1.46 -0.49  0.49]]
# 온도(행 0)는 마지막 자리 9가 2.99, 진동(행 1)은 자리 7이 2.98로 솟아 있죠.

# ② 마지막 시점(자리 9)만 손으로 가중합해 봅니다.
#    zmat[:, 9] = "모든 행의 9번 열" - 콜론(:)이 '행은 전부'라는 뜻입니다.
#    즉 자리 9 시점의 세 센서 값이 한 줄로 뽑혀 나옵니다.
print("자리 9의 세 센서 z:", np.round(zmat[:, 9], 2))
# → 자리 9의 세 센서 z: [ 2.99 -0.48  0.49]
print("자리 9 가중합:", round(0.5 * zmat[0, 9] + 0.3 * zmat[1, 9] + 0.2 * zmat[2, 9], 2))
# → 자리 9 가중합: 1.45
#   0.5 × 2.99  =  1.50
#   0.3 × -0.48 = -0.14
#   0.2 ×  0.49 =  0.10
#   합치면 1.45. 온도가 크게 튀었고 온도 몫이 50%라 점수가 높게 나왔습니다.
#
# 문제: 시점이 열 개니 이 손계산을 열 번 되풀이해야 합니다.
#       시점이 천 개면? 이 되풀이를 없애는 게 다음의 행렬곱입니다.


# ----------------------------------------
# 종합 이상 점수 ② - 행렬곱(@)으로 한 줄에
# ----------------------------------------

# '짝지어 곱해서 전부 더하기'를 모든 열에 한꺼번에 걸어 주는 연산이 행렬곱 @ 입니다.
#
#    가중치           z 점수표(zmat)              결과
#  [0.5 0.3 0.2]  @  [ ... 2.99 ]  (온도)   =  [ ... 1.45 ]
#                    [ ... -0.48]  (진동)
#                    [ ...  0.49]  (압력)
#                          └ 자리 9 열 ┘           └ 자리 9 ┘
#
#  가중치 한 줄이 표의 각 '열'과 짝을 지어 곱해 더합니다. 열이 열 개면 결과도 열 개.

w = np.array([0.5, 0.3, 0.2])   # 온도 50%, 진동 30%, 압력 20%
score = w @ zmat

print("형상 흐름:", w.shape, "@", zmat.shape, "->", score.shape)
# → 형상 흐름: (3,) @ (3, 10) -> (10,)
# 행렬곱의 규칙: (m, n) @ (n, p) -> (m, p). 안쪽 숫자가 같아야 계산됩니다.
# 여기선 센서 수 3이 서로 맞물려 사라지고 시점 10만 남았죠.
# 형상만 봐도 "센서 축이 접히고 시점 축만 남았다"가 읽힙니다.
# (안 맞으면 numpy가 ValueError로 멈춰 줍니다. @ 가 안 될 땐 양쪽 shape부터 찍어 보세요.)

print("시점별 종합 이상 점수:", np.round(score, 2))
# → 시점별 종합 이상 점수: [-0.42 -0.07 -0.54 -0.11 -0.24 -0.18 -0.59  1.07 -0.37  1.45]
# 자리 9의 1.45 - 위에서 손으로 구한 그 숫자와 정확히 같습니다.
# 손계산 열 번이 @ 한 글자로 끝난 거죠.

print("위험 시점(점수 > 1):", np.where(score > 1)[0])   # → 위험 시점(점수 > 1): [7 9]
# 자리 7과 자리 9가 솟았습니다.
#   자리 7 = 진동 65가 튄 시점, 자리 9 = 온도 120이 튄 시점.
#   앞서 센서별 IQR로 하나씩 찾아낸 바로 그 둘입니다.
# 센서 세 줄짜리 표가 시점 열 개의 점수 한 줄로 압축돼, 한 번의 비교로 답이 나왔어요.
#
# 가중치를 바꾸면 판단이 바뀝니다. 진동이 먼저 신호를 주는 설비라면 진동 몫을 올리세요.
# 주의: @ 는 행렬곱, * 는 같은 자리끼리 곱셈으로 전혀 다른 연산입니다.
#       w * zmat 은 값을 합쳐 주지 않아 시점별 점수가 나오지 않아요.


# ----------------------------------------
# 2차원 설비별 통계 - axis로 방향 정하기
# ----------------------------------------

# 이번엔 행을 '설비', 열을 '시간대'로 둔 표를 봅시다.
#
#            시간대0 1  2   3
#   M-101 [   85  84 86 120 ]   ← 행 0
#   M-102 [   86  85 84  95 ]   ← 행 1
grid = np.array([[85, 84, 86, 120],
                 [86, 85, 84,  95]])

# 설비별 통계 = 각 '행'을 요약 = axis=1 (가로로 눌러 행별)
print("설비별 평균(axis=1):", grid.mean(axis=1))   # → 설비별 평균(axis=1): [93.75 87.5 ]
print("설비별 최대(axis=1):", grid.max(axis=1))    # → 설비별 최대(axis=1): [120  95]
# M-101이 120도까지 치솟은 게 한눈에 보이죠.

# 시간대별 통계 = 각 '열'을 요약 = axis=0 (세로로 눌러 열별)
print("시간대별 평균(axis=0):", grid.mean(axis=0))  # → 시간대별 평균(axis=0): [85.5 84.5 85.  107.5]
# 처음 세 시간대는 잔잔한데 네 번째만 평균 107.5도로 확 뛰었죠.
#
# 두 방향을 오가면 이상이 '설비 탓'인지 '시간 탓'인지 갈립니다.
# 특정 시간대에 두 설비가 함께 튄다면 개별 고장이 아니라
# 정전·냉각수 문제처럼 전체에 영향을 준 사건일 수 있어요.


# ----------------------------------------
# 조건 조합 분석 - & 로 두 조건을 동시에
# ----------------------------------------

# 실제 이상 판단은 여러 조건을 함께 보는 경우가 많습니다.
# 온도만 높은 건 잠깐 부하일 수 있지만,
# 온도도 높으면서 진동도 크다면 확실한 고장 신호에 가깝죠.

# numpy에서 조건을 잇는 연산자: & 는 '그리고', | 는 '또는'.
# 주의: 각 조건을 반드시 괄호로 감싸야 합니다. 안 그러면 연산 순서가 꼬여 오류가 나요.
tt = np.array([84, 86, 85, 83, 86, 85, 84, 86, 85, 83,
               86, 84, 85, 86, 84, 86, 85, 102, 86, 125])
vv = np.array([30, 32, 31, 29, 33, 30, 31, 32, 30, 29,
               33, 31, 30, 32, 29, 33, 31, 65, 32, 70])

both = (tt > 100) & (vv > 60)   # 둘 다 참인 자리만 True
print("동시 이상 개수:", both.sum())            # → 동시 이상 개수: 2
print("동시 이상 시점:", np.where(both)[0])     # → 동시 이상 시점: [17 19]
# 17번과 19번 시점에 온도와 진동이 '함께' 튀었다는 뜻입니다.
# 조합한 조건도 결국 불리언 배열이라 sum·np.where가 그대로 통하죠.
# 조건을 조합하면 넓게 걸리던 게 '확실한 것만' 남습니다.


# ----------------------------------------
# 시간대별 집계 - reshape로 시간 구간 묶기
# ----------------------------------------

# 센서는 아주 촘촘하게 값을 남깁니다. 하루를 한 시간마다 재면 스물네 개죠.
# 이 긴 배열을 통째로 보면 '언제' 이상이 몰렸는지 알기 어렵습니다.
# 그래서 값들을 시간 구간으로 묶어 구간마다 요약하는 게 '시간대별 집계'예요.

hourly = np.array([82, 88, 85, 84, 80, 84,    # 0~5시
                   90, 88, 120, 86, 85, 75,   # 6~11시
                   85, 84, 86, 85, 84, 86,    # 12~17시
                   91, 88, 125, 87, 90, 86])  # 18~23시

# 핵심: 한 줄로 늘어선 긴 배열을 '각 행이 한 시간 구간'이 되도록 reshape로 접습니다.
# 스물네 개를 여섯 개씩 네 구간으로 → reshape(4, 6).
# reshape가 '값은 그대로, 배치만 바꾸는' 성질을 시간 묶기에 쓰는 거예요.
blocks = hourly.reshape(4, 6)

# 각 구간이 한 행이 되었으니 구간별 요약은 axis=1.
print("구간별 평균:", np.round(blocks.mean(axis=1), 2))  # → 구간별 평균: [83.83 90.67 85.   94.5 ]
print("구간별 최대:", blocks.max(axis=1))                # → 구간별 최대: [ 88 120  86 125]
# 2구간·4구간이 높아 그 시간대에 이상이 몰렸다는 뜻이죠.
# 긴 배열을 그냥 보면 놓쳤을 시간대 패턴이 구간으로 묶으면 선명해집니다.


# ----------------------------------------
# [실습 재료] 다중 센서 종합 분석
# ----------------------------------------

# 위 도구들(2차원 쌓기·axis·IQR·조건 조합)을 하나로 엮어 봅니다.
# 여러 센서를 행으로 쌓아 axis로 센서별 통계를 내고, IQR로 센서마다 이상을 탐지한 뒤,
# 두 센서의 조건을 조합해 동시에 이상을 보인 시점까지 짚어냅니다.

def analyze_sensors(mat):
    q1 = np.percentile(mat, 25, axis=1)
    q3 = np.percentile(mat, 75, axis=1)
    high = q3 + 1.5 * (q3 - q1)
    low = q1 - 1.5 * (q3 - q1)
    mask = (mat > high.reshape(-1, 1)) | (mat < low.reshape(-1, 1))
    return mat.mean(axis=1), mask.sum(axis=1)

means, counts = analyze_sensors(sensors)
print("[종합] 센서별 평균:", np.round(means, 2))   # → [종합] 센서별 평균: [88.4 34.  55.5]
print("[종합] 센서별 이상 개수:", counts)          # → [종합] 센서별 이상 개수: [1 1 0]


