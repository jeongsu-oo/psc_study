#
#                      NumPy 분석 도구
#            ┌───────────┬──┴───────┬───────────┐
#      통계 심화     관계 분석     이상 탐지    형상·행렬곱
#    median·std·    corrcoef·    z-score·IQR·   shape·ndim·
#   z-score·정규분포  상관 행렬   불리언·axis      @ 가중합
#
#   - 통계 심화 : median·percentile·std, 정규분포와 68-95-99.7, z-score 표준화
#   - 관계 분석 : corrcoef로 함께 움직이는 정도, 상관 행렬 (단, 상관 ≠ 인과)
#   - 이상 탐지 : z-score·IQR로 튀는 값 찾기, 불리언 인덱싱, 조건 조합, axis·reshape
#   - 형상·행렬곱 : shape로 배열 치수 확인, @ 로 여러 센서 점수를 종합 점수 한 줄로
#
# 이 넷이 합쳐져 '센서 데이터를 요약하고, 관계를 재고, 이상을 찾아, 한 점수로 묶는'
