#   ① 전체 요약   여섯 통계 함수로 평균·양 끝·흩어짐 → 큰 그림
#       ↓
#   ② 이상 탐지   z-score / IQR 로 튀는 값의 정체 밝히기
#       ↓
#   ③ 조건 분석   조건 통계·조합으로 특정 부분 파고들기
#       ↓
#   ④ 방향별 집계 axis(2차원) / reshape(긴 배열)로 방향별·시간별 다시 보기
