#
# numpy 배열 기초 - 인덱싱과 원소별 연산
#
"""
[배열에서 값을 어떻게 꺼내나]
리스트 인덱싱과 같음
"""

import numpy as np
import time

temps = np.array([82.0, 91.5, 78.2, 88.0, 95.1, 80.4])

#
# 배열 인덱싱
#
print(temps[1])
print(temps[-3])

temps[0] = 100
# >> 값 교체
# 배열이나 리스트는 값을 바꿀 수 있는 '가변'
# 센서가 넘긴 값에 오류가 있어서 다시 잰 값으로 교체할 때,
# 배열 전체를 새로 만들 필요 없이 그 한 자리만 고쳐 넣으면 된다.

# 주의 : 배열은 '같은 자료형'만 담긴다


#
# 원소별 연산 - 반복 없이 한 번에
#
t0 = time.time()
print(temps + 2)
t1 = time.time()
print(f"실행 시간 : {t1 - t0:.4f}초")
# 원소별 연산 >> 벡터연산 | 벡터화 연산
# 사칙연산 전부 가능


#
# 배열과 스칼라 - 브로드캐스팅
#
# 배열에 숫자 하나를 더함
# 그 숫자 하나를 "스칼라"
# 값이 묶인 배열과 구분해 홀로 있는 값 하나를 가리킴

# 배열에 스칼라를 연산하면 그 스칼라가 배열의 모든 값으로 "퍼짐"
# 이렇게 한 값이 배열 전체로 퍼지는 걸 '브로드캐스팅'
# 방송(broadcast)이 한 곳에서 나가듯, 숫자 하나가 배열에 뿌려짐

# 스칼라는 홀로 있는 값이라 배열이 아무리 길어도 괜찮음

#
# 배열과 배열 - 같은 자리까지
#
# 원소별 연산은 '배열과 배열' 사이도 가능
b = np.array([80.0, 90.0, 79.0, 85.0, 79.0, 90.0])
# 배열과 배열은 같은 위치끼리 계산
print(temps + b)
print(temps - b)
print(temps * b)
print(np.round(temps / b, 2))


#
# 원소별 연산이 '빠른" 이유
#
# 왜 배열이 for보다 빠른가
# 파이썬 밖에 있는 '미리 최적화가 된 컴파일된 내부 코드'에 넘겨 한꺼번에 처리
#
# 대용량 자료일 경우 속도 차이가 유의미

# 리스트 : 빈 그릇 + for + append
# 배열 : 배열 + 계산


#
# 비교 연산 - 배열이 기준을 넘는지
#
# 배열에서 할 수 있는 연산은 산술만이 아님.
# 온도 배열에서 어느 값이 경고 기준 85도를 넘는지 알고 싶다면
print(temps >= 80)
print(temps[temps >= 80])


#
# 불리언 배열 - 참 거짓만 담긴 배열
#
# 각 자리에 참(True) 또는 거짓(False)이 담긴 '새 배열'입니다
# 원래 배열과 길이가 같은데, 값이 숫자가 아니라 참 거짓으로 채워진 것

# 참 거짓 지도를 흔히 '마스크(mask)'라고 함


#
# 불리언 인덱싱 - 조건으로 걸러내기
#
# 마스크가 있으면 그 지도에서 참인 값만 추출 가능
# 불리언 배열을 그냥 대괄호 안에 넣는다


# [절차]
# 조건 정하기 : 걸러 낼 조건을 비교 연산으로 결정
# 마스크 만들기 : 비교가 참 거짓 배열을 만듦
# 값 뽑기 : 마스크를 대괄호에 넣어 arr[마스크] / 참의 자리 값 추출


#
# 조건 만족 개수 - sum
#
# 값을 걸러 내는 거 말고 조건을 만족하는 값이 몇 개인지
print(np.sum(temps >= 80))

# np.sqrt = 제곱근
# np.round = 반올림
print(np.sqrt(np.array([9.0, 16.0, 25.0])))
print(np.round(np.array([82.37, 91.55]), 1))


#
# 단위 변환과 정규화
#
# 정규화 - 크기가 제각각인 값을 0~1 범위로 맞추기
#       같은 잣대로 비교하려고 다듬는 일
# 각 값에서 최솟값을 뺴고, (최댓값 - 최솟값)으로 나눔
# >> 가장 작은 값은 0, 가장 큰 값은 1, 나머지는 그 사이에 놓임

norm = np.array([82.0, 91.5, 78.2])
a = (norm - norm.min()) / (norm.max() - norm.min())
print(a)
