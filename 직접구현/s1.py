# 수치 계산 직접 구현 - 통계를 손으로 짜 본다
# -------------------------------


"""[통계 함수 안에는 뭐가 들어 있나요?]
지금까지 통계가 필요하면 준비된 함수를 한 줄 불러 값만 받았습니다.
temps.mean() 하면 평균이, temps.std() 하면 표준편차가 툭 나왔죠.

오늘은 그 함수 '안'을 열어 봅니다.
평균, 분산, 표준편차 세 개를 준비된 함수 없이,
반복문과 나눗셈만으로 직접 만들어 봅니다.

왜 굳이 직접 만드나?
  - 수식이 코드로 어떻게 바뀌는지 눈으로 익히려고 (시그마 = 반복문)
  - 내가 짠 함수가 맞았는지 확인하는 검증 습관을 들이려고
그리고 마지막에 numpy 와 나란히 놓아 채점합니다.
numpy 는 계산을 대신해 주는 도구가 아니라, 오늘은 '채점표'로만 씁니다.

이 파일은 그 세 함수를 위에서 아래로, 손계산 → 코드 → 검증 순으로 쌓습니다.
"""

# 마지막에 내 함수를 채점할 때만 씁니다. 그전까지는 전부 순수 파이썬.
import numpy as np


# 이 파일 전체에서 쓸 작은 온도 리스트. 손으로 계산하기 좋게 다섯 값만.
# (파일 안에 직접 적어 둡니다 — 외부 CSV 없이 그냥 실행됩니다.)
온도5 = [70, 72, 74, 76, 78]


# ========================================================
#  PART 1 : 수식을 코드로 - 평균
# ========================================================

# ----------------------------------------
# 평균 = 값의 합을 개수로 나눔
# ----------------------------------------

# 평균의 정의는 딱 한 줄입니다.
#
#   평균 = Σx / n
#          (모든 값을 더한 합)  나누기  (값의 개수)
#
# 수식 기호를 파이썬 도구로 하나씩 바꿔 보면:
#   Σx (모든 값의 합)  →  sum()
#   n  (값의 개수)     →  len()
#   ÷ n (개수로 나눔)  →  / len(...)
#
# 그래서 수식 한 줄이 코드 한 줄로 그대로 옮겨집니다.

def 평균(xs):
    return sum(xs) / len(xs)   # Σx / n  그대로

print("평균(온도5):", 평균(온도5))   # → 평균(온도5): 74.0

# 손으로 확인:  70+72+74+76+78 = 370,  개수 5,  370 / 5 = 74.0
# 코드 값 74.0 과 손계산 74.0 이 같습니다.


# ----------------------------------------
# 흔한 실수 - 합계는 평균이 아니다
# ----------------------------------------

# 여기서 노베이스가 가장 자주 하는 실수 하나.
# 나눗셈을 빠뜨리고 '합계'만 돌려주는 것입니다.

print("합계만 구하면:", sum(온도5))   # → 합계만 구하면: 370

# 370 은 합계이지 평균이 아닙니다.
# 평균은 반드시 '개수로 나누기'까지 해야 완성됩니다.
#
#   합계 = sum(xs)              ← 여기서 멈추면 틀림
#   평균 = sum(xs) / len(xs)    ← 나눗셈 한 걸음을 더 가야 맞음
#
# 합을 구하는 것과 평균을 구하는 것은 나눗셈 한 걸음 차이입니다.
# 그 한 걸음을 빠뜨리지 마세요.


# ----------------------------------------
# 시그마의 정체는 반복문
# ----------------------------------------

# sum() 은 편하지만, 수식의 Σ(시그마) 기호가 코드로 어떻게 생겼는지
# 보려면 반복문으로 펼쳐 봐야 합니다.
#
#   Σx  =  값을 하나씩 꺼내 상자에 누적해 더하는 일
#
#   합 상자를 0으로 두고
#   [70]→ 합 70   [72]→ 합 142   [74]→ 합 216 ...  이렇게 다섯 번 누적

def 평균_반복(xs):
    합 = 0
    for x in xs:          # Σ = 값을 하나씩 꺼내
        합 = 합 + x       #     상자에 누적해 더함
    return 합 / len(xs)   # 분모 n = len()

print("평균_반복(온도5):", 평균_반복(온도5))   # → 평균_반복(온도5): 74.0

# sum 으로 짠 평균() 과 for 로 펼친 평균_반복(), 둘 다 74.0 으로 같습니다.
# 하나는 짧고, 하나는 시그마의 속을 보여 줄 뿐 하는 일은 똑같아요.


# ----------------------------------------
# 수식 기호와 파이썬 코드의 대응
# ----------------------------------------

#   수식 기호  |  뜻            |  파이썬 코드
#  -----------+----------------+---------------------
#   Σ (시그마) |  값을 모두 더함 |  sum()  또는  for 누적
#   n (분모)   |  값의 개수     |  len()
#   ÷ n        |  개수로 나눔   |  / len(xs)
#
# 이 대응표만 손에 쥐면 평균뿐 아니라 앞으로 만날 어떤 합산형 계산
# 정의도 코드로 옮길 수 있습니다. 시그마 보면 반복문, 분모 n 보면 len.


# ========================================================
#  PART 2 : 분산과 표준편차
# ========================================================

# ----------------------------------------
# 평균이 같아도 흩어짐은 다르다
# ----------------------------------------

# 평균만으로는 부족할 때가 있습니다.
# 평균이 똑같이 74도인 두 설비를 상상해 보죠.
#
#   설비 A :  73  74  75  73  75   ← 73~75 로 잔잔
#   설비 B :  60  90  74  60  86   ← 60~90 으로 크게 출렁
#
# 두 설비의 평균은 둘 다 74 로 같습니다. 평균만 보면 똑같아 보이죠.
# 그런데 B 는 훨씬 불안정합니다. 이 '흩어진 정도'를 평균은 못 잡아냅니다.
# 그래서 흩어진 정도를 숫자 하나로 만든 것이 바로 '분산' 입니다.

A = [73, 74, 75, 73, 75]
B = [60, 90, 74, 60, 86]
print("A 평균:", 평균(A), "/ B 평균:", 평균(B))   # → A 평균: 74.0 / B 평균: 74.0
# 평균은 같습니다. 흩어짐은 곧 분산으로 재 보면 완전히 다를 겁니다.


# ----------------------------------------
# 분산 만드는 세 걸음
# ----------------------------------------

# 분산 = Σ(x - 평균)² / n
#
# 말로 풀면 세 걸음입니다.
#
#   1) 편차   : 각 값에서 평균을 뺀다        (x - 평균)  ← 평균과의 거리
#   2) 제곱   : 그 편차를 제곱한다           (x - 평균)²
#   3) 평균   : 제곱을 모두 더해 개수로 나눈다  Σ(...) / n
#
# 여기서 꼭 짚을 질문 하나. 왜 2단계에서 '제곱'을 할까요?
#
#   편차를 그냥 더하면 평균보다 큰 값(양수 편차)과
#   작은 값(음수 편차)이 서로 상쇄되어 항상 0 이 됩니다.
#   → 흩어짐이 사라져 버리죠.
#   제곱하면 음수도 양수가 되어 흩어짐이 살아남습니다.
#
# 실제로 편차를 그냥 더하면 0 이 되는지 눈으로 확인해 봅시다.

m = 평균(온도5)                        # 74.0
편차들 = [x - m for x in 온도5]        # 각 값 - 평균
print("편차들:", 편차들)               # → 편차들: [-4.0, -2.0, 0.0, 2.0, 4.0]
print("편차 그냥 합:", sum(편차들))    # → 편차 그냥 합: 0.0
# 보시다시피 그냥 더하면 0. 그래서 제곱이 필요합니다.


# ----------------------------------------
# 편차 제곱의 평균 손계산 (표로)
# ----------------------------------------

# 코드를 짜기 전에, 온도 다섯 개로 분산을 '손으로' 먼저 구해 봅니다.
# 평균은 74 였습니다. 각 값에서 74 를 빼고, 제곱하면:
#
#   값  |  편차 (값-74)  |  편차 제곱
#  -----+---------------+-----------
#   70  |     -4        |    16
#   72  |     -2        |     4
#   74  |      0        |     0
#   76  |      2        |     4
#   78  |      4        |    16
#  -----+---------------+-----------
#              편차 제곱 합계  =  16+4+0+4+16 = 40
#              개수 n = 5
#              분산 = 40 / 5 = 8
#
# 손으로 낸 분산은 8 입니다. 이제 코드가 같은 8 을 내는지 봅시다.


# ----------------------------------------
# 분산 코드로 옮기기
# ----------------------------------------

# 위 손계산 세 걸음을 그대로 코드로 옮깁니다.
# 먼저 평균을 구하고(1단계용), 각 값에서 평균을 빼 제곱한 것을
# 모두 더해(2·3단계) 개수로 나눕니다.

def 분산(xs):
    m = 평균(xs)                                    # 먼저 평균
    return sum((x - m) ** 2 for x in xs) / len(xs)  # Σ(x-평균)² / n

print("분산(온도5):", 분산(온도5))   # → 분산(온도5): 8.0

# 손계산 8 과 코드 8.0 이 똑같습니다.
#
# 분모 주의 : 우리는 '개수 n' 으로 나눕니다 (n-1 이 아닙니다).
#            n-1 로 나누면 다른 정의가 되어, 뒤에서 대조할 numpy 의
#            기본값(np.var 은 n 으로 나눔)과 값이 어긋납니다.
#            그래서 numpy 와 맞추려고 n 으로 나눕니다.

# 앞에서 평균이 같던 A, B 에 분산을 걸어 보면 흩어짐 차이가 숫자로 드러납니다.
print("A 분산:", 분산(A), "/ B 분산:", 분산(B))
# → A 분산: 0.8 / B 분산: 158.4
# 평균은 같아도(둘 다 74) 분산은 A 는 작고 B 는 큽니다. B 가 훨씬 흩어졌죠.


# ----------------------------------------
# 표준편차는 분산의 제곱근
# ----------------------------------------

# 분산 8 은 흩어짐을 담고 있지만 단위가 '도의 제곱' 이라 감이 안 옵니다.
# 편차를 제곱하는 과정에서 단위까지 제곱돼 버렸거든요.
#
#   표준편차 = √분산
#
# 왜 제곱근? 제곱하느라 틀어진 단위를 원래(도)로 되돌리려는 겁니다.
# 파이썬에서 제곱근은 '0.5 제곱' 으로 표현합니다. (x ** 0.5)
# 그래서 앞서 만든 분산 함수를 부른 뒤 ** 0.5 만 붙이면 끝입니다.

def 표준편차(xs):
    return 분산(xs) ** 0.5   # √분산 = 분산의 0.5 제곱

print("표준편차(온도5):", round(표준편차(온도5), 4))   # → 표준편차(온도5): 2.8284

# 분산이 8 이었으니 표준편차는 √8, 약 2.83 도.
# 이제 "이 설비 온도는 평균 74도에 약 2.83도만큼 흩어져 있다" 고
# 도 단위로 자연스럽게 말할 수 있습니다.


# ----------------------------------------
# 함수 위에 함수를 쌓기
# ----------------------------------------

# 여기서 눈여겨볼 구조 하나.
#
#          표준편차(xs)
#              │  분산을 부름
#          분산(xs)
#              │  평균을 부름
#          평균(xs)
#
# 표준편차는 분산을 부르고, 분산은 다시 평균을 부릅니다.
# 평균이라는 벽돌 위에 분산을 쌓고, 그 위에 표준편차를 쌓은 구조죠.
# 각각을 독립된 작은 함수로 만들어 두면
#   - 하나를 고치면 그걸 쓰는 나머지가 자동으로 따라오고
#   - 큰 계산을 작은 조각으로 나눠 짤 수 있습니다.
# 세 함수가 다 갖춰졌으니, 이제 진짜 센서 데이터에 그대로 걸어 봅시다.


# ========================================================
#  PART 3 : 센서 데이터 적용
# ========================================================

# ----------------------------------------
# 세 함수를 센서 온도에 적용
# ----------------------------------------

# 손계산용 다섯 개가 아니라, 실제 설비에서 잰 온도 측정값입니다.
# (외부 파일 없이 파일 안에 직접 적어 둡니다.)
# 함수는 하나도 손대지 않고, 만든 그대로 걸기만 합니다.

센서온도 = [73, 72, 74, 71, 73, 72, 75, 74, 73, 72, 74, 73, 72, 121]
#          └──────── 대부분 71~75도 ────────┘           └ 튀는 값 하나

print("측정 개수:", len(센서온도))   # → 측정 개수: 14
print("평균:", round(평균(센서온도), 4))              # → 평균: 76.3571
print("표준편차:", round(표준편차(센서온도), 4))      # → 표준편차: 12.4247

# 평균이 약 76도, 표준편차가 약 12도로 꽤 큽니다.
# 왜 이렇게 클까요? 대부분 71~75도인데 한 측정이 121도로 크게 튀기 때문입니다.
# 튀는 값 하나가 흩어짐(표준편차)을 크게 끌어올린 거죠.


# ----------------------------------------
# numpy 와 나란히 대조 (채점)
# ----------------------------------------

# 내가 만든 함수를 믿으려면 채점이 필요합니다.
# 이미 수많은 사람이 검증한 numpy 의 결과와 내 결과를 나란히 놓고 봅니다.
#   평균  → np.mean
#   분산  → np.var   (기본 분모 n — 우리와 같음)
#   표준편차 → np.std

print("[직접 구현]",
      round(평균(센서온도), 4),
      round(분산(센서온도), 4),
      round(표준편차(센서온도), 4))
# → [직접 구현] 76.3571 154.3724 12.4247

print("[numpy   ]",
      round(np.mean(센서온도), 4),
      round(np.var(센서온도), 4),
      round(np.std(센서온도), 4))
# → [numpy   ] 76.3571 154.3724 12.4247

# 세 값이 소수점까지 똑같습니다.
# numpy 의 분산이 기본적으로 n 으로 나누는데, 우리도 n 으로 나눴기 때문에 일치하죠.
# 만약 앞에서 실수로 n-1 로 나눴다면 여기서 값이 어긋나 바로 틀렸음을 알았을 겁니다.
# numpy 는 답을 대신 내주는 도구가 아니라, 내가 낸 답을 채점하는 채점표입니다.


# ----------------------------------------
# 네 열을 한 번에 채점
# ----------------------------------------

# 대조를 온도 한 열에만 쓸 필요는 없습니다.
# 여러 센서 열을 한 번에 돌면서, 각 열마다 내 함수 결과와 numpy 결과가
# 같은지 자동으로 확인합니다.
# (두 값의 차이가 아주 작으면 — 1e-9 미만 — 같은 것으로 봅니다.
#  실수 계산은 아주 미세한 오차가 생길 수 있어 '완전히 같음' 대신 이렇게 비교해요.)

센서열 = {
    "온도":   [73, 72, 74, 71, 73, 72, 75, 74, 73, 72, 74, 73, 72, 121],
    "진동":   [0.8, 1.1, 0.9, 1.0, 1.2, 0.7, 1.0, 0.9, 1.1, 1.0],
    "회전수": [1500, 1520, 1490, 1510, 1505, 1495, 1600, 1480],
    "압력":   [4.2, 4.5, 4.1, 4.3, 4.4, 4.2, 4.6, 4.0, 4.3],
}

print("[네 열 채점 — 직접 구현 == numpy?]")
for 열, 값 in 센서열.items():
    일치 = abs(평균(값) - np.mean(값)) < 1e-9
    print(" ", 열, 일치)
# → [네 열 채점 — 직접 구현 == numpy?]
# →   온도 True
# →   진동 True
# →   회전수 True
# →   압력 True

# 네 열이 모두 True 면 우리 함수가 모든 열에서 정확하다는 증거입니다.


# ----------------------------------------
# 오늘 만든 세 함수 - 정리
# ----------------------------------------

#   함수        |  정의                  |  코드 핵심
#  ------------+------------------------+----------------------------
#   평균(xs)    |  Σx / n               |  sum(xs) / len(xs)
#   분산(xs)    |  Σ(x-평균)² / n        |  편차 제곱 합 / len(xs)
#   표준편차(xs) |  √분산                 |  분산(xs) ** 0.5
#
