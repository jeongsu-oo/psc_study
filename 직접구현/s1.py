#   케이스 B : 압력 열의 평균·분산·표준편차 직접 구현 후 numpy 대조
#
#   Step 1) 대상 열을 센서열 딕셔너리에서 꺼내기       (예: 값 = 센서열["진동"])
#   Step 2) 평균·분산·표준편차 세 함수로 계산
#   Step 3) np.mean·np.var·np.std 와 나란히 대조 (차이 1e-9 미만이면 일치)
#
# 완료 기준 : 직접 구현 세 값이 화면에 나오고, numpy 세 값과 나란히 출력되며,
#            두 결과가 같음이 확인되면 성공입니다.
