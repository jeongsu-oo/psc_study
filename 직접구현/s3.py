# 원시 데이터부터 다시 정제할 필요가 없어지죠.
#
# ★ 정제 데이터만 저장하고 기준을 버리면,
#   나중에 새 데이터가 들어왔을 때 '같은 잣대로 변환할 방법'이 사라집니다.


# ==========================================================
#  재현 : 저장한 기준을 되살려 새 데이터에 '같은 잣대' 적용
# ==========================================================

# 저장의 진짜 가치는 다시 불러 쓸 때 드러납니다.
# 몇 주 뒤 새 센서 파일이 들어왔다고 해봅시다.
# 어떻게 처리해야 이전 데이터와 이어 붙일 수 있을까요?

# 1) 저장해 둔 스케일링 기준을 다시 읽어 딕셔너리로 되살립니다.
기준표_로드 = pd.read_csv(BASE / "스케일링_기준.csv",
                        index_col=0, encoding="utf-8-sig")
불러온기준 = {열: {"min": 행["min"], "max": 행["max"]}
             for 열, 행 in 기준표_로드.iterrows()}
# 저장하기 전과 '똑같은 기준'이 손에 들어옵니다.
# 온도 상한 기준 100 이 파일에서 그대로 되살아나죠.

# 2) 새 데이터가 들어옴 (몇 주 뒤 새 센서 측정치라고 가정)
새데이터 = pd.DataFrame([
    [16, 73.0, 3.5, 1422, 5.1],
    [17, 79.0, 4.6, 1440, 5.3],
], columns=["측정ID", "온도", "진동", "회전수", "압력"])

# 3) 스케일링 함수에 '불러온 기준'을 넘깁니다.
#    기준을 새로 만들지 않고 받은 기준을 쓰기 때문에
#    새 데이터도 원본과 '완전히 같은 눈금'으로 변환됩니다.
새변환, _ = 스케일링(새데이터, 기준=불러온기준)

print("\n[재현 - 저장한 기준으로 새 데이터 변환]")
print("  새데이터 온도(0~1):", 새변환["온도"].tolist())
# → 새데이터 온도(0~1): [0.069, 0.276]
# 온도 73 → (73-71)/(100-71)=0.069, 79 → (79-71)/29=0.276.
# 새 데이터의 min·max 를 새로 잡은 게 아니라, '저장된 학습 기준(71~100)'을 썼습니다.


# ----------------------------------------
# 새 기준을 '다시 만들면' 왜 안 되나 - 직접 비교
# ----------------------------------------

# 흔한 실수: 새 데이터로 기준을 새로 만들어 버리는 것.
# 그러면 새 데이터의 min·max(여기선 73~79)로 눈금이 다시 잡혀
# 이전 데이터와 '다른 잣대'가 됩니다.

잘못된변환, 잘못된기준 = 스케일링(새데이터)   # 기준 안 넘김 → 새로 만듦(잘못된 방식)

print("\n[잘못된 방식 - 새 데이터로 기준을 새로 만들면]")
print("  잘못된 온도(0~1):", 잘못된변환["온도"].tolist())
# → 잘못된 온도(0~1): [0.0, 1.0]
# 같은 온도 73, 79 인데 눈금이 73~79 로 다시 잡혀 0.0 과 1.0 으로 벌어졌습니다.
# 저장 기준(71~100)으로는 0.069, 0.276 이었는데 완전히 달라졌죠.
#
# 이게 바로 데이터 누출입니다.
#   스케일링 기준은 '학습 데이터에서만' 정하고,
#   이후 데이터는 그 기준을 '받아 쓰기만' 해야 합니다.
#   새로 잡으면 몰라야 할 정보가 눈금에 섞여 성능이 부풀려집니다.
#
# 답은 하나: 저장한 기준을 인자로 넘겨 그대로 재사용.
# 함수를 '기준을 인자로 받도록' 만든 덕분에 재현과 누출 방지가 자연스럽게 됩니다.


# ==========================================================
#  재현성 자체 검증 - 같은 기준을 두 번 적용
# ==========================================================

# "같은 기준을 두 번 적용하면 결과가 정말 같을까?"
# 이걸 코드로 못 박아 확인합니다. 재현 가능한 절차의 증거예요.

새변환2, _ = 스케일링(새데이터, 기준=불러온기준)
assert 새변환["온도"].tolist() == 새변환2["온도"].tolist(), "재현 실패!"

# 파이프라인 전체도 두 번 돌려 학습 분리가 같은지 확인 (시드 고정 덕분)
