"""[전처리를 왜 굳이 정리하나요?]
지난 파트12에서 우리는 원시 센서 데이터를 손질하는 법을 하나씩 익혔습니다.
빈 칸 채우기(결측), 말 안 되는 값 걸러내기(이상값),
자릿수 제각각인 열을 같은 눈금으로 맞추기(스케일링),
학습용과 평가용으로 나누기(분리)까지요.

그런데 이걸 매번 손으로 새로 짜면 문제가 생깁니다.
오늘은 빈 칸을 평균으로, 내일은 중앙값으로 채우는 식으로
정제 기준이 조금씩 흔들리거든요. 기준이 흔들리면 나중에
두 모델을 비교했을 때 그 차이가 '모델이 좋아서'인지
'데이터를 다르게 손질해서'인지 구분할 수가 없습니다.

그래서 오늘은 이 흩어진 손질법 넷을 함수로 묶고,
하나의 파이프라인으로 이어 붙인 뒤, 결과와 기준을 저장해
누가 언제 실행해도 똑같이 재현되는 절차로 완성합니다.
"""

import numpy as np
import pandas as pd
from pathlib import Path

# 이 파일이 있는 폴더. 실습 CSV를 여기에 쓰고 읽습니다(자족 패턴).
