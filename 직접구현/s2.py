# 목표: SSE·MSE·MAE를 직접 함수로 만들고, 이상값 유무로 세 값을 비교한다.
#   Step 1  def로 sse·mse·mae 세 함수 만들기      (위 함수를 직접 타이핑)
#   Step 2  정상·이상값 두 데이터에 세 함수 걸기
#   Step 3  제곱 계열이 절댓값 계열보다 더 튀는지 확인
#
# 아래는 케이스 B: 진동 실측을 기준 3.1과 비교.
# 진동 15.2짜리 이상값 한 칸이 SSE·MSE를 크게 끌어올리는지 봅니다.

진동_실측 = [3.0, 3.2, 2.9, 15.2, 3.1, 2.8]   # 4번째가 이상값(15.2)
진동_예측 = [3.1, 3.1, 3.1, 3.1, 3.1, 3.1]     # 기준 3.1

print("[실습 - 진동 케이스 B]")
print("  SSE =", round(sse(진동_실측, 진동_예측), 2))   # → SSE = 146.56
print("  MSE =", round(mse(진동_실측, 진동_예측), 2))   # → MSE = 24.43
print("  MAE =", round(mae(진동_실측, 진동_예측), 2))   # → MAE = 2.13
# 이상값 15.2 하나 때문에 제곱 계열(SSE·MSE)이 크게 부풀고,
# MAE는 상대적으로 차분합니다. 정상 데이터와 같은 결론이죠.
#
# 일찍 끝난 분은: 이상값 15.2를 정상 범위(3.0쯤)로 바꿔 다시 돌려
