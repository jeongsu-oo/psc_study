# -------------------------------
# 오차 계산 직접 구현 - SSE·MSE·MAE 손으로 만들기
# -------------------------------


"""[값 하나가 얼마나 맞았는지 어떻게 숫자로 재나요?]
제조 현장에서 우리는 늘 두 값을 나란히 놓습니다.
센서가 실제로 잰 '실측값', 그리고 기대하거나 기준으로 잡은 '예측값'.
이 둘이 얼마나 벌어졌는지를 하나의 숫자로 잰 것이 '오차'입니다.

라이브러리에는 이미 mean_squared_error 같은 게 다 들어 있습니다.
그런데 오늘은 그걸 가져다 쓰기 전에, 세 도구(SSE·MSE·MAE)를
def·for·abs·제곱만으로 처음부터 손으로 직접 만들어 봅니다.

안에서 무슨 일이 벌어지는지 겪어 봐야, 나중에 상황에 맞는 도구를
스스로 고를 수 있거든요. 이 파일을 위에서 아래로 훑으며 익힙니다.
"""


# ----------------------------------------
# 실측과 예측 사이의 거리
# ----------------------------------------

# 어떤 설비의 온도를 재면 72.3도, 73.1도, 74.0도처럼
# 매번 조금씩 다르게 나옵니다. 이게 '실측값'입니다.
# 그 설비가 대체로 72도 근처에서 안정적으로 돈다고 알고 있으면
# 72.0도를 기준선으로 잡을 수 있죠. 이게 '예측값'입니다.
#
#   실측값  실제로 잰 값        72.3, 73.1 ... 매번 다름
#   예측값  기준으로 잡은 값    72.0 (안정적으로 도는 기준선)
#   오차    둘 사이 벌어진 거리  실측 - 예측
#
# 외부 CSV 없이, 작은 리스트 두 개를 이 파일 안에 그냥 적어 둡니다.

실제 = [72.3, 73.1, 71.8, 74.0, 72.6]   # 센서가 실제로 잰 온도 5개
예측 = [72.0, 72.0, 72.0, 72.0, 72.0]   # 전부 72.0으로 잡은 기준값


# ----------------------------------------
# 오차 하나의 정의 - 실측 빼기 예측
# ----------------------------------------

# 오차의 정의는 아주 간단합니다.
#
#   오차(residual) = 실측 - 예측
#
# zip은 두 리스트를 같은 자리끼리 짝지어 줍니다.
# 첫 칸은 72.3과 72.0, 둘째 칸은 73.1과 72.0 ...
# 그 짝마다 실제에서 예측을 빼면 그 칸의 오차가 나옵니다.

오차목록 = [a - b for a, b in zip(실제, 예측)]
print("오차 다섯 개:", [round(e, 2) for e in 오차목록])
# → 오차 다섯 개: [0.3, 1.1, -0.2, 2.0, 0.6]

# 오차는 '실제 빼기 예측'. 이 정의 하나에서 오늘 모든 게 출발합니다.
# 부호가 있다는 점을 눈여겨보세요. 실측이 기준보다 높으면 양수(+0.3),
# 낮으면 음수(-0.2)입니다. 이 부호가 곧 문제를 일으킵니다.


# ----------------------------------------
# 오늘 만들 세 가지 도구
# ----------------------------------------

# 측정이 하나가 아니라 여럿이면 오차도 여러 개가 나옵니다.
# 우리가 진짜 알고 싶은 건 이걸 뭉뚱그린 '하나의 대표 숫자'죠.
# 오차 하나에서 세 갈래로 갈라집니다.
#
#            [오차 정의]  실제 빼기 예측
#                 │
#     ┌───────────┼───────────┐
#     │ 제곱해 더함           절댓값 평균
#   [SSE]                    [MAE]
#     │  개수로 나눔
#   [MSE]
#
#   SSE  오차를 제곱해서 다 더함
#   MSE  그 SSE를 개수로 나눔 (평균)
#   MAE  제곱 대신 절댓값을 씌워 평균
#
# for, abs, 제곱만 있으면 셋 다 def로 직접 만들 수 있습니다.


# ----------------------------------------
# 오차를 그냥 더하면 상쇄된다
# ----------------------------------------

# 왜 굳이 제곱이나 절댓값을 씌울까요? 그냥 더하면 안 될까요?
# 안 됩니다. 부호를 그대로 둔 채 더하면 양수와 음수가 서로 깎아 먹습니다.

print("그냥 합:", sum(오차목록))
# → 그냥 합: 3.799999999999983
# (0.3 + 1.1 - 0.2 + 2.0 + 0.6.  소수점 뒤가 지저분한 건
#  컴퓨터가 소수를 다루는 방식 탓입니다. 값은 사실상 3.8이에요.)

# 여기서 -0.2가 양수 오차들을 조금 깎아 먹었습니다.
# 더 극단적인 예를 봅시다.

print("+5와 -5의 합:", sum([5, -5]))
# → +5와 -5의 합: 0

# 한 측정이 +5도, 다른 측정이 -5도 벌어졌습니다.
# 둘 다 5도씩이나 틀렸는데 그냥 더하면 0.
# 오차가 하나도 없는 것처럼 보이죠. 이게 '상쇄'입니다.
# 방향만 반대일 뿐 둘 다 5도씩 벌어져 있는데도요.


# ----------------------------------------
# 부호를 없애는 두 갈래
# ----------------------------------------

# 그래서 오차를 모으기 전에 먼저 '부호를 없애야' 합니다.
# 방법이 두 갈래입니다.
#
#   ① 제곱으로 없애기  : 어떤 수든 제곱하면 양수
#                        (-0.2)**2 = 0.04,  (2.0)**2 = 4.0
#                        → SSE·MSE 계열
#
#   ② 절댓값으로 없애기 : abs로 부호만 벗김
#                        abs(-0.2) = 0.2,   abs(2.0) = 2.0
#                        → MAE 계열
#
# 그냥 취향 차이가 아닙니다. 부호를 어떻게 없애느냐에 따라
# 나중에 '크게 튄 값 하나'에 대한 반응이 완전히 달라집니다.
# 이건 세 도구를 다 만든 뒤 직접 숫자로 비교해 봅니다.


# ==========================================================
#  세 가지 오차 도구를 직접 만들기
# ==========================================================

# ----------------------------------------
# SSE - 오차 제곱합
# ----------------------------------------

# 첫 번째 도구 SSE, 오차 제곱합입니다.
#
#   SSE = Σ(실측 - 예측)²     (모든 칸의 오차를 제곱해 다 더함)
#
# y가 실제값, yhat이 예측값입니다.
# a 빼기 b로 오차를 구하고, 별 두 개(**2)로 제곱해 부호를 없앤 뒤,
# sum으로 다 더합니다. 한 줄에 담깁니다.

def sse(y, yhat):
    return sum((a - b) ** 2 for a, b in zip(y, yhat))

print("SSE:", round(sse(실제, 예측), 2))
# → SSE: 5.7
# 오차 0.3, 1.1, -0.2, 2.0, 0.6을 각각 제곱하면
# 0.09 + 1.21 + 0.04 + 4.0 + 0.36 = 5.7.  손계산과 정확히 맞습니다.

# 여기서 제곱의 성질 하나를 기억하세요.
# 제곱은 큰 오차를 유독 크게 부풀립니다.
# 오차 2.0은 제곱하면 4.0인데, 오차 0.2는 0.04에 불과하죠.
# 이 성질이 뒤에서 핵심이 됩니다.


# ----------------------------------------
# MSE - 제곱합의 평균
# ----------------------------------------

# SSE에는 불편함이 하나 있습니다.
# 측정을 많이 할수록 무조건 커진다는 점입니다.
# 작은 오차도 백 개 더해지면 SSE가 커지죠.
# 개수가 다른 두 데이터를 공정하게 비교하려면 개수의 영향을 빼야 합니다.
#
#   MSE = SSE / n            (제곱오차의 평균, 한 칸당 크기)
#
# 이미 만든 sse 함수를 재활용해서, len으로 개수를 구해 나눕니다.

def mse(y, yhat):
    return sse(y, yhat) / len(y)

print("MSE:", round(mse(실제, 예측), 2))
# → MSE: 1.14
# 5.7 / 5 = 1.14.  이건 '한 측정당 평균 제곱 오차'라는 뜻입니다.
# 개수로 나눴으니 다섯 개든 백 개든 한 칸당 기준으로 견줄 수 있죠.

# MSE는 SSE를 개수로 나눈 것뿐이라 제곱 계열의 성질을 그대로 물려받습니다.
# 큰 오차에 여전히 민감합니다.


# ----------------------------------------
# MAE - 절댓값의 평균
# ----------------------------------------

# 세 번째 도구 MAE, 오차 절댓값의 평균입니다.
#
#   MAE = Σ|실측 - 예측| / n     (절댓값오차의 평균)
#
# 앞의 둘이 제곱으로 부호를 없앴다면, MAE는 abs로 없앱니다.
# 오차마다 abs를 씌워 전부 양수로 만들고, sum으로 더해 len으로 나눕니다.
# 제곱이 없다는 점만 빼면 MSE와 흐름이 똑같죠.

def mae(y, yhat):
    return sum(abs(a - b) for a, b in zip(y, yhat)) / len(y)

print("MAE:", round(mae(실제, 예측), 2))
# → MAE: 0.84
# 절댓값 0.3 + 1.1 + 0.2 + 2.0 + 0.6 = 4.2,  4.2 / 5 = 0.84.
# 이 값은 '한 측정당 평균 0.84도 벌어져 있다'는 뜻으로,
# 온도라는 원래 단위 그대로 읽힙니다.

# MAE는 제곱하지 않아서 오차 2.0을 그냥 2.0으로 다룹니다.
# 4.0으로 부풀리지 않죠. 그래서 실제 벌어진 평균 거리에 가깝습니다.


# ----------------------------------------
# 같은 데이터, 세 값
# ----------------------------------------

# 같은 다섯 개 오차인데 세 도구가 낸 값이 다 다릅니다.
#
#   도구 |  방식          |  값
#  ------+---------------+------
#   SSE  |  제곱해 합      |  5.7    ← 가장 큼 (제곱값 다섯 개를 그대로 더함)
#   MSE  |  제곱합의 평균  |  1.14   ← SSE를 5로 나눠 한 칸당 크기로
#   MAE  |  절댓값 평균    |  0.84   ← 가장 작음 (제곱으로 부풀리지 않음)

print("[정상 데이터]")
print("  SSE =", round(sse(실제, 예측), 2))   # → SSE = 5.7
print("  MSE =", round(mse(실제, 예측), 2))   # → MSE = 1.14
print("  MAE =", round(mae(실제, 예측), 2))   # → MAE = 0.84

# 지금은 값이 다르다는 것보다 '왜 다른지'가 중요합니다.
# 이 차이가 극적으로 드러나는 순간이 '이상값이 섞일 때'입니다.


# ----------------------------------------
# 셋의 공통 뿌리
# ----------------------------------------

# 세 도구를 다 만들었으니 감각 하나를 짚고 갑니다.
# 이름은 SSE, MSE, MAE로 제각각이지만 뿌리는 하나입니다.
#   - 셋 다 '실제값 - 예측값'인 오차에서 출발합니다. 한 가족이에요.
#   - 갈림길은 '부호를 없애는 방식' 하나.
#       제곱으로 없애면 → SSE, MSE
#       절댓값으로 없애면 → MAE
#   - 그리고 '개수로 나누느냐 마느냐'로 합이냐 평균이냐가 갈립니다.
#       SSE(합) → 나누면 → MSE(평균)
#
# 복잡해 보이는 세 이름이 사실은 오차 하나에서
# 부호 처리 방식만 바꾼 형제라는 것. 이 구조를 잡으면 안 헷갈립니다.


# ==========================================================
#  이상값 하나가 섞이면 - 제곱과 절댓값의 진짜 차이
# ==========================================================

# ----------------------------------------
# 이상값 하나를 섞으면
# ----------------------------------------

# 이제 세 도구의 진짜 차이를 봅니다.
# 데이터 두 벌을 준비하는데 거의 같습니다.
# 정상 데이터에서 네 번째 칸 하나만 74.0도 → 120.5도로 바꿉니다.
# 용접기 온도가 순간 치솟은 상황이죠. 기준은 그대로 72.0입니다.

실제_이상 = [72.3, 73.1, 71.8, 120.5, 72.6]   # 4번째 칸만 튐(이상값)
예측_이상 = [72.0, 72.0, 72.0, 72.0, 72.0]

print("[이상값 섞은 데이터]")
print("  SSE =", round(sse(실제_이상, 예측_이상), 2))   # → SSE = 2353.95
print("  MSE =", round(mse(실제_이상, 예측_이상), 2))   # → MSE = 470.79
print("  MAE =", round(mae(실제_이상, 예측_이상), 2))   # → MAE = 10.14

# 정상: SSE 5.7,  MSE 1.14,  MAE 0.84
# 이상: SSE 2353.95,  MSE 470.79,  MAE 10.14
# 세 값 다 커졌지만 '커진 정도'가 전혀 다릅니다. 배수로 봅시다.


# ----------------------------------------
# 몇 배나 튀었나
# ----------------------------------------

# 정상값 대비 이상값에서 몇 배로 튀었는지 실제로 계산해 봅니다.

mse_배수 = mse(실제_이상, 예측_이상) / mse(실제, 예측)
mae_배수 = mae(실제_이상, 예측_이상) / mae(실제, 예측)

print("MSE 튄 배수:", round(mse_배수, 1), "배")   # → MSE 튄 배수: 413.0 배
print("MAE 튄 배수:", round(mae_배수, 1), "배")   # → MAE 튄 배수: 12.1 배

#   도구 |  정상  |  이상값  |  튄 배수
#  ------+--------+---------+---------
#   MSE  |  1.14  |  470.79 |  약 413배   ← 제곱 계열, 수백 배 폭발
#   MAE  |  0.84  |  10.14  |  약 12배    ← 절댓값 계열, 열몇 배에 그침
#
# 같은 이상값 하나인데 한쪽은 수백 배, 다른 쪽은 열몇 배.
# MSE는 이상값에 민감, MAE는 덜 민감. 이게 핵심 결론입니다.


# ----------------------------------------
# 제곱이 큰 오차를 부풀리는 구조
# ----------------------------------------

# 이유는 '제곱'에 있습니다. 이상값 칸의 오차를 따라가 봅시다.

이상_오차 = 120.5 - 72.0
print("이상값 칸의 오차:", 이상_오차)          # → 이상값 칸의 오차: 48.5
print("  제곱하면:", 이상_오차 ** 2)           # → 제곱하면: 2352.25
print("  절댓값은:", abs(이상_오차))           # → 절댓값은: 48.5

#                  [오차 48.5]
#                       │
#         ┌─────────────┼─────────────┐
#     제곱하면        절댓값은        합을
#      2352.25          48.5          지배
#     (SSE·MSE)        (MAE)      (2352가 나머지를 압도)
#
# 120.5도와 기준 72.0도의 오차는 48.5도입니다.
#   - SSE·MSE는 이 48.5를 제곱합니다. 48.5² = 2352.25.
#     하나의 오차가 순식간에 2352라는 거대한 숫자가 됩니다.
#     이게 나머지 작은 오차(0.09, 1.21 ...)들을 압도해 합을 지배하죠.
#   - MAE는 abs만 씌우니 48.5 그대로. 부풀지 않습니다.
#     그 한 칸이 다른 칸들과 비슷한 무게라 상대적으로 둔합니다.
#
# 그래서 제곱 계열(SSE·MSE)이 이상값에 민감하고,
# 절댓값 계열(MAE)이 이상값에 덜 흔들립니다.


# ----------------------------------------
# 언제 무엇을 쓰나
# ----------------------------------------

#   제곱 계열(MSE)   |  크게 틀린 하나를 절대 놓치면 안 될 때
#                    |  그 이상값을 크게 부각해 줌
#
#   절댓값 계열(MAE) |  튄 값 하나에 판단이 휘둘리기 싫을 때
#                    |  이상값에 덜 흔들려 안정적
#
#   옳고 그름 없음    |  정답이 아니라 '성격의 차이'
#                    |  데이터에 이상값이 있느냐로 선택
#
# 어느 쪽이 맞고 틀린 문제가 아닙니다. 성격의 차이죠.
# 판단 기준은 '이 데이터에 이상값이 있느냐'입니다.


# ----------------------------------------
# 자를 직접 그려 손에 쥐기 - 이 파트 종합
# ----------------------------------------

# 오늘 정말 중요한 건 이 도구들을 라이브러리에서 꺼내 쓰기 전에
# 손으로 직접 만들어 봤다는 점입니다.
#   def 로 함수를 정의하고,
#   for(와 zip)로 오차를 하나씩 돌고,
