"""[내 파일이 분명히 있는데 왜 없대요?]
데이터를 다루는 코드의 첫 줄은 거의 늘 '파일 열기'입니다.
센서 기록이든 검사 결과든, 파일을 열어야 코드가 일을 시작하죠.

그런데 바로 이 첫 관문에서 막히는 분이 놀랄 만큼 많습니다.
파일 탐색기로 보면 파일은 멀쩡히 그 자리에 있는데,
코드는 "그런 파일 없다"며 FileNotFoundError를 뱉습니다.

이 오류의 진짜 정체는 '파일이 없다'가 아니라 '주소가 어긋났다'입니다.
택배가 반송되는 이유가 상품이 없어서가 아니라 주소가 틀려서인 것과
똑같아요. 이 파일은 그 주소(경로)를 안전하게 잡는 법부터,
파일 속 데이터를 표로 읽어 그 성격을 살피는 데까지 위에서 아래로
훑어 갑니다. 외부 CSV에 의존하지 않게, 실습용 데이터는
이 파일 안에서 직접 만들어 그 자리에서 쓰고 다시 읽습니다.
"""

import os
import csv
from pathlib import Path

import pandas as pd


# ==========================================================
#  실습 데이터 준비 : 파일 안에서 만들어 그 자리서 CSV로 쓴다
# ==========================================================

# 외부 파일 경로에 기대지 않습니다. 제조 센서 데이터를 흉내 낸
# 표를 코드 안에서 직접 만들어, 이 파일 옆에 CSV로 써 둡니다.
# 그러면 어느 컴퓨터에서 실행하든 데이터가 항상 곁에 있습니다.
#
#   측정ID  설비명   온도   진동   회전수  압력  상태
