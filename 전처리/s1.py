# ----------------------------------------
# 제조 데이터의 세 가지 특징
# ----------------------------------------

# 표를 손에 넣었습니다. 그런데 제조 현장 데이터에는 다른 분야와
# 구별되는 특징이 있어요. 이걸 알아야 표를 제대로 읽습니다.
#
#              제조 센서 데이터
#              /      |       \
#         다중 측정  시간 순서  상태 비율
#
#   1) 다중 측정 : 한 설비를 여러 번 잰다 → 같은 설비명이 여러 행에 반복
#                  '한 행 = 한 설비'가 아니라 '한 행 = 한 번의 측정'
#   2) 시간 순서 : 데이터가 시간 순으로 쌓인다 → 측정ID 1,2,3... 이 곧 순서
#                  위가 먼저, 아래가 나중. 행 순서 자체가 정보다
#   3) 상태 비율 : 양품과 불량이 섞여 있고 그 비율이 크게 치우쳐 있다 (오늘의 핵심)


# ----------------------------------------
# 다중 측정과 시간 순서 확인
# ----------------------------------------

# 어떤 설비가 몇 번 측정됐는지 궁금할 때, '한 열 안에서 각 값이 몇 번
# 나오는지' 셉니다. 이때 쓰는 도구가 value_counts입니다. 오늘 여러 번
# 쓸 아주 중요한 도구예요. 결과는 개수가 많은 순으로 정렬되어 나옵니다.

print("[설비별 측정 횟수]")
print(df["설비명"].value_counts())
# → 설비명
# → 절삭기C    6
# → 프레스A    5
# → 용접기B    5
# → Name: count, dtype: int64

# 측정ID 열이 시간의 흐름을 담고 있습니다. 첫 세 행을 꺼내면 1,2,3으로
# 이어지죠. 번호가 작을수록 먼저 측정된 겁니다.
print("측정ID 앞 3개:", df["측정ID"].head(3).tolist())   # → 측정ID 앞 3개: [1, 2, 3]
# 표를 위→아래로 읽는 게 곧 '시간을 따라 읽는' 게 됩니다.
# 그래서 행 순서를 함부로 흩뜨리지 않게 조심합니다. 순서가 정보니까요.


# ----------------------------------------
# 양품과 불량의 비율 - 그리고 분석의 반전
# ----------------------------------------

# 세 번째 특징이자 오늘의 핵심입니다. 상태 열은 각 측정에 대한 판정이에요.
#   정상 = 문제없이 잘 도는 상태
#   주의 = 지켜봐야 할 애매한 상태
#   이상 = 불량 신호가 잡힌 상태
#
# 잘 관리되는 라인이라면 대부분 제품이 '정상'으로 나옵니다. 이상이 자주
# 나오면 공장에 심각한 문제가 있다는 뜻이겠죠. 그러니 '정상 다수, 불량
# 소수'는 나쁜 게 아니라 오히려 건강한 공장의 자연스러운 모습입니다.
#
# 그런데 여기 반전이 있습니다. '데이터로 배우려는' 입장에선 이 치우침이
# 까다로운 성질이 돼요. 우리가 정말 잡고 싶은 건 드물게 나오는 '불량'인데,
# 배울 데이터에 불량 사례가 몇 개 없으면 그 특징을 익히기 어렵습니다.
# 흔한 것은 넘치고, 정작 궁금한 것은 부족한 상황이죠.


# ----------------------------------------
# value_counts로 상태 세기 - 개수와 비율을 나란히
# ----------------------------------------

# 이제 우리 표의 상태를 직접 셉니다. 상태 열에 value_counts 한 줄이면 됩니다.
print("[상태별 개수]")
print(df["상태"].value_counts())
# → 상태
# → 정상    9
# → 주의    4
# → 이상    3
# → Name: count, dtype: int64
# 16번 측정 중 9번 정상, 4번 주의, 3번 이상으로 판정됐다는 뜻입니다.

# 개수만으론 치우침 정도가 한눈에 안 들어올 수 있습니다. normalize=True를
# 넣으면 '비율'을 돌려줍니다. 100을 곱하고 반올림하면 백분율이죠.
print("[상태별 비율(%)]")
print((df["상태"].value_counts(normalize=True) * 100).round(1))
# → 상태
# → 정상    56.2
# → 주의    25.0
# → 이상    18.8
# → Name: proportion, dtype: float64
#
# 전체 절반이 넘는 56.2%가 정상, 정작 잡고 싶은 이상은 18.8% — 다섯에
# 하나가 채 안 됩니다. 비율로 보니 불균형이 훨씬 실감 나죠.
# 개수는 '불량 사례가 충분한지' 판단할 때, 비율은 '치우침 정도'를
# 직관적으로 볼 때 유용합니다. 나란히 보는 습관이 좋습니다.


# ----------------------------------------
# 클래스 불균형이라는 함정
# ----------------------------------------

# 오늘의 가장 중요한 개념, '클래스 불균형'입니다.
#   클래스   = 상태처럼 데이터를 나누는 분류 항목(정상/주의/이상)
#   불균형   = 그 개수가 크게 치우친 상태
#
# 사고 실험을 해 보죠. 어떤 판정기가 아무 생각 없이 '모든 측정을 무조건
# 정상'이라고 찍는다면? 정상이 56.2%니까, 그것만으로 정확도 56.2%를
# 얻습니다. 얼핏 나쁘지 않은 점수죠. 하지만 이 판정기는 이상을 단 하나도
# 못 잡았습니다. 진짜 잡고 싶던 불량 3건을 '전부' 놓쳤는데 말이죠.

majority_ratio = (df["상태"] == "정상").mean() * 100
missed = (df["상태"] == "이상").sum()
print(f"무조건 '정상'으로 찍는 판정기의 정확도: {majority_ratio:.1f}%")
# → 무조건 '정상'으로 찍는 판정기의 정확도: 56.2%
print(f"그런데 놓친 불량(이상) 건수: {missed}건 전부")
# → 그런데 놓친 불량(이상) 건수: 3건 전부
#
# 아무 일도 안 한 판정기가 절반 넘는 점수를 받는 것 — 이게 불균형의
# 함정입니다. 무서운 건 '숫자가 우리를 안심시키기 때문'이에요. 나중에
# 판정 모델을 만들어 정확도가 높게 나오면 "잘 만들었다"고 착각하기 쉽습니다.
# 하지만 데이터가 불균형하면 그 높은 정확도는 '다수를 따라 찍어' 나온
# 허수일 수 있습니다. 그래서 데이터를 처음 탐색하는 이 단계에서 불균형을
# 미리 확인해 둬야 합니다. 높은 정확도를 '의심할 줄' 아는 게 시작이죠.


# ----------------------------------------
# 확인까지가 오늘의 목표
# ----------------------------------------

# 불균형이 함정이라는 걸 알았으니 자연히 "그럼 어떻게 고치느냐"가
# 궁금해집니다. 여기서 오늘의 범위를 분명히 긋겠습니다.
#
# 불균형을 다루는 기법은 여럿 있습니다 — 부족한 쪽을 늘리거나, 많은 쪽을
# 줄이거나, 판정기에게 불량을 더 무겁게 여기도록 가중치를 주거나. 분명
# 중요한 기법들이지만 '오늘은 다루지 않습니다'.
#
# 왜 확인까지만? 순서 때문입니다. 문제를 고치려면 먼저 '문제가 있다'는 걸
# 알아야 합니다. 확인하는 습관을 먼저 몸에 익히면, 나중에 처리 기법을
# 배울 때 "이건 내가 확인했던 그 문제를 푸는 도구구나" 하고 정확히
# 자리를 잡습니다. 확인이 먼저입니다.


# ----------------------------------------
# 데이터 탐색의 전체 흐름 - 오늘 배운 순서
# ----------------------------------------

#   경로 잡기  →  표로 읽기   →  특징 파악      →  불균형 확인
#   os.path로     pd.read_csv    다중 측정·         value_counts로
#   안전한 경로   로 표 완성     시간 순서 읽기      개수·비율 확인
#
# 낯선 제조 데이터를 만나면 이 네 단계로 훑으세요.
#   1) __file__·os.path.join으로 파일을 못 찾을 걱정 없이 경로를 잡고
#   2) pd.read_csv 한 줄로 표(DataFrame)를 완성한 뒤
#   3) value_counts로 설비별 측정 횟수·시간 순서 같은 특징을 살피고
#   4) 상태 열에 value_counts(+normalize)를 걸어 클래스 불균형을 확인한다.
#
# 불균형을 확인하는 눈을 가진 사람은 나중에 높은 정확도를 봐도 함부로
# 기뻐하지 않습니다. 그 신중함이 오늘 이 확인 습관에서 시작됩니다.


# ==========================================================
#  실습 : 센서 CSV 탐색
# ==========================================================

# 목표: 센서 CSV를 안전하게 불러오고, 상태 열의 클래스 불균형을
#       개수와 비율로 확인한다. 완료 기준 세 가지 —
#   (1) 경로가 실제 파일을 가리키는지 exists로 확인
#   (2) 표가 16행 7열로 불러와지는지
#   (3) 상태 분포가 정상 9·주의 4·이상 3이고 다수가 절반을 넘는지

print("\n========== [실습] 센서 CSV 탐색 ==========")

# --- 케이스 A : 안전한 경로 ---
# __file__·dirname·join으로 경로를 만들고, exists로 확인한 뒤 read_csv.
here = os.path.dirname(os.path.abspath(__file__))
path_A = os.path.join(here, "12_제조센서_전처리.csv")
print("케이스 A - 파일 존재:", os.path.exists(path_A))   # → 케이스 A - 파일 존재: True
df_A = pd.read_csv(path_A, encoding="utf-8-sig")
print("케이스 A - 표 크기:", df_A.shape)                 # → 케이스 A - 표 크기: (16, 7)

# --- 케이스 B : 파싱 비교 ---
# csv 모듈과 수동 split으로 같은 첫 행을 읽어 결과가 일치하는지 확인.
with open(path_A, encoding="utf-8-sig") as fb:
    lines_B = fb.read().splitlines()
manual_row = lines_B[1].split(",")
with open(path_A, encoding="utf-8-sig") as fb:
    csv_row = next(csv.reader(fb))   # 헤더
    csv_row = next(csv.reader(fb))   # 첫 데이터 행
print("케이스 B - 두 결과 일치:", manual_row == csv_row)   # → 케이스 B - 두 결과 일치: True

# --- 공통 마무리 : 상태 열의 불균형 확인 ---
counts = df_A["상태"].value_counts()
ratio = (df_A["상태"].value_counts(normalize=True) * 100).round(1)
print("상태 개수:", counts.to_dict())
# → 상태 개수: {'정상': 9, '주의': 4, '이상': 3}
print("상태 비율(%):", ratio.to_dict())
# → 상태 비율(%): {'정상': 56.2, '주의': 25.0, '이상': 18.8}
verdict = "불균형" if ratio.max() > 50 else "균형"
print(f"판정: 다수 클래스 {ratio.max()}% > 50% 이므로 → {verdict}")
# → 판정: 다수 클래스 56.2% > 50% 이므로 → 불균형
