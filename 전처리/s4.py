# -------------------------------
# 데이터 탐색과 전처리 - 난수·재현성과 데이터 분리
# -------------------------------


"""[정해진 값만 다루다가, 무작위 값이 왜 필요할까요?]
지금까지 우리가 다룬 센서 값은 사람이 정해 준 고정된 숫자였습니다.
그런데 모델을 만들려면 수천 줄의 데이터를 '무작위로 뒤섞어'
일부는 학습에, 일부는 검증·테스트에 나눠 써야 합니다.

이때 '어느 행을 어디로 보낼지'를 정하는 도구가 난수(무작위 값)입니다.
주사위 눈처럼 미리 알 수 없는 값이죠.

이 파일은 위에서 아래로 이렇게 흐릅니다.
  난수 만들기 → 실행마다 달라짐 → 시드로 고정(재현성)
  → 데이터를 섞어 학습·검증·테스트로 나누기 → 데이터 누출 막기
마지막은 '시드를 고정한 데이터 분리' 실습입니다.

중요: 이 파일은 시드를 전부 고정해 두어서, 아래 '# →' 출력이
      몇 번을 돌려도 똑같이 나옵니다. 그게 오늘 배울 '재현성'입니다.
"""

# 값 하나짜리 난수는 파이썬 기본 random,
# 배열 단위 난수는 우리가 배운 numpy 를 씁니다. 오늘 둘 다 다룹니다.
import random
import numpy as np
import pandas as pd


# ==========================================================
#  PART 1. 난수와 시드
# ==========================================================

# ----------------------------------------
# 파이썬 난수 도구의 두 갈래
# ----------------------------------------

# 파이썬에서 난수를 뽑는 길은 크게 둘로 갈립니다.
#
#                파이썬 난수
#                 /        \
#      random (값 하나)   np.random (배열 단위)
#
#   random     : 파이썬에 기본으로 들어 있음. 값 하나가 필요할 때 간편.
#   np.random  : 우리가 배운 NumPy. 배열 단위로 많이 필요할 때 빠름.
#
# 먼저 값 하나를 뽑는 기본 random 부터 손으로 만져 봅니다.


# ----------------------------------------
# 파이썬 기본 난수 만들기
# ----------------------------------------

# random.random()  : 0 이상 1 미만 실수 하나
# random.uniform(a,b) : a~b 사이 실수 하나 (센서 온도 70~80 같은 범위)
# random.randint(a,b) : a~b 사이 정수 하나 (끝 b 포함)

random.seed(42)   # 재현 위해 '뽑기 직전'에 시드부터 심는다
print("[기본 난수]")
print("  random.random :", random.random())        # → random.random : 0.6394267984578837
print("  random.uniform:", random.uniform(70, 80)) # → random.uniform: 70.25010755222667
print("  random.randint:", random.randint(1400, 1500))  # → random.randint: 1435

# 초보자가 자주 하는 실수: random.random() 값에 직접 숫자를 곱해
# 범위를 억지로 맞추는 것. 소수가 지저분하게 딸려 나옵니다.
# 정수가 필요하면 처음부터 randint 를 쓰세요.


# ----------------------------------------
# 배열 난수와 정규분포 난수 - np.random
# ----------------------------------------

# 센서 값 수백 개를 한꺼번에 만들 땐 하나씩 뽑는 게 비효율적입니다.
# np.random 은 배열을 통째로 만들어 줍니다.
#
#   np.random.rand(n)  : 0~1 사이 '균등' 난수 n개 (전 구간 고르게)
#   np.random.randn(n) : '정규분포' 난수 n개 (평균 0 근처에 몰림)
#
# 이름 끝 글자로 구분하세요. rand 는 0~1, randn 은 n 이 붙어 정규분포.

np.random.seed(42)
print("\n[배열 난수]")
print("  rand(3) 균등  :", np.random.rand(3))   # → rand(3) 균등  : [0.37454012 0.95071431 0.73199394]

np.random.seed(42)
print("  randn(3) 정규 :", np.random.randn(3))  # → randn(3) 정규 : [ 0.49671415 -0.1382643   0.64768854]

# randn 은 0 근처가 많이 나오고 멀어질수록 드뭅니다(종 모양).
# 현실의 측정 오차가 이런 모양이라, 나중에 모델 초깃값을 줄 때 씁니다.
# 오늘은 '생성 방법'만 봅니다. 통계적 성질은 다루지 않습니다.


# ----------------------------------------
# 시드가 없으면 실행마다 값이 달라진다
# ----------------------------------------

# 난수의 본질은 '무작위'입니다. 시드를 안 심고 연달아 뽑으면 값이 다릅니다.
# (여기선 아무 시드도 심지 않고 두 번 뽑아 비교합니다.)

첫번째 = np.random.rand(3)
두번째 = np.random.rand(3)
print("\n[시드 없이 두 번]")
print("  같은가:", np.array_equal(첫번째, 두번째))   # → 같은가: False
#   (두 배열의 값이 서로 다름)

# 이게 왜 문제일까요.
# 제조 데이터로 모델을 만들어 성능이 잘 나왔는데, 동료에게 코드를 넘겨
# 실행하면 결과가 다르게 나옵니다. 데이터 섞는 부분이 매번 다르게
# 동작하기 때문이죠. 방금 바꾼 설정 덕인지, 그냥 우연인지 구분이 안 됩니다.
# 이 문제를 푸는 장치가 바로 다음에 배울 '시드'입니다.


# ==========================================================
#  PART 2. 재현성 확보
# ==========================================================

# ----------------------------------------
# 시드로 결과 고정하기
# ----------------------------------------

# 컴퓨터 난수는 사실 완전한 무작위가 아니라, 어떤 '시작점'에서
# 정해진 방식으로 값을 이어 만듭니다. 이 시작점이 '시드'입니다.
# 시드를 똑같이 정하면 그 뒤 난수 순서도 똑같아집니다.
#
# 핵심은 '뽑기 직전에 심는다' 이 순서 하나입니다.

np.random.seed(0)
A = np.random.rand(3)
np.random.seed(0)      # 같은 시드를 다시 심고
B = np.random.rand(3)  # 다시 뽑으면
print("\n[시드 고정]")
print("  A     :", A)                      # → A     : [0.5488135  0.71518937 0.60276338]
print("  같은가:", np.array_equal(A, B))    # → 같은가: True

# 아까 실행마다 달라지던 값이 이제 딱 붙잡혀 재현됩니다.
# 시드는 미신이 아니라 스위치입니다. 뽑기 직전에 심는다, 이것만 지키면 됩니다.


# ----------------------------------------
# 두 난수 세계의 시드는 별개
# ----------------------------------------

# 흔한 착각: random.seed(42) 한 줄만 심고 NumPy 난수까지 다 고정됐다고 믿는 것.
#
#   도구        시드 심는 법        고정 대상
#   random      random.seed()       random 함수만
#   np.random   np.random.seed()    NumPy 함수만
#
# 파이썬 기본 random 과 NumPy 의 np.random 은 완전히 다른 두 세계입니다.
# 각자 자기만의 시드를 가져서, 한쪽을 고정해도 다른 쪽은 여전히 흔들립니다.
# 두 도구를 함께 쓴다면 시드도 두 줄로 각각 심어야 합니다.
# 재현이 안 되면 대개 나머지 한 세계의 시드를 빠뜨린 겁니다.


# ----------------------------------------
# 재현성이 중요한 이유
# ----------------------------------------

# 재현성 = 같은 코드를 언제 누가 돌려도 같은 결과가 나오는 성질.
#
#   상황          시드 없음          시드 고정
#   성능 향상 시   설정 덕? 우연?     설정 덕이 확실
#   팀원과 결과    서로 다름          똑같이 재현
#
# 모델 만들기는 끝없는 비교의 연속입니다. 설정을 바꿔 성능이 올랐는지 보고,
# 또 바꿔 비교하죠. 데이터 섞는 부분이 매번 달라지면, 성능이 오른 게
# 내 설정 덕인지 우연인지 알 수 없습니다.
# 시드를 고정하면 달라진 건 오직 '내가 바꾼 설정 하나'뿐이라,
# 성능 변화를 온전히 그 효과로 해석할 수 있습니다.
# 재현성은 실험의 '공정한 저울'입니다.


# ==========================================================
#  PART 3. 데이터 분리
# ==========================================================

# ----------------------------------------
# [실습 재료] 제조 센서 데이터 (파일 없이 코드 안에서 정의)
# ----------------------------------------

# 외부 CSV 에 의존하지 않고, 여기서 직접 표를 만듭니다.
# 일부러 '설비가 한쪽으로 쏠린' 데이터로 만들었습니다.
#   앞쪽 10줄 = 프레스A,  뒤쪽 6줄 = 절삭기C
# 이렇게 몰려 있으면, 그냥 앞에서부터 자를 때 왜 안 되는지 바로 보입니다.

df = pd.DataFrame({
    "설비": ["프레스A"] * 10 + ["절삭기C"] * 6,
    "온도": [72, 75, 71, 78, 74, 76, 73, 77, 70, 79,   # 프레스A
             88, 91, 85, 93, 87, 90],                  # 절삭기C
})
print("\n[원본 데이터]")
print("  전체 행 수:", len(df))          # → 전체 행 수: 16
print("  프레스A 수:", (df["설비"] == "프레스A").sum())   # → 프레스A 수: 10
print("  절삭기C 수:", (df["설비"] == "절삭기C").sum())   # → 절삭기C 수: 6


# ----------------------------------------
# 앞에서부터 자르면 안 되는 이유
# ----------------------------------------

# 나누기 전에 왜 섞어야 할까요. 그냥 앞 60% 를 잘라 보면 답이 나옵니다.

앞60 = df.iloc[:int(len(df) * 0.6)]   # 앞에서부터 그냥 자름 (앞 9줄)
print("\n[안 섞고 앞 60% 만 자르면]")
print("  이 안의 설비:", 앞60["설비"].unique().tolist())   # → 이 안의 설비: ['프레스A']

# 프레스A 만 들어갔습니다. 학습엔 프레스만, 테스트엔 절삭기만 가 버리죠.
# 그래서 나누기 '전에' 무작위로 섞어야 합니다.
#
# 요령: 표 자체를 섞기보다, '행 번호 목록'을 만들어 그 번호를 섞습니다.
#       섞인 번호 순서대로 행을 골라 나누면 설비가 고르게 퍼집니다.


# ----------------------------------------
# 인덱스 섞기 - random.shuffle
# ----------------------------------------

# random.shuffle 은 목록을 '제자리에서' 섞고 아무것도 돌려주지 않습니다.
# 반환값을 받으려 하면 None 이 담기니, 그냥 실행만 하세요.

random.seed(42)                 # 섞는 순서까지 재현되도록 고정
인덱스 = list(range(len(df)))   # [0, 1, 2, ..., 15]
random.shuffle(인덱스)          # 제자리에서 섞음 (반환값 없음)
print("\n[섞은 인덱스]")
print(" ", 인덱스)
# → [7, 9, 5, 6, 14, 10, 12, 8, 1, 2, 13, 15, 4, 11, 0, 3]

# 앞서 random.seed(42) 를 심어 뒀으니, 이 섞이는 순서가 매번 똑같습니다.
# (return 값을 확인해 보면 아무것도 없습니다)
print("  shuffle 반환값:", random.shuffle([1, 2, 3]))   # → shuffle 반환값: None


# ----------------------------------------
# 비율로 학습·검증·테스트 분리
# ----------------------------------------

# 섞인 인덱스를 비율 위치에서 '슬라이싱'해 세 덩어리로 나눕니다.
# 전체 16줄을 6:2:2 로 나눕니다.

n = len(df)                                    # 16
train_end, val_end = int(n * 0.6), int(n * 0.8)   # 9, 12
# 소수점은 int 가 '버림'해 깔끔한 정수 경계를 만들어 줍니다.

train = df.iloc[인덱스[:train_end]]        # 앞 60%  (인덱스 0~8번째)
val   = df.iloc[인덱스[train_end:val_end]]  # 다음 20% (9~11번째)
test  = df.iloc[인덱스[val_end:]]           # 나머지 20% (12번째부터)

print("\n[6:2:2 분리]")
print("  경계:", train_end, val_end)          # → 경계: 9 12
print("  학습/검증/테스트:", len(train), len(val), len(test))   # → 학습/검증/테스트: 9 3 4
print("  합계:", len(train) + len(val) + len(test))   # → 합계: 16

# 세 표의 행 수를 더하면 원래 16 이 그대로 나옵니다. 하나도 안 흘렸죠.
# 이제 섞어 나눴으니 학습에도 두 설비가 고르게 들어갑니다.
print("  학습 안의 설비:", sorted(train["설비"].unique().tolist()))
# → 학습 안의 설비: ['절삭기C', '프레스A']
#   (안 섞었을 땐 프레스A 뿐이었는데, 이제 둘 다 들어갔습니다)


# ----------------------------------------
# 세 덩어리의 역할
# ----------------------------------------

#   덩어리    역할          언제 쓰나
#   학습      모델이 배움    학습 내내 (가장 큰 몫, 여기서만 규칙을 익힘)
#   검증      설정 비교      학습 도중 (어느 설정이 나은지 점수로 비교)
#   테스트    실전 확인      맨 마지막 한 번 (모든 준비가 끝난 뒤 딱 한 번)
#
# 테스트는 마지막에 딱 한 번. 점수 보고 모델을 또 고치면
# 실전 시험이 연습 문제로 전락합니다.


# ----------------------------------------
# 데이터 누출이란
# ----------------------------------------

# 데이터를 애써 나눴는데도, 나눠 놓은 벽을 몰래 넘나드는 실수가 있습니다.
# 데이터 누출(leakage)입니다.
#
#                    데이터 누출
#                 /       |        \
#   테스트 값이   →   점수만    →   실전 성능
#   기준에 섞임        부풀려짐        하락
#
# 가장 흔한 누출은 값의 크기를 조정하는 '스케일링'에서 생깁니다.
# 값을 줄이는 기준(최솟값·최댓값)을 '전체 데이터'에서 구하면,
# 그 안에 테스트도 섞여 있으니 몰라야 할 값을 기준에 써 버린 겁니다.
# → 테스트 점수는 좋게 나오지만, 현장에 배포하면 성능이 뚝 떨어집니다.
# 시험 문제를 가려 놓고 준비 과정에서 그 문제를 살짝 엿본 셈이죠.


# ----------------------------------------
# 스케일 기준은 학습에서만
# ----------------------------------------

# 데이터 누출을 막는 규칙은 한 문장입니다.
#   "값을 줄이는 기준은 오직 학습 데이터에서만 구한다."

lo = train["온도"].min()      # 학습에서만 기준 (최솟값)
hi = train["온도"].max()      # 학습에서만 기준 (최댓값)
print("\n[스케일 기준 = 학습에서만]")
print("  학습 온도 min/max:", lo, hi)   # → 학습 온도 min/max: 70 88

# 검증·테스트는 '자기 값'으로 기준을 다시 구하지 않고,
# 학습에서 구한 그 기준을 그대로 가져다 0~1 로 변환합니다.
# (학습 범위를 벗어난 값은 0~1 밖으로 나갈 수도 있습니다. 정상입니다 —
#  기준을 학습에서만 잡았다는 증거죠.)
val_scaled  = (val["온도"]  - lo) / (hi - lo)
test_scaled = (test["온도"] - lo) / (hi - lo)
print("  검증 스케일:", np.round(val_scaled.values, 3))    # → 검증 스케일: [0.056 1.278 1.111]
print("  테스트 스케일:", np.round(test_scaled.values, 3)) # → 테스트 스케일: [0.222 1.167 0.111 0.444]

# 실전에서 우리는 미래 데이터를 미리 볼 수 없으니,
# 손에 쥔 학습 데이터 안에서만 기준을 정하는 게 공정한 방식입니다.
# df 전체로 min·max 를 구하는 순간 누출이 시작됩니다.
# 기준은 학습에서만, 나머지는 그 기준을 빌려 쓴다 — 이게 핵심입니다.


# ----------------------------------------
# 오늘의 흐름 정리
# ----------------------------------------

#   1) 시드 고정   → 재현성 확보 (바꾼 설정 효과와 우연을 구분)
#   2) 난수 생성   → 무작위 값 (시드 없으면 실행마다 달라짐)
#   3) 인덱스 섞기 → 설비 쏠림 방지
