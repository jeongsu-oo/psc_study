# ==========================================================
#  [실습] 시드 고정 데이터 분리
# ==========================================================

# 목표: 시드를 고정해 재현 가능하게 섞고, 비율로 나누고,
#       스케일 기준은 학습에서만 구한다.
# 아래 두 케이스는 앞에서 배운 흐름을 함수 하나로 묶은 것뿐입니다.


def 분리하기(df, 비율, 시드=42):
    """섞어서 비율대로 나누는 흐름을 한 함수로. 비율 예: (0.7, 0.3)"""
    random.seed(시드)                 # 시드 고정 → 매번 같은 순서
    idx = list(range(len(df)))
    random.shuffle(idx)               # 제자리에서 섞기
    n = len(df)
    조각들, 시작 = [], 0
    for r in 비율:
        끝 = 시작 + int(n * r)
        조각들.append(df.iloc[idx[시작:끝]])
        시작 = 끝
    조각들[-1] = df.iloc[idx[시작 - int(n * 비율[-1]):]]  # 마지막은 나머지 전부
    return 조각들


# --- 케이스 A : 7:3 분리 후, 같은 시드로 재현 확인 ---
print("\n[케이스 A] 7:3 분리 + 재현 확인")
a1, _ = 분리하기(df, (0.7, 0.3), 시드=1)   # 첫 번째 실행 (학습, 테스트)
a2, _ = 분리하기(df, (0.7, 0.3), 시드=1)   # 같은 시드로 두 번째 실행
print("  학습 행 수:", len(a1))            # → 학습 행 수: 11
# 같은 시드라 두 번 나눠도 학습 인덱스가 완전히 똑같습니다.
print("  재현되나:", list(a1.index) == list(a2.index))   # → 재현되나: True


# --- 케이스 B : 6:2:2 분리 후, 압력 기준을 학습에서만 ---
print("\n[케이스 B] 6:2:2 분리 + 학습에서만 스케일")
df_b = df.assign(압력=[10, 12, 11, 14, 13, 15, 12, 16, 11, 17,   # 프레스A
                       20, 22, 19, 24, 21, 23])                  # 절삭기C
tr, va, te = 분리하기(df_b, (0.6, 0.2, 0.2), 시드=42)
print("  학습/검증/테스트:", len(tr), len(va), len(te))   # → 학습/검증/테스트: 9 3 4

lo2, hi2 = tr["압력"].min(), tr["압력"].max()   # 기준은 학습에서만!
print("  학습 압력 min/max:", lo2, hi2)          # → 학습 압력 min/max: 11 21
te_scaled = (te["압력"] - lo2) / (hi2 - lo2)     # 테스트는 학습 기준으로 변환
print("  테스트 압력 스케일:", np.round(te_scaled.values, 3))
# → 테스트 압력 스케일: [ 0.2  1.1 -0.1  0.3]

