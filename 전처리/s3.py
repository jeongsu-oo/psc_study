"""[숫자 크기가 열마다 다른데 그냥 모델에 넣어도 될까요?]
제조 라인에서 뽑아 온 센서 표를 하나 펼쳐 봅시다.
온도, 회전수, 진동이 한 행에 나란히 있습니다.

그런데 온도는 71~120 사이 두세 자리,
회전수는 1450처럼 네 자리, 진동은 한 자리 근처입니다.
같은 표에 있지만 숫자의 크기 자체가 열마다 완전히 다릅니다.

앞으로 만들 모델은 값의 크기를 그대로 받아들입니다.
회전수가 온도보다 스무 배쯤 크면, 실제 중요도와 무관하게
단지 숫자가 크다는 이유로 회전수가 계산을 지배해 버립니다.
온도의 의미 있는 변화가 큰 숫자에 묻혀 목소리를 잃죠.

스케일링은 값을 왜곡하는 게 아닙니다.
열마다 다른 '자'를 같은 자로 바꿔 공평하게 보게 만드는 겁니다.
이 파일은 그 스케일링과, 글자 열을 숫자로 바꾸는 인코딩을
라이브러리에 맡기지 않고 손으로 직접 만들어 봅니다.
"""

import numpy as np
import pandas as pd


# ----------------------------------------
# 실습 데이터 - 파일 없이 표를 코드 안에 정의
# ----------------------------------------

# 외부 CSV 없이, 범위가 서로 다른 센서 열들을 코드 안에 직접 적어 둡니다.
# 온도(두~세 자리), 회전수(네 자리, -50 이상값 섞임), 진동(한~두 자리),
# 그리고 숫자가 아닌 상태(정상/주의/이상) 열까지 한 표에 담았습니다.
df = pd.DataFrame({
    "온도":   [72.3, 73.1, 120.5, 74.0, 72.8, 73.5],
    "회전수": [1445, 1452, 1449, -50, 1450, 1470],
    "진동":   [2.9, 3.1, 15.2, 3.0, 2.8, 3.3],
    "상태":   ["정상", "정상", "이상", "주의", "정상", "정상"],
})
print(df)
# →       온도    회전수    진동  상태
# → 0    72.3   1445   2.9  정상
# → 1    73.1   1452   3.1  정상
# → 2   120.5   1449  15.2  이상
# → 3    74.0    -50   3.0  주의
# → 4    72.8   1450   2.8  정상
# → 5    73.5   1470   3.3  정상


# ----------------------------------------
# 열마다 다른 값의 범위 - 눈으로 확인
# ----------------------------------------

# 스케일링이 왜 필요한지, 각 열의 최소·최대를 나란히 놓아 봅니다.
for col in ["온도", "회전수", "진동"]:
    print(col, "범위:", df[col].min(), "~", df[col].max())
# → 온도 범위: 72.3 ~ 120.5
# → 회전수 범위: -50 ~ 1470
# → 진동 범위: 2.8 ~ 15.2

# 온도는 두~세 자리, 회전수는 네 자리, 진동은 한 자리 근처입니다.
# 자릿수가 열마다 다르죠. 이 상태 그대로 모델에 넣으면
# 큰 숫자 열(회전수)이 판을 지배합니다. 그래서 공통 기준으로 맞춰 줍니다.
#
# 참고: 회전수 최소가 -50인 건 센서가 잠깐 오작동해 찍힌 이상값입니다.
# 이런 값이 있어도 스케일링은 최소·최대를 기준으로 눌러 담습니다.


# ==========================================================
#  방법 1 : Min-Max 스케일링 - 0~1 범위로 당기기
# ==========================================================

# ----------------------------------------
# Min-Max의 아이디어
# ----------------------------------------

# 첫 번째 방법은 Min-Max 스케일링입니다.
# 한마디로 '가장 작은 값을 0, 가장 큰 값을 1로 당겨 0~1 범위로' 만드는 겁니다.
#
#   수식(참고용):  x' = (x - 최소) / (최대 - 최소)
#
# 손으로 따라가 봅시다.
#   - 가장 작은 값을 넣으면 → 분자가 0이라 결과 0
#   - 가장 큰 값을 넣으면   → 분자와 분모가 같아 결과 1
#   - 나머지 값은          → 그 사이 어딘가(0~1)에 배치
#
# 결국 어떤 열이든 0에서 1까지의 칸 안으로 눌러 담는 변환이죠.


# ----------------------------------------
# Min-Max를 반복문으로 직접 만들기
# ----------------------------------------

# 라이브러리를 부르지 않고, 반복문 몇 줄로 공식을 그대로 옮겨 봅니다.
온도값 = df["온도"].dropna().tolist()   # 빈 칸 빼고 값만 리스트로
최소, 최대 = min(온도값), max(온도값)   # 최솟값·최댓값을 미리 구해 둠

결과 = []
for x in 온도값:
    결과.append(round((x - 최소) / (최대 - 최소), 3))   # 공식을 값마다 적용
print("Min-Max(온도):", 결과)
# → Min-Max(온도): [0.0, 0.017, 1.0, 0.035, 0.01, 0.025]

# 세 번째 값이 1.0인데, 이게 120.5도입니다. 가장 큰 값이라 1로 눌렸죠.
# 나머지는 대부분 0에 가깝습니다. 온도 대부분이 72도 근처에 몰려 있고
# 120.5 하나만 멀리 떨어져 있으니까요.


# ----------------------------------------
# 반복을 함수로 묶기 - 온도든 회전수든 재사용
# ----------------------------------------

# 앞의 반복문을 온도에만 썼는데, 회전수에도 진동에도 똑같이 쓰고 싶죠.
# 매번 다시 쓰긴 번거로우니 def 로 묶습니다.
# 값 리스트를 받아 최소·최대를 구하고 범위로 나눈 결과를 돌려주는 함수예요.

def minmax(values):
    lo, hi = min(values), max(values)
    return [round((x - lo) / (hi - lo), 3) for x in values]

회전수값 = df["회전수"].dropna().tolist()
진동값 = df["진동"].dropna().tolist()

print("minmax(온도):", minmax(온도값))       # → minmax(온도): [0.0, 0.017, 1.0, 0.035, 0.01, 0.025]
print("minmax(회전수):", minmax(회전수값))   # → minmax(회전수): [0.984, 0.988, 0.986, 0.0, 0.987, 1.0]

# 온도에 넣으면 앞의 반복문과 똑같은 결과가 나오고,
# 코드 한 줄 고치지 않고 회전수도 0~1 사이로 변환됩니다.
# 회전수는 값이 좁게 몰려 있고 -50이 섞여 있어도 함수는 묵묵히 눌러 담죠.
# (-50이 최소라 0.0으로 눌리고, 1470이 최대라 1.0이 됩니다.)
#
# 함수의 힘은 재사용입니다. 한 번 잘 만들면 열 이름만 바꿔 넣으면 됩니다.


# ==========================================================
#  방법 2 : 표준화 - 다른 기준으로 맞추기
# ==========================================================

# ----------------------------------------
# 표준화는 0~1이 아니다 (헷갈리기 쉬운 지점)
# ----------------------------------------

# 여기서 반드시 짚고 갈 게 있습니다.
#
#   Q. 표준화는 0~1로 바꾸나?    → 아니오. 그건 방금 배운 Min-Max의 일.
#   Q. 그럼 무엇으로 바꾸나?      → 평균 기준 '상대 위치'로 이동.
#   Q. 공식은?                   → (x - 평균) / 표준편차
#
# 한마디로 '평균을 0, 표준편차를 1 단위로' 맞추는 겁니다.
#
#   수식(참고용):  z = (x - 평균) / 표준편차
#
# 평균을 빼서 중심을 0으로 옮기고, 표준편차로 나눠 퍼진 정도를 1로 맞춥니다.
# 다시 강조 - 표준화 결과는 0~1 사이가 아닙니다. 음수도, 큰 값도 나옵니다.


# ----------------------------------------
# 표준화를 함수로
# ----------------------------------------

# standardize 함수는 값 리스트를 받아, 넘파이로 평균과 표준편차를 구한 뒤,
# 각 값에 공식을 적용해 돌려줍니다.

def standardize(values):
    arr = np.array(values)
    m, s = arr.mean(), arr.std()   # 평균, 표준편차
    return [round(float((x - m) / s), 3) for x in values]

print("표준화(온도):", standardize(온도값))
# → 표준화(온도): [-0.495, -0.449, 2.235, -0.398, -0.466, -0.427]

# 온도 값 대부분이 0 근처에 모여 있습니다.
# 온도가 대체로 72도 언저리에 몰려 있어 평균에서 크게 벗어나지 않으니까요.
# 그런데 120.5도 하나(세 번째 값)만 2.2로 튑니다.
# 평균에서 표준편차의 2.2배만큼 멀리 떨어져 있다는 뜻이에요.
# 표준화는 이렇게 유독 튀는 값을 또렷하게 드러내 줍니다.


# ----------------------------------------
# 표준편차가 0이면 - 분모 0의 함정
# ----------------------------------------

# 표준화 공식에는 조심할 지점이 있습니다. 분모에 표준편차가 들어간다는 점이에요.
# 나눗셈에서 분모가 0이면 계산이 무너집니다.
#
# 표준편차가 0이 되는 경우가 실제로 있습니다.
# 한 열의 모든 값이 완전히 똑같으면 퍼진 정도가 없으니 표준편차가 정확히 0입니다.
# 어떤 설비의 회전수가 점검 내내 1450으로 고정돼 있었다면 그렇죠.
#
# 이때 (x - 평균) / 0 을 하면 넘파이는 오류 대신 조용히 nan 을 돌려줍니다.
# 오류가 안 나니 더 위험해요. 모르고 지나가면 nan 이 모델까지 흘러갑니다.

같은값 = [1450, 1450, 1450]
arr = np.array(같은값)
print("표준편차:", arr.std())                 # → 표준편차: 0.0
print("그냥 나누면:", (arr - arr.mean()) / arr.std())   # → 그냥 나누면: [nan nan nan]
# 오류 없이 nan 세 개. 이래서 미리 걸러 줘야 합니다.


# ----------------------------------------
# 분모 0을 막는 조건 분기
# ----------------------------------------

# 그래서 함수 안에 조건 분기를 하나 넣습니다.
# 표준편차 s 를 구한 뒤, 만약 그 값이 0이면 나눗셈을 하지 말고
# 전부 0으로 채워 돌려줍니다. (모든 값이 같으면 상대 위치도 다 같으니 0이 자연스럽죠.)

def standardize_safe(values):
    m, s = np.mean(values), np.std(values)
    if s == 0:                       # 분모 0 방지
        return [0.0 for _ in values]
    return [round(float((x - m) / s), 3) for x in values]

print("safe(같은값):", standardize_safe(같은값))   # → safe(같은값): [0.0, 0.0, 0.0]
print("safe(온도):", standardize_safe(온도값))     # → safe(온도): [-0.495, -0.449, 2.235, -0.398, -0.466, -0.427]

# 같은 값만 든 리스트를 넣어도 오류도 nan도 없이 0으로 채워집니다.
# 조건 분기 한 줄이 데이터 전체를 지켜 줍니다.
# 스케일링 함수를 직접 만들 때 이 예외 처리를 빠뜨리면 안 됩니다.


# ----------------------------------------
# 같은 값을 두 방법으로 - 성격 비교
# ----------------------------------------

# 두 방법을 같은 온도 열에 적용해 나란히 놓아 봅니다.
# 같은 데이터인데 결과 성격이 완전히 다르죠.
mm = minmax(온도값)
zz = standardize(온도값)
print("원본 / Min-Max / 표준화")
for x, a, b in zip(온도값, mm, zz):
    print(f"  {x:>6} | {a:>6} | {b:>7}")
# →   72.3 |    0.0 |  -0.495
# →   73.1 |  0.017 |  -0.449
# →  120.5 |    1.0 |   2.235
# →   74.0 |  0.035 |  -0.398
# →   72.8 |   0.01 |  -0.466
# →   73.5 |  0.025 |  -0.427

# Min-Max 는 모든 값을 0~1 사이 정해진 칸에 밀어 넣습니다.
#   최솟값은 0, 최댓값은 1로 경계가 딱 정해지죠.
# 표준화 는 경계가 없습니다. 평균 근처는 0 언저리, 멀수록 크게 벌어져요.
#   120.5도가 Min-Max에서는 그냥 1.0으로 눌리지만,
#   표준화에서는 2.2라는 눈에 띄는 값으로 드러납니다.


# ----------------------------------------
# 언제 어느 방법을 쓰나
# ----------------------------------------

#   Min-Max  |  값을 0~1 정해진 범위로 딱 맞출 때
#            |  상한·하한이 분명한 데이터(예: 이미지 밝기)에 적합
#   표준화   |  튀는 값의 정도를 살려 보고 싶을 때
#            |  이상값을 눌러 버리지 않고 평균에서 벗어난 정도를 보존
#   공통     |  둘 다 라이브러리가 아니라 우리가 손으로 만든 함수
#            |  안에서 무슨 계산인지 알고 골라 쓰는 게 핵심
#
# 정답은 하나가 아닙니다. 데이터 성격과 목적에 따라 고르는 겁니다.


# ==========================================================
#  범주형 인코딩 : 글자 열을 숫자로
# ==========================================================

# ----------------------------------------
# 글자 열은 어떻게 하나
# ----------------------------------------

# 지금까지 다룬 스케일링은 모두 '숫자 열'을 위한 것이었습니다.
# 그런데 우리 표에는 숫자가 아닌 열이 있어요.
# 상태 열은 정상, 주의, 이상이라는 '글자'로 채워져 있죠.
#
# 이렇게 정해진 몇 가지 값 중 하나를 갖는 열을 '범주형'이라 부릅니다.
# 문제는 모델이 글자를 그대로 받지 못한다는 점이에요.
# 모델은 숫자로 계산하는 기계라서 '정상'이라는 글자를 넣으면 이해하지 못합니다.
#
# 그래서 범주형 값을 숫자로 바꿔 주는 '인코딩'이 필요합니다. 두 방법을 봅니다.

# 먼저 어떤 값들이 있는지부터 확인하는 습관 (매핑 빠뜨림 방지)
print("상태 종류:", list(df["상태"].unique()))   # → 상태 종류: ['정상', '이상', '주의']


# ----------------------------------------
# 방법 1 - 정수 인코딩
# ----------------------------------------

# 가장 단순한 방법. 각 범주에 정수를 하나씩 붙이는 규칙을 딕셔너리로 정합니다.
매핑 = {"정상": 0, "주의": 1, "이상": 2}
df["상태코드"] = df["상태"].map(매핑)   # 모든 글자가 규칙대로 정수로 바뀜
print(df[["상태", "상태코드"]])
# →    상태  상태코드
# → 0  정상     0
# → 1  정상     0
# → 2  이상     2
# → 3  주의     1
# → 4  정상     0
# → 5  정상     0

# 정상이 있던 자리엔 0, 이상엔 2가 채워집니다. 글자 열이 숫자 열로 변신했죠.
#
# 함정: 매핑에 범주 하나를 빠뜨리면 그 자리는 규칙에 없어서 nan 이 됩니다.
# 그래서 위에서 unique 로 값 종류를 먼저 확인한 겁니다.


# ----------------------------------------
# 방법 2 - 원핫 인코딩
# ----------------------------------------

# 정수 인코딩엔 부작용이 있습니다.
# 정상 0, 주의 1, 이상 2로 바꾸면 숫자에 '크기 순서'가 생겨요.
# 모델이 '이상이 정상보다 두 배 크다'고 오해할 수 있습니다.
# 사실 그냥 '다른 종류'일 뿐인데요.
#
# 그 오해를 피하려고 원핫 인코딩을 씁니다.
# 범주마다 열을 하나씩 만들고, 상태가 그 범주와 같으면 1, 아니면 0을 채웁니다.

범주 = ["정상", "주의", "이상"]
for c in 범주:
    df["상태_" + c] = (df["상태"] == c).astype(int)   # 같으면 1, 아니면 0
print(df[["상태", "상태_정상", "상태_주의", "상태_이상"]])
