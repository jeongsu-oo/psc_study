# → 3  주의       0      1      0
# → 4  정상       1      0      0
# → 5  정상       1      0      0

# 정상인 행은 상태_정상 열만 1, 이상인 행은 상태_이상만 1입니다.
# 0과 1만 남으니 크기 순서 오해가 사라집니다.
# (판다스 pd.get_dummies 를 쓰면 이 반복문을 한 줄로 대신할 수도 있어요.)
#
# 원핫은 크기 오해를 없애는 대신 열이 늘어납니다. 범주가 셋이면 열도 셋이죠.


