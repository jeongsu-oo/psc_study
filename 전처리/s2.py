# -------------------------------
# 데이터 전처리 - 결측값과 이상값 처리
# -------------------------------


"""[표를 불러왔으면 바로 계산하면 되나요?]
아직 안 됩니다. 실무에서 받은 표에는 거의 항상 두 가지 함정이 숨어 있어요.

  첫째, 값이 있어야 할 자리가 비어 있는 '빈 칸'(결측값).
        Pandas는 이걸 NaN 으로 표시하는데, 무서운 건 조용하다는 겁니다.
        빈 칸이 섞여 있어도 표는 멀쩡히 나오고 오류도 안 나면서
        통계만 미묘하게 어긋납니다.

  둘째, 다른 값과 동떨어지게 크거나 작은 '튀는 값'(이상값).
        딱 하나만 섞여도 평균과 표준편차를 크게 흔들어 놓습니다.

이 둘을 걷어내는 손질이 '정제'입니다.
계산에 들어가기 전 반드시 거쳐야 하는 관문이죠.
이 파일은 그 정제 도구들을 위에서 아래로 훑으며 익힙니다.
"""

# pandas는 pd, numpy는 np 로 부르는 게 전 세계 관례입니다. 다르게 쓰지 마세요.
import pandas as pd
import numpy as np


# ----------------------------------------
# 왜 정제부터 하나 - 조용한 함정 두 가지
# ----------------------------------------

# 앞 시간에 우리는 센서 표를 불러오고 크기와 통계를 훑어봤습니다.
# 표가 어떻게 생겼는지는 알았죠. 그런데 이 표를 진짜로 계산에 쓰려면
# 아래 두 함정을 먼저 걷어내야 합니다.
#
#   빈 칸(NaN)   →  조용해서 오류 없이 통계만 어긋남
#   튀는 값       →  평균·표준편차를 크게 왜곡
#
# 그래서 오늘의 정제는 이어질 스케일링이 쓰는 '평균과 표준편차'를
# 바로잡는 필수 단계입니다. (스케일링 얘기는 맨 끝에서 다시 합니다.)


# ----------------------------------------
# 오늘의 정제 흐름 - 네 단계
# ----------------------------------------

#   [1] 결측 확인   →  [2] 결측 처리   →  [3] 이상값 처리  →  [4] 결과 확인
#   isnull로            dropna·fillna       필터·클리핑        왜곡 사라짐
#   빈 칸 세기                                                  확인
#
# 먼저 빈 칸이 어디에 몇 개 있는지 확인하고 시작합니다. 이게 안전한 순서예요.
# 빈 칸을 지우거나 대표값으로 채우고, 그다음 튀는 값을 걸러 내거나 눌러 담고,
# 마지막에 처리 전후 통계를 비교해 왜곡이 사라졌는지 확인합니다.


# ----------------------------------------
# 실습 데이터 - 결측·이상값을 일부러 섞은 센서 표
# ----------------------------------------

# 외부 CSV 없이 파일 안에서 직접 표를 만듭니다.
# 빈 칸은 None(=NaN)으로, 이상값은 말이 안 되는 숫자로 일부러 심어 뒀어요.
#
#   - 온도 열: 빈 칸 2개, 이상값 120.5 하나 (정상은 70도 초반)
#   - 압력 열: 빈 칸 1개
#   - 진동 열: 이상값 15.2 하나 (정상은 2 안팎)
#   - 회전수 열: 이상값 -50 하나 (회전수는 음수가 될 수 없음)
#   - 측정ID 8번은 일부러 두 번 넣어 '중복 행'을 만듦

data = {
    "측정ID": [1, 2, 3, 4, 5, 6, 7, 8, 8, 9, 10, 11, 12, 13, 14],
    "온도":   [71.2, 73.5, None, 72.8, 120.5, 70.1, 74.0, 73.0, 73.0,
               None, 73.9, 71.8, 72.2, 74.6, 73.0],
    "압력":   [101.3, 102.0, 100.8, None, 101.5, 100.9, 102.3, 101.1, 101.1,
               100.5, 101.9, 102.1, 100.7, 101.4, 101.0],
    "진동":   [2.1, 2.3, 1.9, 2.0, 2.5, 15.2, 2.2, 2.4, 2.4,
               1.8, 2.1, 2.3, 2.0, 2.6, 2.2],
    "회전수": [1450, 1470, 1440, 1460, 1480, 1455, 1465, 1445, 1445,
               -50, 1475, 1450, 1460, 1470, 1455],
}
df = pd.DataFrame(data)

print("[처음 받은 표]")
print("행·열 크기:", df.shape)   # → 행·열 크기: (15, 5)
# 15행 5열. 이 안에 빈 칸, 이상값, 중복이 섞여 있습니다.


# ----------------------------------------
# 결측 개수 한 번에 세기 - isnull().sum()
# ----------------------------------------

# 계산에 들어가기 전 '반드시 먼저 쳐 보는 한 줄'입니다.
# isnull()은 표의 모든 칸을 검사해서 빈 칸이면 True, 값이 있으면 False로 바꿉니다.
# 여기에 sum()을 이어 붙이면, 파이썬이 True를 1로 세기 때문에
# 열마다 빈 칸이 몇 개인지 숫자로 나옵니다.

print("\n[열별 빈 칸 개수]")
print(df.isnull().sum())
# → 측정ID    0
# → 온도      2
# → 압력      1
# → 진동      0
# → 회전수    0
# → dtype: int64
#
# 온도 열에 2개, 압력 열에 1개가 뜹니다.
# 0이 나오면 통과, 숫자가 뜨면 처리 대상입니다.
# (isna() 라는 형제 함수도 있는데 기능은 완전히 같습니다.)


# ----------------------------------------
# 중복 행 점검 - duplicated / drop_duplicates
# ----------------------------------------

# 빈 칸을 확인했다면 한 가지 더 봅니다. 완전히 똑같은 행이 두 번 들어간 '중복'입니다.
# 로그를 합치다 같은 측정이 두 번 기록되기도 하죠.
# duplicated().sum() 으로 세고, drop_duplicates() 로 지웁니다.

print("\n중복 행 개수:", df.duplicated().sum())   # → 중복 행 개수: 1

df = df.drop_duplicates()   # 결과는 다시 담기 (원본을 안 바꿈)
print("중복 제거 후 행 수:", len(df))   # → 중복 제거 후 행 수: 14
# 측정ID 8번이 두 번 있었으니, 지우면 15행이 14행으로 줄어듭니다.
#
# ★ 지금 중요한 습관 하나: 계산을 시작하기 전에 '빈 칸과 중복부터' 확인한다.


# ----------------------------------------
# dropna - 빈 칸이 있는 행을 통째로 제거
# ----------------------------------------

# 결측을 처리하는 가장 단순한 방법은 빈 칸이 있는 행을 아예 빼는 겁니다.
# df.dropna() 는 빈 칸이 하나라도 있는 행을 통째로 제거한 '새 표'를 돌려줍니다.

제거본 = df.dropna()            # 결과는 변수에 담기
print("\n[dropna 로 전부 제거]")
print("14행 →", len(제거본), "행")   # → 14행 → 11 행
# 빈 칸이 든 행 3개(온도 2 + 압력 1)가 빠져 11행이 됩니다.

# 행 전체를 지우기 아까울 때는 subset 으로 '기준 열'만 지정합니다.
온도만_제거 = df.dropna(subset=["온도"])
print("온도 기준만 제거 →", len(온도만_제거), "행")   # → 온도 기준만 제거 → 12 행
# 온도가 빈 행만 지우고, 압력이 빈 행은 남겨 12행이 됩니다.
#
# ★ 초보가 가장 많이 걸리는 곳:
#   dropna 는 원본을 바꾸지 않습니다.
#   제거본 = df.dropna() 처럼 결과를 '변수에 담아야' 실제로 쓸 수 있어요.


# ----------------------------------------
# 행 제거의 대가 - 멀쩡한 값까지 버려진다
# ----------------------------------------

# 행 제거는 단순하고 확실합니다.
# 전체 데이터가 넉넉하고 빈 칸이 몇 개 안 될 때는 그 몇 줄을 지워도
# 통계가 거의 영향을 안 받으니 깔끔한 선택입니다.
#
# 다만 대가가 있습니다.
#   온도만 비었을 뿐 진동과 회전수는 멀쩡했는데,
#   그 행을 통째로 지우면 '멀쩡한 값들도 함께' 버려집니다.
#
# 행 하나하나가 아까운 상황이라면 이 손실이 부담스럽죠.
# 그래서 행을 버리는 대신 빈 칸만 그럴듯한 값으로 채우는 반대 방법,
# fillna 로 넘어갑니다.


# ----------------------------------------
# fillna - 빈 칸을 대표값으로 채우기
# ----------------------------------------

# 행을 버리기 아까울 때는 빈 칸을 '대표값'으로 채웁니다.
# 대표값으로 자주 쓰는 건 평균과 중앙값이에요.

평균 = df["온도"].mean()      # 빈 칸은 빼고 나머지로 계산
중앙값 = df["온도"].median()
print("\n온도 평균:", round(평균, 2))     # → 온도 평균: 76.72
print("온도 중앙값:", 중앙값)              # → 온도 중앙값: 73.0
#
# 대부분의 온도가 70도 초반인데 '평균만' 유독 76.72로 높습니다.
# 이상값 120.5 하나가 평균을 위로 확 끌어올린 거죠.
# 그래서 중앙값(73.0)을 씁니다. 극단값이 하나 있어도 거의 안 흔들려 안전합니다.

df["온도"] = df["온도"].fillna(중앙값)   # 결과를 '다시 그 열에' 담아야 반영됨
print("채운 뒤 온도 빈 칸:", df["온도"].isnull().sum())   # → 채운 뒤 온도 빈 칸: 0
#
# ★ fillna 도 dropna 처럼 원본을 안 바꿉니다.
#   df["온도"] = df["온도"].fillna(...) 처럼 다시 담지 않으면 빈 칸이 그대로예요.
#   ("fillna 를 쳤는데 빈 칸이 그대로다" → 십중팔구 '다시 담기'를 빠뜨린 것)


# ----------------------------------------
# 평균 vs 중앙값 - 이상값에 대한 반응
# ----------------------------------------

#   대표값        |  온도 결과값  |  이상값 영향
#  --------------+--------------+-----------------
#   평균 mean     |    76.72     |  위로 크게 끌림
#   중앙값 median |    73.0      |  거의 안 흔들림
#
# 같은 온도 열인데 대표값을 뭘로 잡느냐에 따라 숫자가 달라집니다.
#   - 평균은 이상값 120.5 하나에 위로 크게 끌려갑니다(극단값에 약함).
#   - 중앙값은 값을 크기순으로 줄 세웠을 때 '한가운데' 오는 값이라,
#     극단값이 하나 있어도 한 칸 옆으로 밀릴 뿐 거의 흔들리지 않습니다.
#
# ★ 이상값이 의심되는 데이터의 빈 칸은 평균보다 중앙값으로 채우는 게 대체로 안전합니다.

# 압력도 같은 방식으로 채워 둡니다(압력엔 이상값이 없어 중앙값으로 무난하게).
df["압력"] = df["압력"].fillna(df["압력"].median())
print("\n채운 뒤 압력 빈 칸:", df["압력"].isnull().sum())   # → 채운 뒤 압력 빈 칸: 0


# ----------------------------------------
# 제거 vs 대체 - 무엇을 고를까
# ----------------------------------------

#   기준        |  제거 dropna         |  대체 fillna
#  ------------+----------------------+---------------------
#   데이터 양   |  행이 넉넉할 때        |  행이 아까울 때
#   빈 칸 비율  |  비율 크면 열 폐기 검토 |  비율 작을 때 안전
#   값의 성격   |  종류형 값에 적합       |  연속 수치에 적합
#
#   - 데이터 양: 수천 줄인데 빈 칸이 몇 줄이면 지워도 통계가 거의 안 변함 → 제거.
#               행 하나하나가 아까우면 → 대체.
#   - 빈 칸 비율: 한 열의 절반 이상이 비었다면 채워도 못 믿음(없는 값을 지어내는 셈)
#               → 그 열 자체를 폐기하는 게 나을 수도. 한두 개면 대체가 안전.
#   - 값의 성격: 온도·압력 같은 연속 수치는 평균·중앙값으로 채우기 좋고,
#               설비명·상태 같은 종류형 값은 평균이 없어 제거하거나 최빈값으로.
#
# ★ 정답은 하나가 아닙니다. 데이터 양·빈 칸 비율·값의 성격을 그때그때 저울질하는 겁니다.
#
# 우리 표는? 온도·압력 빈 칸이 적고 연속 수치라 '중앙값 대체'를 택해 행을 최대한 살렸습니다.
# (앞뒤 값 추정이나 모델로 빈 칸을 예측하는 방식은 이 범위 밖 — 단순·설명 가능한 방법으로 충분합니다.)


# ----------------------------------------
# 조건 필터로 이상값 제거 - '남길 것'을 고른다
# ----------------------------------------

# 빈 칸을 다 채웠으니, 이제 표 안에 멀쩡한 숫자처럼 앉아 있는 이상값 차례입니다.
# 우리 표엔 온도 120.5, 진동 15.2, 회전수 -50 이 있죠.
#
# 특히 회전수 -50 은 대놓고 이상합니다. 회전수는 물리적으로 음수가 될 수 없으니까요.
# 이렇게 '말이 안 되는' 값은 채우지 말고 행을 빼는 게 맞습니다.
#
# 방법은 조건 필터인데, 발상이 중요합니다.
#   '지울 것'을 고르는 게 아니라 '남길 것'을 조건으로 고릅니다.

작업본 = df.copy()   # 원본 df 는 그대로 두고 사본에서 작업
작업본 = 작업본[작업본["회전수"] > 0]   # 회전수가 0보다 큰 행만 남기기
print("\n[회전수 음수 행 제거]")
print("14행 →", len(작업본), "행")   # → 14행 → 13 행
# 회전수 -50 행이 자연스레 빠져 13행이 됩니다.
#
# ★ 앞에서 '조건으로 행 고르기'를 배웠던 그 문법 그대로, 이번엔 이상값을 걸러 낸 거예요.


# ----------------------------------------
# 함부로 지우면 안 되는 값 - 고장 직전의 진짜 신호
# ----------------------------------------

# 조건을 잡을 때 신중해야 합니다.
#   - 회전수 음수처럼 '물리적으로 불가능한' 값은 명백한 오류라 지워도 안전합니다.
#   - 하지만 단지 값이 '좀 크다'는 이유로 함부로 지우면 위험합니다.
#
# 설비가 고장 나기 직전엔 값이 크게 튀는 게 정상이고,
# 그게 바로 우리가 잡아야 할 신호일 수 있습니다.
# 그걸 이상값이라 지워 버리면 가장 중요한 정보를 버리는 셈이죠.
#
# ★ 그래서 '명백히 오류인 값'만 제거하고, '방향은 맞지만 과한 값'은 다음의 클리핑으로 다룹니다.


# ----------------------------------------
# 상한 클리핑 - 행은 살리고 튀는 값만 눌러 담기
# ----------------------------------------

# 이상값을 무조건 지우면 그 행의 '다른 멀쩡한 값'도 함께 사라집니다.
# 온도만 120.5로 튀었을 뿐 진동·회전수는 정상이었다면 아깝죠.
# 이럴 때 행은 그대로 두고 '튀는 값만' 상한선으로 눌러 담는 게 클리핑입니다.
#
# 핵심 도구는 loc 입니다.
#   작업본.loc[ 행 조건 , 열 이름 ] = 새 값
#   → 대괄호 안, 쉼표 '앞'이 행 조건, '뒤'가 열 이름.
#     어느 행의 어느 열을 고칠지 한 번에 콕 집어 지정합니다.

print("\n클리핑 전 최고 온도:", 작업본["온도"].max())   # → 클리핑 전 최고 온도: 120.5
작업본.loc[작업본["온도"] > 100, "온도"] = 100   # 온도가 100 넘는 행의 온도만 100으로
print("클리핑 후 최고 온도:", 작업본["온도"].max())   # → 클리핑 후 최고 온도: 100.0
# 120.5가 100으로 눌려 최고 온도가 정리됩니다.
#
# ★ loc 없이 조건 필터에 바로 값을 대입하면 '사본'에 대입되어 원본이 안 바뀔 수 있습니다.
#   조건 위치를 고쳐 쓸 때는 반드시 loc 로 행과 열을 한 번에 지정하세요.


# ----------------------------------------
# 제거 vs 클리핑 - 값의 성격으로 나눠 쓰기
# ----------------------------------------

#   제거      |  물리적으로 불가능해 못 믿을 값  |  회전수 -50 → 행 삭제
#   클리핑    |  방향은 맞지만 지나치게 큰 값    |  온도 120.5 → 상한 100
#   실수 주의 |  조건에 바로 대입은 위험         |  반드시 loc 로 행·열 지정
#
#   - 명백한 오류(회전수 음수)는 → 제거.
#   - 과한 값(온도 120.5)은 → 완전히 버리기보다 상한으로 눌러 정보를 덜 잃는 클리핑.


# ----------------------------------------
# 처리 전후 - 왜곡이 사라지는 것을 숫자로 확인
# ----------------------------------------

# 정제가 통계 왜곡을 얼마나 줄였는지 '숫자로' 확인하며 정리합니다.
# 정제 전(원본 데이터)과 정제 후(작업본)를 나란히 놓고 비교해 보죠.

원본 = pd.DataFrame(data).drop_duplicates()   # 아무것도 손대지 않은 비교용 표

print("\n[처리 전후 비교]")
print("  온도 평균 :", round(원본["온도"].mean(), 2),
      "→", round(작업본["온도"].mean(), 2))   # → 온도 평균 : 76.72 → 74.85
print("  최고 온도 :", 원본["온도"].max(),
      "→", 작업본["온도"].max())               # → 최고 온도 : 120.5 → 100.0
print("  최소 회전수:", 원본["회전수"].min(),
      "→", 작업본["회전수"].min())             # → 최소 회전수: -50 → 1440
print("  온도 표준편차:", round(원본["온도"].std(), 2),
      "→", round(작업본["온도"].std(), 2))     # → 온도 표준편차: 13.85 → 7.65
#
# 온도 평균은 76.72에서 74.85로 내려와 실제 중심에 훨씬 가까워졌습니다.
# 최고 온도는 120.5→100, 최소 회전수는 -50→1440 으로 제자리를 찾았고요.
# ★ 특히 표준편차를 보세요. 13.85에서 7.65로 확 줄었습니다.
#   이상값 '딱 하나'가 평균과 표준편차를 동시에 부풀렸던 겁니다.
#   정제는 통계를 '정직하게' 만드는 필수 절차예요.


# ----------------------------------------
# 정제가 스케일링을 살리는 이유
# ----------------------------------------

# 이게 왜 결정적이냐면, 다음 작업인 '스케일링'이 바로 이 평균과 표준편차를
# 재료로 쓰기 때문입니다.
#
#   스케일링 = 값들을 일정한 기준으로 다시 맞추는 작업
#           그 기준을 '평균과 표준편차'로 잡음
#
# 재료가 되는 이 두 숫자가 이상값 때문에 어긋나 있으면,
# 그걸 기준으로 맞춘 '모든 값'이 함께 어긋납니다.
# 왜곡된 자로 잰 길이가 전부 틀리는 것과 같죠.
#
# ★ 새 센서 파일을 받으면: 빈 칸 확인 → 결측 처리 → 이상값 처리.
#   이 순서를 습관처럼 밟는 것이 데이터를 다루는 기본기입니다.


# ----------------------------------------
# [실습] 센서 데이터 정제 한 바퀴
# ----------------------------------------

# 오늘 배운 도구를 하나의 흐름으로 이어 직접 손에 익히는 시간입니다.
# 아래 두 케이스 중 흥미 있는 쪽을 골라, 처음부터 끝까지 정제를 한 바퀴 돌리세요.
#
#   케이스 A (온도)      : 온도 결측 → 중앙값 대체,  이상값 → 상한 100 클리핑
#   케이스 B (압력·회전수): 압력 결측 → 평균 대체,   회전수 음수 행 → 조건 필터 제거
#
#   Step 1 | drop_duplicates 로 중복 제거, isnull().sum() 으로 결측 확인
#   Step 2 | fillna 로 대상 열 결측 대체
#   Step 3 | loc 클리핑 또는 조건 필터로 이상값 처리 후 통계 확인
#
# [완료 기준 3가지]
#   1) isnull().sum() 결과에서 대상 열 빈 칸이 0
#   2) 이상값 처리 후 그 열의 최댓값/최솟값이 정상 범위에 들어옴
#   3) 처리 후 평균이 처리 전보다 현실적인 값으로 안정됨
#
# 아래는 케이스 A를 처음부터 한 바퀴 돌린 예시입니다(정답 코드).

실습 = pd.DataFrame(data).drop_duplicates()          # Step 1: 중복 제거
실습["온도"] = 실습["온도"].fillna(실습["온도"].median())  # Step 2: 중앙값 대체
실습.loc[실습["온도"] > 100, "온도"] = 100             # Step 3: 상한 100 클리핑

print("\n[실습 - 케이스 A 완료 점검]")
print("  온도 빈 칸:", 실습["온도"].isnull().sum())   # → 온도 빈 칸: 0
print("  최고 온도:", 실습["온도"].max())              # → 최고 온도: 100.0
print("  온도 평균:", round(실습["온도"].mean(), 2))   # → 온도 평균: 74.72
#
