print("""
스마트 무인 카페에 오신 것을 환영합니다!
----------------------------------------------
""")
coffee = input("아메리카노 1잔의 가격을 입력하세요 (예 : 4000) : ")
cups = input("주문할 잔 수를 입력하세요 (예 : 3) : ")
upto = input("오늘의 할인율(%)을 입력하세요 (예 : 10.5) : ")
cash = input("지갑에 가진 현금 총액을 입력하세요 (예 : 15000) : ")

tot = int(coffee) * int(cups)
sales = int(int(coffee) * int(cups) * int(upto) / 100)
pay = bool(tot - sales < int(cash))

print(f"""
=============================================
              [영수증 및 결제 내역]
=============================================
* 메뉴 가격 : {coffee}원
* 주문 수량 : {cups}잔
* 총 주문액 : {tot}원
* 할인 적용 : -{sales}원 ({float(upto)}%)
---------------------------------------------
* 최종 결제 : {tot - sales}원
* 보유 현금 : {cash}원
---------------------------------------------
* 결제 가능 여부 : {pay}
* 남은 잔돈 : {int(cash) - (tot - sales)}원
=============================================
이용해주셔서 감사합니다. 좋은 하루 보내세요!
""")
