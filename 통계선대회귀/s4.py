# ----------------------------------------
# 오늘 만든 세 함수 - 정리
# ----------------------------------------

#   함수       |  하는 일                    |  핵심
#  -----------+-----------------------------+------------------------------
#   fit(x,y)   |  데이터 보고 w,b 정하기      |  w=공분산/분산,  b=ȳ-w·x̄
#   predict(x) |  새 x 의 y 예측             |  y = w·x + b
#   score(x,y) |  얼마나 잘 맞나 (R²)        |  R² = 1 - SSE/SST
#
# 그리고 4부작이 하나로 이어진 그림:
#   1편 평균·표준편차 → 데이터 성격 재기
#   2편 행렬          → 여러 값을 표로 다루기
#   3편 공분산        → x와 y가 같이 움직이는 정도   ┐
#   4편 회귀          → 그 공분산 ÷ 분산 = 예측 직선 기울기 ┘ 여기서 합류
#
# 오늘 만든 예측 직선의 심장(기울기 w)이 3편의 공분산이었습니다.
# 앞의 세 편이 흩어진 조각이 아니라, 오늘의 예측 모델을 위한 부품이었던 거죠.


# ----------------------------------------
# 이 방식의 한계 - 그리고 다음 이야기(경사하강법)
# ----------------------------------------

# 오늘은 공식에 값만 넣어 w, b 를 '한 번에' 구했습니다(closed-form).
# 변수가 하나(온도)라 공식이 딱 떨어졌기 때문이에요.
#
# 그런데 현실에선 예측에 쓰는 입력이 여러 개인 경우가 많습니다.
# 온도만이 아니라 습도·압력·가동시간까지 함께 넣어 불량을 예측한다면,
# 또는 관계가 직선이 아니라 더 복잡하다면, 이 깔끔한 공식이
# 통째로 풀리지 않거나 계산이 감당 안 되는 상황이 옵니다.
#
# 그럴 때 쓰는 방법이 '경사하강법' 입니다.
#   - 한 번에 정답을 구하는 대신,
#   - 아무 w, b 에서 출발해 오차(SSE)가 줄어드는 쪽으로 조금씩 이동하며
#   - 정답에 '점점 다가가는' 방식이죠.
#
# 오늘의 최소제곱이 "공식으로 단번에", 다음 과정의 경사하강법이
# "조금씩 걸어서 찾아가기" 입니다. 같은 목표(SSE 최소)를 향한 두 길인 셈이죠.
# 오늘 SSE 라는 목표와 예측 직선의 뼈대를 손으로 만들어 봤으니,
# 다음 과정에서 그 목표를 '걸어서' 찾아가는 이야기로 이어집니다.


# ----------------------------------------
# [실습] 나만의 예측 직선 만들기
# ----------------------------------------

# 오늘 만든 선형회귀 클래스를 그대로 써서, 새 데이터에 직선을 맞춰 보세요.
#
#   케이스 A : 가동시간(x)으로 진동(y) 예측
#   케이스 B : 압력(x)으로 불량(y) 예측
#
#   Step 1) 모델 = 선형회귀()  만들고  모델.fit(x, y)
#   Step 2) 모델.w, 모델.b 출력 — 기울기와 절편 확인
#   Step 3) 모델.predict(새값) 으로 안 겪은 x 의 y 예측
#   Step 4) 모델.score(x, y) 로 R² 확인 (1에 가까울수록 잘 맞음)
#   Step 5) sklearn LinearRegression 과 w, b 가 같은지 대조
#
# 완료 기준 : w·b·예측값·R² 가 화면에 나오고, sklearn 과 w,b 가 일치하면 성공.

# (실습 정답 예시 — 케이스 A 가동시간 → 진동)
가동시간 = [10, 20, 30, 40, 50, 60, 70, 80]
진동     = [0.5, 0.7, 0.9, 1.0, 1.3, 1.4, 1.6, 1.8]

실습모델 = 선형회귀()
실습모델.fit(가동시간, 진동)
print("[실습 예시 · 가동시간→진동]")
print("  w:", round(실습모델.w, 4), "/ b:", round(실습모델.b, 4))
print("  가동 55시간 예측 진동:", round(실습모델.predict(55), 4))
print("  R²:", round(실습모델.score(가동시간, 진동), 4))

X실습 = np.array(가동시간).reshape(-1, 1)
sk실습 = LinearRegression().fit(X실습, 진동)
print("  sklearn w:", round(sk실습.coef_[0], 4), "/ b:", round(sk실습.intercept_, 4))
# → [실습 예시 · 가동시간→진동]
# →   w: 0.0183 / b: 0.325
# →   가동 55시간 예측 진동: 1.3333
# →   R²: 0.9941
# →   sklearn w: 0.0183 / b: 0.325
