# ----------------------------------------
# 우리가 만든 게 진짜 맞을까 - sklearn 으로 채점
# ----------------------------------------

# 파트13에서 numpy 를 '채점표'로 썼듯이, 오늘은 선형회귀의 표준 도구인
# sklearn 의 LinearRegression 과 나란히 놓고 채점합니다.
# 값이 소수점까지 같으면, 우리가 만든 게 그 유명한 도구와 '똑같은 것' 이라는 뜻이죠.
#
#   우리 fit 의 w        ↔  sklearn 의 coef_ (기울기)
#   우리 fit 의 b        ↔  sklearn 의 intercept_ (절편)
#   우리 score 의 R²     ↔  sklearn 의 score

from sklearn.linear_model import LinearRegression

# sklearn 은 x 를 '세로 표(2차원)' 로 받습니다. 한 줄 온도를 세로로 세워 줍니다.
X = np.array(온도).reshape(-1, 1)
sk = LinearRegression().fit(X, 불량)

print("[직접 구현]", "w:", round(제조모델.w, 6),
      "b:", round(제조모델.b, 6),
      "R²:", round(제조모델.score(온도, 불량), 6))
# → [직접 구현] w: 0.5 b: -7.2 R²: 0.980975

print("[sklearn ]", "w:", round(sk.coef_[0], 6),
      "b:", round(sk.intercept_, 6),
      "R²:", round(sk.score(X, 불량), 6))
# → [sklearn ] w: 0.5 b: -7.2 R²: 0.980975

# 세 값이 소수점까지 똑같습니다.
# 부동소수점의 아주 미세한 오차(1e-9 미만)까지 감안해 자동 채점하면:

w일치 = abs(제조모델.w - sk.coef_[0]) < 1e-9
b일치 = abs(제조모델.b - sk.intercept_) < 1e-9
r2일치 = abs(제조모델.score(온도, 불량) - sk.score(X, 불량)) < 1e-9
print("직접==sklearn ?  w:", w일치, "/ b:", b일치, "/ R²:", r2일치)
# → 직접==sklearn ?  w: True / b: True / R²: True

# 전부 True.
# sklearn 안에서 벌어지는 일이 오늘 우리가 손으로 짠 그 공식과 똑같습니다.
# closed-form 공식(공분산÷분산)을 그대로 계산할 뿐이에요.
# 도구를 '가져다 쓰는' 사람에서, 도구 '안을 아는' 사람이 된 겁니다.


