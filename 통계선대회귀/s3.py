# ----------------------------------------
# n vs n-1 분모 함정
# ----------------------------------------

# 내 함수를 채점할 때 반드시 짚어야 할 함정이 하나 있습니다.
# 우리는 공분산·분산을 '개수 n' 으로 나눴습니다.
# 그런데 np.cov 의 기본값은 'n-1' 로 나눕니다 (표본 보정이라는 다른 정의).
#
# 그래서 그냥 대조하면 값이 살짝 어긋납니다.
# 우리(n)와 맞추려면 numpy 에 이렇게 알려 줘야 합니다.
#   np.cov(...,  bias=True)   ← 분모를 n 으로 (기본 n-1 을 끔)
#   np.var(...,  ddof=0)      ← 분모를 n 으로 (기본값이 이미 0)
#
# np.corrcoef(상관계수)는 분모가 위아래에서 약분돼 사라지므로
# n / n-1 차이에 영향받지 않습니다. 그건 그냥 대조하면 됩니다.

# np.cov 는 2×2 표(행렬)로 돌려줍니다. 대각선이 각자의 분산,
# 바깥 칸([0][1])이 둘 사이의 공분산입니다.
np_cov = np.cov(온도, 불량, bias=True)[0][1]
print("[직접] cov(온도,불량):", round(공분산(온도, 불량), 4))   # → [직접] cov(온도,불량): 8.75
print("[numpy] cov (bias=True):", round(np_cov, 4))            # → [numpy] cov (bias=True): 8.75

# bias 를 빼면(기본 n-1) 어긋난다는 것도 눈으로 확인:
print("[numpy] cov (기본 n-1):", round(np.cov(온도, 불량)[0][1], 4))   # → [numpy] cov (기본 n-1): 10.0
# 8.75 가 아니라 10.0. 이래서 bias=True 로 분모를 맞춰 줘야 합니다.


# ----------------------------------------
# 공분산·상관 나란히 채점
# ----------------------------------------

# np.corrcoef 도 2×2 표로 돌려주고, 바깥 칸이 상관계수 r 입니다.
np_r = np.corrcoef(온도, 불량)[0][1]

print("[직접 구현]",
      round(공분산(온도, 불량), 4),
      round(상관계수(온도, 불량), 4))
# → [직접 구현] 8.75 0.9547

print("[numpy   ]",
      round(np.cov(온도, 불량, bias=True)[0][1], 4),
      round(np_r, 4))
# → [numpy   ] 8.75 0.9547

# 공분산은 bias=True 로 분모를 n 에 맞춰 8.75 로 일치,
# 상관계수는 약분 덕에 그냥도 0.9547 로 일치합니다.


# ----------------------------------------
# 세 센서 쌍을 한 번에 채점
# ----------------------------------------

# 온도-불량 한 쌍이 아니라, 세 쌍을 한 번에 돌며
# 내 함수와 numpy 가 (분모를 맞췄을 때) 같은지 자동 확인합니다.
# (실수 계산은 미세 오차가 있어 '완전히 같음' 대신 1e-9 미만이면 같다고 봅니다.)

쌍들 = {
    "온도-불량": (온도, 불량),
    "온도-압력": (온도, 압력),
    "온도-수율": (온도, 수율),
}

print("[세 쌍 채점 — 직접 == numpy?]")
for 이름, (a, b) in 쌍들.items():
    cov_같음 = abs(공분산(a, b) - np.cov(a, b, bias=True)[0][1]) < 1e-9
    r_같음   = abs(상관계수(a, b) - np.corrcoef(a, b)[0][1]) < 1e-9
    print(f"  {이름}  cov={cov_같음}  r={r_같음}")
# → [세 쌍 채점 — 직접 == numpy?]
# →   온도-불량  cov=True  r=True
# →   온도-압력  cov=True  r=True
# →   온도-수율  cov=True  r=True
# 세 쌍 모두 True → 직접 구현이 numpy 와 정확히 일치합니다.


