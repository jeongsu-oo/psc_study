# -------------------------------
# 공분산·상관·표준화 - 두 변수가 같이 움직이나
# -------------------------------


"""[한 변수 말고, 두 변수 사이는 어떻게 재나요?]
지난 편까지는 '한 변수'가 얼마나 흩어졌나를 봤습니다.
온도가 평균에서 얼마나 퍼져 있나 — 분산·표준편차였죠.

그런데 현장에서 진짜 궁금한 건 대개 '두 변수 사이'입니다.
  "온도가 올라가면 불량도 같이 오르나?"
  "압력을 높이면 불량이 줄어드나?"
한 변수의 흩어짐을 넘어, 두 변수가 '같이 움직이나'를 보는 겁니다.

이걸 재는 도구가 공분산과 상관계수입니다.
오늘도 준비된 함수를 그냥 쓰지 않고, 순수 파이썬으로 직접 만들어
numpy 와 나란히 채점합니다. 그리고 이 공분산이 다음 편 '회귀의
기울기'로 곧장 이어진다는 것까지 미리 봐 둡니다.
"""

# 마지막에 직접 구현을 채점할 때만 씁니다. 그전까지는 전부 순수 파이썬.
import numpy as np


# 이 파일 전체에서 쓸 센서 측정값. 외부 파일 없이 직접 적어 둡니다.
# 어떤 설비를 8번(8일) 관찰하며 매번 세 가지를 같이 잰 기록입니다.
#   온도  : 그날 설비 평균 온도(도)
#   불량  : 그날 나온 불량품 개수(개)
#   압력  : 그날 설비 평균 압력(bar)
온도 = [70, 72, 74, 76, 78, 80, 82, 84]
불량 = [3,  4,  4,  6,  7,  7,  9,  8]
압력 = [4.0, 4.1, 4.0, 4.2, 4.3, 4.2, 4.5, 4.4]


# 지난 편에서 만든 세 함수를 그대로 가져옵니다(이 편의 밑돌).
# 공분산·상관은 이 위에 쌓입니다.
def 평균(xs):
    return sum(xs) / len(xs)                         # Σx / n

def 분산(xs):
    m = 평균(xs)
    return sum((x - m) ** 2 for x in xs) / len(xs)   # Σ(x-평균)² / n

def 표준편차(xs):
    return 분산(xs) ** 0.5                            # √분산


# ========================================================
#  PART 1 : 두 센서가 같이 움직이나 (직관)
# ========================================================

# ----------------------------------------
# 온도가 오르면 불량도 오르나 - 눈으로 먼저
# ----------------------------------------

# 숫자를 재기 전에 그림으로 감을 잡습니다.
# 8일치 (온도, 불량) 을 산점도처럼 대충 찍어 보면:
#
#   불량
#    9 |                         o        ← 온도 높을수록
#    8 |                            o       불량도 위로
#    7 |               o    o
#    6 |          o
#    4 |     o  o
#    3 |  o
#      +---------------------------------  온도
#       70  72  74  76  78  80  82  84
#
# 점들이 왼쪽 아래 → 오른쪽 위로 줄지어 오릅니다.
# "온도가 높은 날은 불량도 많다" 는 경향이 눈에 보이죠.
# 이렇게 한쪽이 오를 때 다른 쪽도 같이 오르는 관계를 숫자 하나로
# 잡아내는 것이 오늘의 목표입니다.

for i in range(len(온도)):
    막대 = "o" * 불량[i]
    print(f"  온도 {온도[i]}도 | {막대} ({불량[i]}개)")
# →   온도 70도 | ooo (3개)
# →   온도 72도 | oooo (4개)
# →   온도 74도 | oooo (4개)
# →   온도 76도 | oooooo (6개)
# →   온도 78도 | ooooooo (7개)
# →   온도 80도 | ooooooo (7개)
# →   온도 82도 | ooooooooo (9개)
# →   온도 84도 | oooooooo (8개)
# 위에서 아래로 내려갈수록(온도가 오를수록) 막대가 대체로 길어지죠.


# ----------------------------------------
# 방향에는 세 가지가 있다
# ----------------------------------------

# 두 변수가 움직이는 방향은 크게 셋으로 나뉩니다.
#
#   같이 오름  : 한쪽 ↑ 이면 다른 쪽도 ↑   (온도 ↑ → 불량 ↑)
#   반대로 감  : 한쪽 ↑ 이면 다른 쪽은 ↓   (압력 ↑ → 불량 ↓ 같은)
#   무관       : 한쪽이 움직여도 다른 쪽은 제멋대로
#
# 우리가 만들 공분산은 바로 이 '방향'을 부호(+, -, 0)로 알려 줍니다.
# +면 같이 오르고, -면 반대로 가고, 0 근처면 무관합니다.


# ========================================================
#  PART 2 : 공분산 - 편차 곱의 평균
# ========================================================

# ----------------------------------------
# 공분산 수식과 직관
# ----------------------------------------

# 공분산 정의는 이렇습니다.
#
#   cov(x, y) = Σ(xᵢ - x̄)(yᵢ - ȳ) / n
#                └편차x┘ └편차y┘
#
# 분산이 '편차를 제곱해 평균낸 것' 이었죠. Σ(x-x̄)² / n.
# 공분산은 제곱 대신 'x의 편차 × y의 편차' 를 평균낸 것입니다.
# 곧, 같은 자리의 두 편차를 곱해서 다 더한 뒤 개수로 나누는 겁니다.
#
# 왜 이게 '방향'을 잡아낼까? 한 자리씩 뜯어 보면:
#   x도 y도 둘 다 평균보다 큰 날  → (+)×(+) = +
#   x도 y도 둘 다 평균보다 작은 날 → (−)×(−) = +   ← 같이 움직이면 +
#   한쪽만 평균보다 큰 날          → (+)×(−) = −   ← 엇갈리면 −
#
# 같이 움직이는 날이 많으면 +가 쌓여 합이 양수,
# 엇갈리는 날이 많으면 −가 쌓여 합이 음수가 됩니다.
# 그 합의 평균이 공분산이에요.


# ----------------------------------------
# 공분산 직접 구현
# ----------------------------------------

# 수식을 그대로 코드로 옮깁니다.
# x의 편차와 y의 편차를 같은 자리끼리 곱해(zip) 더하고, 개수로 나눕니다.
# 주의: x 와 y 는 길이가 같아야 짝을 맞출 수 있습니다.

def 공분산(xs, ys):
    mx = 평균(xs)                      # x̄
    my = 평균(ys)                      # ȳ
    합 = 0
    for x, y in zip(xs, ys):           # 같은 날의 x, y 를 짝지어
        합 += (x - mx) * (y - my)      # (x-x̄)(y-ȳ) 를 누적
    return 합 / len(xs)                # Σ(...) / n

print("cov(온도, 불량):", round(공분산(온도, 불량), 4))
# → cov(온도, 불량): 8.75
# 부호가 +(양수)입니다. 온도가 오르면 불량도 같이 오른다는 신호죠.


# ----------------------------------------
# 부호의 의미 - +, -, 0
# ----------------------------------------

# 공분산에서 당장 읽어야 할 것은 '크기'가 아니라 '부호' 입니다.
#
#   cov > 0  →  같이 오름 (한쪽 ↑ 면 다른 쪽도 ↑)
#   cov < 0  →  반대로 감 (한쪽 ↑ 면 다른 쪽은 ↓)
#   cov ≈ 0  →  뚜렷한 방향 없음 (무관)
#
# 온도-불량은 +12 로 양수 → 같이 오름.
# 반대 방향도 하나 만들어 확인해 봅시다.
# 온도가 오를 때 오히려 줄어드는 가짜 값(수율 같은)을 넣어 보면:

수율 = [96, 94, 95, 92, 91, 90, 88, 89]   # 온도 오르면 대체로 내려감
print("cov(온도, 수율):", round(공분산(온도, 수율), 4))
# → cov(온도, 수율): -11.875
# 부호가 −(음수). 온도가 오를수록 수율은 내려간다는 반대 방향입니다.


# ----------------------------------------
# 분산은 자기 자신과의 공분산
# ----------------------------------------

# 여기서 지난 편과 이어지는 예쁜 사실 하나.
# 공분산 수식에서 y 자리에 x 를 그대로 넣으면:
#
#   cov(x, x) = Σ(xᵢ - x̄)(xᵢ - x̄) / n = Σ(xᵢ - x̄)² / n = 분산(x)
#
# 즉 분산은 'x와 x 자신의 공분산' 입니다.
# 공분산은 분산을 두 변수로 넓힌 것이라고 보면 됩니다.

print("cov(온도, 온도):", round(공분산(온도, 온도), 4))   # → cov(온도, 온도): 21.0
print("var(온도)     :", round(분산(온도), 4))            # → var(온도)     : 21.0
# 두 값이 똑같죠. 분산은 공분산의 특별한 경우(자기 자신과의)입니다.


# ========================================================
#  PART 3 : 공분산의 한계
# ========================================================

# ----------------------------------------
# 크기는 단위에 휘둘린다 - 비교가 안 됨
# ----------------------------------------

# 공분산은 '방향(부호)' 은 잘 알려 주지만, '크기' 는 믿기 어렵습니다.
# 단위와 값의 크기에 통째로 휘둘리기 때문이에요.
#
# 온도-불량 공분산과 온도-압력 공분산을 나란히 놓아 봅시다.

print("cov(온도, 불량):", round(공분산(온도, 불량), 4))   # → cov(온도, 불량): 8.75
print("cov(온도, 압력):", round(공분산(온도, 압력), 4))   # → cov(온도, 압력): 0.6875

# 숫자만 보면 8.75 ≫ 0.69 라, "온도는 압력보다 불량과 훨씬 세게 엮였다"
# 고 말하고 싶어집니다. 하지만 이 비교는 공정하지 않습니다.
#   불량은 3~9(개) 단위라 편차가 크고,
#   압력은 4.0~4.5(bar) 단위라 편차가 애초에 작습니다.
# 압력을 bar 대신 kPa(×100)로 적었다면 공분산은 100배로 뛰었을 겁니다.
# 값은 그대로인데 단위만 바꿔도 공분산 크기가 변한다는 뜻이죠.
#
# 그래서 공분산 크기로 두 관계의 '세기'를 비교하면 안 됩니다.
# 부호(방향)만 읽고, 세기는 다음의 상관계수로 넘겨야 합니다.


# ========================================================
#  PART 4 : 상관계수 - 단위를 지운 −1~+1
# ========================================================

# ----------------------------------------
# 상관계수 수식과 직관
# ----------------------------------------

# 공분산의 '단위 문제' 를 없애는 방법은 간단합니다.
# 각자의 표준편차로 나눠서 단위를 지워 버리는 겁니다.
#
#   r = cov(x, y) / (σx · σy)
#           공분산  나누기  (x의 표준편차 × y의 표준편차)
#
# 표준편차도 x, y 와 같은 단위를 가지므로, 나누고 나면 단위가 상쇄돼
# 사라집니다. 그 결과 r 은 항상 −1 ~ +1 사이의 '단위 없는 숫자' 가 됩니다.
#
#   r = +1  →  완벽하게 같이 오름 (점이 정확히 오르는 직선 위)
#   r =  0  →  직선 관계 없음
#   r = −1  →  완벽하게 반대로 감 (점이 정확히 내리는 직선 위)
#   |r| 이 클수록 강한 직선 관계, 작을수록 약함.


# ----------------------------------------
# 상관계수 직접 구현
# ----------------------------------------

# 공분산과 표준편차 함수를 이미 만들어 뒀으니, 수식 그대로 나누기만 하면 됩니다.

def 상관계수(xs, ys):
    return 공분산(xs, ys) / (표준편차(xs) * 표준편차(ys))   # cov / (σx·σy)

print("r(온도, 불량):", round(상관계수(온도, 불량), 4))   # → r(온도, 불량): 0.9547
print("r(온도, 압력):", round(상관계수(온도, 압력), 4))   # → r(온도, 압력): 0.8872
print("r(온도, 수율):", round(상관계수(온도, 수율), 4))   # → r(온도, 수율): -0.9552

# 이제 공분산 때와 이야기가 달라집니다.
# 공분산 크기로는 온도-불량(8.75)이 온도-압력(0.69)을 압도했지만,
# 단위를 지운 r 로 보면 0.95 대 0.89 로 둘 다 강하게 엮여 있었어요.
# 압력은 값의 폭이 작아 공분산이 작아 보였을 뿐, 관계 자체는 셌던 겁니다.
# r 은 −1~+1 안에 있으니 서로 다른 쌍끼리 바로 비교할 수 있습니다.


# ----------------------------------------
# 주의 - r=0 은 '직선 관계'가 없다는 뜻
# ----------------------------------------

# r 을 읽을 때 흔한 오해 하나를 짚고 갑니다.
# r 이 재는 것은 오직 '직선' 관계입니다. 곡선 관계는 못 잡습니다.
#
# 예를 들어 y = x² 처럼 U자로 휘는 관계를 보죠.
# 뚜렷한 규칙(완벽한 곡선 관계)이 있는데도 r 은 0 에 가깝게 나옵니다.

xx = [-3, -2, -1, 0, 1, 2, 3]
yy = [x ** 2 for x in xx]              # 완벽한 U자 곡선: 9,4,1,0,1,4,9
print("r(U자 곡선):", round(상관계수(xx, yy), 4))   # → r(U자 곡선): 0.0

# 분명히 x 와 y 사이에 규칙이 있는데 r 은 0 입니다.
# 그러니 "r=0 = 아무 관계 없음" 이 아니라
# "r=0 = 직선 관계가 없음" 으로 읽어야 합니다.
# r 을 믿기 전에 PART 1 처럼 산점도로 모양부터 보는 습관이 필요한 이유죠.


# ========================================================
#  PART 5 : 표준화(z-score)와 연결
# ========================================================

# ----------------------------------------
# 표준화 복습 - 평균 빼고 표준편차로 나눔
# ----------------------------------------

# 지난 편에서 본 표준화(z-score)를 다시 꺼냅니다.
#
#   z = (x - 평균) / 표준편차
#
# 각 값이 '평균에서 표준편차 몇 개만큼 떨어졌나' 로 바꾸는 것이었죠.
# 표준화하면 어떤 데이터든 평균 0, 표준편차 1 로 맞춰집니다.

def 표준화(xs):
    m = 평균(xs)
    s = 표준편차(xs)
    return [(x - m) / s for x in xs]

z온도 = 표준화(온도)
print("표준화한 온도 평균:", round(평균(z온도), 4))       # → 표준화한 온도 평균: 0.0
print("표준화한 온도 표준편차:", round(표준편차(z온도), 4))   # → 표준화한 온도 표준편차: 1.0
# 평균은 0, 표준편차는 1 로 맞춰졌습니다.


# ----------------------------------------
# 상관계수 = 표준화한 두 변수의 공분산
# ----------------------------------------

# 여기서 오늘의 두 주제가 하나로 만납니다.
# r = cov(x,y) / (σx·σy) 인데, 표준화가 바로 표준편차로 나누는 일이었죠.
# 그래서 x, y 를 먼저 각각 표준화한 뒤 그 둘의 공분산을 구하면,
# 그게 곧 상관계수 r 과 같아집니다.
#
#   r(x, y) = cov(표준화한 x, 표준화한 y)
#
# 표준화가 σ 로 나누는 일을 '미리' 해 두니, 남은 건 공분산뿐인 거죠.

직접r = 상관계수(온도, 불량)
표준화후공분산 = 공분산(표준화(온도), 표준화(불량))
print("상관계수 그대로       :", round(직접r, 4))            # → 상관계수 그대로       : 0.9547
print("표준화 후 공분산      :", round(표준화후공분산, 4))    # → 표준화 후 공분산      : 0.9547
# 두 값이 똑같습니다. 상관계수는 '표준화한 두 변수의 공분산' 이에요.
# 공분산·표준편차·표준화가 따로 놀던 게 한 줄로 이어졌습니다.


# ========================================================
