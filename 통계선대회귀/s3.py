# 오늘 만든 공분산·상관계수를 손에 익히는 시간입니다.
# 아래 세 쌍의 상관계수를 모두 구해, 어느 쌍이 가장 강한 직선 관계인지
# (|r| 이 가장 큰 쌍) 찾아보세요.
#
#   쌍 1 : 온도 - 불량
#   쌍 2 : 온도 - 압력
#   쌍 3 : 온도 - 수율
#
#   Step 1) 각 쌍에 상관계수() 를 걸어 r 을 구한다
#   Step 2) |r| (부호 떼고 크기) 을 비교한다
#   Step 3) 부호로 방향(+ 같이 오름 / − 반대)까지 읽는다
#
# 완료 기준 : 세 r 이 화면에 나오고, |r| 이 가장 큰 쌍을 고르면 성공.
#            일찍 끝난 분은 numpy(np.corrcoef)로 대조까지 해 보세요.

# (실습 정답 예시)
print("[실습 정답 · 세 쌍 상관 비교]")
for 이름, (a, b) in 쌍들.items():
    r = 상관계수(a, b)
    방향 = "같이 오름(+)" if r > 0 else "반대로 감(-)"
    print(f"  {이름}: r={round(r, 4)}  |r|={round(abs(r), 4)}  {방향}")
# → [실습 정답 · 세 쌍 상관 비교]
# →   온도-불량: r=0.9547  |r|=0.9547  같이 오름(+)
# →   온도-압력: r=0.8872  |r|=0.8872  같이 오름(+)
# →   온도-수율: r=-0.9552  |r|=0.9552  반대로 감(-)
# |r| 이 가장 큰 쌍은 온도-수율(0.9552). 방향은 반대지만 가장 강하게 엮였죠.
# 부호는 방향, |r| 크기는 세기 — 둘을 나눠 읽는 게 핵심입니다.


# ----------------------------------------
# 오늘 만든 것 - 정리
# ----------------------------------------

#   함수           |  정의                       |  코드 핵심
#  ---------------+-----------------------------+--------------------------
#   공분산(x,y)    |  Σ(x-x̄)(y-ȳ) / n           |  편차 곱의 평균 (부호=방향)
#   상관계수(x,y)  |  cov(x,y) / (σx·σy)         |  공분산을 표준편차로 정규화
#   표준화(x)      |  (x-평균) / 표준편차         |  평균 0·표준편차 1 로 맞춤
#
# 오늘 배운 흐름:
#   1) 공분산으로 '방향(부호)' 을 잡되, 크기는 단위에 휘둘려 못 믿는다
#   2) 표준편차로 나눠(=상관계수) −1~+1 로 정규화하면 쌍끼리 비교 가능
#   3) 상관계수 = 표준화한 두 변수의 공분산 (오늘 주제들이 한 줄로 연결)
#   4) numpy 대조 시 n vs n-1 분모 함정 — cov 는 bias=True 로 맞춘다
#   5) r 은 '직선' 관계만 잡는다 — r=0 은 무관이 아니라 '직선 관계 없음'


# ----------------------------------------
# 다음 편 예고 - 이 공분산이 회귀의 기울기가 된다
# ----------------------------------------

# 오늘 만든 공분산은 다음 편에서 곧장 다시 등장합니다.
# 온도(x)로 불량(y)을 예측하는 직선 y = w·x + b 를 그을 때,
# 그 직선의 기울기 w 는 이렇게 구합니다.
#
#   w = cov(x, y) / var(x)
#         공분산   나누기   x의 분산
#
# 오늘 만든 공분산 함수와 지난 편의 분산 함수만으로 기울기가 나오는 거죠.

기울기 = 공분산(온도, 불량) / 분산(온도)
print("미리 본 회귀 기울기 w:", round(기울기, 4))   # → 미리 본 회귀 기울기 w: 0.4167
