# ----------------------------------------
# 정리 - 곱의 세 종류를 절대 헷갈리지 말기
# ----------------------------------------

#   연산          |  하는 일                        |  결과      |  numpy
#  --------------+---------------------------------+-----------+--------
#   원소별/성분별곱 |  같은 자리끼리 곱하고 멈춤         |  벡터/행렬  |  *
#   내적(dot)     |  같은 자리끼리 곱한 뒤 다 더함      |  숫자 하나  |  np.dot
#   행렬곱(matmul)|  행과 열을 짝지어 내적을 잔뜩       |  행렬      |  @
#
# 초보가 가장 많이 헷갈리는 지점: numpy 의 * 와 @ 는 완전히 다른 연산입니다.
#   *  → 같은 자리끼리 (성분별)
#   @  → 행과 열을 내적 (행렬곱)
# 회귀 예측(w·x, X@W)에서 쓰는 건 내적/행렬곱(더하기가 들어간 쪽)입니다.


