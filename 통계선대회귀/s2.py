# [실습] 벡터·행렬 연산 직접 구현
# ----------------------------------------

# 오늘 만든 함수들을 손에 익히는 시간입니다.
# 아래 두 케이스 중 하나를 골라, 위 함수를 그대로 적용하고 numpy 와 대조하세요.
#
#   케이스 A (벡터) : u = [2, 4, 6], t = [1, 3, 5] 로
#        벡터덧셈·스칼라곱(3배)·내적 을 직접 구현하고 numpy와 대조
#   케이스 B (행렬) : 아래 R(2×3) 과 S(3×2) 를 행렬곱 하고 A@B 와 대조
#
#   완료 기준 : 직접 구현 값이 화면에 나오고, numpy 값과 나란히 출력되며,
#              두 결과가 같음이 확인되면 성공입니다.

# (실습 정답 예시 — 케이스 B 행렬곱)
R = [[1, 0, 2],
     [3, 1, 1]]       # (2 × 3)
S = [[4, 1],
     [2, 5],
     [0, 3]]          # (3 × 2)  → 안쪽 3 == 3, 결과 (2 × 2)

직접 = 행렬곱(R, S)
넘파이 = (np.array(R) @ np.array(S)).tolist()
print("[실습 예시 · 행렬곱]")
print("  직접 :", 직접)      # → 직접 : [[4, 7], [14, 11]]
print("  numpy:", 넘파이)    # → numpy: [[4, 7], [14, 11]]
print("  일치 :", 직접 == 넘파이)   # → 일치 : True
# 손 검산: 직접[0] = R의 0행[1,0,2]을 S의 각 열과 내적
#   0열[4,2,0]: 1×4+0×2+2×0 = 4 / 1열[1,5,3]: 1×1+0×5+2×3 = 7  ✓
