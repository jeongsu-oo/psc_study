# -------------------------------
# 벡터·행렬 연산 직접 구현 - 숫자 여러 개를 묶어서 다룬다
# -------------------------------


"""[숫자 여러 개를 한 덩어리로 다루면 뭐가 좋나요?]
지금까지는 값 하나하나를 따로 다뤘습니다.
그런데 센서를 한 번 측정하면 값이 하나만 나오지 않죠.
온도·압력·진동이 '한 세트'로 같이 나옵니다.

  한 번 측정 = [온도, 압력, 진동] = [70, 4.2, 0.8]

이렇게 숫자 여러 개를 한 줄로 묶은 것을 '벡터' 라고 부릅니다.
측정을 여러 번 쌓으면 표가 되는데, 그 표를 '행렬' 이라고 부르죠.

오늘은 이 벡터와 행렬을 다루는 연산을 준비된 도구 없이
순수 파이썬 반복문으로 직접 만들어 봅니다.
특히 마지막의 '행렬곱' 이 핵심입니다.
왜냐면 다음 시간에 배울 회귀에서
  예측값 = 가중치 · 입력  =  결국 곱해서 더하기
가 바로 이 벡터·행렬 연산이거든요.
회귀 예측을 손에 쥐려면 오늘 이 곱셈을 먼저 손으로 겪어 둬야 합니다.

이 파일은 벡터 → 벡터연산 → 내적 → 행렬 → 행렬연산 → 행렬곱 순으로,
개념 → ASCII 그림 → 직접 구현 → numpy 대조 순으로 쌓습니다.
"""

# 마지막에 내 계산을 채점할 때만 씁니다. 그전까지는 전부 순수 파이썬.
import numpy as np


# ========================================================
#  PART 1 : 벡터란 무엇인가
# ========================================================

# ----------------------------------------
# 벡터 = 숫자 여러 개를 한 줄로 묶은 것
# ----------------------------------------

# 센서를 한 번 측정하면 값이 여러 개 한꺼번에 나옵니다.
# 온도, 압력, 진동을 한 세트로 묶으면 그게 벡터입니다.
#
#   측정 한 번  →  [ 온도  압력  진동 ]
#                  [  70   4.2   0.8 ]   ← 값 세 개가 한 줄
#
# 파이썬에서는 그냥 '리스트' 로 표현합니다. 새 자료형이 아니에요.
# 리스트를 '한 세트의 측정값' 이라는 눈으로 보는 것, 그게 벡터의 시작입니다.

v = [70, 4.2, 0.8]   # 센서 한 번 측정: 온도 70, 압력 4.2, 진동 0.8
print("벡터 v:", v)          # → 벡터 v: [70, 4.2, 0.8]
print("길이(값 개수):", len(v))   # → 길이(값 개수): 3

# 벡터의 '길이' 는 그 안에 든 값의 개수입니다. 여기선 3 (세 항목).
# 앞으로 두 벡터를 연산할 때 이 길이가 서로 같아야 합니다.


# ========================================================
#  PART 2 : 벡터 연산 - 덧셈, 스칼라곱, 원소별 곱
# ========================================================

# ----------------------------------------
# 벡터 덧셈 - 같은 자리끼리 더한다
# ----------------------------------------

# 두 벡터를 더하는 규칙은 딱 하나입니다.
#   '같은 자리에 있는 값끼리' 더한다.
#
#     [1, 2, 3]
#   + [4, 5, 6]
#   -----------
#     [5, 7, 9]     ← 1+4, 2+5, 3+6
#
# 앞자리는 앞자리끼리, 뒷자리는 뒷자리끼리. 자리를 섞지 않습니다.
# 그래서 두 벡터의 길이가 같아야 짝이 딱 맞습니다.

a = [1, 2, 3]
b = [4, 5, 6]

# 순수 파이썬으로 직접 구현: 자리 번호 i 를 돌며 같은 자리끼리 더함
def 벡터덧셈(x, y):
    결과 = []
    for i in range(len(x)):      # 자리 번호 0, 1, 2 를 차례로
        결과.append(x[i] + y[i]) # 같은 자리 값끼리 더해 담음
    return 결과

print("벡터덧셈:", 벡터덧셈(a, b))   # → 벡터덧셈: [5, 7, 9]

# numpy 로 대조: 배열끼리 그냥 + 하면 자리끼리 알아서 더해 줍니다.
print("numpy 덧셈:", np.array(a) + np.array(b))   # → numpy 덧셈: [5 7 9]
# 직접 구현한 [5, 7, 9] 와 numpy 의 [5 7 9] 가 같습니다.


# ----------------------------------------
# 스칼라곱 - 벡터 전체에 숫자 하나를 곱한다
# ----------------------------------------

# '스칼라' 는 그냥 숫자 하나를 뜻하는 말입니다. (벡터=여러 개 ↔ 스칼라=한 개)
# 스칼라곱은 그 숫자 하나를 벡터의 모든 자리에 똑같이 곱하는 겁니다.
#
#   2 × [1, 2, 3]  =  [2, 4, 6]     ← 모든 자리에 2를 곱함
#
# 예를 들어 모든 측정값을 2배로 뻥튀기하거나, 0.1을 곱해 10%로 줄일 때 씁니다.

def 스칼라곱(s, x):
    결과 = []
    for i in range(len(x)):   # 자리마다
        결과.append(s * x[i]) # 그 자리 값에 s 를 곱함
    return 결과

print("스칼라곱 2 x a:", 스칼라곱(2, a))   # → 스칼라곱 2 x a: [2, 4, 6]
print("numpy 스칼라곱:", 2 * np.array(a))  # → numpy 스칼라곱: [2 4 6]
# numpy 는 2 * 배열 이라고만 써도 모든 자리에 2를 곱해 줍니다.


# ----------------------------------------
# 원소별 곱 - 같은 자리끼리 곱한다
# ----------------------------------------

# 덧셈이 '같은 자리끼리 더하기' 였듯,
# 원소별 곱은 '같은 자리끼리 곱하기' 입니다.
#
#     [1, 2, 3]
#   × [4, 5, 6]
#   -----------
#     [4, 10, 18]   ← 1×4, 2×5, 3×6
#
# 주의: 이건 잠시 뒤에 나올 '내적' 과 다릅니다.
#       원소별 곱은 곱한 결과를 벡터 그대로 남겨 둡니다 (더하지 않음).

def 원소별곱(x, y):
    결과 = []
    for i in range(len(x)):
        결과.append(x[i] * y[i])   # 같은 자리끼리 곱해서 그대로 담음
    return 결과

print("원소별곱:", 원소별곱(a, b))         # → 원소별곱: [4, 10, 18]
print("numpy 원소별곱:", np.array(a) * np.array(b))   # → numpy 원소별곱: [ 4 10 18]
# numpy 도 배열끼리 * 하면 (행렬곱이 아니라) 같은 자리끼리 곱합니다.


# ========================================================
#  PART 3 : 내적(dot) - 곱해서 다 더한다
# ========================================================

# ----------------------------------------
# 내적 = 대응끼리 곱해 전부 더함
# ----------------------------------------

# 이번 것이 오늘의 첫 번째 핵심입니다. 회귀 예측이 바로 이 모양이에요.
#
#   내적 공식:  a · b = Σ aᵢ bᵢ
#              (같은 자리끼리 곱한 뒤, 그 곱들을 전부 더함)
#
#     a = [1, 2, 3]
#     b = [4, 5, 6]
#
#     같은 자리끼리 곱:  1×4=4,  2×5=10,  3×6=18
#     그 곱을 전부 더함:  4 + 10 + 18 = 32
#
#     → a · b = 32   (결과는 벡터가 아니라 '숫자 하나')
#
# 원소별 곱과 딱 한 걸음 차이입니다.
#   원소별 곱 : 같은 자리끼리 곱하고 멈춤        → [4, 10, 18] (벡터)
#   내적      : 같은 자리끼리 곱한 뒤 '다 더함'  → 32         (숫자 하나)

def 내적(x, y):
    합 = 0
    for i in range(len(x)):     # 같은 자리끼리
        합 = 합 + x[i] * y[i]   # 곱해서 합에 누적 (Σ)
    return 합

print("내적 a·b:", 내적(a, b))        # → 내적 a·b: 32
print("numpy dot:", np.dot(a, b))     # → numpy dot: 32
# 직접 구현 32 와 np.dot 의 32 가 같습니다.


# ----------------------------------------
# 내적이 왜 중요한가 - 회귀 예측의 심장
# ----------------------------------------

# 다음 시간 회귀에서 예측값은 이렇게 생겼습니다.
#
#   예측 = w₁·x₁ + w₂·x₂ + w₃·x₃ + ...
#        = (가중치 벡터 w) · (입력 벡터 x)      ← 바로 내적!
#
# 즉 '각 입력에 가중치를 곱해 다 더한다' 는 게 내적 한 번입니다.
# 예를 들어 온도·압력·진동으로 설비 점수를 예측한다면:

w = [0.5, 2.0, 10.0]   # 각 항목의 가중치 (중요도)
x = [70, 4.2, 0.8]     # 센서 한 번 측정
print("예측 점수:", 내적(w, x))   # → 예측 점수: 51.4
# 0.5×70 + 2.0×4.2 + 10.0×0.8 = 35 + 8.4 + 8 = 51.4
# 이 '곱해서 더하기' 한 방이 회귀 예측의 심장입니다. 오늘 손에 쥐어 두세요.


# ========================================================
#  PART 4 : 행렬이란 무엇인가
# ========================================================

# ----------------------------------------
# 행렬 = 벡터를 여러 줄 쌓은 표
# ----------------------------------------

# 측정을 한 번만 하면 벡터(한 줄) 였습니다.
# 그런데 실제로는 여러 번 측정하죠. 그 여러 줄을 위아래로 쌓으면 '표' 가 되고,
# 그 표를 '행렬' 이라고 부릅니다.
#
#           온도  압력  진동    ← 열(column) 3개
#   측정1 [  70   4.2   0.8 ]   ← 행(row) : 벡터 한 줄
#   측정2 [  72   4.5   0.9 ]
#   측정3 [  68   4.0   0.7 ]
#     ↑
#   행 3개
#
# 파이썬에서는 '리스트 안에 리스트' 로 표현합니다.
# 바깥 리스트 = 표 전체, 안쪽 리스트 하나 = 한 행(측정 한 번).

M = [
    [70, 4.2, 0.8],   # 측정1
    [72, 4.5, 0.9],   # 측정2
    [68, 4.0, 0.7],   # 측정3
]

# ----------------------------------------
# 행·열·shape 로 모양 확인
# ----------------------------------------

# 행렬을 다루기 전에 항상 '모양(shape)' 부터 확인합니다.
#   행(row) 수    = 안쪽 리스트가 몇 개인가        → len(M)
#   열(column) 수 = 한 행에 값이 몇 개인가          → len(M[0])
# 이 (행 수, 열 수) 짝을 shape 라고 부릅니다.

행수 = len(M)       # 안쪽 리스트 개수 = 행 개수
열수 = len(M[0])    # 첫 행의 값 개수 = 열 개수
print("shape (행, 열):", (행수, 열수))   # → shape (행, 열): (3, 3)

# 특정 칸을 꺼낼 때는 [행 번호][열 번호]. 번호는 0부터 셉니다.
print("M[1][2] =", M[1][2])   # → M[1][2] = 0.9
# 1번 행(측정2 [72, 4.5, 0.9])의 2번 열(세 번째 값) = 0.9

# numpy 로 shape 대조: 배열의 .shape 속성이 같은 (3, 3) 을 줍니다.
print("numpy shape:", np.array(M).shape)   # → numpy shape: (3, 3)


# ========================================================
#  PART 5 : 행렬 연산 - 덧셈, 스칼라곱, 성분별 곱
# ========================================================

# 행렬 연산은 벡터 연산과 규칙이 똑같습니다. 다만 자리가 이제 (행, 열) 두 개죠.
# 그래서 반복문이 한 겹 더 늘어 '이중 for' 가 됩니다.
#   바깥 for = 행을 하나씩,  안쪽 for = 그 행의 열을 하나씩.

# 두 행렬을 미리 만들어 둡니다. 모양이 같아야(같은 shape) 짝이 맞습니다.
P = [[1, 2, 3],
     [4, 5, 6]]
Q = [[10, 20, 30],
     [40, 50, 60]]


# ----------------------------------------
# 행렬 덧셈 - 같은 칸끼리 더한다
# ----------------------------------------

#     [1 2 3]   [10 20 30]   [11 22 33]
#     [4 5 6] + [40 50 60] = [44 55 66]   ← 같은 (행,열) 칸끼리 더함

def 행렬덧셈(A, B):
    결과 = []
    for i in range(len(A)):           # 행을 하나씩
        행 = []
        for j in range(len(A[0])):    # 그 행의 열을 하나씩
            행.append(A[i][j] + B[i][j])   # 같은 칸끼리 더함
        결과.append(행)
    return 결과

print("행렬덧셈:", 행렬덧셈(P, Q))   # → 행렬덧셈: [[11, 22, 33], [44, 55, 66]]
print("numpy 덧셈:\n", np.array(P) + np.array(Q))
# → numpy 덧셈:
# →  [[11 22 33]
# →  [44 55 66]]


# ----------------------------------------
# 행렬 스칼라곱 - 모든 칸에 숫자 하나
# ----------------------------------------

#   2 × [1 2 3]   [ 2  4  6]
#       [4 5 6] = [ 8 10 12]   ← 모든 칸에 2를 곱함

def 행렬스칼라곱(s, A):
    return [[s * A[i][j] for j in range(len(A[0]))] for i in range(len(A))]

print("행렬스칼라곱:", 행렬스칼라곱(2, P))   # → 행렬스칼라곱: [[2, 4, 6], [8, 10, 12]]
print("numpy 스칼라곱:\n", 2 * np.array(P))
# → numpy 스칼라곱:
# →  [[ 2  4  6]
# →  [ 8 10 12]]


# ----------------------------------------
# 성분별 곱 - 같은 칸끼리 곱한다
# ----------------------------------------

# 벡터의 원소별 곱과 똑같은 발상. 같은 (행,열) 칸끼리 곱합니다.
#   주의: 이것도 잠시 뒤의 '행렬곱' 과는 완전히 다릅니다.
#   성분별 곱은 같은 칸끼리 곱해 그 자리에 그대로 둘 뿐입니다.

def 성분별곱(A, B):
    return [[A[i][j] * B[i][j] for j in range(len(A[0]))] for i in range(len(A))]

print("성분별곱:", 성분별곱(P, Q))   # → 성분별곱: [[10, 40, 90], [160, 250, 360]]
print("numpy 성분별곱:\n", np.array(P) * np.array(Q))
# → numpy 성분별곱:
# →  [[ 10  40  90]
# →  [160 250 360]]
# numpy 에서 A * B 는 (행렬곱이 아니라) 같은 칸끼리 곱임을 다시 확인하세요.


# ========================================================
#  PART 6 : 행렬곱(matmul) - 오늘의 진짜 핵심
# ========================================================

# ----------------------------------------
# 행렬곱은 '성분별 곱' 과 완전히 다르다
# ----------------------------------------

# 지금까지의 곱(원소별·성분별)은 그냥 같은 자리끼리 곱하는 것이었습니다.
# 그런데 수학과 회귀에서 말하는 '행렬곱' 은 규칙이 전혀 다릅니다.
#
#   행렬곱 공식:  C[i][j] = Σ_k A[i][k]·B[k][j]
#
# 말로 풀면 이렇습니다.
#   결과의 (i행, j열) 칸 하나는
#   A 의 i번째 '행' 과  B 의 j번째 '열' 을 꺼내
#   그 둘을 '내적' 한 값이다.   ← PART 3 의 내적이 여기서 쓰입니다!
#
#   A 의 i행:  [ A[i][0]  A[i][1]  A[i][2] ]   (가로 한 줄)
#   B 의 j열:  [ B[0][j]                        (세로 한 줄)
#               B[1][j]
#               B[2][j] ]
#   내적 = A[i][0]·B[0][j] + A[i][1]·B[1][j] + A[i][2]·B[2][j]
#
# 즉 행렬곱은 '행과 열을 짝지어 내적을 잔뜩 하는 일' 입니다.


# ----------------------------------------
# 형상 규칙 - 안쪽 숫자가 같아야 한다
# ----------------------------------------

# 행렬곱은 아무 두 행렬이나 곱할 수 없습니다. '형상' 이 맞아야 합니다.
#
#     (m × n) · (n × p) = (m × p)
#          └───┘ └───┘
#           안쪽 n 이 서로 같아야 곱셈이 성립!
#          └───────────┘
#           바깥 m, p 가 결과의 모양이 됨
#
#   그림으로:
#         A            B            C
#      (2 × 3)  ·   (3 × 2)   =   (2 × 2)
#           ↑         ↑
#           └── 3 == 3 (같음, OK) ──┘
#           바깥 2 와 2 → 결과는 (2 × 2)
#
# 왜 안쪽이 같아야 할까요?
#   A 의 한 '행' 길이(=A의 열 수 n)와
#   B 의 한 '열' 길이(=B의 행 수 n)가 같아야
#   둘을 내적할 때 자리가 딱 맞기 때문입니다. (내적은 길이가 같아야 했죠.)


# ----------------------------------------
# 행렬곱 직접 구현 - 3중 for
# ----------------------------------------

# 공식 C[i][j] = Σ_k A[i][k]·B[k][j] 를 그대로 반복문 세 겹으로 옮깁니다.
#   i (바깥) : 결과의 행
#   j (가운데): 결과의 열
#   k (안쪽) : 내적을 위해 A의 행·B의 열을 훑는 자리 (여기서 Σ)

A = [[1, 2, 3],
     [4, 5, 6]]        # (2 × 3)
B = [[7, 8],
     [9, 10],
     [11, 12]]         # (3 × 2)
# 안쪽 3 == 3 이므로 곱셈 성립. 결과는 (2 × 2) 가 나올 것입니다.

def 행렬곱(A, B):
    m = len(A)         # A의 행 수
    n = len(A[0])      # A의 열 수 = B의 행 수 (안쪽, 같아야 함)
    p = len(B[0])      # B의 열 수
    C = [[0] * p for _ in range(m)]   # 결과 (m × p) 를 0으로 채워 준비
    for i in range(m):          # 결과의 각 행
        for j in range(p):      # 결과의 각 열
            합 = 0
            for k in range(n):  # A의 i행 · B의 j열 을 내적 (Σ_k)
                합 = 합 + A[i][k] * B[k][j]
            C[i][j] = 합
    return C

내결과 = 행렬곱(A, B)
print("행렬곱(직접):", 내결과)   # → 행렬곱(직접): [[58, 64], [139, 154]]

# 손으로 한 칸 검산: C[0][0] = A의 0행[1,2,3] · B의 0열[7,9,11]
#   = 1×7 + 2×9 + 3×11 = 7 + 18 + 33 = 58  ✓


# ----------------------------------------
# numpy @ 로 대조 - A @ B
# ----------------------------------------

# numpy 에서 행렬곱은 '@' 기호 하나입니다. (별표 * 는 성분별 곱이었죠, 헷갈리지 마세요.)

np결과 = np.array(A) @ np.array(B)
print("행렬곱(numpy @):\n", np결과)
# → 행렬곱(numpy @):
# →  [[ 58  64]
# →  [139 154]]

# 직접 구현과 numpy 가 정말 같은지 프로그램이 스스로 채점하게 합니다.
같은가 = (내결과 == np결과.tolist())
print("직접 == numpy ?", 같은가)   # → 직접 == numpy ? True
assert 같은가, "행렬곱 직접 구현이 numpy 와 다릅니다!"
# True 가 나오면 우리가 짠 3중 for 행렬곱이 정확하다는 증거입니다.


# ----------------------------------------
# 왜 회귀에서 행렬곱을 쓰나 - 여러 예측을 한 번에
# ----------------------------------------

# 내적 하나는 '측정 한 번' 의 예측이었습니다. (PART 3)
# 그런데 측정이 여러 번이면? 매번 내적을 따로 하지 않고,
# 측정들을 행렬로 쌓아 '행렬곱 한 번' 으로 전부 예측합니다.
#
#   측정 3번을 행렬 X 로 쌓고(3 × 2), 가중치 W 를 (2 × 1) 로 두면
#   X @ W = (3 × 1)  →  세 예측이 한 번에 나옴!

X = [[70, 4.2],    # 측정1: 온도, 압력
     [72, 4.5],    # 측정2
     [68, 4.0]]    # 측정3  → (3 × 2)
W = [[0.5],
     [2.0]]        # 가중치 (2 × 1)

예측들 = 행렬곱(X, W)   # (3 × 2)·(2 × 1) = (3 × 1)
print("세 측정의 예측 한 번에:", 예측들)
# → 세 측정의 예측 한 번에: [[43.4], [45.0], [42.0]]
# 측정1: 0.5×70 + 2.0×4.2 = 35 + 8.4 = 43.4  ✓
# for 문으로 측정마다 내적을 반복하지 않고, 행렬곱 한 줄로 끝냈습니다.
# 이게 회귀가 수천 개 샘플을 한 번에 예측하는 방식입니다.


# ========================================================
#  PART 7 : 형상이 안 맞으면 오류가 난다
# ========================================================

# ----------------------------------------
# 안쪽 숫자가 다르면 곱할 수 없다
# ----------------------------------------

# 형상 규칙 (m×n)·(n×p) 에서 안쪽 n 이 서로 다르면 곱셈 자체가 불가능합니다.
# 억지로 곱하려 하면 numpy 는 조용히 넘어가지 않고 '오류' 를 냅니다.
# 일부러 안 맞는 걸 곱해 어떤 오류가 나는지 눈으로 확인해 봅시다.
# (오류를 try 로 잡아 메시지만 보여 줍니다. 실무에선 이 메시지를 읽고 shape를 고칩니다.)

왼쪽 = np.array([[1, 2, 3],
                [4, 5, 6]])     # (2 × 3), 안쪽이 될 값 = 3
오른쪽 = np.array([[1, 2],
                  [3, 4]])       # (2 × 2), 안쪽이 될 값 = 2
# 3 != 2 이므로 곱할 수 없습니다.

try:
    왼쪽 @ 오른쪽   # (2×3) · (2×2) → 안쪽 3 과 2 가 다름
except ValueError as e:
    print("오류 발생:", e)
# → 오류 발생: matmul: Input operand 1 has a mismatch in its core dimension 0, with gufunc signature (n?,k),(k,m?)->(n?,m?) (size 2 is different from 3)

# 오류가 나면 당황하지 말고 두 행렬의 shape 부터 찍어 보세요.
print("왼쪽 shape:", 왼쪽.shape, "/ 오른쪽 shape:", 오른쪽.shape)
# → 왼쪽 shape: (2, 3) / 오른쪽 shape: (2, 2)
# 왼쪽의 열(3)과 오른쪽의 행(2)이 다릅니다 → 안쪽 불일치 → 곱셈 불가.
# 형상만 맞춰 주면(예: 오른쪽을 3행짜리로) 바로 계산됩니다.


