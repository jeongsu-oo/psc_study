# 기술통계 심화 - 여러 센서를 숫자 몇 개로 요약한다
# -------------------------------


"""[측정값이 수백 개인데, 뭘 봐야 하나요?]
설비 한 대에서 온도가 초 단위로 찍혀 나오면 하루에 수만 개입니다.
그 숫자를 다 눈으로 볼 수는 없죠. 그래서 우리는 '요약'을 합니다.
수백 개의 값을 '대표값 하나', '흩어짐 하나' 같은 숫자 몇 개로 압축해
"이 설비는 대략 이런 상태다" 를 한눈에 파악하는 거예요.

지난 파트13에서 평균·분산·표준편차를 준비된 함수 없이
반복문과 나눗셈만으로 직접 만들어 봤습니다.
오늘은 그걸 복습하면서 대표값 3형제(평균·중앙값·최빈값)와
위치·범위(사분위수)까지 넓히고, 센서 여러 열을 한 표로 요약합니다.

이게 왜 중요하냐면 — 앞으로 배울 선형대수와 회귀분석은
'여러 열의 관계'를 다룹니다. 그 관계를 재려면 먼저 각 열을
제대로 요약할 줄 알아야 해요. 오늘이 그 발판입니다.

이 파일은 손계산 → 직접 구현 → numpy 대조 순으로 위에서 아래로 쌓습니다.
"""

# 마지막에 내 손계산을 채점할 때만 씁니다. 그전까지는 전부 순수 파이썬.
import numpy as np


# 이 파일 전체에서 쓸 설비 M-101 의 온도 측정값 10개.
# 대부분 71~74도인데, 90도짜리 하나가 튀어 있습니다(이상치).
# 이 튀는 값 하나가 뒤에서 '평균 vs 중앙값' 이야기의 주인공이 됩니다.
# (외부 CSV 없이 파일 안에 직접 적어 둡니다 — 그냥 실행됩니다.)
온도 = [72, 71, 73, 72, 74, 72, 73, 90, 72, 71]


# ========================================================
#  PART 1 : 왜 통계로 요약하나
# ========================================================

# ----------------------------------------
# 수백 개를 숫자 몇 개로
# ----------------------------------------

# 측정값 10개를 그냥 나열하면 이렇습니다.
print("측정값:", 온도)   # → 측정값: [72, 71, 73, 72, 74, 72, 73, 90, 72, 71]

# 10개는 그래도 눈에 들어오지만, 이게 10,000개라면?
# 화면에 다 찍어도 아무것도 안 보입니다.
# 그래서 우리는 이 덩어리를 '성격을 말해 주는 숫자 몇 개'로 줄입니다.
#
#   - 대표값   : 이 값들의 '중심'은 어디인가   (평균·중앙값·최빈값)
#   - 흩어짐   : 중심에서 얼마나 퍼져 있나     (분산·표준편차)
#   - 범위     : 어디부터 어디까지 걸쳐 있나   (최소·최대·사분위수)
#
# 이 세 각도만 잡으면 수백 개 값의 성격이 손안에 들어옵니다.
# 오늘은 이 셋을 차례로, 직접 만들어 보며 익힙니다.


# ========================================================
#  PART 2 : 대표값 3형제 - 평균·중앙값·최빈값
# ========================================================

# 값들의 '중심'을 말하는 방법은 하나가 아닙니다. 세 가지가 있어요.
# 셋 다 "대표값" 이지만 성격이 다르고, 상황에 따라 골라 써야 합니다.

# ----------------------------------------
# 평균 - 다 더해서 개수로 나눔
# ----------------------------------------

# 가장 익숙한 대표값. 지난 파트에서 직접 만들어 봤죠.
#
#   평균 = Σx / n   (모든 값의 합 ÷ 개수)

def 평균(xs):
    return sum(xs) / len(xs)   # Σx / n 그대로

print("평균:", 평균(온도))   # → 평균: 74.0

# 손으로 확인: 71·71·72·72·72·72·73·73·74·90 합이 740, 개수 10 → 74.0
# 그런데 이상하죠? 값 대부분이 72~73인데 평균은 74가 나옵니다.
# 90 하나가 평균을 위로 끌어올린 겁니다. 이게 평균의 약점이에요.


# ----------------------------------------
# 중앙값 - 줄 세웠을 때 한가운데
# ----------------------------------------

# 중앙값은 값들을 '크기순으로 줄 세웠을 때 딱 가운데' 있는 값입니다.
# 평균처럼 더하고 나누는 게 아니라, 정렬한 뒤 가운데를 짚는 거예요.
#
#   정렬 [71 71 72 72 | 72 72 | 73 73 74 90]
#                       └──┬──┘
#              값이 10개(짝수)라 가운데가 두 개(72, 72)
#              → 그 둘의 평균이 중앙값
#
# 개수가 홀수면 정가운데 하나, 짝수면 가운데 두 개의 평균입니다.

def 중앙값(xs):
    s = sorted(xs)          # 먼저 크기순 정렬
    n = len(s)
    가운데 = n // 2
    if n % 2 == 1:                      # 홀수 → 정가운데 하나
        return s[가운데]
    else:                               # 짝수 → 가운데 두 개의 평균
        return (s[가운데 - 1] + s[가운데]) / 2

print("중앙값:", 중앙값(온도))   # → 중앙값: 72.0

# 평균은 74.0, 중앙값은 72.0. 값이 다릅니다.
# 대부분의 실제 값(72~73)에 더 가까운 건 중앙값 쪽이죠.


# ----------------------------------------
# 왜 중앙값이 이상치에 강한가
# ----------------------------------------

# 핵심은 이겁니다.
#   평균은 '값 자체'를 다 더하므로, 90처럼 튀는 값이 크게 영향을 줍니다.
#   중앙값은 '순서'만 보므로, 90이 900이 되어도 가운데 자리는 그대로예요.
#
# 실제로 확인해 봅시다. 90을 900으로 바꾸면?

온도_극단 = [72, 71, 73, 72, 74, 72, 73, 900, 72, 71]
print("평균(900으로):", 평균(온도_극단))       # → 평균(900으로): 155.0
print("중앙값(900으로):", 중앙값(온도_극단))   # → 중앙값(900으로): 72.0

# 평균은 74에서 155로 폭등했지만, 중앙값은 72 그대로입니다.
# 그래서 급여·집값·불량 건수처럼 튀는 값이 섞이기 쉬운 데이터는
# 평균보다 중앙값이 '진짜 중심'을 더 잘 말해 줍니다.
# 반대로 튀는 값이 없는 잔잔한 데이터라면 둘은 거의 같아요.


# ----------------------------------------
# 최빈값 - 가장 자주 나온 값
# ----------------------------------------

# 세 번째 대표값은 '가장 많이 등장한 값' 입니다.
# 평균·중앙값이 '숫자의 크기'를 다뤘다면, 최빈값은 '빈도(횟수)'를 봅니다.
#
# 어떻게 세나?  값마다 몇 번 나왔는지 세어(딕셔너리), 최고 횟수를 찾습니다.

def 최빈값(xs):
    횟수 = {}
    for x in xs:                        # 값마다 등장 횟수 누적
        횟수[x] = 횟수.get(x, 0) + 1
    최고 = max(횟수.values())            # 가장 많이 나온 횟수
    return [k for k, v in 횟수.items() if v == 최고]   # 그 횟수인 값(들)

print("등장 횟수:", {72: 온도.count(72), 71: 온도.count(71), 73: 온도.count(73)})
# → 등장 횟수: {72: 4, 71: 2, 73: 2}
print("최빈값:", 최빈값(온도))   # → 최빈값: [72]

# 72가 네 번으로 가장 많으니 최빈값은 72입니다.
# 최빈값은 '리스트'로 돌려줍니다 — 최고 횟수인 값이 여럿일 수 있으니까요
# (예: 71도 72도 똑같이 4번이면 최빈값이 둘). 그래서 대비해 리스트로 받습니다.
#
# 최빈값은 특히 '불량 유형', '가장 흔한 설비 상태'처럼
# 숫자 크기보다 '무엇이 제일 자주 일어나나'가 궁금할 때 씁니다.


# ----------------------------------------
# 대표값 3형제 - 언제 뭘 쓰나
# ----------------------------------------

#   대표값   |  뜻                  |  강한 상황                |  약점
#  ---------+---------------------+--------------------------+------------------
#   평균     |  다 더해 개수로 나눔  |  잔잔한(튀는 값 없는) 값   |  이상치에 끌려감
#   중앙값   |  줄 세운 한가운데     |  이상치 섞인 값           |  값의 크기 정보 버림
#   최빈값   |  가장 자주 나온 값    |  '가장 흔한 것'이 궁금할 때 |  숫자 데이터엔 덜 유용
#
# 실무 요령 하나: 평균과 중앙값을 나란히 찍어 보세요.
#   - 둘이 비슷하다  → 데이터가 고르게 퍼져 있다
#   - 둘이 크게 다르다 → 어딘가에 튀는 값이 있다는 신호 (오늘 온도가 그 예)
# 이 한 가지 비교만으로도 이상치 존재를 냄새 맡을 수 있습니다.


# ========================================================
#  PART 3 : 흩어짐 - 분산과 표준편차
# ========================================================

# 대표값이 '중심'을 말했다면, 이제 '그 중심에서 얼마나 퍼졌나'를 잽니다.
# 지난 파트13에서 만든 그 분산·표준편차를, 복습 삼아 다시 세웁니다.

# ----------------------------------------
# 분산 - 편차를 제곱해서 평균
# ----------------------------------------

# 분산 = Σ(x - 평균)² / n
#
# 세 걸음입니다.
#   1) 편차 : 각 값에서 평균을 뺀다      (x - 평균)  ← 중심과의 거리
#   2) 제곱 : 그 편차를 제곱한다         (x - 평균)²
#   3) 평균 : 제곱들을 더해 개수로 나눈다  Σ(...) / n
#
# 왜 2단계에서 '제곱'을 할까요?
#   편차를 그냥 더하면 평균보다 큰 값(+)과 작은 값(-)이 상쇄돼 항상 0이 됩니다.
#   → 흩어짐이 사라지죠. 제곱하면 음수도 양수가 되어 흩어짐이 살아남습니다.

# 실제로 편차를 그냥 더하면 0이 되는지 눈으로 확인:
m = 평균(온도)                        # 74.0
편차들 = [x - m for x in 온도]
print("편차 그냥 합:", round(sum(편차들), 10))   # → 편차 그냥 합: 0.0
# 보다시피 0. 그래서 제곱이 필요합니다.

def 분산(xs):
    m = 평균(xs)                                    # 먼저 중심(평균)
    return sum((x - m) ** 2 for x in xs) / len(xs)  # Σ(x-평균)² / n

print("분산:", 분산(온도))   # → 분산: 29.2

# 분모 주의: 우리는 '개수 n'으로 나눕니다 (n-1이 아님).
#           뒤에서 대조할 numpy 의 기본값(np.var 은 n으로 나눔)과 맞추려는 겁니다.
#           n-1로 나누면 다른 정의가 되어 값이 어긋납니다.


# ----------------------------------------
# 표준편차 - 분산의 제곱근
# ----------------------------------------

# 분산 29.2는 흩어짐을 담고 있지만 단위가 '도의 제곱'이라 감이 안 옵니다.
# 편차를 제곱하는 과정에서 단위까지 제곱돼 버렸거든요.
#
#   표준편차 = √분산
#
# 왜 제곱근? 제곱하느라 틀어진 단위를 원래(도)로 되돌리려는 겁니다.
# 파이썬에서 제곱근은 '0.5 제곱'으로 씁니다. (x ** 0.5)

def 표준편차(xs):
    return 분산(xs) ** 0.5   # √분산 = 분산의 0.5 제곱

print("표준편차:", round(표준편차(온도), 4))   # → 표준편차: 5.4037

# 분산이 29.2였으니 표준편차는 √29.2, 약 5.4도.
# 이제 "이 설비 온도는 중심에서 약 5.4도만큼 흩어져 있다"고
# 도 단위로 자연스럽게 말할 수 있습니다.
# (5.4도가 꽤 큰 이유? 90도 이상치 하나가 흩어짐을 크게 부풀린 탓입니다.)


# ========================================================
#  PART 4 : 위치와 범위 - 최소·최대·사분위수
# ========================================================

# 대표값(중심)과 흩어짐을 봤으니, 이제 '값들이 어디부터 어디까지
# 걸쳐 있나'를 봅니다. 데이터의 양 끝과 허리를 짚는 단계입니다.

# ----------------------------------------
# 최소·최대·범위
# ----------------------------------------

# 가장 단순한 위치 정보는 양 끝, 곧 최솟값과 최댓값입니다.
# 그 둘의 차이가 '범위(range)' — 데이터가 걸친 폭이죠.

최소 = min(온도)
최대 = max(온도)
범위 = 최대 - 최소
print("최소:", 최소, "/ 최대:", 최대, "/ 범위:", 범위)   # → 최소: 71 / 최대: 90 / 범위: 19

# 범위 19도. 그런데 이 폭도 90 이상치 하나 때문에 부풀려진 값입니다.
# 71~74에 몰려 있는데 90 하나가 폭을 19까지 벌려 놨죠.
# 범위는 '딱 양 끝 두 값'만 보므로 이상치에 아주 약합니다.
# 그래서 이상치에 덜 흔들리는 위치 지표가 필요합니다 — 사분위수입니다.


# ----------------------------------------
# 사분위수 - 데이터를 4등분하는 경계
# ----------------------------------------

# 값들을 크기순으로 줄 세운 뒤 넷으로 똑같이 나누는 세 경계점입니다.
#
#   [ 25% ][ 25% ][ 25% ][ 25% ]
#         Q1     Q2     Q3
#   Q1 (하위 25% 지점) = 아래에서 1/4 되는 자리
#   Q2 (하위 50% 지점) = 한가운데 = 중앙값과 같음
#   Q3 (하위 75% 지점) = 아래에서 3/4 되는 자리
#
# 중앙값이 데이터를 '반'으로 갈랐다면, 사분위수는 '네 조각'으로 가른 거예요.
# Q1과 Q3는 '가운데 절반(50%)이 어디에 모여 있나'를 알려 줍니다.

def 분위수(xs, q):
    # q는 0~1 비율. 정렬 후 그 비율 위치의 값을 선형보간으로 구함.
    # (numpy 기본 방식과 맞추려고 위치가 정수가 아니면 이웃 두 값을 비례 배분)
    s = sorted(xs)
    n = len(s)
    위치 = q * (n - 1)          # 0-기준 소수 위치
    아래 = int(위치)             # 왼쪽 정수 위치
    나머지 = 위치 - 아래         # 이웃 사이의 비율
    if 아래 + 1 < n:
        return s[아래] + 나머지 * (s[아래 + 1] - s[아래])   # 두 값 사이 보간
    return s[아래]              # 맨 끝이면 그 값

Q1 = 분위수(온도, 0.25)
Q3 = 분위수(온도, 0.75)
IQR = Q3 - Q1                   # IQR = Q3 - Q1
print("Q1:", Q1, "/ Q3:", Q3, "/ IQR:", IQR)   # → Q1: 72.0 / Q3: 73.0 / IQR: 1.0

# 여기가 사분위수의 진짜 쓸모입니다.
# IQR(Q3-Q1) = '가운데 절반이 걸친 폭'. 지금 IQR은 겨우 1.0도예요.
# 범위는 19였는데 IQR은 1.0. 왜 이렇게 차이 날까요?
#   범위는 양 끝(90 포함)을 보지만, IQR은 위아래 25%씩을 잘라 낸
#   '허리 부분'만 보기 때문입니다. 90 이상치가 자동으로 잘려 나가죠.
# 그래서 IQR은 이상치에 흔들리지 않는, 더 믿을 만한 '퍼짐' 지표입니다.
# (참고: 이상치 판정에 Q1-1.5·IQR, Q3+1.5·IQR 기준을 쓰는데, 오늘은 개념까지만.)


# ========================================================
#  PART 5 : 다변수 요약 - 센서 여러 열을 한 표로
# ========================================================

# 지금까지 온도 한 열만 봤습니다. 하지만 실제 설비는 온도만 재지 않죠.
# 압력·진동·회전수까지 여러 열이 동시에 찍혀 나옵니다.
# 각 열을 따로따로 요약해 '표 하나'로 나란히 놓으면
# "열마다 대표값도 흩어짐도 다르다"가 한눈에 보입니다.

# 설비 M-101 의 세 센서, 각 10회 측정. (외부 파일 없이 인라인)
센서 = {
    "온도": [72, 71, 73, 72, 74, 72, 73, 90, 72, 71],
    "압력": [4.2, 4.3, 4.1, 4.4, 4.2, 4.3, 4.2, 4.5, 4.1, 4.3],
    "진동": [0.9, 1.1, 0.8, 1.0, 1.2, 0.9, 1.0, 1.1, 0.8, 1.0],
}

# 앞에서 만든 함수들을 열마다 그대로 걸어 한 줄씩 출력합니다.
# 함수는 하나도 새로 만들지 않습니다 — 만든 걸 재사용할 뿐이에요.
print("[센서별 요약]")
print("  열     평균     중앙값   표준편차   최소    최대")
for 열, 값 in 센서.items():
    print(f"  {열}  {평균(값):7.3f}  {중앙값(값):6.2f}  {표준편차(값):8.4f}  {min(값):5}  {max(값):5}")
# → [센서별 요약]
# →   열     평균     중앙값   표준편차   최소    최대
# →   온도   74.000   72.00    5.4037     71     90
# →   압력    4.260    4.25    0.1200    4.1    4.5
# →   진동    0.980    1.00    0.1249    0.8    1.2

# 이 표 하나로 여러 가지가 드러납니다.
#   - 온도: 평균(74)과 중앙값(72)이 벌어짐 → 이상치 낌새 (90 때문)
#   - 압력·진동: 평균과 중앙값이 거의 붙음 → 고르게 퍼진 안정적인 열
#   - 표준편차의 크기(5.4 / 0.12 / 0.12)는 단위가 달라 직접 비교는 조심해야 함
#     (온도는 '도', 압력은 'bar' 단위라 숫자 크기만으로 우열을 못 매김)
#
# 핵심: 열마다 성격이 다르므로, 각 열을 따로 요약해 나란히 놓고 봐야 합니다.
# 이렇게 여러 열을 다루기 시작한 게, 다음에 배울 '열 사이의 관계'
# (공분산·상관·회귀)의 출발점입니다.


# ========================================================
#  PART 6 : numpy 대조 - 우리가 만든 게 라이브러리와 같은가
# ========================================================

# 내가 만든 함수를 믿으려면 채점이 필요합니다.
# 수많은 사람이 검증한 numpy 결과와 내 결과를 나란히 놓고 봅니다.
#   평균     → np.mean
#   중앙값   → np.median
#   분산     → np.var    (기본 분모 n — 우리와 같음)
#   표준편차 → np.std
#   Q1·Q3   → np.percentile(값, 25) / np.percentile(값, 75)

print("[온도 열 채점 — 직접 구현 vs numpy]")
print("  평균    ", round(평균(온도), 4),     "/", round(np.mean(온도), 4))
print("  중앙값  ", 중앙값(온도),              "/", np.median(온도))
print("  분산    ", round(분산(온도), 4),     "/", round(np.var(온도), 4))
print("  표준편차", round(표준편차(온도), 4), "/", round(np.std(온도), 4))
print("  Q1      ", 분위수(온도, 0.25),        "/", np.percentile(온도, 25))
print("  Q3      ", 분위수(온도, 0.75),        "/", np.percentile(온도, 75))
# → [온도 열 채점 — 직접 구현 vs numpy]
# →   평균     74.0 / 74.0
# →   중앙값   72.0 / 72.0
# →   분산     29.2 / 29.2
# →   표준편차 5.4037 / 5.4037
# →   Q1       72.0 / 72.0
# →   Q3       73.0 / 73.0

# 여섯 값이 소수점까지 전부 일치합니다.
# 우리가 반복문과 나눗셈으로 손수 만든 함수가, 라이브러리와 똑같은 답을 냈어요.
# numpy 는 답을 대신 내주는 도구가 아니라, 내 답을 채점하는 채점표입니다.
# (참고: 최빈값은 numpy 기본엔 함수가 없어 여기선 대조에서 뺐습니다.
#  scipy.stats.mode 를 따로 쓰면 되지만, 오늘은 직접 구현으로 충분합니다.)

# 실수 계산은 아주 미세한 오차가 생길 수 있어, 세 열을 자동 채점할 때는
# '완전히 같음' 대신 '차이가 1e-9 미만이면 같음'으로 봅니다.
print("[세 열 자동 채점 — 평균이 numpy와 같은가]")
for 열, 값 in 센서.items():
    일치 = abs(평균(값) - np.mean(값)) < 1e-9
    print(" ", 열, 일치)
# → [세 열 자동 채점 — 평균이 numpy와 같은가]
# →   온도 True
# →   압력 True
# →   진동 True


