# 오늘 만든 함수들을 손에 익히는 시간입니다.
# 새로 들어온 '회전수' 센서 측정값 10개를, 위 함수들로 요약하고 numpy 와 대조하세요.
#
#   Step 1) 평균·중앙값·최빈값 (대표값 3형제)
#   Step 2) 분산·표준편차 (흩어짐)
#   Step 3) 최소·최대·범위·Q1·Q3·IQR (위치·범위)
#   Step 4) np.mean / np.median / np.var / np.std / np.percentile 과 대조
#
# 완료 기준: 직접 구현 값들이 화면에 나오고, numpy 값과 나란히 찍혀 같으면 성공.

회전수 = [1500, 1520, 1490, 1510, 1505, 1495, 1600, 1480, 1510, 1490]

# (실습 정답 예시)
print("[실습 · 회전수 요약]")
print("  평균:",     round(평균(회전수), 4),     "/ numpy:", round(np.mean(회전수), 4))
print("  중앙값:",   중앙값(회전수),             "/ numpy:", np.median(회전수))
print("  최빈값:",   최빈값(회전수))
print("  분산:",     round(분산(회전수), 4),     "/ numpy:", round(np.var(회전수), 4))
print("  표준편차:", round(표준편차(회전수), 4), "/ numpy:", round(np.std(회전수), 4))
print("  최소/최대/범위:", min(회전수), max(회전수), max(회전수) - min(회전수))
Q1r = 분위수(회전수, 0.25)
Q3r = 분위수(회전수, 0.75)
print("  Q1/Q3/IQR:", Q1r, Q3r, Q3r - Q1r)
# → [실습 · 회전수 요약]
# →   평균: 1510.0 / numpy: 1510.0
# →   중앙값: 1502.5 / numpy: 1502.5
# →   최빈값: [1490, 1510]
# →   분산: 1025.0 / numpy: 1025.0
# →   표준편차: 32.0156 / numpy: 32.0156
# →   최소/최대/범위: 1480 1600 120
# →   Q1/Q3/IQR: 1491.25 1510.0 18.75

# 회전수도 1600 하나가 튀는 값입니다.
# 평균(1510)과 중앙값(1502.5)이 벌어진 것, 범위(120)에 비해 IQR(18.75)이
# 훨씬 작은 것 — 둘 다 "1600 이상치가 있다"는 같은 신호예요.
# 오늘 온도에서 본 그림이 회전수에서도 그대로 반복됩니다.


