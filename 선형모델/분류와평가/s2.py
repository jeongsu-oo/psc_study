# 로지스틱 분류기 만들기 - fit·predict 로 묶고, 임계값 다루기 (분류 4부작 2편)
# -------------------------------


"""[불량이냐 아니냐, 어디서 선을 긋죠?]
1편에서 로지스틱 회귀로 '온도 → 불량 확률' 을 구했습니다.
   p = sigmoid(w·x + b)      온도가 오를수록 불량일 확률이 올라가는 S 곡선
그런데 확률(0.73 같은 값)만으로는 현장에서 못 씁니다.
결국 "이 제품 불량이야, 아니야?" 라는 0/1 판정이 필요하죠.

오늘 할 일은 두 가지입니다.
  1) 1편의 로지스틱을 '재사용 가능한 분류기' 로 묶습니다.
       fit(X, y)          → 데이터 보고 w, b 학습 (경사하강)
       predict_proba(x)   → 불량일 확률 p 를 돌려줌
       predict(x, 임계값) → 확률을 0/1 판정으로 바꿔줌
  2) 그 '임계값' 을 손봅니다. 다들 0.5 인 줄 알지만, 0.5 는 절대 규칙이
     아니에요. 임계값을 어디에 두느냐가 곧 '어떤 실수를 더 무서워하느냐' 입니다.

특히 제조에선 이 감이 중요합니다. 불량을 못 걸러 고객에게 나가는 것과,
멀쩡한 걸 불량이라 붙잡는 것 — 둘 중 뭐가 더 치명적일까요?
그 답에 따라 선(임계값)을 옮깁니다. 오늘 그 감을 잡습니다.

이 파일은 시그모이드 복습 → 분류기 fit → 확률·판정 표 → 임계값 조정 →
sklearn 대조 → 실습 순으로 위에서 아래로 쌓아 갑니다.
"""

import math
import numpy as np


# ========================================================
#  PART 1 : 재료 복습 - 시그모이드와 그래디언트
# ========================================================

# ----------------------------------------
# 시그모이드 - 아무 수나 0~1 확률로
# ----------------------------------------

# 로지스틱의 심장은 시그모이드입니다. 어떤 실수든 0~1 사이로 눌러줘요.
# 그래서 '확률' 로 읽을 수 있습니다.
#
#   sigmoid(z) = 1 / (1 + e^-z)
#
#   p
#   1 |            ______
#     |          /                z 가 크면(온도 높으면) → 1 에 가까움
#  0.5|- - - - -/- - - - -         z=0 이면 딱 0.5
#     |      _/                    z 가 작으면(온도 낮으면) → 0 에 가까움
#   0 |____/____________ z
#          0

def sigmoid(z):
    # z 가 너무 작으면 e^-z 가 폭발하니 아래로 잘라 오버플로를 막습니다.
    if z < -60:
        return 0.0
    return 1.0 / (1.0 + math.exp(-z))


# ----------------------------------------
# 로지스틱 그래디언트 - 어느 쪽으로 걸을까
# ----------------------------------------

# 학습은 경사하강입니다(3부작에서 몸에 익힌 그 걸음 그대로).
# 로지스틱의 그래디언트는 신기하게도 선형회귀와 모양이 똑같아요.
#
#   ∂L/∂w = (1/n) Σ (p - y) · x        ← p 는 예측 확률, y 는 실제 0/1
#   ∂L/∂b = (1/n) Σ (p - y)
#
#   (유도는 생략합니다. 이 식만 재료로 씁니다. '예측-실제 오차 × x' 라는
#    꼴이 선형회귀랑 판박이라는 것만 눈에 담아 두세요.)

def 그래디언트(zs, ys, w, b):
    n = len(zs)
    ps = [sigmoid(w * z + b) for z in zs]                       # 각 샘플 예측 확률
    gw = sum((p - y) * z for z, y, p in zip(zs, ys, ps)) / n    # ∂L/∂w
    gb = sum((p - y) for y, p in zip(ys, ps)) / n               # ∂L/∂b
    return gw, gb


# 표준화도 3부작에서 쓴 그대로입니다. x 값이 크면 걸음이 휘청여서,
# '평균 0, 퍼짐 1' 눈금으로 갈아탄 뒤 걷습니다.
def 표준화(xs):
    m = sum(xs) / len(xs)
    s = (sum((x - m) ** 2 for x in xs) / len(xs)) ** 0.5
    zs = [(x - m) / s for x in xs]
    return zs, m, s                                             # 되돌릴 때 쓰려고 m, s 도


# ========================================================
#  PART 2 : 분류기로 묶기 - fit / predict_proba / predict
# ========================================================

# ----------------------------------------
# 왜 '묶어서' 만드나
# ----------------------------------------

# 지금까지는 학습 코드, 예측 코드가 여기저기 흩어져 있었습니다.
# 이걸 하나의 '분류기' 로 묶으면 세 가지를 정갈하게 나눠 쓸 수 있어요.
#
#   fit(X, y)          : 데이터를 보여주고 w, b 를 학습시킨다 (딱 한 번)
#   predict_proba(x)   : 학습된 w, b 로 '확률' 을 답한다
#   predict(x, 임계값) : 그 확률을 0/1 '판정' 으로 바꾼다
#
# 이 세 이름(fit / predict_proba / predict)은 sklearn 도 똑같이 씁니다.
# 세계 표준 도구와 같은 이름표를 우리 손으로 붙이는 겁니다.

# 함수 묶음(딕셔너리) 하나로 분류기를 표현합니다. 학습이 끝나면
# w, b 와 되돌릴 눈금(m, s)을 이 안에 담아 두고 계속 꺼내 씁니다.

def fit(xs, ys, lr=0.3, epochs=3000, 로그=False):
    zs, m, s = 표준화(xs)                     # z 눈금으로 갈아타고
    w, b = 0.0, 0.0                           # 아무 데서나 출발
    for epoch in range(epochs):
        gw, gb = 그래디언트(zs, ys, w, b)     # 지금 위치의 내리막 방향
        w = w - lr * gw                       # w ← w - lr·∂L/∂w
        b = b - lr * gb                       # b ← b - lr·∂L/∂b
        if 로그 and epoch % 600 == 0:
            print(f"  epoch {epoch:5d}   w {w:+.4f}  b {b:+.4f}")
    # 학습 결과를 딕셔너리에 담아 돌려줍니다. 이게 우리의 '학습된 분류기'.
    return {"w": w, "b": b, "m": m, "s": s}


# predict_proba : 원래 x 를 넣으면, 학습 때 쓴 눈금(m, s)으로 표준화한 뒤
#                 확률 p 를 돌려줍니다. 사용자는 표준화를 신경 쓸 필요 없어요.
def predict_proba(분류기, x):
    z = (x - 분류기["m"]) / 분류기["s"]       # 학습 때와 같은 눈금으로 맞춤
    return sigmoid(분류기["w"] * z + 분류기["b"])


# predict : 확률을 임계값과 비교해 0/1 로 자릅니다. 임계값 기본 0.5.
#           확률이 임계값 이상이면 1(불량), 아니면 0(양품).
def predict(분류기, x, 임계값=0.5):
    return 1 if predict_proba(분류기, x) >= 임계값 else 0


# ----------------------------------------
# 제조 데이터로 학습시키기
# ----------------------------------------

# 과정3 분류 공통 데이터입니다. 온도가 오를수록 불량(1)이 늘어나는 흐름.
# 다만 딱 떨어지진 않아요 — 30도에서 양품(0), 34도에서 양품(0) 처럼
# 뒤섞인 구간이 있습니다. 현실 데이터가 원래 이렇죠.
온도 = [18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40]
불량 = [ 0,  0,  0,  0,  1,  0,  1,  1,  0,  1,  1,  1]

print("[로지스틱 분류기 학습 로그]")
분류기 = fit(온도, 불량, lr=0.3, epochs=3000, 로그=True)
# → [로지스틱 분류기 학습 로그]
# →   epoch     0   w +0.1014  b +0.0000
# →   epoch   600   w +2.0455  b -0.0000
# →   epoch  1200   w +2.0455  b -0.0000
# →   epoch  1800   w +2.0455  b -0.0000
# →   epoch  2400   w +2.0455  b -0.0000

print(f"  학습 완료 → w: {분류기['w']:.4f} / b: {분류기['b']:.4f}")
# →   학습 완료 → w: 2.0455 / b: -0.0000

# w 가 양수(+2.0)라는 게 핵심입니다. z(온도)가 오르면 w·z 가 커지고,
# 시그모이드를 지나 확률도 올라갑니다 = "온도 높을수록 불량 확률 ↑".
# 데이터의 흐름을 분류기가 제대로 잡았다는 뜻이죠.


# ========================================================
#  PART 3 : 확률과 판정 - 각 샘플을 표로
# ========================================================

# ----------------------------------------
# 온도마다 확률·판정 한눈에
# ----------------------------------------

# 학습된 분류기로 각 온도의 '불량 확률' 과 '0.5 기준 판정' 을 뽑아
# 실제 정답(불량)과 나란히 놓고 봅니다. 맞았는지 O/X 로 표시.

print("\n[온도별 확률과 판정 · 임계값 0.5]")
print("  온도  확률    판정(0.5)  실제   맞음?")
for x, y_실제 in zip(온도, 불량):
    p = predict_proba(분류기, x)
    y_예측 = predict(분류기, x, 임계값=0.5)
    맞음 = "O" if y_예측 == y_실제 else "X"
    print(f"  {x:>3}   {p:.3f}     {y_예측}        {y_실제}      {맞음}")
# → [온도별 확률과 판정 · 임계값 0.5]
# →   온도  확률    판정(0.5)  실제   맞음?
# →    18   0.037     0        0      O
# →    20   0.065     0        0      O
# →    22   0.112     0        0      O
# →    24   0.185     0        0      O
# →    26   0.291     0        1      X
# →    28   0.426     0        0      O
# →    30   0.574     1        1      O
# →    32   0.709     1        1      O
# →    34   0.815     1        0      X
# →    36   0.888     1        1      O
# →    38   0.935     1        1      O
# →    40   0.963     1        1      O

# 확률이 온도 따라 매끈하게 오릅니다(0.04 → 0.96). S 곡선이죠.
# 26도(실제 불량인데 확률 0.29라 양품 판정)와 34도(실제 양품인데
# 확률 0.82라 불량 판정)에서 틀렸습니다. 뒤섞인 그 두 점이에요.
# 12개 중 10개 정답. 나머지는 데이터가 원래 겹쳐 있어 어쩔 수 없는 실수입니다.


# ========================================================
#  PART 4 : 임계값 조정 - 0.5 는 절대 규칙이 아니다
# ========================================================

# ----------------------------------------
# 임계값을 낮추면 무슨 일이
# ----------------------------------------

# 지금까지 '0.5 이상이면 불량' 이라 했죠. 그런데 이 0.5 는 어디서 온
# 절대값이 아닙니다. 그냥 '반반' 이라는 관습일 뿐이에요.
# 이 선을 옮기면 판정이 통째로 바뀝니다.
#
#   임계값 0.5  →  확률 0.5 이상만 불량       (선이 가운데)
#   임계값 0.25 →  확률 0.25 이상이면 불량      (선을 아래로 내림)
#
#   확률 축:  0 ---- 0.25 ------ 0.5 -------- 1
#                     ↑          ↑
#                  0.25 선     0.5 선
#             선을 왼쪽으로 내릴수록 → 더 많은 샘플이 '불량' 쪽에 걸림
#
# 임계값을 0.25 로 내리면, 확률이 0.25~0.5 인 애매한 샘플들도
# 전부 '불량' 으로 잡힙니다. 그물코를 촘촘히 하는 셈이죠.

print("\n[임계값 0.5 vs 0.25 판정 비교]")
print("  온도  확률    0.5기준  0.25기준  바뀜?")
바뀐수 = 0
for x in 온도:
    p = predict_proba(분류기, x)
    판정_05 = predict(분류기, x, 임계값=0.5)
    판정_025 = predict(분류기, x, 임계값=0.25)
    바뀜 = "←바뀜" if 판정_05 != 판정_025 else ""
    if 판정_05 != 판정_025:
        바뀐수 += 1
    print(f"  {x:>3}   {p:.3f}     {판정_05}         {판정_025}       {바뀜}")
print(f"  → 임계값을 낮추자 {바뀐수}개 샘플이 '불량' 쪽으로 넘어감")
# → [임계값 0.5 vs 0.25 판정 비교]
# →   온도  확률    0.5기준  0.25기준  바뀜?
# →    18   0.037     0         0
# →    20   0.065     0         0
# →    22   0.112     0         0
# →    24   0.185     0         0
# →    26   0.291     0         1       ←바뀜
# →    28   0.426     0         1       ←바뀜
# →    30   0.574     1         1
# →    32   0.709     1         1
# →    34   0.815     1         1
# →    36   0.888     1         1
# →    38   0.935     1         1
# →    40   0.963     1         1
# →   → 임계값을 낮추자 2개 샘플이 '불량' 쪽으로 넘어감

# 26도(확률 0.29)와 28도(확률 0.426)가 0.5 기준에선 양품이었는데,
# 0.25 기준에선 불량으로 넘어왔습니다. 선을 내렸더니 그물에 더 걸린 거죠.
# 특히 26도는 실제로 불량이었는데 0.5 에선 놓쳤던 점입니다 — 이걸 되찾았어요.


# ----------------------------------------
# 놓친 불량은 줄고, 헛짚음은 는다
# ----------------------------------------

# 임계값을 내리면 좋기만 할까요? 아닙니다. 맞바꿈(trade-off)이 있어요.
# 실제 불량을 얼마나 놓쳤는지, 멀쩡한 걸 얼마나 불량이라 했는지 세어 봅시다.

def 놓친불량_헛짚음(분류기, xs, ys, 임계값):
    놓친불량 = 0    # 실제 불량(1)인데 양품(0)이라 판정 = 놓침 (제조에서 치명적)
    헛짚음 = 0      # 실제 양품(0)인데 불량(1)이라 판정 = 멀쩡한 걸 붙잡음
    for x, y in zip(xs, ys):
        예측 = predict(분류기, x, 임계값)
        if y == 1 and 예측 == 0:
            놓친불량 += 1
        if y == 0 and 예측 == 1:
            헛짚음 += 1
    return 놓친불량, 헛짚음

print("\n[임계값별 맞바꿈]")
print("  임계값   놓친 불량   헛짚음(멀쩡한걸 불량)")
for 임계값 in [0.5, 0.25]:
    놓침, 헛짚 = 놓친불량_헛짚음(분류기, 온도, 불량, 임계값)
    print(f"   {임계값}       {놓침}개        {헛짚}개")
# → [임계값별 맞바꿈]
# →   임계값   놓친 불량   헛짚음(멀쩡한걸 불량)
# →    0.5       1개        1개
# →    0.25       0개        2개

# 여기가 오늘의 핵심입니다. 임계값을 0.5 → 0.25 로 내렸더니:
#   · 놓친 불량 : 1개 → 0개   (실제 불량 26도를 이제 놓치지 않음)
#   · 헛짚음    : 1개 → 2개   (멀쩡한 28도까지 불량이라 붙잡음. 34도는 원래 헛짚음)
#
#   임계값 ↓  →  놓친 불량 ↓ (재현율 ↑)  대신  헛짚음 ↑ (정밀도 ↓)
#
# 둘 다 좋게 만들 순 없어요. 하나를 얻으면 하나를 내주는 맞바꿈입니다.


# ----------------------------------------
# 그럼 제조에선 임계값을 어디에?
# ----------------------------------------

# 판단 기준은 '어떤 실수가 더 아픈가' 입니다.
#
#   놓친 불량(불량을 양품이라 통과) → 고객에게 불량품이 나감.
#                                     리콜·클레임·신뢰 붕괴. 치명적.
#   헛짚음(양품을 불량이라 붙잡음)   → 멀쩡한 걸 다시 검사. 시간·비용 낭비.
#                                     아깝지만 사고는 아님.
#
# 제조 현장에선 대개 '놓친 불량' 이 훨씬 무섭습니다. 그래서 일부러
# 임계값을 0.5 아래로 내려, 조금이라도 의심되면 불량으로 붙잡습니다.
# 헛짚음이 늘어 재검사가 많아지는 건 감수하는 거죠. "놓치느니 붙잡자."
