# 오늘 만든 fit / predict_proba / predict 를 그대로 써서
# 새 데이터에 분류기를 학습시키고, 임계값을 바꿔 보세요.
#
#   Step 1) 분류기 = fit(x, y, lr=0.3, epochs=3000)     학습
#   Step 2) predict_proba(분류기, 새값) 으로 확률 확인
#   Step 3) predict(분류기, 새값, 임계값=0.5) 와 0.25 판정 비교
#   Step 4) 임계값 낮추면 놓친 불량이 주는지 세어 보기
#
#   완료 기준 : 확률·판정이 화면에 나오고, 임계값 0.5 와 0.25 의
#               판정 차이가 눈에 보이면 성공.

# (실습 정답 예시 — 진동 세기 → 베어링 불량)
진동 = [1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0, 5.5]
불량2 = [ 0,   0,   0,   1,   0,   1,   1,   0,   1,   1 ]

분류기2 = fit(진동, 불량2, lr=0.3, epochs=3000)
print("\n[실습 예시 · 진동 → 베어링 불량]")
print(f"  학습 → w: {분류기2['w']:.4f} / b: {분류기2['b']:.4f}")
print(f"  진동 3.2 불량 확률: {predict_proba(분류기2, 3.2):.3f}")
print(f"  진동 3.2 판정(0.5): {predict(분류기2, 3.2, 0.5)}  /  판정(0.25): {predict(분류기2, 3.2, 0.25)}")
놓침05, 헛짚05 = 놓친불량_헛짚음(분류기2, 진동, 불량2, 0.5)
놓침025, 헛짚025 = 놓친불량_헛짚음(분류기2, 진동, 불량2, 0.25)
print(f"  임계값 0.5  → 놓친 불량 {놓침05}개 / 헛짚음 {헛짚05}개")
print(f"  임계값 0.25 → 놓친 불량 {놓침025}개 / 헛짚음 {헛짚025}개")
# → [실습 예시 · 진동 → 베어링 불량]
# →   학습 → w: 1.5616 / b: -0.0000
# →   진동 3.2 불량 확률: 0.486
# →   진동 3.2 판정(0.5): 0  /  판정(0.25): 1
# →   임계값 0.5  → 놓친 불량 1개 / 헛짚음 1개
# →   임계값 0.25 → 놓친 불량 0개 / 헛짚음 2개

# 여기서도 똑같은 결론입니다. 임계값을 0.5 → 0.25 로 내리자
# 놓친 불량이 1개 → 0개로 줄고, 대신 헛짚음이 1개 → 2개로 늘었습니다.
# '놓치느니 붙잡자' 를 원하면 임계값을 내린다 — 이 감이 오늘의 핵심입니다.


