def diagnose(degree):
    """주어진 차수로 모델을 맞추고 과적합 여부를 진단해 돌려줌."""
    coef = fit_poly(x_train, y_train, degree)
    e_tr = mse(coef, x_train, y_train)
    e_te = mse(coef, x_test,  y_test)
    ratio = e_te / e_tr if e_tr > 0 else float("inf")
    return e_tr, e_te, ratio

