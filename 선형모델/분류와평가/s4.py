# 과적합 진단 - 학습엔 잘, 새 데이터엔 엉망 (분류·평가 4부작 4편)
# -------------------------------


"""[학습 데이터에선 100점인데 현장에선 왜 틀리죠?]
분류·평가 4부작의 마지막입니다.

앞에서 우리는 모델을 '학습'시키고 그 성능을 '숫자'로 쟀습니다.
그런데 실무에서 가장 자주, 가장 뼈아프게 겪는 함정이 하나 있습니다.
   "학습에 쓴 데이터로 재면 성능이 아주 좋은데,
    막상 현장의 새 데이터에 넣으면 형편없다."

이걸 '과적합(overfitting)' 이라고 합니다.
모델이 데이터의 '규칙'을 배운 게 아니라, 학습 데이터 그 자체를
'통째로 외워' 버린 상태예요. 시험 범위를 이해한 게 아니라
답안지를 외운 학생과 같습니다. 본 문제는 다 맞지만, 새 문제엔 무너지죠.

이 파일에서 할 일:
  1) 왜 데이터를 학습용·시험용으로 나누나 (진짜 실력은 안 본 데이터로)
  2) 세 가지 상태 — 과소적합 / 적정 / 과적합 (ASCII 그림)
  3) 모델을 점점 복잡하게 만들며 train 오차·test 오차를 직접 재서
     train은 계속 줄지만 test는 U자로 다시 치솟는 걸 숫자로 확인
  4) 진단법 — train 성능 ≫ test 성능이면 과적합 신호
  5) 처방 — 데이터 늘리기 / 단순화 / 정규화 / 조기종료 (개념만)
  6) 실습 — 복잡도를 바꿔 과적합을 재현하고 진단

이 파일은 넘파이만 씁니다. 밑바닥 숫자로 과적합을 '눈으로' 봅니다.
"""

import numpy as np
import warnings

# 높은 차수에서 polyfit 이 "곡선이 불안정하다"는 경고를 냅니다.
# 그 불안정함이 바로 우리가 '과적합'으로 보여줄 현상이라 일부러 만드는 것이니,
# 경고 메시지는 화면에서 꺼 둡니다. (현상 자체는 오차 숫자로 확인합니다.)
warnings.simplefilter("ignore", np.exceptions.RankWarning)


# ==========================================================
#  1. 왜 데이터를 나누나 - 시험문제를 미리 본 학생
# ==========================================================

# 과정2에서 데이터를 학습용(train)과 시험용(test)으로 나눴던 것,
# 기억하시죠? 그게 왜 그렇게 중요한지 이제 뼈저리게 이해할 차례입니다.
#
# 생각해 봅시다. 학생의 진짜 실력을 어떻게 잽니까?
#   - 시험문제를 미리 보여 주고 푼 점수  → 실력이 아님 (외웠을 수도)
#   - 처음 보는 문제로 잰 점수           → 이게 진짜 실력
#
# 모델도 똑같습니다.
#   - train 데이터로 잰 성능  → 모델이 '본 문제'로 잰 것. 부풀려질 수 있음
#   - test 데이터로 잰 성능   → '안 본 문제'로 잰 것. 이게 진짜 실력
#
# 그래서 규칙은 하나입니다.
#   "성능은 반드시 '학습에 안 쓴' test 데이터로 잰다."
#   train 성능만 보고 좋아하면 안 됩니다. 그건 답안지를 외운 점수예요.
#
# 우리가 진짜 원하는 건 '일반화(generalization)' — 새 데이터에서도
# 잘 맞는 능력입니다. test 오차가 바로 그 일반화 실력의 척도예요.


# 제조 현장 데이터 하나를 인라인으로 만들겠습니다.
# 어떤 설비의 '가동 온도(x)' 에 따른 '미세한 품질 편차(y)' 라고 합시다.
# 진짜 관계는 완만한 곡선인데, 측정에는 늘 노이즈가 섞입니다.
# 점을 일부러 적게(12개) 둡니다 — 과적합이 선명하게 보이도록.

np.random.seed(42)   # 시드 고정: 몇 번을 돌려도 같은 결과 (재현성)

# x: 설비 온도 (정규화된 값 0~1 범위로 둠). 촘촘하게 12개.
x_all = np.linspace(0, 1, 12)

# 진짜 숨은 규칙: y = 완만한 2차 곡선.  여기에 노이즈를 살짝 얹음.
true_curve = lambda t: 2.0 * t**2 - 1.0 * t + 0.5
noise = np.random.normal(0, 0.05, size=x_all.shape)   # 표준편차 0.05 잡음
y_all = true_curve(x_all) + noise

# 학습용·시험용을 '번갈아' 나눕니다.
#   짝수 번째 점 → 학습(train),  홀수 번째 점 → 시험(test)
# 이렇게 하면 test 점들이 train 점들 '사이사이'에 놓입니다.
# 복잡한 모델이 train 점 사이에서 심하게 출렁이면, 바로 그 사이에 있는
# test 점에서 예측이 크게 빗나가죠 — 과적합이 test 오차로 또렷이 드러납니다.
train_mask = np.arange(12) % 2 == 0
x_train, y_train = x_all[train_mask],  y_all[train_mask]
x_test,  y_test  = x_all[~train_mask], y_all[~train_mask]

print("[데이터 분할]")
print("  전체:", len(x_all), "개  ->  학습:", len(x_train), "개 / 시험:", len(x_test), "개")
# → [데이터 분할]
# →   전체: 12 개  ->  학습: 6 개 / 시험: 6 개


# ==========================================================
#  2. 세 가지 상태 - 과소적합 / 적정 / 과적합
# ==========================================================

# 모델을 데이터에 맞출 때, 결과는 크게 세 가지 상태로 갈립니다.
# 그림으로 먼저 눈에 새기고 갑니다. (o = 데이터 점, 선 = 모델)
#
#   [과소적합 underfitting]     [적정 good fit]         [과적합 overfitting]
#    너무 단순한 모델            딱 맞는 복잡도            너무 복잡한 모델
#
#      o                          o                        o
#   ─────────  o              ╭──╮   o                    ╱╲   o
#      o   o                 o╯   ╰─╮                     o  ╲ ╱╲
#   ────────────           ╭╯      ╰o                   ╭─╮╲╯  ╰o
#      o                   o         o                  o ╰──╮  ╱
#                                                            ╰╯
#   직선 하나로 뭉갬          곡선이 흐름을 탐          점 하나하나 다 지나감
#   train X, test X          train O, test O          train O(완벽), test X
#
# 핵심 대비:
#   과소적합 — 모델이 너무 단순해 데이터의 흐름조차 못 잡음.
#              train 도 나쁘고 test 도 나쁨. (덜 배운 상태)
#   적정     — 데이터의 '흐름(규칙)'을 잡되 노이즈는 무시.
#              train 도 test 도 고르게 좋음. (우리가 원하는 상태)
#   과적합   — 모델이 노이즈까지 통째로 외워 점을 하나하나 다 지나감.
#              train 은 완벽에 가깝지만 test 는 엉망. (외운 상태)
#
# 과소적합과 과적합은 정반대처럼 보이지만, 원인은 하나의 손잡이 —
# '모델 복잡도' 입니다. 너무 낮으면 과소, 너무 높으면 과적합.
# 그 사이 어딘가에 딱 맞는 지점이 있어요. 이제 그걸 숫자로 찾아봅니다.


# ==========================================================
#  3. 과적합 데모 - 복잡도를 올리며 train·test 오차를 재기
# ==========================================================

# 모델 복잡도를 조절하는 가장 직관적인 손잡이: '다항 회귀의 차수'.
#   차수 1 = 직선 (y = ax + b)              ← 가장 단순
#   차수 3 = 완만한 곡선                     ← 적당
#   차수 9 = 구불구불 곡선 (점 10개면 거의 다 통과) ← 과하게 복잡
#
# 차수가 오를수록 모델이 표현할 수 있는 곡선이 더 자유로워집니다.
# 즉 복잡도가 올라갑니다.
#
# 오차는 MSE(평균제곱오차)로 잽니다 — 예측과 실제의 차이를 제곱해 평균.
#   MSE = 평균( (예측 - 실제)^2 )
# 작을수록 잘 맞는 겁니다. 이 오차를 train 과 test 에서 각각 재요.

def fit_poly(x, y, degree):
    """x, y 에 degree 차 다항식을 최소제곱으로 맞춰 계수를 돌려줌.
    (np.polyfit 이 '가장 잘 맞는 다항식 계수'를 한 방에 구해 줍니다.)"""
    return np.polyfit(x, y, degree)

def mse(coef, x, y):
    """맞춘 계수(coef)로 x 를 예측해 실제 y 와의 평균제곱오차를 냄."""
    pred = np.polyval(coef, x)     # 다항식에 x 를 넣어 예측값 계산
    return np.mean((pred - y) ** 2)

print("\n[복잡도(차수)를 올리며 오차 재기]")
print("  차수 | train 오차(MSE) | test 오차(MSE)")
print("  -----+-----------------+----------------")

degrees = [1, 3, 6, 9]
train_errors, test_errors = [], []
for d in degrees:
    coef = fit_poly(x_train, y_train, d)
    e_tr = mse(coef, x_train, y_train)
    e_te = mse(coef, x_test,  y_test)
    train_errors.append(e_tr)
    test_errors.append(e_te)
    print(f"  {d:>4} | {e_tr:>15.6f} | {e_te:>14.6f}")
# → [복잡도(차수)를 올리며 오차 재기]
# →   차수 | train 오차(MSE) | test 오차(MSE)
# →   -----+-----------------+----------------
# →      1 |        0.024352 |       0.037926
# →      3 |        0.000928 |       0.001402
# →      6 |        0.000000 |       0.107667
# →      9 |        0.000000 |       0.510300

# 위 표를 천천히 읽어 봅시다. 여기가 이 파일의 심장입니다.
#
#   train 오차 : 0.0244 → 0.0009 → 0.0000 → 0.0000
#                차수가 오를수록 '계속' 줄어듭니다. 끝엔 0 (완벽히 통과)
#   test  오차 : 0.0379 → 0.0014 → 0.1077 → 0.5103
#                줄었다가(차수3) 다시 '치솟습니다'. 전형적인 U자.
#
# 이게 과적합의 정체입니다.
#   - 차수가 낮을 땐(1) 둘 다 좀 큼        → 과소적합
#   - 차수 2~3쯤에서 test 가 최소          → 적정 (딱 맞는 복잡도)
#   - 차수를 더 올리면(6, 9) train 은 0까지 떨어지는데
#     test 는 오히려 커집니다               → 과적합
#
# 차수 6, 9에서 train 오차가 '0' 이라는 게 핵심 함정입니다.
# 점 6개를 고차 곡선이 하나도 안 틀리고 다 지나가 버렸어요.
# 완벽해 보이죠? 하지만 그 대가로 test 오차는 수십 배로 커집니다.
# 학습 점 사이에서 곡선이 미친 듯이 출렁이거든요 —
# 그 사이에 놓인 test 점들이 바로 그 출렁임에 걸려 빗나갑니다.
#
# 제조 맥락으로 옮기면 뼈아픕니다.
#   설비 데이터가 겨우 몇 개(여기선 6개)인데 아주 복잡한 모델을 쓰면,
#   그 몇 개는 완벽히 맞추지만 새로 들어온 측정값엔 엉터리 예측을 냅니다.
#   "데이터는 적은데 모델만 화려" 하면 반드시 이 함정에 빠져요.


# ==========================================================
#  4. 진단법 - train 성능 >> test 성능이면 과적합 신호
# ==========================================================

# 그럼 실무에서 과적합을 어떻게 '알아채나'? 규칙은 놀랄 만큼 단순합니다.
#
#   train 성능은 아주 좋은데 test 성능이 훨씬 나쁘면 → 과적합.
#   (오차로 말하면: train 오차 ≪ test 오차, 격차가 크게 벌어짐)
#
# 두 숫자의 '격차' 를 보는 게 핵심입니다. 절대값 하나만 보면 안 돼요.
# test 오차를 train 오차로 나눈 '배율' 로 격차를 한눈에 봅시다.

print("\n[진단: train 대비 test 오차가 몇 배 벌어졌나]")
print("  차수 | test/train 배율 | 진단")
print("  -----+-----------------+--------------------")
for d, e_tr, e_te in zip(degrees, train_errors, test_errors):
    ratio = e_te / e_tr
    # 배율 표시: 너무 크면(train 오차가 0에 가까울 때) 숫자가 지저분해지므로
    # 1000배가 넘으면 ">1000" 로 뭉뚱그려 보여 줍니다. 뜻은 "격차가 폭발".
    shown = f"{ratio:>13.1f}" if ratio < 1000 else "        >1000"
    if ratio < 3:
        verdict = "건강 (격차 작음)"
    elif ratio < 50:
        verdict = "과적합 의심"
    else:
        verdict = "심한 과적합!"
    print(f"  {d:>4} | {shown} | {verdict}")
# → [진단: train 대비 test 오차가 몇 배 벌어졌나]
# →   차수 | test/train 배율 | 진단
# →   -----+-----------------+--------------------
# →      1 |           1.6 | 건강 (격차 작음)
# →      3 |           1.5 | 건강 (격차 작음)
# →      6 |         >1000 | 심한 과적합!
# →      9 |         >1000 | 심한 과적합!

# 배율이 작으면(차수 1, 3) train 과 test 가 사이좋게 비슷 → 건강합니다.
# 배율이 커질수록(차수 6, 9) train 만 좋고 test 는 뒤처짐 → 과적합.
# 차수 6·9는 train 오차가 거의 0이라 배율이 폭발합니다(>1000으로 표시).
#
# [학습곡선 개념]
# 실무에선 여기서 한 걸음 더 나아가 '학습곡선'을 그립니다.
#   가로축 = 학습 데이터 양(또는 모델 복잡도),
#   세로축 = train 오차와 test 오차 두 곡선.
# 두 곡선이 가까이 붙어 있으면 건강, 크게 벌어지면 과적합이에요.
# 위 표가 사실상 '복잡도 축 학습곡선'을 숫자로 적어 둔 겁니다.
#   train 곡선은 아래로 쭉 (0.0244→0.0000),
#   test 곡선은 U자로 갈라져 나감 (0.0379→0.0014→0.5103).
# 그 '벌어짐' 이 눈에 보이면 과적합을 진단한 겁니다.


# ==========================================================
#  5. 처방 - 과적합을 어떻게 줄이나 (개념만)
# ==========================================================

# 과적합이라고 진단했으면, 처방은 크게 네 갈래입니다. 개념만 잡습니다.
#
#   1) 데이터 늘리기
#      가장 확실한 약. 점이 많아지면 모델이 노이즈를 외우기 어렵고
#      '흐름'을 배울 수밖에 없어집니다. 데이터 7개니까 9차 곡선이
#      다 외워졌지, 700개였으면 어림없죠.
#
#   2) 모델 단순화
#      복잡도 손잡이를 낮춥니다. 차수 9 대신 3으로. 위 표에서 봤듯
#      test 오차가 최소가 되는 적정 복잡도로 되돌리는 겁니다.
#
#   3) 정규화 (regularization)
#      '큰 가중치에 벌점' 을 물려 모델이 지나치게 출렁이지 못하게 막습니다.
#      손실에 벌점 항을 하나 더합니다:
#          손실 = 원래오차 + λ·Σ(w²)
#      λ(람다)가 벌점의 세기예요. w(가중치)가 커지면 벌점도 커지니,
#      모델은 되도록 w 를 작게 유지하려 합니다 → 곡선이 얌전해짐 → 과적합↓.
#      (유도는 안 합니다. "큰 가중치에 벌금 물린다" 한 줄로 충분해요.)
#
#   4) 조기종료 (early stopping)
#      학습을 반복하다 보면 어느 순간부터 train 오차는 계속 주는데
#      test 오차가 다시 오르기 시작합니다. 바로 그 지점에서 학습을 멈춰요.
#      test 오차가 최저인 순간이 일반화가 가장 좋은 순간이니까요.
#
