# ----------------------------------------

#   [로지스틱 회귀 한 줄 정리]
#     회귀는 '값', 분류는 '어느 편(0/1)'. 로지스틱 회귀는 확률로 분류한다.
#
#   [핵심 3단]
#     1) 확률   :  p = sigmoid(w·x + b)   ← 직선값을 S자로 눌러 0~1 로
#     2) 손실   :  로그손실(BCE)          ← 확신 틀림을 크게 벌하는 자
#     3) 학습   :  경사하강 (3부작 그대로) ← ∂L/∂w=(1/n)Σ(p-y)·x, 오차가 p-y
#
#   [기억할 것]
#     · 직선은 0~1 을 벗어나니 sigmoid 로 눌러 확률로 만든다
#     · 판정은 p≥0.5 면 불량(1), 아니면 양품(0) — 0.5 가 결정경계
#     · 분류엔 MSE 말고 로그손실. 맞으면 손실↓, 확신 틀림은 손실 폭증
#     · 그래디언트는 회귀와 형태가 같다(오차 p-y × x) — 걸음은 3부작 재활용
#     · 데이터가 겹치면 손실 0·정확도 100% 는 불가능. 확률로 답하는 게 최선
#
#   다음 편에서는 이렇게 만든 분류기를 '얼마나 믿을 수 있나' 제대로 재는
#   평가 지표들(정확도만으로 부족한 이유, 혼동행렬 등)로 넘어갑니다.
