# 로지스틱 회귀 - '값'이 아니라 '양품이냐 불량이냐'를 맞힌다 (분류·평가 4부작 1편)
# -------------------------------


"""[온도를 보고 이 제품이 불량인지 아닌지, 어떻게 답하나요?]
바로 앞 3부작에서 우리는 '값' 을 예측했습니다.
온도를 넣으면 불량이 몇 개 나올지 — 3개, 5개, 12개 하는 '숫자' 요.
직선 하나(ŷ = w·x + b)를 데이터에 맞춰서요.

그런데 현장에서 진짜 자주 묻는 건 이겁니다.
  "이 제품, 불량이야 아니야?"
개수가 아니라 둘 중 하나 — 양품(0)이냐 불량(1)이냐 판정.
이렇게 '어느 편인지' 를 맞히는 일을 분류(classification) 라고 부릅니다.

오늘 배울 로지스틱 회귀는, 앞에서 걸어서 직선을 찾던 그 경사하강을
'분류' 로 확장한 겁니다. 직선 대신 확률(0~1)을 예측하게 바꾸고,
0.5 를 넘으면 불량, 아니면 양품 — 이렇게 판정하죠.
뼈대(그래디언트 구해 조금씩 걷기)는 3부작과 놀랍도록 똑같습니다.

이 파일은 전환 → 왜 확률인가(sigmoid) → 손실은 왜 로그손실인가 →
경사하강으로 학습 → 확률·판정 확인 → 실습 순으로 쌓아 갑니다.
"""

# 순수 파이썬으로 갑니다. e^ 계산에 math 만 씁니다.
# 맨 끝에서 numpy 로 같은 결과가 나오는지 대조할 때만 numpy 를 불러요.
import math
import numpy as np


# ========================================================
#  PART 1 : 전환 - '개수' 예측에서 '양품/불량' 판정으로
# ========================================================

# ----------------------------------------
# 회귀와 분류, 뭐가 다른가
# ----------------------------------------

# 앞 3부작(회귀)이 답한 것 :  "이 온도면 불량이 몇 개?"  → 5.3개 같은 '숫자'
# 오늘(분류)이 답할 것    :  "이 제품, 불량이야?"       → 불량(1) / 양품(0)
#
#   회귀  :  출력이 연속된 값 (개수·무게·온도…)    → 직선 ŷ = w·x + b
#   분류  :  출력이 둘 중 하나 (불량이냐 아니냐)   → 확률 p, 그리고 0/1 판정
#
# 이번 데이터도 온도 하나로 판정합니다. 다만 y 가 개수가 아니라
# 0 아니면 1 이에요 — 그 제품이 불량이었나(1), 양품이었나(0).

# 온도가 높을수록 불량이 늘어나는 흐름. 단, 딱 갈리진 않고 살짝 겹칩니다.
# (36도 위는 대체로 불량, 아래는 대체로 양품 — 완벽 분리는 아님)
온도 = [18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40]
불량 = [ 0,  0,  0,  0,  1,  0,  1,  1,  0,  1,  1,  1]   # 1=불량, 0=양품

# 26도인데 불량(1), 34도인데 양품(0) 처럼 흐름을 거스르는 점이 섞여 있죠.
# 현실 데이터가 원래 이렇습니다. 칼같이 안 갈려요. 그래서 '확률' 이 필요합니다.


# ========================================================
#  PART 2 : 왜 직선이 아니라 확률인가 - sigmoid
# ========================================================

# ----------------------------------------
# 직선을 그대로 쓰면 안 되는 이유
# ----------------------------------------

# "그냥 앞에서 하던 직선 ŷ = w·x + b 를 쓰면 안 되나?" 싶죠.
# 문제가 있어요. 직선은 위아래로 끝없이 뻗습니다.
# 온도가 아주 높으면 직선 값이 1.7, 2.3 처럼 1 을 훌쩍 넘고,
# 아주 낮으면 -0.5 처럼 0 밑으로도 내려갑니다.
#
#   확률이 1.7? -0.5?  그런 확률은 없습니다. 확률은 반드시 0~1 사이예요.
#
#   직선(그냥 쓰면)              우리가 원하는 것
#     y                            p
#      |        /                   1 |      ______
#    1 |------/-----               　 |     /
#      |     /   ← 1 넘어감          　|    /
#    0 |----/------                 0 |___/
#      |   /  ← 0 밑으로              　+----------→ x
#      +--------→ x                    0~1 안에 얌전히
#
# 그래서 직선 값(w·x+b)을 '0~1 사이로 눌러 주는' 장치가 필요합니다.
# 그 장치가 sigmoid 함수예요.


# ----------------------------------------
# sigmoid - 아무 값이나 0~1 로 눌러 주는 S자
# ----------------------------------------

# sigmoid 는 -∞~+∞ 의 어떤 수가 들어와도 0~1 사이 값 하나로 눌러 냅니다.
#
#   수식 :   sigmoid(z) = 1 / (1 + e^(-z))      ← e 는 자연상수 2.718...
#
# 유도는 안 합니다. 모양과 성질만 잡으면 됩니다.
#   z 가 아주 크면(양수)  →  e^(-z) 가 0 에 가까워져  →  p ≈ 1
#   z 가 0 이면           →  e^0=1 이라  1/(1+1)      →  p = 0.5  (딱 가운데)
#   z 가 아주 작으면(음수) →  e^(-z) 가 커져           →  p ≈ 0
#
#   sigmoid 는 이렇게 생긴 완만한 S자 곡선입니다.
#
#     p
#   1.0 |                    ________
#       |                 __/
#       |               _/
#   0.5 |- - - - - - -●- - - - - - - -   ← z=0 에서 딱 0.5
#       |          _/
#       |     ____/
#   0.0 |____/
#       +----------|----------→ z (= w·x+b)
#      음수 ←      0      → 양수
#
# 직선 값 z = w·x+b 를 이 S자에 통과시키면, 얼마가 나오든 0~1 확률이 됩니다.

def sigmoid(z):
    return 1 / (1 + math.exp(-z))               # 1 / (1 + e^(-z))

# 몇 개 넣어서 정말 0~1 로 눌리는지, z=0 이 0.5 인지 눈으로 봅시다.
print("[sigmoid 맛보기]")
print("  sigmoid(-4) =", round(sigmoid(-4), 4))   # → sigmoid(-4) = 0.018
print("  sigmoid( 0) =", round(sigmoid(0), 4))     # → sigmoid( 0) = 0.5
print("  sigmoid( 4) =", round(sigmoid(4), 4))     # → sigmoid( 4) = 0.982

# 아무리 큰 -4, 4 를 넣어도 0.018, 0.982 처럼 0~1 안에 얌전히 들어옵니다.
# 그리고 z=0 은 정확히 0.5 — 이 0.5 가 곧 판정의 경계선이 됩니다.


# ----------------------------------------
# 예측 = 확률, 판정 = 0.5 기준
# ----------------------------------------

# 로지스틱 회귀의 예측은 두 단계입니다.
#   1) 확률 구하기 :  p = sigmoid(w·x + b)     ← 이 제품이 불량일 확률
#   2) 판정하기    :  p ≥ 0.5 이면 불량(1), 아니면 양품(0)
#
# 왜 0.5 냐면, sigmoid 가 z=0 에서 0.5 라서 그래요.
# p=0.5 를 경계로 반반이 갈리니, 그 위는 불량 쪽, 아래는 양품 쪽.
#
#   확률 p        0 ─────── 0.5 ─────── 1
#   판정        양품(0)  │  불량(1)
#                        ↑ 결정경계

def 확률예측(x, w, b):
    return sigmoid(w * x + b)                    # p = sigmoid(w·x + b)

def 판정(x, w, b):
    return 1 if 확률예측(x, w, b) >= 0.5 else 0   # 0.5 넘으면 불량(1)

# 아직 w, b 를 학습하기 전이라, 임시로 아무 값이나 넣어 흐름만 확인합니다.
# (진짜 w, b 는 PART 4 경사하강으로 찾습니다.)
print("\n[학습 전 · 임시 w=0.5, b=-15 로 흐름만]")
print("  22도 불량확률:", round(확률예측(22, 0.5, -15), 4), "→ 판정", 판정(22, 0.5, -15))
print("  38도 불량확률:", round(확률예측(38, 0.5, -15), 4), "→ 판정", 판정(38, 0.5, -15))
# → [학습 전 · 임시 w=0.5, b=-15 로 흐름만]
# →   22도 불량확률: 0.018 → 판정 0
# →   38도 불량확률: 0.982 → 판정 1

# 낮은 온도(22)는 확률이 낮아 양품(0), 높은 온도(38)는 확률이 높아 불량(1).
# 흐름은 그럴듯하죠? 하지만 이 w, b 는 제가 손으로 대충 넣은 값입니다.
# '데이터에 가장 잘 맞는' w, b 를 찾아야 하는데 — 그러려면 먼저
# "얼마나 틀렸나" 를 재는 자(= 손실)가 필요합니다. 다음 PART 로.


# ========================================================
#  PART 3 : 손실은 왜 MSE 가 아닌가 - 로그손실(BCE)
# ========================================================

# ----------------------------------------
# 분류에는 MSE 대신 로그손실을 쓴다
# ----------------------------------------

# 회귀에선 손실로 MSE(오차 제곱의 평균)를 썼죠. 분류에선 안 씁니다.
# 정답이 0/1 인데 예측은 확률(0~1)이라, 제곱 오차로는 학습이 잘 안 돼요.
# 대신 분류 전용 자를 씁니다 — 로그손실, 또는 BCE(이진 교차 엔트로피).
#
#   수식 :  L = -(1/n) Σ [ y·log(p) + (1-y)·log(1-p) ]
#
# 겁먹지 말고 딱 두 경우로 쪼개 보면 아주 단순합니다.
#   · 정답이 불량(y=1) 이면 뒤 항 (1-y)=0 이라 사라지고  →  -log(p)
#         내가 준 불량확률 p 가 1 에 가까우면 -log(p)≈0  (손실 작음, 잘 맞힘)
#         p 가 0 에 가까우면 -log(p) 가 급격히 커짐        (손실 큼, 크게 틀림)
#   · 정답이 양품(y=0) 이면 앞 항 y=0 이라 사라지고    →  -log(1-p)
#         불량확률 p 가 0 에 가까우면(=양품일 확률 큼) 손실 작음
#         p 가 1 에 가까우면 크게 틀린 거라 손실 폭증
#
# 한마디로 : 맞으면 손실↓, 틀리면 손실↑.
# 특히 '확신에 차서 틀리면' 손실이 폭발합니다 — 확신 틀림을 크게 벌하는 자예요.


# ----------------------------------------
# '확신 틀림' 을 크게 벌한다 - 숫자로 확인
# ----------------------------------------

# 정답이 불량(y=1) 인 한 제품에 대해, 내가 준 불량확률에 따라
# 손실 -log(p) 가 어떻게 달라지는지 봅시다.

print("\n[정답이 불량(1)일 때, 내 확률에 따른 손실 -log(p)]")
for p in [0.99, 0.7, 0.5, 0.1, 0.01]:
    print(f"  불량확률 p={p:<5} → 손실 {-math.log(p):.4f}")
# → [정답이 불량(1)일 때, 내 확률에 따른 손실 -log(p)]
# →   불량확률 p=0.99  → 손실 0.0101
# →   불량확률 p=0.7   → 손실 0.3567
# →   불량확률 p=0.5   → 손실 0.6931
# →   불량확률 p=0.1   → 손실 2.3026
# →   불량확률 p=0.01  → 손실 4.6052

# 정답이 불량인데 "불량일 확률 0.99" 라고 자신 있게 맞히면 손실 0.01 — 거의 0.
# 반대로 "불량 확률 0.01" 이라고 확신에 차서 틀리면 손실 4.6 — 확 커지죠.
# 이게 로그손실의 성격입니다. 애매하게(0.5) 찍으면 중간, 확신 틀림은 크게 벌.


# ----------------------------------------
# log(0) 방지 - 확률을 아주 살짝 클리핑
# ----------------------------------------

# 한 가지 조심할 게 있어요. 확률 p 가 정확히 0 이나 1 이 되면
# log(0) = -무한대 라서 계산이 터집니다.
# 그래서 p 를 0 이나 1 에 '딱 붙지 않게' 아주 살짝 안으로 밀어 둡니다.
# 이걸 클리핑이라 해요. 결과엔 영향 거의 없고, 폭발만 막습니다.

def _clip(p, eps=1e-12):
    return min(max(p, eps), 1 - eps)            # p 를 [eps, 1-eps] 안에 가둠

def 로그손실(xs, ys, w, b):
    n = len(xs)
    total = 0.0
    for x, y in zip(xs, ys):
        p = _clip(확률예측(x, w, b))            # log(0) 방지
        total += y * math.log(p) + (1 - y) * math.log(1 - p)
    return -total / n                            # L = -(1/n)Σ[y·log p + (1-y)·log(1-p)]


# ========================================================
#  PART 4 : 경사하강으로 학습 - 3부작의 그 걸음 그대로
# ========================================================

# ----------------------------------------
# 그래디언트가 놀랍도록 깔끔하다
# ----------------------------------------

# 이제 로그손실을 가장 작게 만드는 w, b 를 찾습니다. 방법은 3부작과 똑같아요 —
# 그래디언트(내리막 방향) 구해서 조금씩 걷기.
#
# 로그손실의 그래디언트가 정말 깔끔합니다. (유도는 생략, 결과만)
#   ∂L/∂w = (1/n) Σ (p - y)·x
#   ∂L/∂b = (1/n) Σ (p - y)
#
# 회귀(MSE)의 그래디언트와 형태가 사실상 같습니다!
#   회귀   :  ∂L/∂w ∝ Σ (ŷ - y)·x       ← 오차 = ŷ - y
#   로지스틱:  ∂L/∂w  = (1/n)Σ (p - y)·x  ← 오차 = p - y
# 예측이 직선값(ŷ)이냐 확률(p)이냐만 다르고, '오차 × x' 구조는 판박이죠.
# 그래서 3부작에서 걸은 걸음을 여기서 거의 그대로 재활용합니다.

def 확률들(xs, w, b):
    return [확률예측(x, w, b) for x in xs]       # 각 x 의 불량확률 p

def 그래디언트(xs, ys, w, b):
    n = len(xs)
    ps = 확률들(xs, w, b)
    gw = sum((p - y) * x for x, y, p in zip(xs, ys, ps)) / n   # (1/n)Σ(p-y)·x
    gb = sum((p - y) for y, p in zip(ys, ps)) / n              # (1/n)Σ(p-y)
    return gw, gb


# ----------------------------------------
# 표준화 - 걸음을 안정시키는 준비 (3부작 회수)
# ----------------------------------------

# 온도는 18~40 처럼 큰 값이라, 그대로 걸으면 그래디언트가 커져 휘청댑니다.
# 3부작에서처럼 '평균 0, 퍼짐 1' 로 눈금을 바꿔(표준화) 걸음을 안정시켜요.
#   z = (x - x평균) / x표준편차

def 평균(xs):
    return sum(xs) / len(xs)

def 표준화(xs):
    m = 평균(xs)
    s = (sum((x - m) ** 2 for x in xs) / len(xs)) ** 0.5   # 표준편차
    zs = [(x - m) / s for x in xs]
    return zs, m, s                              # 되돌릴 때 쓰려고 m, s 도 반환


# ----------------------------------------
# fit - 로지스틱 회귀 경사하강 본체
# ----------------------------------------

# 3부작 fit 과 뼈대가 똑같습니다. 딱 두 군데만 바뀌었어요.
#   · 예측이 직선(w·x+b) → 확률(sigmoid(w·x+b))
#   · 손실이 MSE → 로그손실
# 걷는 방식(그래디언트 구해 w ← w - lr·gw)은 완전히 동일합니다.

def fit(xs, ys, lr=0.5, epochs=3000, 로그=False):
    zs, m, s = 표준화(xs)                        # z 눈금으로 갈아타고
    w, b = 0.0, 0.0                              # 아무 데서나 출발

    for epoch in range(epochs):
        gw, gb = 그래디언트(zs, ys, w, b)        # 지금 위치의 내리막 방향
        w = w - lr * gw                          # w ← w - lr·∂L/∂w
        b = b - lr * gb                          # b ← b - lr·∂L/∂b
        if 로그 and epoch % 600 == 0:            # 600 epoch마다 손실 찍기
            print(f"  epoch {epoch:5d}   로그손실 {로그손실(zs, ys, w, b):.4f}")

    if 로그:
        print(f"  epoch {epochs:5d}   로그손실 {로그손실(zs, ys, w, b):.4f}")

    # z 공간에서 찾은 (w, b) 를 원래 온도 눈금으로 되돌린다. (3부작과 동일)
    #   w·z + b = w·(x - m)/s + b = (w/s)·x + (b - w·m/s)
    w실제 = w / s
    b실제 = b - w * m / s
    return w실제, b실제


