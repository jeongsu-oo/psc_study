# -------------------------------
# 정규화 회귀 - 큰 가중치에 벌금을 물려 과적합 잡기 (Ridge·Lasso)
# -------------------------------


"""[과적합, 진단만 하고 끝인가요? 이제 '처방'입니다]
지난 편(과적합)에서 우리는 이런 걸 배웠습니다.
   "모델이 학습 데이터를 통째로 외우면(과적합), train 성능은 좋은데
    새 데이터(test)에선 무너진다."
그리고 처방을 네 갈래로 훑었죠 — 데이터 늘리기 / 단순화 / 정규화 / 조기종료.

이 파일은 그중 '정규화(regularization)' 를 손으로 직접 만들어 봅니다.
정규화 한 줄 요약:
   "가중치(w)가 너무 커지지 않게, 손실에 '벌점'을 얹는다."

왜 하필 '큰 가중치'가 문제일까요?
특징이 많거나 데이터가 적으면, 모델은 몇 안 되는 학습 점을 완벽히
맞추려고 어떤 가중치는 아주 크게, 어떤 건 반대로 크게 키웁니다.
그렇게 커진 가중치들이 서로 밀고 당기며 곡선을 미친 듯이 출렁이게 만들죠.
그 출렁임이 곧 과적합입니다. 그러니 가중치를 얌전하게 눌러 두면 됩니다.

이 파일에서 할 일:
  1) 왜 큰 가중치가 과적합인가 (전환)
  2) Ridge(L2) — 손실에 λ·Σwj² 를 더하고, gradient 에 +2λwj 한 줄 추가
  3) λ 를 0/작게/크게 바꿔 가며 가중치 크기·train·test 성능 비교 (표)
     → 적당한 λ 에서 test 가 최고 (과적합과 과소적합 사이)
  4) Lasso(L1) — λ·Σ|wj| 를 더함. 덜 중요한 가중치를 '정확히 0' 으로 만들어
     특징 선택(feature selection) 효과. Ridge 와 뭐가 다른지
  5) 언제 뭘 쓰나 — 특징 많고 일부만 중요하면 Lasso, 전반적 축소는 Ridge
  6) sklearn 의 Ridge·Lasso 로 우리 손계산 대조
  7) 실습 — λ 를 바꿔 가며 가중치·성능 직접 확인

넘파이만 씁니다(6번만 sklearn 대조). 데이터는 인라인으로 만듭니다.
"""

import numpy as np


# ==========================================================
#  1. 전환 - 왜 '큰 가중치'가 과적합인가
# ==========================================================

# 다변수 회귀를 떠올려 봅시다. 예측은 이렇게 생겼죠.
#   예측 = w1·특징1 + w2·특징2 + ... + wj·특징j + 편향(b)
# 각 wj 는 '그 특징이 결과에 얼마나 세게 영향을 주나' 를 나타내는 손잡이입니다.
#
# 그런데 특징이 많거나(예: 6개) 데이터가 적으면(예: 6개) 문제가 생깁니다.
# 모델은 그 몇 안 되는 학습 점을 '완벽히' 맞추려고 무리를 합니다.
#   - 어떤 wj 는 +8 처럼 크게,
#   - 다른 wj 는 -7 처럼 반대로 크게
# 이렇게 큰 값들이 서로 밀고 당겨 겨우 점을 다 지나가는 곡선을 만들죠.
# 그 곡선은 학습 점 사이에서 심하게 출렁입니다 → 새 데이터에서 엉망 → 과적합.
#
# 그래서 아이디어는 단순합니다.
#   "가중치가 너무 커지지 못하게, 손실에 벌점을 하나 더한다."
#
#   기존 손실:   L = MSE                     (예측이 실제와 얼마나 틀렸나)
#   정규화 손실: L = MSE + λ·(가중치 벌점)     (틀린 정도 + 가중치가 커진 벌금)
#
# λ(람다) 는 벌점의 세기입니다.
#   - λ 를 크게 → 벌금이 무서워 모델이 가중치를 작게 유지 → 곡선이 얌전 → 과적합↓
#   - λ 를 0   → 벌금 없음 → 그냥 예전 MSE (정규화 안 함)
#
# 이제 이 '벌점' 을 어떻게 계산하느냐에 따라 Ridge 와 Lasso 로 갈립니다.
#   Ridge : 벌점 = λ·Σ(wj²)   ← 제곱의 합 (L2)
#   Lasso : 벌점 = λ·Σ|wj|    ← 절댓값의 합 (L1)
# 먼저 Ridge 부터 손으로 만들어 봅니다.


# ----------------------------------------
# 제조 데이터 만들기 - 진짜 특징 3개 + 잡음 특징 3개
# ----------------------------------------

# 어떤 설비의 측정값 6가지로 '불량 수' 를 예측하는 상황입니다.
# 일부러 이렇게 설계합니다.
#   - 특징 6개 중 앞 3개만 불량과 진짜 관계가 있음 (온도·진동·압력)
#   - 뒤 3개는 불량과 아무 상관없는 '잡음 특징' (조명·습도·소음 같은 것)
#     → 정규화, 특히 Lasso 가 이 셋을 0으로 눌러 없애는 걸 눈으로 볼 겁니다.
#   - 데이터를 적게(12개) 둠 → 특징 6개에 비해 데이터가 적어 과적합이 잘 남.

np.random.seed(0)   # 시드 고정: 몇 번 돌려도 같은 결과 (재현성)

n = 12
# 특징 6개를 표준정규(평균0, 표준편차1)로 뽑음. 이미 스케일이 비슷하게 나옵니다.
X_raw = np.random.normal(0, 1, (n, 6))

# 진짜 숨은 규칙: 앞 3개만 계수가 있고, 뒤 3개는 계수 0 (불량과 무관).
true_w = np.array([2.0, 3.0, 1.5, 0.0, 0.0, 0.0])
noise = np.random.normal(0, 0.8, n)          # 측정 잡음
y = X_raw @ true_w + 5 + noise               # 불량 수 = 특징·계수 합 + 편향5 + 잡음

# 표준화(standardization): 각 특징을 (값-평균)/표준편차 로 바꿔 스케일을 맞춥니다.
# 정규화는 가중치 크기에 벌점을 물리므로, 특징 스케일이 제각각이면 불공평합니다.
# (스케일 큰 특징은 가중치가 자연히 작게 나와 벌점을 덜 받으니까요.)
# 그래서 정규화 전에는 표준화가 사실상 필수입니다.
mu = X_raw.mean(axis=0)
sd = X_raw.std(axis=0)
Xs = (X_raw - mu) / sd

# train/test 분할: 짝수 번째 → 학습, 홀수 번째 → 시험.
tr = np.arange(n) % 2 == 0
Xtr, ytr = Xs[tr],  y[tr]
Xte, yte = Xs[~tr], y[~tr]

print("[데이터]")
print("  전체", n, "개 / 특징 6개(진짜 3 + 잡음 3) ->  학습", len(ytr), "개 / 시험", len(yte), "개")
# → [데이터]
# →   전체 12 개 / 특징 6개(진짜 3 + 잡음 3) ->  학습 6 개 / 시험 6 개

# 특징이 6개인데 학습 데이터가 6개뿐 — 딱 과적합 나기 좋은 상황입니다.


# 앞으로 모든 모델은 '편향(b)' 을 하나 붙여 씁니다.
# 편향을 가중치처럼 다루려고, 특징 앞에 '전부 1인 열' 을 하나 끼웁니다.
# 그러면 예측 = w0·1 + w1·특징1 + ... 이 되어 w0 이 곧 편향 b 가 됩니다.
def add_bias(X):
    """특징 행렬 앞에 1로 채운 열을 붙여 편향을 가중치로 흡수."""
    return np.column_stack([np.ones(len(X)), X])

def mse(w, X, y):
    """가중치 w 로 X 를 예측해 실제 y 와의 평균제곱오차."""
    pred = add_bias(X) @ w
    return np.mean((pred - y) ** 2)

def wnorm(w):
    """가중치 크기(편향 w[0] 은 빼고). Σwj² 의 제곱근 = 벡터 길이."""
    return np.sqrt(np.sum(w[1:] ** 2))


# ==========================================================
#  2. Ridge (L2) - 제곱합에 벌점, gradient 에 +2λwj 한 줄
# ==========================================================

# Ridge 의 손실 함수입니다. (편향 b 는 벌점에서 뺍니다 — 벌줄 이유가 없어요.)
#
#   L = MSE + λ·Σ(wj²)
#       └ 원래오차   └ 가중치 제곱을 다 더한 벌점 (편향 제외)
#
# 경사하강으로 학습하려면 이 L 을 각 wj 로 미분한 gradient 가 필요합니다.
# MSE 부분의 gradient 는 예전과 똑같고, 새로 더한 벌점 항 λ·wj² 를
# wj 로 미분하면 딱 '2λwj' 가 나옵니다. (제곱의 미분 = 2배)
#
#   gradient(wj) = [MSE 의 gradient] + 2λwj
#                                      └── 이 한 줄이 Ridge 의 전부입니다.
#
# 그러니까 기존 경사하강 코드에서 '가중치 갱신 전에 gradient 에 2λw 를 더하는'
# 딱 한 줄만 추가하면 Ridge 가 됩니다. 정말 그게 답니다.

def gd_ridge(X, y, lam, lr=0.05, epochs=20000):
    """경사하강으로 Ridge 회귀를 학습. lam(λ)이 벌점 세기."""
    Xb = add_bias(X)
    m, d = Xb.shape
    w = np.zeros(d)
    for _ in range(epochs):
        pred = Xb @ w
        grad = (2 / m) * Xb.T @ (pred - y)   # 여기까지는 그냥 MSE 의 gradient
        grad[1:] += 2 * lam * w[1:]          # ★ Ridge 한 줄: 벌점의 gradient +2λw (편향 w[0] 제외)
        w -= lr * grad                       # 가중치 갱신
    return w

# 먼저 λ=0 (정규화 없음) 과 λ=1 을 나란히 학습해 가중치를 눈으로 비교합니다.
w0 = gd_ridge(Xtr, ytr, lam=0.0)
w1 = gd_ridge(Xtr, ytr, lam=1.0)

print("\n[Ridge - λ 에 따른 가중치 변화]")
print("  λ=0 (벌점 없음) 가중치:", np.round(w0[0:1], 2), "b, ", np.round(w0[1:], 2))
print("  λ=1 (벌점 있음) 가중치:", np.round(w1[0:1], 2), "b, ", np.round(w1[1:], 2))
# → [Ridge - λ 에 따른 가중치 변화]
# →   λ=0 (벌점 없음) 가중치: [3.59] b,  [ 2.93  1.68  2.25 -0.91  0.56 -1.68]
# →   λ=1 (벌점 있음) 가중치: [4.96] b,  [ 1.42  1.16  0.89  0.46  0.32 -0.38]

# 두 줄을 비교해 보세요. λ 를 0 에서 1 로 올렸더니
#   - 큰 가중치(2.93, 2.25, -1.68 ...)들이 전부 0 쪽으로 '줄어들었습니다'.
#   - 특히 잡음 특징(뒤 3개: -0.91, 0.56, -1.68)도 함께 작아졌어요.
# 이게 Ridge 가 하는 일입니다 — 모든 가중치를 0 쪽으로 '축소(shrink)'.
# 완전히 0 으로 만들진 않고, 전반적으로 작게 눌러 곡선을 얌전하게 만듭니다.


# ==========================================================
#  3. λ 효과 실험 - 축소 정도와 train/test 성능
# ==========================================================

# 이제 λ 를 0 부터 크게까지 죽 훑으며, 가중치 크기와 train·test 오차를
# 한 표로 봅니다. 여기가 정규화의 심장입니다.
#
# 지켜볼 세 가지:
#   1) λ 가 커질수록 |w|(가중치 크기)가 계속 줄어드는가? (축소 효과)
#   2) train 오차는 λ 가 커질수록 어떻게 되나? (벌점 때문에 train 은 나빠짐)
#   3) test 오차는? — 어느 λ 에서 최소가 되는가? (그게 최적)

print("\n[λ 를 바꿔 가며: 가중치 크기와 성능]")
print("    λ   | 가중치크기 |w| | train 오차 | test 오차 | 상태")
print("  ------+--------------+-----------+-----------+----------------")
lambdas = [0.0, 0.3, 1.0, 3.0, 10.0]
states  = ["정규화 없음(과적합)", "적당 (test 최소)", "축소 진행", "과하게 축소", "과소적합 쪽"]
for lam, state in zip(lambdas, states):
    w = gd_ridge(Xtr, ytr, lam)
    print(f"  {lam:>5} | {wnorm(w):>12.3f} | {mse(w,Xtr,ytr):>9.3f} | {mse(w,Xte,yte):>9.3f} | {state}")
# → [λ 를 바꿔 가며: 가중치 크기와 성능]
# →     λ   | 가중치크기 |w| | train 오차 | test 오차 | 상태
# →   ------+--------------+-----------+-----------+----------------
# →    0.0 |        4.524 |     0.000 |     9.385 | 정규화 없음(과적합)
# →    0.3 |        3.123 |     0.978 |     2.400 | 적당 (test 최소)
# →    1.0 |        2.155 |     3.904 |     4.723 | 축소 진행
# →    3.0 |        1.240 |     9.213 |     7.937 | 과하게 축소
# →   10.0 |        0.522 |    15.613 |    11.169 | 과소적합 쪽

# 이 표를 천천히 읽어 봅시다. 세 열이 각자 다른 이야기를 합니다.
#
#   |w| (가중치 크기): 4.524 → 3.123 → 2.155 → 1.240 → 0.522
#       λ 가 커질수록 '계속' 줄어듭니다. 벌점이 셀수록 가중치가 눌리니까요. (축소)
#
#   train 오차: 0.000 → 0.978 → ... → 15.613
#       λ=0 일 땐 0 (학습 점을 완벽히 외움 = 과적합!). λ 를 올리면 계속 나빠집니다.
#       벌점 때문에 모델이 train 을 완벽히 맞추길 '포기' 하거든요.
#
#   test 오차: 9.385 → 2.400 → 4.723 → 7.937 → 11.169
#       U자입니다! λ=0 에선 9.385 로 엉망(과적합), λ=0.3 에서 2.400 으로 '최소',
#       그 뒤로 다시 커집니다(과소적합).
#
# 핵심 결론:
#   - λ 너무 작으면(0) → 과적합. train 은 완벽하나 test 는 엉망.
#   - λ 적당하면(0.3)  → test 최소. 과적합과 과소적합 사이 '딱 좋은' 지점. ★
#   - λ 너무 크면(10)  → 과소적합. 가중치를 너무 눌러 흐름조차 못 잡음.
#
# 즉 λ 는 '과적합↔과소적합' 을 조절하는 손잡이입니다.
# 우리가 고를 값은 'train 이 가장 좋은' λ(=0)가 아니라
# 'test 가 가장 좋은' λ(=0.3)입니다. 지난 편의 교훈 그대로예요 — test 를 보라.


# ==========================================================
#  4. Lasso (L1) - 덜 중요한 가중치를 '정확히 0' 으로
# ==========================================================

# Ridge 는 모든 가중치를 0 '쪽' 으로 줄였지만, 완전히 0 으로 만들진 않았죠.
# (위에서 잡음 특징도 0.46, 0.32, -0.38 처럼 작지만 0 은 아니었습니다.)
#
# Lasso 는 벌점의 모양만 바꿉니다 — 제곱(²) 대신 절댓값(| |) 을 씁니다.
#
#   Ridge:  L = MSE + λ·Σ(wj²)     ← 제곱합 (L2)
#   Lasso:  L = MSE + λ·Σ|wj|      ← 절댓값합 (L1)
#
# 이 작은 차이가 놀라운 결과를 냅니다.
#   Lasso 는 덜 중요한 가중치를 '정확히 0' 으로 만들어 버립니다.
#   0 이 된 특징은 예측에서 완전히 빠지죠 → 이게 곧 '특징 선택(feature selection)'.
#
# 왜 0 이 되나(직관만): 절댓값 |wj| 의 벌점은 wj 가 0 근처에서도 '일정한 힘' 으로
# 0 을 향해 밀어붙입니다. 그래서 중요하지 않아 딱히 버틸 이유가 없는 가중치는
# 그 힘에 밀려 정확히 0 에 '붙어' 버려요.
# (제곱 벌점은 0 근처에선 미는 힘이 약해져서, 작게는 만들어도 0 에 못 붙입니다.)
#
# 구현은 '좌표하강(coordinate descent)' 을 씁니다 — 가중치를 한 개씩 돌아가며
# 최적값으로 갱신하는 방법. 절댓값 벌점의 최적해는 '소프트 임계(soft-threshold)'
# 라는 한 줄 규칙으로 딱 떨어집니다.

def soft_threshold(rho, lam):
    """소프트 임계: |rho| 가 lam 보다 작으면 0, 아니면 lam 만큼 0 쪽으로 당김.
    바로 이 '작으면 0' 규칙이 Lasso 가 가중치를 0 으로 만드는 정체입니다."""
    if rho < -lam:
        return rho + lam
    elif rho > lam:
        return rho - lam
    else:
        return 0.0        # ★ rho 가 ±lam 안이면 정확히 0 — 특징이 버려짐

def lasso_cd(X, y, lam, epochs=1000):
    """좌표하강으로 Lasso 회귀 학습. 가중치를 한 개씩 소프트 임계로 갱신."""
    Xb = add_bias(X)
    m, d = Xb.shape
    w = np.zeros(d)
    for _ in range(epochs):
        for j in range(d):
            # j 번째만 빼고 나머지로 예측한 '잔차' 에, j 번째 특징이 얼마나 설명하는가
            r = y - Xb @ w + Xb[:, j] * w[j]
            rho = Xb[:, j] @ r / m
            if j == 0:
                w[j] = rho                              # 편향은 벌점 없음 (그냥 최적값)
            else:
                z = (Xb[:, j] ** 2).sum() / m
                w[j] = soft_threshold(rho, lam) / z     # ★ 벌점 있는 특징은 소프트 임계
    return w

print("\n[Lasso - 잡음 특징을 0 으로 만드는가]")
print("    λ   | 살아남은 특징 수 | test 오차 | 가중치 (앞3=진짜, 뒤3=잡음)")
print("  ------+------------------+-----------+---------------------------------")
for lam in [0.0, 0.3, 1.0]:
    w = lasso_cd(Xtr, ytr, lam)
    nonzero = int(np.sum(np.abs(w[1:]) > 1e-8))
    print(f"  {lam:>5} | {nonzero:>16} | {mse(w,Xte,yte):>9.3f} | {np.round(w[1:], 2)}")
# → [Lasso - 잡음 특징을 0 으로 만드는가]
# →     λ   | 살아남은 특징 수 | test 오차 | 가중치 (앞3=진짜, 뒤3=잡음)
# →   ------+------------------+-----------+---------------------------------
# →    0.0 |                6 |     8.072 | [ 3.1   2.4   0.74 -0.6   1.31 -1.39]
# →    0.3 |                3 |     0.498 | [2.27 2.43 1.61 0.   0.   0.  ]
# →    1.0 |                3 |     2.592 | [2.09 1.72 0.77 0.   0.   0.  ]

# 표를 보세요. 이게 Lasso 의 마법입니다.
#   λ=0   : 벌점 없음 → 6개 특징 다 살아 있고(잡음까지 -0.6, 1.31, -1.39) 과적합. test 8.072
#   λ=0.3 : 뒤 3개(잡음 특징)가 '정확히 0.  0.  0.' 이 됐습니다! 살아남은 건 앞 3개뿐.
#           우리가 데이터를 만들 때 심은 진짜 특징이 바로 그 앞 3개죠 — 정확히 골라냈습니다.
#           게다가 test 오차도 0.498 로 뚝 떨어졌어요.
#   λ=1.0 : 여전히 앞 3개만 살아남되 가중치가 더 축소됨.
#
# Lasso 는 "이 특징은 필요 없다" 를 스스로 판단해 가중치를 0 으로 꺼 버립니다.
# 잡음 특징이 사라지니 모델이 간결해지고, 사람도 "아, 온도·진동·압력이 중요하구나"
# 하고 읽을 수 있죠. 이게 '특징 선택' 효과입니다.


