#   │ 가중치      │  전부 0쪽으로 '축소'      │  일부를 '정확히 0'        │
#   │ 특징 선택   │  안 함 (다 남김)          │  함 (덜 중요한 건 버림)   │
#   │ 언제        │  특징 대부분이 조금씩     │  특징 많고 그중 일부만    │
#   │             │  다 쓸모 있을 때          │  진짜 중요할 때           │
#   └─────────────┴──────────────────────────┴──────────────────────────┘
#
#   - 특징이 아주 많고 그중 '몇 개만' 진짜 중요할 것 같다  → Lasso.
#     불필요한 특징을 0 으로 꺼 주니 모델이 간결하고 해석하기 좋아요.
#     (방금 데이터가 딱 이 경우였죠 — 진짜 3 + 잡음 3.)
#   - 특징들이 대체로 조금씩은 다 쓸모 있고, 전반적으로 살살 눌러 안정시키고 싶다
#     → Ridge. 특징을 버리지 않고 전체를 얌전하게 만듭니다.
#   - 둘의 장점을 섞은 ElasticNet(L1+L2) 도 있습니다 (이름만 알아 두세요).
