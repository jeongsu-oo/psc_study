# 위 흐름을 한 함수로 묶습니다. λ 와 방식(ridge/lasso)을 넣으면
# 가중치 크기·살아남은 특징 수·train·test 오차를 한 번에 돌려줍니다.
# 여러 λ 로 돌려 보며 'test 오차가 최소인 λ' 를 직접 찾아보세요.

def experiment(kind, lam):
    """kind='ridge' 또는 'lasso', lam=λ. 학습 후 성능 요약을 돌려줌."""
    if kind == "ridge":
        w = gd_ridge(Xtr, ytr, lam)
    else:
        w = lasso_cd(Xtr, ytr, lam)
    nonzero = int(np.sum(np.abs(w[1:]) > 1e-8))
    return wnorm(w), nonzero, mse(w, Xtr, ytr), mse(w, Xte, yte)

print("\n[실습: Ridge λ 훑기]")
print("    λ   | |w|   | train | test")
print("  ------+-------+-------+-------")
for lam in [0.0, 0.3, 1.0, 3.0]:
    wn, _, etr, ete = experiment("ridge", lam)
    print(f"  {lam:>5} | {wn:>5.2f} | {etr:>5.2f} | {ete:>5.2f}")
