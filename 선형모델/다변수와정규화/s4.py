# ========================================================
#  PART 6 : 학습률 스케줄 - 처음 크게, 나중 작게
# ========================================================

# ----------------------------------------
# 왜 줄여가나 - 골짜기 근처에선 살살
# ----------------------------------------

# SGD 가 바닥에서 지글지글 출렁였죠(30에폭 0.83 → 50에폭 0.98). 이유는
# 바닥 근처에서도 걸음(lr)이 그대로라, 최저점을 자꾸 넘나들어서예요.
# 해법: '처음엔 성큼성큼, 바닥에 가까워지면 살금살금' 걸음을 줄입니다.
#
#   [고정 lr]          [줄여가는 lr]
#     성큼 성큼 성큼      성큼 성큼 걸음 살짝 톡톡
#     ~~바닥에서 출렁~~   ~~바닥에 살며시 안착~~
#
# 걸음을 스텝마다 줄이는 가장 흔한 공식(한 줄):
#
#   lr_t = lr0 / (1 + 감쇠·t)      t = 지금까지 뗀 스텝 번호
#
# t 가 커질수록 분모가 커져 lr 이 서서히 작아집니다. 처음(t=0)엔 lr0,
# 갈수록 조금씩 줄죠. 감쇠(decay)는 '얼마나 빨리 줄일지' 조절 손잡이.

def lr_스케줄(lr0, 감쇠, t):
    return lr0 / (1 + 감쇠 * t)                # lr_t = lr0/(1+감쇠·t)

print("\n[학습률이 줄어드는 모습 · lr0=0.1, 감쇠=0.01]")
for t in [0, 10, 50, 100, 500]:
    print(f"  스텝 {t:4d} → lr {lr_스케줄(0.1, 0.01, t):.5f}")
# → [학습률이 줄어드는 모습 · lr0=0.1, 감쇠=0.01]
# →   스텝    0 → lr 0.10000
# →   스텝   10 → lr 0.09091
# →   스텝   50 → lr 0.06667
# →   스텝  100 → lr 0.05000
# →   스텝  500 → lr 0.01667

# 처음 0.1 로 성큼 걷다가 스텝 500쯤엔 0.017 로 살살 걷습니다.


# ----------------------------------------
# 스케줄 적용 SGD - 출렁임이 줄어드나
# ----------------------------------------

# SGD 에 이 스케줄을 얹어, 고정 lr SGD 와 최종 손실을 비교합니다.
# 걸음을 줄여가면 바닥에서 덜 출렁여 손실이 더 낮게 안착해야 합니다.

def SGD_스케줄(x, y, lr0=0.05, 감쇠=0.01, epochs=50):
    w, b = 0.0, 0.0
    손실기록 = []
    n = len(x)
    t = 0                                      # 전체 스텝 카운터
    for epoch in range(epochs):
        순서 = np.random.permutation(n)
        for i in 순서:
            lr = lr_스케줄(lr0, 감쇠, t)        # 스텝마다 줄어든 걸음
            xi, yi = x[i:i+1], y[i:i+1]
            gw, gb = 기울기(xi, yi, w, b)
            w = w - lr * gw
            b = b - lr * gb
            t += 1
        손실기록.append(손실(x, y, w, b))
    return w, b, 손실기록

_, _, 손실_고정 = SGD(x, y, lr=0.05)           # 고정 lr=0.05 SGD
_, _, 손실_스케줄 = SGD_스케줄(x, y, lr0=0.05, 감쇠=0.01)
print("\n[고정 lr SGD  vs  학습률 스케줄 SGD · 50 에폭 후]")
print("  고정   lr=0.05        → 손실", round(손실_고정[-1], 4))
print("  스케줄 lr0=0.05 감쇠0.01 → 손실", round(손실_스케줄[-1], 4))
# → [고정 lr SGD  vs  학습률 스케줄 SGD · 50 에폭 후]
# →   고정   lr=0.05        → 손실 0.8756
# →   스케줄 lr0=0.05 감쇠0.01 → 손실 0.8297

# 스케줄 쪽이 확 낮습니다(0.8756 → 0.8297). 바닥 근처에서 걸음을 줄여
# 출렁임 없이 최저점에 살포시 안착한 거죠. 배치 수준(0.8296)까지 붙었어요.
# 큰 모델·긴 학습에선 이 '줄여가기'가 최종 성능을 눈에 띄게 끌어올립니다.


