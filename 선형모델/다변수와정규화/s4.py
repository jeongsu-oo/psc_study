# ========================================================
#  PART 5 : 에폭 vs 스텝 - 헷갈리는 두 단위 정리
# ========================================================

# ----------------------------------------
# 1 에폭 = 전체 1회, 스텝 = 갱신 1회
# ----------------------------------------

# 여기서 용어를 확실히 못 박습니다. 딥러닝 내내 나오는 두 단어예요.
#
#   에폭(epoch) : 전체 데이터를 '한 번 다 훑는 것'. 40개면 40개를 한 바퀴.
#   스텝(step)  : w, b 를 '한 번 갱신하는 것'. 기울기 구해 한 발 떼기.
#
# 이 둘의 관계는 배치 크기가 정합니다.
#
#   한 에폭의 스텝 수 = 데이터 개수 ÷ 배치 크기
#
#   배치(크기 40)   → 40÷40 = 1 스텝  / 에폭   (한 바퀴에 한 발)
#   미니배치(크기 8) → 40÷8  = 5 스텝  / 에폭   (한 바퀴에 다섯 발)
#   SGD(크기 1)     → 40÷1  = 40 스텝 / 에폭   (한 바퀴에 마흔 발)

print("\n[에폭당 스텝 수 = 데이터수 ÷ 배치크기]")
for 크기 in [40, 8, 1]:
    스텝수 = n_data // 크기
    이름 = "배치" if 크기 == 40 else ("SGD" if 크기 == 1 else "미니배치")
    print(f"  {이름:4s} (배치크기 {크기:2d}) → 에폭당 {스텝수:2d} 스텝")
# → [에폭당 스텝 수 = 데이터수 ÷ 배치크기]
# →   배치   (배치크기 40) → 에폭당  1 스텝
# →   미니배치 (배치크기  8) → 에폭당  5 스텝
# →   SGD  (배치크기  1) → 에폭당 40 스텝

# 그래서 "50 에폭 돌렸다"가 세 방식에서 실제 갱신 횟수는 천차만별이죠.
#   배치 50스텝  vs  미니배치 250스텝  vs  SGD 2000스텝.
# 같은 '에폭 수'라도 SGD 가 훨씬 많이 걸어서 초반에 빨리 내려간 겁니다.
