#   [경사하강 세 방식 한 줄 정리]
#     배치     매 스텝 전체 n개  → 정확·매끈, 큰 데이터엔 무거움
#     SGD      매 스텝 1개       → 빠름·출렁, 자주 갱신
#     미니배치 매 스텝 몇 개      → 절충, 실무 표준
#
#   [기억할 것]
#     · 기울기 공식은 하나. 다른 건 'Σ 에서 몇 개(n) 보느냐' 뿐
#     · 1 에폭 = 전체 1회 / 1 스텝 = 갱신 1회, 관계는 배치크기가 정함
#     · 에폭당 스텝 = 데이터수 ÷ 배치크기
#     · SGD 는 초반 빠르나 바닥서 출렁 / 배치는 느리나 매끈
#     · 학습률 스케줄(lr_t = lr0/(1+감쇠·t))로 바닥에서 살며시 안착
#     · 이 미니배치+학습률이 과정4 신경망 학습의 뼈대 그대로다
