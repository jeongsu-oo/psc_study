# 경사하강법 변형 - 배치 / SGD / 미니배치 (심화 4편)
# -------------------------------


"""[매 스텝 전체 데이터를 다 훑는 게, 데이터가 크면 너무 느리지 않나요?]
지금까지 우리가 걸어 내려온 방식은 매 스텝마다 '전체 데이터 n개'로
기울기를 구했습니다. 이걸 배치(batch) 경사하강이라 부릅니다.
정확합니다. 방향이 흔들림 없이 곧게 바닥을 향해요.

그런데 데이터가 100만 개라면? 한 걸음을 떼려고 100만 개를 다 훑어야
합니다. 한 스텝이 통째로 무거워집니다. 걸음이 굼떠져요.

그래서 나온 꾀가 오늘의 주제입니다.
  · SGD       : 매 스텝 '샘플 딱 하나'로 기울기. 빠르지만 방향이 출렁
  · 미니배치  : 한 번에 '몇 개(배치)'씩. 둘의 절충 - 실무 표준

기울기 공식은 전편과 똑같습니다. ∇=(2/n)Σ... 딱 하나 다른 건
그 Σ 에서 'n 의 범위' 뿐이에요 — 전체냐(배치), 일부냐(미니배치),
하나냐(SGD). 식이 아니라 '몇 개를 보고 한 발 떼느냐' 의 차이입니다.

이 파일은 배치 회수 → SGD → 미니배치 → 세 방식 비교 →
에폭vs스텝 → 학습률 스케줄 → 과정4 예고 → 실습 순으로
위에서 아래로 쌓아 갑니다.
"""

# 재현성을 위해 numpy 시드를 고정합니다. 셔플·데이터 생성이 매번 같아야
# 아래 '# →' 출력이 돌릴 때마다 똑같이 나옵니다.
import numpy as np
np.random.seed(42)


# ========================================================
#  PART 1 : 회수 - 배치 경사하강 (매 스텝 전체 n개)
# ========================================================

# ----------------------------------------
# 데이터 준비 - 제조 센서 회귀 데이터 40개
# ----------------------------------------

# 미니배치가 '의미 있으려면' 데이터가 좀 넉넉해야 합니다. 10개짜리로는
# 나눠 봤자 티가 안 나죠. 그래서 40개를 인라인으로 만듭니다.
#
# 상황: 설비 온도(x)가 오를수록 불량(y)이 느는 흐름.
# 진짜 관계는 y ≈ 0.8·온도 + 2 인데, 현실이니 잡음을 살짝 얹습니다.

n_data = 40
온도 = np.linspace(0, 10, n_data)              # 원래 눈금 온도 0~10
잡음 = np.random.randn(n_data) * 1.0           # 시드 고정된 랜덤 잡음
y = 0.8 * 온도 + 2 + 잡음                       # 진짜 직선 + 잡음 = 관측된 불량

# 전편에서 배운 표준화를 그대로 씁니다. x 를 '평균 0, 퍼짐 1' 눈금으로
# 바꾸면 걸음이 안정돼요. 특히 SGD 는 샘플 하나로 걷다 큰 x 값에 휘청여
# 발산하기 쉬운데, 표준화가 그걸 막아 줍니다. (되돌리려면 평균·표준편차 보관)
x = (온도 - 온도.mean()) / 온도.std()          # z = (x - 평균) / 표준편차

print("[데이터 준비]")
print("  샘플 개수:", n_data)                  # → 샘플 개수: 40
print("  표준화 x 앞 3개:", np.round(x[:3], 3))  # → 표준화 x 앞 3개: [-1.689 -1.603 -1.516]
print("  y 앞 3개:", np.round(y[:3], 3))       # → y 앞 3개: [2.497 2.067 3.058]

# 우리가 찾을 목표는 이 40개 점을 가장 잘 지나는 직선의 w, b 입니다.
# 표준화된 x 공간에서 걸으니 w, b 값 자체는 원래 눈금과 다르지만,
# 오늘의 관전 포인트는 그 값이 아니라 '세 방식이 같은 바닥에 닿느냐' 예요.


# ----------------------------------------
# 손실·기울기 - 전편 그대로, n 범위만 기억
# ----------------------------------------

# 손실(MSE)과 기울기 공식은 3부작에서 만든 것과 똑같습니다.
#   손실 :  L = (1/n)Σ(y - ŷ)²
#   기울기:  ∂L/∂w = -(2/n)Σ x(y - ŷ)
#           ∂L/∂b = -(2/n)Σ  (y - ŷ)
#
# 오늘의 핵심 한 줄: 이 Σ 와 n 이 '몇 개를 보느냐' 로 바뀝니다.
#   배치     → 전체 40개
#   미니배치 → 일부 8개
#   SGD      → 딱 1개
# 함수는 넘겨받은 xb, yb 의 개수만큼만 계산하도록 짜 둡니다. 그럼
# 같은 함수에 40개를 주면 배치, 1개를 주면 SGD 가 됩니다.

def 손실(xb, yb, w, b):
    preds = w * xb + b
    return np.mean((yb - preds) ** 2)          # (1/n)Σ(y-ŷ)²

def 기울기(xb, yb, w, b):
    n = len(xb)                                # ← 넘겨준 개수가 곧 n
    preds = w * xb + b
    gw = -(2 / n) * np.sum(xb * (yb - preds))  # ∂L/∂w
    gb = -(2 / n) * np.sum(yb - preds)         # ∂L/∂b
    return gw, gb


# ----------------------------------------
# 배치 경사하강 - 매 스텝 전체 40개로 한 발
# ----------------------------------------

# 우리가 지금까지 걸어온 방식입니다. 한 에폭에 딱 한 번, 전체 데이터로
# 기울기를 구해 w, b 를 갱신합니다. 정확하지만 데이터가 크면 무겁죠.
#
#   [전체 데이터로 한 발]
#     ●●●●●●●●●●●●●●●●●●●●  40개 전부 훑어서
#              ↓
#           한 걸음         ← 정확한 내리막 방향

def 배치_경사하강(x, y, lr=0.1, epochs=50):
    w, b = 0.0, 0.0
    손실기록 = []
    for epoch in range(epochs):
        gw, gb = 기울기(x, y, w, b)            # 전체 40개로 기울기
        w = w - lr * gw
        b = b - lr * gb
        손실기록.append(손실(x, y, w, b))
    return w, b, 손실기록

w_b, b_b, 손실_배치 = 배치_경사하강(x, y)
print("\n[배치 경사하강 · 50 에폭]")
print("  찾은 w:", round(w_b, 4), "/ b:", round(b_b, 4))
# → [배치 경사하강 · 50 에폭]
# →   찾은 w: 2.1322 / b: 5.7813
print("  최종 손실:", round(손실_배치[-1], 4))   # → 최종 손실: 0.8296

# 50 에폭이면 40개짜리엔 충분히 바닥에 닿았습니다. 문제는 데이터가 클 때
# 이 '전체 훑기'가 매 스텝 부담이라는 것. 뒤에서 이게 초반에 얼마나
# 굼뜬지(스텝이 적어) 곧 숫자로 보게 됩니다.


# ========================================================
#  PART 2 : 확률적 경사하강(SGD) - 매 스텝 샘플 하나
# ========================================================

# ----------------------------------------
# 아이디어 - 전부 말고, 딱 하나 보고 걷자
# ----------------------------------------

# SGD(Stochastic Gradient Descent, 확률적 경사하강)의 발상은 과감합니다.
# "전체를 다 봐야 방향을 아는 건 아니잖아? 한 개만 보고 대충이라도
#  그쪽으로 한 발 떼자. 대신 아주 많이 떼자."
#
#   [샘플 하나로 한 발]
#     ●  ← 딱 한 개만 훑어서
#     ↓
#   한 걸음   ← 방향이 정확하진 않음. 그 한 개 쪽으로 삐끗
#
# 'Stochastic(확률적)' 이라는 이름은 매번 무작위로 샘플 하나를 뽑기
# 때문에 붙었습니다. 기울기가 그 한 개에 휘둘려 출렁이거든요.
# 대신 한 스텝이 깃털처럼 가볍습니다 — 데이터 하나만 계산하니까.

def SGD(x, y, lr=0.05, epochs=50):
    w, b = 0.0, 0.0
    손실기록 = []
    n = len(x)
    for epoch in range(epochs):
        순서 = np.random.permutation(n)        # 매 에폭 무작위로 섞고
        for i in 순서:
            xi = x[i:i+1]                      # 샘플 '하나'만 슬라이스
            yi = y[i:i+1]                      # (배열 모양 유지하려 i:i+1)
            gw, gb = 기울기(xi, yi, w, b)      # n=1 로 기울기 → 출렁임
            w = w - lr * gw
            b = b - lr * gb
        손실기록.append(손실(x, y, w, b))       # 에폭 끝에서 전체 손실 확인
    return w, b, 손실기록

w_s, b_s, 손실_SGD = SGD(x, y)
print("\n[SGD · 50 에폭]")
print("  찾은 w:", round(w_s, 4), "/ b:", round(b_s, 4))
# → [SGD · 50 에폭]
# →   찾은 w: 2.4722 / b: 5.5924
print("  최종 손실:", round(손실_SGD[-1], 4))   # → 최종 손실: 0.9809

# 대충 비슷한 골짜기 근처에 닿긴 했습니다(배치 w≈2.13 / SGD w≈2.47).
# 한 개씩 삐뚤삐뚤 걸어서 배치만큼 딱 붙진 못하고 살짝 어긋나 있죠.
# 손실도 0.98 로 배치(0.83)보다 조금 높습니다 — 바닥에서 출렁이는 탓.
# 대신 '많이' 걸었어요. 40개 데이터면 한 에폭에 40 스텝을 뗍니다.
# 배치가 한 에폭에 1 스텝인 것과 정반대죠. 다음 파트에서 이 차이를 셉니다.


# ----------------------------------------
# 배치 vs SGD - 스텝 수가 다르다
# ----------------------------------------

# 같은 '50 에폭' 인데 실제로 뗀 걸음(스텝) 수가 완전히 다릅니다.
#
#            한 에폭당 스텝 |  50 에폭 총 스텝 |  한 스텝 무게
#   -------+---------------+-----------------+---------------
#   배치   |       1       |       50        |  무거움(40개)
#   SGD    |      40       |     2000        |  가벼움(1개)
#
# SGD 는 걸음이 가벼운 대신 훨씬 자주 뗍니다. 방향이 출렁여도
# 자주 갱신하니 초반엔 배치보다 훨씬 빨리 내려가죠. 이게 큰 데이터에서
# SGD 를 쓰는 이유입니다 — 전체를 한 번 훑기 전에 이미 많이 갱신돼요.


# ========================================================
#  PART 3 : 미니배치 경사하강 - 절충 (몇 개씩)
# ========================================================

# ----------------------------------------
# 아이디어 - 하나는 불안, 전부는 무거움 → 몇 개
# ----------------------------------------

# SGD 는 하나만 봐서 출렁이고, 배치는 전부 봐서 무겁습니다.
# 미니배치는 그 사이 절충입니다 — "한 번에 몇 개(예: 8개)씩만 보자."
#
#   [배치 8개로 한 발]
#     ●●●●●●●●  ← 8개 훑어서
#         ↓
#     한 걸음     ← 하나보단 안정, 전부보단 가벼움
#
# 8개 평균 방향은 1개보다 훨씬 덜 흔들리고, 40개 전부보다 훨씬 쌉니다.
# '배치 크기(batch size)'라는 손잡이 하나로 SGD~배치 사이를 조절해요.
#   배치크기 1  = SGD,  배치크기 40(=전체) = 배치.  그 사이가 미니배치.
# 실무의 사실상 표준이 이 미니배치입니다.

def 미니배치_경사하강(x, y, lr=0.05, epochs=50, 배치크기=8):
    w, b = 0.0, 0.0
    손실기록 = []
    n = len(x)
    for epoch in range(epochs):
        순서 = np.random.permutation(n)        # 매 에폭 섞고
        for 시작 in range(0, n, 배치크기):      # 배치크기 만큼 건너뛰며
            골라낸 = 순서[시작:시작 + 배치크기]  # 이번 미니배치 인덱스
            xb, yb = x[골라낸], y[골라낸]
            gw, gb = 기울기(xb, yb, w, b)       # 8개로 기울기 → 적당히 안정
            w = w - lr * gw
            b = b - lr * gb
        손실기록.append(손실(x, y, w, b))
    return w, b, 손실기록

w_m, b_m, 손실_미니 = 미니배치_경사하강(x, y, 배치크기=8)
print("\n[미니배치 경사하강 · 배치크기 8 · 50 에폭]")
print("  찾은 w:", round(w_m, 4), "/ b:", round(b_m, 4))
# → [미니배치 경사하강 · 배치크기 8 · 50 에폭]
# →   찾은 w: 2.1346 / b: 5.7881
print("  최종 손실:", round(손실_미니[-1], 4))   # → 최종 손실: 0.8297

# 배치와 거의 똑같은 바닥에 닿았습니다(w≈2.13, 손실 0.83). SGD 보다
# 훨씬 안정적이죠. 미니배치는 한 에폭에 40/8 = 5 스텝. 배치(1스텝)보다
# 자주, SGD(40스텝)보다 뜸하게 갱신하죠. 딱 중간이에요.


# ----------------------------------------
# 배치 크기 효과 - 크기별로 돌려 보기
# ----------------------------------------

# 배치 크기를 바꾸면 뭐가 달라지나 직접 봅니다. 같은 50 에폭에서
# 크기만 1(=SGD), 4, 8, 40(=전체 배치) 으로 바꿔 최종 손실을 비교해요.

print("\n[배치 크기별 · 50 에폭 후 손실]")
for 크기 in [1, 4, 8, 40]:
    _, _, 기록 = 미니배치_경사하강(x, y, 배치크기=크기)
    이름 = "SGD" if 크기 == 1 else ("전체배치" if 크기 == 40 else "미니배치")
    print(f"  배치크기 {크기:2d} ({이름:4s}) → 손실 {기록[-1]:.4f}")
# → [배치 크기별 · 50 에폭 후 손실]
# →   배치크기  1 (SGD ) → 손실 0.8552
# →   배치크기  4 (미니배치) → 손실 0.8311
# →   배치크기  8 (미니배치) → 손실 0.8299
# →   배치크기 40 (전체배치) → 손실 0.8306

# 다 비슷하지만 미묘하게 다릅니다. 크기가 가장 작은 1(SGD)이 손실이
# 제일 크고 출렁임이 남아요(0.8552). 4·8·40 은 0.83 안쪽으로 매끄럽게
# 붙습니다. 데이터가 작고 에폭이 넉넉하면 차이가 작지만, 큰 데이터·짧은
# 학습에선 이 배치 크기 선택이 속도와 안정성을 좌우합니다.


# ========================================================
#  PART 4 : 세 방식 비교 - 수렴 속도·안정성
# ========================================================

# ----------------------------------------
# 손실 곡선을 숫자로 나란히
# ----------------------------------------

# 이제 배치·미니배치·SGD 를 같은 데이터에 돌려, 에폭별 손실이 어떻게
# 줄어드는지 몇 지점만 찍어 나란히 봅니다. 앞에서 이미 각 손실기록을
# 받아 뒀으니 그걸 그대로 씁니다.

찍을에폭 = [1, 3, 5, 10, 30, 50]
print("\n[세 방식 손실 곡선 · 에폭별]")
print(f"  {'에폭':>4} | {'배치':>8} | {'미니배치':>8} | {'SGD':>8}")
for e in 찍을에폭:
    i = e - 1                                  # 0-based 인덱스
    print(f"  {e:4d} | {손실_배치[i]:8.4f} | {손실_미니[i]:8.4f} | {손실_SGD[i]:8.4f}")
# → [세 방식 손실 곡선 · 에폭별]
# →     에폭 |       배치 |     미니배치 |      SGD
# →      1 |  25.1309 |  14.1099 |   0.8511
# →      3 |  10.7834 |   2.3548 |   0.8363
# →      5 |   4.9067 |   1.0082 |   0.8462
# →     10 |   1.2674 |   0.8306 |   0.9233
# →     30 |   0.8297 |   0.8300 |   0.8354
# →     50 |   0.8296 |   0.8297 |   0.9809

# 이 표가 오늘의 핵심입니다. 세 줄을 뜯어보죠.
#   · 초반(에폭 1): SGD 는 벌써 0.85 로 바닥 근처! 한 에폭에 40 스텝을
#     떼니 순식간에 내려갑니다. 반면 배치는 25.1 로 아직 산꼭대기예요.
