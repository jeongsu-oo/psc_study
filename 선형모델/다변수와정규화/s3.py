# sklearn 은 입력 x 를 '열 벡터'(2차원)로 받습니다. reshape(-1, 1) 로 세워 줍니다.
Xtr = x_train.reshape(-1, 1)
Xte = x_test.reshape(-1, 1)

# 2차 특징으로 펼치고(우리가 손으로 만든 그 [1,x,x²]), 선형회귀를 얹습니다.
poly = PolynomialFeatures(degree=2)          # 특징 확장기
