# -------------------------------
# 다항 회귀 - 직선으로 '곡선'을 그리는 법 (다변수·정규화 심화 3편)
# -------------------------------


"""[온도랑 불량률이 U자로 휘었는데, 직선으론 도저히 안 맞아요. 어떡하죠?]
지금까지 우리가 맞춘 건 전부 '직선' 이었습니다.
   ŷ = w·x + b   (온도 x 하나에 기울기 하나)
그런데 현장 데이터는 곧잘 '휩니다'.
   설비 온도가 너무 낮아도 불량, 너무 높아도 불량 —
   중간 어디쯤이 가장 좋은 'U자' 관계 같은 거요.
직선 하나로는 이 U자를 절대 못 그립니다. 아무리 기울여도 직선이니까요.

"그럼 과정4의 신경망(MLP)을 써야 하나?" — 아직 아닙니다.
훨씬 간단한 방법이 있어요. 놀랍게도 여전히 '선형회귀' 로 곡선을 그립니다.
비결은 딱 하나 : 특징(feature)을 거듭제곱으로 늘리는 겁니다.
   x 하나를  [x, x², x³] 로 뻥튀기하면,
   그 위에서 돌린 평범한 선형회귀가 곡선을 그려요.

이 파일에서 쌓아 갈 순서:
  1) 전환 — 왜 직선으론 휜 관계를 못 맞추나 (숫자로 확인)
  2) 아이디어 — 특징 확장. x를 [x, x², x³]로 늘리면 곡선이 그려진다
  3) 차수별 fit — 1차·2차·3차로 맞춰 곡선이 점에 붙는 걸 눈으로
  4) 차수↑ = 과적합 — 차수를 너무 올리면 train 완벽·test 폭망 (U자 회수)
  5) 적정 차수 고르기 (test 최소) + 정규화 한 줄
  6) sklearn 으로 같은 걸 두 줄에 (PolynomialFeatures + LinearRegression)
  7) 실습 — 차수를 바꿔 fit·과적합을 직접 관찰

넘파이만 씁니다(맨 끝 sklearn 대조만 예외). 밑바닥 숫자로 '곡선'을 봅니다.
"""

import numpy as np
import warnings

# 차수를 높이면 polyfit 이 "곡선이 불안정하다"는 경고를 냅니다.
# 그 불안정함이 바로 우리가 4단계에서 '과적합'으로 보여줄 현상이라
# 일부러 만드는 것이니, 경고 메시지는 화면에서 꺼 둡니다.
# (현상 자체는 오차 숫자로 또렷이 확인합니다.)
warnings.simplefilter("ignore", np.exceptions.RankWarning)


# ==========================================================
#  1. 전환 - 직선으로는 '휜 관계'를 못 맞춘다
# ==========================================================

# 제조 데이터 하나를 인라인으로 만들겠습니다.
# 어떤 설비의 '가동 온도(x)' 에 따른 '불량 지표(y)' 라고 합시다.
# 숨은 진짜 관계는 U자입니다 — 온도가 너무 낮아도, 너무 높아도 불량이 늘고,
# 중간 어디쯤(정규화 온도 0.5 근처)이 가장 낮습니다.
# 측정에는 늘 노이즈가 섞이니 살짝 얹습니다. 점은 14개.

np.random.seed(7)   # 시드 고정: 몇 번을 돌려도 같은 결과 (재현성)

# x: 설비 온도를 0~1 로 정규화한 값. 촘촘하게 14개.
x_all = np.linspace(0, 1, 14)

# 숨은 진짜 규칙: 아래로 볼록한 U자 곡선. 최저점은 x=0.5, 그 값 1.0, 양 끝 3.0.
true_curve = lambda t: 8.0 * (t - 0.5) ** 2 + 1.0
noise = np.random.normal(0, 0.15, size=x_all.shape)   # 표준편차 0.15 잡음
y_all = true_curve(x_all) + noise

# 학습용·시험용을 '번갈아' 나눕니다.
#   짝수 번째 점 → 학습(train), 홀수 번째 점 → 시험(test)
# 이렇게 하면 test 점이 train 점 '사이사이'에 놓여, 나중에 과적합이
# test 오차로 또렷이 드러납니다. (분류·평가 편에서 쓴 그 방식 그대로)
train_mask = np.arange(14) % 2 == 0
x_train, y_train = x_all[train_mask],  y_all[train_mask]
x_test,  y_test  = x_all[~train_mask], y_all[~train_mask]

print("[데이터 준비]")
print("  전체:", len(x_all), "개  ->  학습:", len(x_train), "개 / 시험:", len(x_test), "개")
# → [데이터 준비]
# →   전체: 14 개  ->  학습: 7 개 / 시험: 7 개


# ----------------------------------------
# 직선을 억지로 맞춰 보기 - 얼마나 안 맞나
# ----------------------------------------

# 먼저 지금까지 하던 대로 '직선(1차)' 하나를 이 U자 데이터에 맞춰 봅시다.
# np.polyfit(x, y, 1) 이 최소제곱으로 가장 잘 맞는 직선을 구해 줍니다.
# (차수를 1로 준 게 곧 '직선' 이에요.)

line = np.polyfit(x_train, y_train, 1)     # [기울기, 절편]
line_pred = np.polyval(line, x_train)      # 직선으로 예측
line_mse = np.mean((line_pred - y_train) ** 2)

print("\n[직선(1차)으로 U자를 맞추면]")
print("  기울기:", round(line[0], 3), " 절편:", round(line[1], 3))
print("  train 오차(MSE):", round(line_mse, 4))
# → [직선(1차)으로 U자를 맞추면]
# →   기울기: -0.722  절편: 2.142
# →   train 오차(MSE): 0.5278

# 직선은 이 U자 앞에서 어쩔 줄을 모릅니다.
# U자는 왼쪽에선 내려가고 오른쪽에선 올라갑니다. 직선 하나로 둘 다 맞출 순 없으니
# '이러지도 저러지도 못하고' 밋밋한 직선 하나로 뭉개 버립니다.
# 그림으로 보면 이렇습니다. (o = 데이터 점, --- = 맞춘 직선)
#
#     o                          o        <- 양 끝은 높고
#       o                      o
#   -----o------o------o------o-------     <- 직선은 중간 높이로 뭉갬
#           o        o                     <- 가운데는 낮은데
#                o                            직선이 여기를 못 내려감
#
# train 오차가 0.53 이나 됩니다. 뒤에서 곡선을 쓰면 이게 0.01 이하로 떨어져요.
# 직선이 나빠서가 아니라, '직선이라는 틀' 자체가 U자를 담을 수 없어서입니다.


# ==========================================================
#  2. 아이디어 - 특징을 거듭제곱으로 '확장'한다
# ==========================================================

# 여기가 이 파일의 핵심 아이디어입니다. 딱 한 문장으로:
#
#     x 하나를  [x, x², x³] 로 늘리면,
#     그 위의 '선형회귀' 가 곡선을 그린다.
#
# 무슨 말이냐면 — 지금까지 예측식은 이랬죠.
#     ŷ = w0 + w1·x                         (특징이 x 하나)
# 여기에 x², x³ 를 '새로운 특징' 인 척 추가합니다.
#     ŷ = w0 + w1·x + w2·x² + w3·x³         (특징이 셋)
#
# 이 식은 x 에 대해서는 '곡선' 이지만,
# 가중치 w0, w1, w2, w3 에 대해서는 여전히 '선형(1차)' 입니다.
# x², x³ 를 그냥 '값이 정해진 새 열' 로 보면, 이건 우리가 아는
# 다변수 선형회귀(여러 특징의 가중합)와 완전히 똑같은 문제예요.
#   → "모델은 여전히 선형(가중치에 대해), 특징만 비선형."
# 그래서 새 이론이 필요 없습니다. 특징 열만 늘려서 기존 선형회귀에 넣으면 끝.


# ----------------------------------------
# 특징 행렬 만들기 - x를 여러 거듭제곱 열로
# ----------------------------------------

# 손으로 특징을 확장해 봅시다. x 한 열을 [1, x, x², x³] 네 열로 펼칩니다.
# (맨 앞의 1 열은 절편 w0 을 위한 자리입니다. 상수항도 '1이라는 특징' 이에요.)

def design_matrix(x, degree):
    """x(1차원)를 [1, x, x², ..., x^degree] 열들로 펼친 '특징 행렬'을 만든다.
    각 행이 한 데이터 점, 각 열이 하나의 거듭제곱 특징."""
    # x**0=1, x**1=x, x**2=x², ... 을 세로로 쌓고 전치(.T)해 열로 세움
    return np.vstack([x ** p for p in range(degree + 1)]).T

# 2차(degree=2)로 펼치면 [1, x, x²] 세 열이 나옵니다.
X2 = design_matrix(x_train, 2)
print("\n[특징 확장: x 하나 -> [1, x, x²] 세 열]")
print("  원래 x (앞 3개):", np.round(x_train[:3], 4))
print("  펼친 특징 행렬 (앞 3행):")
print(np.round(X2[:3], 4))
print("  모양(shape):", X2.shape, " -> 점", X2.shape[0], "개 x 특징", X2.shape[1], "개")
# → [특징 확장: x 하나 -> [1, x, x²] 세 열]
# →   원래 x (앞 3개): [0.     0.1538 0.3077]
# →   펼친 특징 행렬 (앞 3행):
# → [[1.     0.     0.    ]
# →  [1.     0.1538 0.0237]
# →  [1.     0.3077 0.0947]]
# →   모양(shape): (7, 3)  -> 점 7 개 x 특징 3 개
#
# 보세요. 첫 열은 전부 1(절편용), 둘째 열은 x 그대로, 셋째 열은 x 제곱.
# 예를 들어 둘째 행 x=0.1538 이면 x²=0.0237 이 자동으로 붙습니다.
# 이제 이 세 열짜리 표를 그냥 '다변수 선형회귀' 에 넣으면 됩니다.
# x², x³ 를 '따로 측정한 다른 센서 값' 이라고 생각해도 계산은 똑같아요.


# ==========================================================
#  3. 차수별 fit - 1차·2차·3차로 곡선이 점에 붙는다
# ==========================================================

# 실제로 맞춰 봅시다. np.polyfit(x, y, degree) 가 위에서 손으로 만든
# 특징 확장 + 최소제곱을 한 방에 처리해 '가장 잘 맞는 다항식 계수'를 줍니다.
# (내부에서 우리가 만든 design_matrix 같은 걸 만들어 푸는 겁니다.)

def fit_poly(x, y, degree):
    """x, y 에 degree 차 다항식을 최소제곱으로 맞춰 계수를 돌려줌."""
    return np.polyfit(x, y, degree)

# 1차·2차·3차 계수를 각각 구합니다.
c1 = fit_poly(x_train, y_train, 1)
c2 = fit_poly(x_train, y_train, 2)
c3 = fit_poly(x_train, y_train, 3)

# polyval 은 계수와 x 를 받아 ŷ = w0 + w1·x + w2·x² + ... 를 계산합니다.
def mse(coef, x, y):
    """맞춘 계수로 x 를 예측해 실제 y 와의 평균제곱오차를 냄."""
    return np.mean((np.polyval(coef, x) - y) ** 2)

print("\n[차수별 train 오차 - 곡선이 점에 얼마나 붙나]")
print("  1차(직선):", round(mse(c1, x_train, y_train), 4))
print("  2차(곡선):", round(mse(c2, x_train, y_train), 4))
print("  3차(곡선):", round(mse(c3, x_train, y_train), 4))
# → [차수별 train 오차 - 곡선이 점에 얼마나 붙나]
# →   1차(직선): 0.5278
# →   2차(곡선): 0.0099
# →   3차(곡선): 0.007
#
# 직선(0.53)에서 2차 곡선(0.0099)로 오차가 '50배 넘게' 줄었습니다!
# 특징에 x² 하나 더했을 뿐인데요. 왜냐면 U자는 2차식(포물선)이 딱 그리는 모양이라,
# 2차 특징만 있으면 데이터의 진짜 흐름을 그대로 잡거든요.


# ----------------------------------------
# 곡선을 ASCII 로 눈에 새기기
# ----------------------------------------

# 2차 곡선이 U자 점들에 어떻게 붙는지 그림으로 봅시다.
# 촘촘한 x 를 만들어 2차 계수로 예측해 곡선을 그리고, 실제 점을 얹습니다.
# (matplotlib 없이 순수 문자로 그립니다. 세로 높이는 y 값에 비례.)

def ascii_plot(coef, x_pts, y_pts, width=40, height=11):
    """맞춘 곡선(coef)과 실제 점(x_pts,y_pts)을 문자 격자에 겹쳐 그린다."""
    xs = np.linspace(0, 1, width)
    ys = np.polyval(coef, xs)
    lo = min(ys.min(), y_pts.min())
    hi = max(ys.max(), y_pts.max())
    grid = [[" "] * width for _ in range(height)]
    def row_of(v):  # y 값 -> 격자 행 번호(위가 큰 값)
        r = int(round((hi - v) / (hi - lo) * (height - 1)))
        return min(max(r, 0), height - 1)
    for c, v in enumerate(ys):          # 곡선은 점(.)으로
        grid[row_of(v)][c] = "."
    for xp, yp in zip(x_pts, y_pts):    # 실제 데이터는 o 로
        c = min(int(round(xp * (width - 1))), width - 1)
        grid[row_of(yp)][c] = "o"
    for line in grid:
        print("   " + "".join(line))

print("\n[2차 곡선이 U자 데이터에 붙는 모습]  (o=실제 점, .=맞춘 곡선)")
ascii_plot(c2, x_all, y_all)
# → [2차 곡선이 U자 데이터에 붙는 모습]  (o=실제 점, .=맞춘 곡선)
# 직선으론 못 그리던 'U자'가 곡선으로 딱 그려집니다.
# 양 끝은 높고 가운데가 낮은 그 모양을, 특징 [1, x, x²] 위의 선형회귀가 잡아냈어요.


# ==========================================================
#  4. 차수를 더 올리면? - 과적합 (분류·평가 편 회수)
# ==========================================================

# "2차가 이렇게 좋으면, 차수를 더 올리면 더 좋아지지 않나?" — 함정입니다.
# 분류·평가 4편에서 봤던 '과적합' 이 바로 여기서 다시 나옵니다.
# 이번엔 train 뿐 아니라 test 오차까지 나란히 재서 U자를 눈으로 확인합니다.

print("\n[차수를 올리며 train·test 오차 재기]")
print("  차수 | train 오차 | test 오차 | 한마디")
print("  -----+-----------+-----------+-----------------")
labels = {1: "과소적합 (직선이라 U자를 못 잡음)",
          2: "적정 (U자를 딱 그림)",
          3: "적정 근처",
          5: "과적합 시작",
          8: "심한 과적합"}
tr_errs, te_errs = {}, {}
for d in [1, 2, 3, 5, 8]:
    coef = fit_poly(x_train, y_train, d)
    e_tr = mse(coef, x_train, y_train)
    e_te = mse(coef, x_test,  y_test)
    tr_errs[d], te_errs[d] = e_tr, e_te
    print(f"  {d:>4} | {e_tr:>9.6f} | {e_te:>9.4f} | {labels[d]}")
# → [차수를 올리며 train·test 오차 재기]
# →   차수 | train 오차 | test 오차 | 한마디
# →   -----+-----------+-----------+-----------------
# →      1 |  0.527771 |    0.6246 | 과소적합 (직선이라 U자를 못 잡음)
# →      2 |  0.009922 |    0.0192 | 적정 (U자를 딱 그림)
# →      3 |  0.007004 |    0.0168 | 적정 근처
# →      5 |  0.000294 |    0.1799 | 과적합 시작
# →      8 |  0.000000 |    0.5677 | 심한 과적합

# 표를 천천히 읽어 봅시다. 여기가 이 파일의 심장입니다.
#
#   train 오차 : 0.528 → 0.010 → 0.007 → 0.0003 → 0.000
#                차수가 오를수록 '계속' 줄어듭니다. 끝엔 0 (점을 다 통과)
#   test  오차 : 0.625 → 0.019 → 0.017 → 0.180 → 0.568
#                줄었다가(차수 2~3) 다시 '치솟습니다'. 전형적인 U자.
#
# 이게 '표현력과 과적합의 트레이드오프' 입니다.
#   - 차수가 낮으면(1) 표현력이 모자라 U자조차 못 그림      → 과소적합
#   - 차수 2~3 에서 test 오차가 최소                        → 적정
#   - 차수를 더 올리면(5, 8) train 은 0까지 떨어지는데
#     test 는 오히려 커짐                                   → 과적합
#
# 차수 8 에서 train 오차가 '0' 인 게 핵심 함정입니다.
# 학습 점 7개를 8차 곡선이 하나도 안 틀리고 다 지나가 버렸어요. 완벽해 보이죠?
# 하지만 그 대가로 학습 점 '사이' 에서 곡선이 미친 듯이 출렁이고,
# 바로 그 사이에 놓인 test 점들이 그 출렁임에 걸려 크게 빗나갑니다.
#
