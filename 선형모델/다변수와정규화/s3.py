# 차수 하나를 넣으면 train·test 오차와 진단을 돌려주는 도구입니다.
# 여러 차수로 돌려 보며 'test 오차가 최소인 적정 차수' 를 직접 찾으세요.

def diagnose(degree):
    """주어진 차수로 맞추고 (train오차, test오차, 진단문구)를 돌려줌."""
    coef = fit_poly(x_train, y_train, degree)
    e_tr = mse(coef, x_train, y_train)
    e_te = mse(coef, x_test,  y_test)
    # 진단은 두 오차의 '관계' 로 봅니다.
    #   둘 다 크면          → 과소적합 (표현력 부족)
    #   train 낮고 test 도 낮으면 → 건강
    #   train 아주 낮은데 test 크면 → 과적합 (외운 상태)
    if e_tr > 0.1:
        verdict = "과소적합 쪽 (둘 다 큼)"
    elif e_te <= 0.03:
        verdict = "건강 (train·test 둘 다 낮음)"
    else:
        verdict = "과적합! (train만 낮고 test 큼)"
    return e_tr, e_te, verdict

print("\n[실습: 차수별 진단표]")
print("  차수 | train 오차 | test 오차 | 진단")
print("  -----+-----------+-----------+---------------------------")
for d in [1, 2, 4, 6, 8]:
    e_tr, e_te, verdict = diagnose(d)
    print(f"  {d:>4} | {e_tr:>9.6f} | {e_te:>9.4f} | {verdict}")
