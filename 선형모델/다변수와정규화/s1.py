# "어느 센서가 불량에 가장 크게 기여하나?" 를 알고 싶습니다.
# 언뜻 w 값이 큰 진동(4.38)이 압도적으로 보이죠. 하지만 함정이 있습니다.
#   원래 w 는 '단위' 가 제각각입니다.
#   온도 w=0.19 는 '온도 1도 오를 때' 불량 증가, 진동 w=4.38 은 '진동 1 오를 때'.
#   그런데 온도는 20도씩 움직이고 진동은 0.8밖에 안 움직입니다.
# 단위가 다르니 w 크기를 그냥 비교하면 안 됩니다. 온도는 조금씩만 곱해져도
# 실제로는 크게 기여할 수 있으니까요.

# ----------------------------------------
# 표준화 가중치로 공정하게 비교
# ----------------------------------------

# 해결: 표준화 공간의 가중치(w_std)를 비교합니다. 모든 특징을 '퍼짐 1' 로
# 통일해 놨으니, 여기서의 w 크기는 '그 특징이 한 표준편차 움직일 때
# 불량이 얼마나 변하나' 라 서로 공정하게 견줄 수 있습니다.

print("\n[가중치 해석 · 표준화 공간 기준]")
특징이름 = ["온도", "압력", "진동"]
순위 = sorted(zip(특징이름, w_std), key=lambda t: abs(t[1]), reverse=True)
for 이름, 값 in 순위:
    방향 = "불량↑" if 값 > 0 else "불량↓"
    print(f"  {이름}: 표준화 가중치 {값:+.3f}  ({방향} 로 기여)")
# → [가중치 해석 · 표준화 공간 기준]
# →   온도: 표준화 가중치 +1.243  (불량↑ 로 기여)
# →   진동: 표준화 가중치 +1.167  (불량↑ 로 기여)
