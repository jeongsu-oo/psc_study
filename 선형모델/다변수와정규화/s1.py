# 원래 w 로는 진동만 커 보였지만, 표준화로 재보니 온도의 영향이 오히려 큽니다.
# 이게 다변수 회귀의 실무 가치예요 — "어느 공정 변수를 잡아야 하나" 의 답.


# ========================================================
#  PART 7 : 정규방정식 - 공식으로 한 번에
# ========================================================

# ----------------------------------------
# w = (XᵀX)⁻¹Xᵀy 한 줄
# ----------------------------------------

# 과정3에서 1변수는 공식으로 단번에 풀렸었죠(최소제곱). 다변수에도 공식이
# 있습니다 — '정규방정식' 입니다. 걸어가지 않고 한 방에 최적 w 를 줍니다.
#
#   w = (XᵀX)⁻¹ Xᵀ y
#         └──┬──┘
#      역행렬 (D파트의 그 역행렬). 이걸 구해 y 에 곱하면 끝.
#
# 절편 b 를 함께 구하려면 X 에 '전부 1인 열' 을 하나 붙입니다.
# 그 1의 열에 대응하는 가중치가 곧 b 예요. (1·b = b 니까)

n = len(y)
X편향 = np.column_stack([X, np.ones(n)])   # X 오른쪽에 1 열 추가 → (10 x 4)

# np.linalg.inv 로 역행렬, @ 로 행렬곱. 공식 그대로 한 줄.
정규해 = np.linalg.inv(X편향.T @ X편향) @ X편향.T @ y   # (XᵀX)⁻¹Xᵀy
w_정규 = 정규해[:3]     # 앞 3개가 특징 가중치
b_정규 = 정규해[3]      # 마지막이 절편(1 열의 가중치)

print("\n[정규방정식 결과]")
print("  w:", np.round(w_정규, 4))   # → w: [0.1877 0.8664 4.3799]
print("  b:", round(b_정규, 4))      # → b: -11.6796

# 경사하강으로 걸어서 찾은 값과 소수점까지 똑같습니다! 길은 달라도 바닥은 하나.


# ----------------------------------------
# 언제 뭘 쓰나 - 걸음 vs 공식
# ----------------------------------------

# 그럼 늘 공식(정규방정식)만 쓰면 되지 왜 경사하강을 배웠을까요? 과정3의 답과 같습니다.
#
#   정규방정식(공식)  : 특징이 적을 때 한 방에. 단, (XᵀX)⁻¹ 역행렬 계산이
#                       특징 수의 세제곱에 비례해 폭발적으로 비싸짐.
#                       특징이 수천·수만이면 역행렬 못 구하거나 너무 느림.
#   경사하강(걸음)    : 그냥 한 걸음씩. 특징이 수만 개여도 감당됨.
#                       신경망처럼 공식 자체가 없는 문제엔 이것만 통함.
#
# 감: 특징 몇 개짜리 작은 회귀 → 공식이 편함.
#     특징 아주 많거나 공식이 없는 문제 → 경사하강.


# ========================================================
#  PART 8 : 표준 도구 대조 - lstsq · sklearn
# ========================================================

# ----------------------------------------
# 네 방법이 같은 곳에서 만난다
# ----------------------------------------

# 오늘의 클라이맥스. 네 가지 방법으로 같은 데이터의 w, b 를 구해 맞춰 봅니다.
#   ① 경사하강        : 표준화 공간에서 걸어서 (오늘 손수 구현)
#   ② 정규방정식      : (XᵀX)⁻¹Xᵀy 공식 한 줄
#   ③ np.linalg.lstsq : numpy 의 최소제곱 전용 함수
#   ④ sklearn         : 세계 표준 머신러닝 도구

# ③ np.linalg.lstsq — 편향 열 붙인 X편향에 대해 최소제곱해를 바로 줌
lstsq해, *_ = np.linalg.lstsq(X편향, y, rcond=None)
w_lstsq = lstsq해[:3]
b_lstsq = lstsq해[3]

# ④ sklearn — 절편은 fit_intercept 가 알아서(1 열 붙일 필요 없음)
from sklearn.linear_model import LinearRegression
sk = LinearRegression().fit(X, y)

print("\n[네 방법 대조]")
print(f"  ① 경사하강   w: {np.round(w_gd, 4)}   b: {b_gd:.4f}")
print(f"  ② 정규방정식 w: {np.round(w_정규, 4)}   b: {b_정규:.4f}")
print(f"  ③ lstsq      w: {np.round(w_lstsq, 4)}   b: {b_lstsq:.4f}")
print(f"  ④ sklearn    w: {np.round(sk.coef_, 4)}   b: {sk.intercept_:.4f}")
# → [네 방법 대조]
# →   ① 경사하강   w: [0.1877 0.8664 4.3799]   b: -11.6796
# →   ② 정규방정식 w: [0.1877 0.8664 4.3799]   b: -11.6796
# →   ③ lstsq      w: [0.1877 0.8664 4.3799]   b: -11.6796
# →   ④ sklearn    w: [0.1877 0.8664 4.3799]   b: -11.6796

# 프로그램이 스스로 채점하게 합니다. (경사하강은 근사라 소수 3자리 근접으로 확인)
근접 = (np.allclose(w_gd, w_정규, atol=1e-3) and
        np.allclose(w_gd, w_lstsq, atol=1e-3) and
        np.allclose(w_gd, sk.coef_, atol=1e-3) and
        abs(b_gd - b_정규) < 1e-3 and abs(b_gd - sk.intercept_) < 1e-3)
print("\n  네 방법이 소수 3자리까지 근접?", 근접)   # → 네 방법이 소수 3자리까지 근접? True
assert 근접, "네 방법의 결과가 어긋납니다 — 데이터나 학습 설정을 점검하세요!"
# True. 완전히 다른 네 길인데 도착점이 같습니다.
# 우리가 손으로 걸어 찾은 값이 세계 표준 도구와 소수점까지 일치 — 검증 끝.


# ----------------------------------------
# predict / R² - 찾은 모델 쓰기
# ----------------------------------------

# 학습한 w, b 로 안 겪은 새 측정의 불량을 예측하고, 얼마나 잘 맞나 점수(R²).
def predict(측정, w, b):
    return np.array(측정) @ w + b     # [온도, 압력, 진동] · w + b

def R2(X, y, w, b):
    preds = 예측(X, w, b)
    SSE = np.sum((y - preds) ** 2)         # 모델이 못 맞힌 오차
    SST = np.sum((y - y.mean()) ** 2)      # 평균으로 찍기의 오차
    return 1 - SSE / SST                    # 1에 가까울수록 잘 맞음

새측정 = [76, 4.8, 0.95]   # 온도 76, 압력 4.8, 진동 0.95 (데이터에 없던 조합)
print("\n새 측정 [76, 4.8, 0.95] 예측 불량:", round(predict(새측정, w_gd, b_gd), 3))
# → 새 측정 [76, 4.8, 0.95] 예측 불량: 10.909
print("R² (설명력):", round(R2(X, y, w_gd, b_gd), 4))   # → R² (설명력): 0.9984

# R²≈0.998 → 불량이 흩어진 정도의 99.8%를 세 센서로 설명. 아주 잘 맞는 모델.


# ========================================================
#  PART 9 : 실습 - 특징을 빼보고 성능 비교
# ========================================================

# ----------------------------------------
# [실습] 센서를 하나씩 빼면 R² 가 얼마나 떨어지나
# ----------------------------------------

# 다변수의 진짜 힘은 '여러 특징을 같이 쓸 때' 나옵니다. 정말 그런지 실험합니다.
# 각 센서를 하나만 빼고 나머지로만 fit 해서 R² 를 비교해 보세요.
# 성능이 크게 떨어지는 센서일수록 예측에 중요한 특징이라는 뜻입니다.
#
#   Step 1) 세 특징 다 쓰기 → R² (기준선)
#   Step 2) 온도만 빼고 [압력, 진동] 로 fit → R²
#   Step 3) 압력만 빼고, 진동만 빼고 각각 → R²
#   Step 4) 어느 걸 뺐을 때 R² 가 가장 많이 떨어지나? = 가장 중요한 특징
#
#   완료 기준 : 네 경우의 R² 가 화면에 나오고, 특징을 뺄수록
#              (대개) R² 가 떨어지는 걸 확인하면 성공.

print("\n[실습 · 특징 빼보기 성능 비교]")
print(f"  세 특징 전체        R²: {R2(X, y, w_gd, b_gd):.4f}")   # 위에서 구한 w_gd, b_gd

for 뺄특징 in range(3):
    남길열 = [j for j in range(3) if j != 뺄특징]
    X부분 = X[:, 남길열]                       # 한 특징 열을 제거한 X
    w부분, b부분, _ = fit(X부분, y)
    r2부분 = R2(X부분, y, w부분, b부분)
    print(f"  {특징이름[뺄특징]} 빼고 [{'·'.join(특징이름[j] for j in 남길열)}]  R²: {r2부분:.4f}")
# → [실습 · 특징 빼보기 성능 비교]
# →   세 특징 전체        R²: 0.9984
# →   온도 빼고 [압력·진동]  R²: 0.8340
# →   압력 빼고 [온도·진동]  R²: 0.9613
# →   진동 빼고 [온도·압력]  R²: 0.9367

# 온도를 빼면 R²가 0.998 → 0.83 으로 가장 크게 떨어지고, 진동을 빼도 0.94 로
# 눈에 띄게 낮아집니다. 반면 압력을 빼면 0.96 으로 별로 안 떨어져요 —
# 상대적으로 덜 중요한 센서죠.
# PART 6의 표준화 가중치 순위(온도·진동 > 압력)와 방향이 같은 결론입니다.
# '가중치 크기' 와 '빼봤을 때 성능 하락' 두 방법이 서로를 뒷받침합니다.


# ----------------------------------------
# 1편 마무리 - 오늘 손에 넣은 것
# ----------------------------------------

#   [다변수 선형회귀 한 줄 정리]
#     특징 1개 → 여러 개.  ŷ = X·w + b  (행렬곱 한 줄로 전부 예측)
#
#   [경사하강 확장 요약]
#     1변수:  gw = (2/n)Σ(ŷ-y)x       (값 하나)
#     다변수: ∇w = (2/n)Xᵀ(ŷ-y)       (길이=특징 수인 벡터)
#     갱신식 w ← w - lr·∇w 는 과정3 그대로, w 가 벡터가 됐을 뿐.
#
#   [기억할 것]
#     · 데이터는 행렬 X(행=측정, 열=특징), 가중치는 벡터 w
#     · 특징 범위가 다르면 발산 → 표준화 필수 (평균0·퍼짐1)
#     · 가중치 해석은 표준화 공간에서 — 어느 센서가 불량에 크게 기여하나
#     · 정규방정식 w=(XᵀX)⁻¹Xᵀy 로 한 방에도 풀림 (특징 적을 때)
#     · 걸어서 찾은 값 ≈ 정규방정식 ≈ lstsq ≈ sklearn (같은 골짜기 바닥)
#     · 특징 많으면 경사하강, 적으면 공식 — 상황 따라 골라 쓴다
