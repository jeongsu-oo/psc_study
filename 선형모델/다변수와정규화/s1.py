# -------------------------------
# 다변수 선형회귀 - 센서 여러 개를 한꺼번에 본다 (과정3 심화 1편)
# -------------------------------


"""[온도 하나로 예측했는데, 압력·진동까지 같이 보면 더 잘 맞지 않나요?]
지금까지 우리는 '온도 하나' 로 불량을 예측했습니다.
  불량 ≈ w·온도 + b       ← 특징(입력)이 딱 하나
그런데 현장에서 불량은 온도만의 문제가 아니죠.
압력이 높아도, 진동이 심해도 불량이 늘어납니다.

그래서 오늘은 여러 센서를 '동시에' 봅니다.
  ŷ = w1·온도 + w2·압력 + w3·진동 + b
특징이 3개가 됐을 뿐, 심장은 과정3의 경사하강 그대로입니다.
1변수에서 두 발로 걸어 골짜기를 내려온 그 걸음을,
오늘은 특징이 여러 개인 골짜기로 자연스럽게 넓힙니다.

핵심 재료는 두 개예요.
  · 행렬 X (행=측정 한 번, 열=특징) — D파트에서 만든 벡터·행렬
  · 예측을 행렬곱 한 줄로:  ŷ = X·w + b

오늘의 성취를 미리 말해 둡니다. 우리가 걸어서 찾은 가중치가 —
  · np.linalg.lstsq(공식 도구) 와
  · 정규방정식 w=(XᵀX)⁻¹Xᵀy 와
  · sklearn LinearRegression 과
소수점까지 같습니다. 특징이 여러 개여도 '같은 골짜기 바닥' 이죠.

이 파일은 전환 → 행렬로 담기 → 행렬 예측·손실 → 다변수 경사하강 →
특징 스케일 문제 → 가중치 해석 → 정규방정식 → 도구 대조 → 실습
순으로 위에서 아래로 쌓아 갑니다.
"""

import numpy as np


# ========================================================
#  PART 1 : 전환 - 특징 하나로는 부족하다
# ========================================================

# ----------------------------------------
# 센서 하나 vs 여러 개
# ----------------------------------------

# 과정3까지의 예측은 이랬습니다.
#   ŷ = w·온도 + b            ← 온도라는 특징 하나
#
# 하지만 불량은 온도만으로 다 설명되지 않습니다.
# 같은 온도라도 압력이 세거나 진동이 심하면 불량이 더 나오죠.
# 그래서 여러 특징을 '동시에' 곱해 더합니다. 이게 다변수 회귀입니다.
#
#   ŷ = w1·온도 + w2·압력 + w3·진동 + b
#        └──┬──┘  └──┬──┘  └──┬──┘  └┬┘
#         각 센서마다 제 몫의 가중치      전체를 위아래로 옮기는 절편
#
# 달라진 건 딱 하나 — 특징이 1개에서 3개로 늘었을 뿐입니다.
# '각 입력에 가중치를 곱해 다 더한다' 는 뼈대는 그대로예요.
# 그 '곱해서 더하기' 가 바로 D파트의 내적이었죠. 오늘 그게 살아납니다.


# ========================================================
#  PART 2 : 데이터를 행렬 X 로 담는다
# ========================================================

# ----------------------------------------
# 제조 데이터 - 측정 10번, 특징 3개
# ----------------------------------------

# 설비에서 10번 측정했습니다. 매 측정마다 온도·압력·진동 세 값이 나오고,
# 그때 나온 불량 수를 함께 기록했습니다. (외부 파일 없이 인라인)
# 실제로 불량이 세 센서에 선형으로 반응하도록 설계한 데이터입니다.

온도 = [72, 68, 80, 65, 78, 82, 70, 85, 74, 66]   # 수십 단위
압력 = [4.5, 5.2, 3.8, 4.0, 5.5, 3.5, 5.0, 4.2, 3.6, 5.8]   # 소수 단위
진동 = [0.8, 0.5, 1.2, 0.7, 0.6, 1.3, 0.9, 1.1, 1.0, 0.55]  # 소수 단위
불량 = [9.2, 7.7, 11.9, 7.2, 10.4, 12.4, 9.8, 12.8, 9.6, 8.1]  # 타깃(예측 대상)

# ----------------------------------------
# X = 행이 측정, 열이 특징
# ----------------------------------------

# 세 특징을 한 표(행렬)로 묶습니다. 규칙은 D파트 그대로예요.
#   행(row) 하나 = 측정 한 번 = [온도, 압력, 진동] 벡터
#   열(column) 하나 = 한 특징이 여러 측정에 걸쳐 늘어선 것
#
#          온도  압력  진동     ← 열 3개 (특징)
#   측정1 [ 72   4.5   0.8 ]    ← 행 : 한 번의 측정
#   측정2 [ 68   5.2   0.5 ]
#     :        :
#   측정10[ 66   5.8   0.55]
#     ↑
#   행 10개 (샘플)
#
# np.array 로 세 리스트를 세로로 쌓아 (10 x 3) 행렬을 만듭니다.
# column_stack 은 '각 리스트를 열로 세워' 나란히 붙이는 함수입니다.

X = np.column_stack([온도, 압력, 진동])   # (10행 x 3열)
y = np.array(불량)                         # 타깃 (10,)

print("X shape (측정 수, 특징 수):", X.shape)   # → X shape (측정 수, 특징 수): (10, 3)
print("y shape (측정 수):", y.shape)            # → y shape (측정 수): (10,)
print("X 첫 행 (측정1의 온도·압력·진동):", X[0])   # → X 첫 행 (측정1의 온도·압력·진동): [72.   4.5  0.8]

# ----------------------------------------
# 가중치 w 도 벡터로 - 형상 맞추기
# ----------------------------------------

# 특징이 3개니 가중치도 3개, 즉 w 는 길이 3짜리 벡터입니다.
#   w = [w1, w2, w3]    ← 온도·압력·진동 각각의 몫
# 절편 b 는 여전히 숫자 하나(모든 예측을 위아래로 옮기는 값).
#
#   X·w 형상 규칙 (D파트 행렬곱):
#     X    ·   w    →  ŷ
#   (10×3) · (3,)  →  (10,)
#        └── 3 == 3 (안쪽이 같아야 곱셈 성립) ──┘
#   결과는 측정 수(10)만큼의 예측이 한 번에 나옴!
#
# 즉 'X의 각 행(측정)' 과 'w' 를 내적한 것이 그 측정의 예측입니다.
# 행이 10개라 내적이 10번 — 그걸 행렬곱 한 줄로 끝냅니다.


# ========================================================
#  PART 3 : 예측을 행렬곱으로, 손실은 MSE
# ========================================================

# ----------------------------------------
# ŷ = X·w + b - 예측 한 줄
# ----------------------------------------

# 다변수 예측의 심장입니다. D파트에서 손으로 짠 행렬곱을 numpy 의 @ 로 씁니다.
#   ŷ = X @ w + b
# X @ w 가 각 측정의 'w1·온도 + w2·압력 + w3·진동' 을 한 번에 계산하고,
# 거기에 절편 b 를 모든 측정에 똑같이 더합니다.

def 예측(X, w, b):
    return X @ w + b          # (10×3)·(3,) = (10,), 거기에 b 를 브로드캐스트로 더함

# 아무 가중치나 하나 넣어 예측이 (10,) 로 나오는지 확인해 봅니다.
w시험 = np.array([0.2, 0.8, 4.0])
b시험 = -12.0
print("시험 예측 (측정 10개):", np.round(예측(X, w시험, b시험), 2))
# → 시험 예측 (측정 10개): [ 9.2   7.76 11.84  7.   10.4  12.4   9.6  12.76  9.68  8.04]

# 손으로 한 칸 검산 (측정1): 0.2×72 + 0.8×4.5 + 4.0×0.8 - 12
#   = 14.4 + 3.6 + 3.2 - 12 = 9.2 → 위 첫 값 9.2 와 일치. (w는 아직 임의값)


# ----------------------------------------
# 손실 MSE - 얼마나 틀렸나
# ----------------------------------------

# 예측 ŷ 가 실제 y 와 얼마나 어긋났는지 한 숫자로 잽니다. 과정3과 같은 MSE.
#   L = (1/n)Σ(ŷ - y)²        ← 오차 제곱의 평균
# 특징이 늘어도 손실 공식은 그대로입니다. 예측이 벡터라 뺄셈도 벡터로 한 번에.

def 손실(X, y, w, b):
    오차 = 예측(X, w, b) - y          # 측정마다 (예측 - 실제)
    return np.mean(오차 ** 2)         # 제곱해서 평균

print("시험 가중치의 손실:", round(손실(X, y, w시험, b시험), 4))   # → 시험 가중치의 손실: 0.0099

# 이 손실을 가장 작게 만드는 w, b 를 찾는 게 목표입니다.
# 찾는 방법은 과정3 그대로 — 경사하강으로 걸어서 내려갑니다.


# ========================================================
#  PART 4 : 다변수 경사하강 - 걸음을 벡터로
# ========================================================

# ----------------------------------------
# 그래디언트 - 각 가중치마다 편미분
# ----------------------------------------

# 과정3(1변수)에서 그래디언트는 w 하나, b 하나였습니다.
#   ∂L/∂w = (2/n)Σ(ŷ-y)·x        ∂L/∂b = (2/n)Σ(ŷ-y)
# 이제 w 가 3개니, 각 가중치 wj 마다 편미분을 따로 구합니다.
#
#   ∂L/∂wj = (2/n)Σ(ŷ-y)·xj      ← j번째 특징 열(xj)을 곱해 더함
#
# w1 은 온도 열을, w2 는 압력 열을, w3 은 진동 열을 곱해서 더하는 거죠.
# 이 셋을 한 번에 쓰면 — 놀랍게도 행렬곱 한 줄이 됩니다.
#
#   ∇w = (2/n)·Xᵀ(ŷ-y)           ← Xᵀ 는 X를 눕힌 것(전치), 형상 (3,)
#         └───────────┘
#     Xᵀ 의 각 '행' = X의 한 특징 열. 그 열과 오차벡터의 내적이 곧 ∂L/∂wj.
#
# 즉 1변수 경사하강의 자연스러운 확장입니다. x 곱하던 자리가 Xᵀ 곱하기로,
# 값 하나이던 gw 가 길이 3짜리 벡터 ∇w 로 늘어났을 뿐이에요.

def 그래디언트(X, y, w, b):
    n = len(y)
    오차 = 예측(X, w, b) - y              # (ŷ - y),  형상 (n,)
    grad_w = (2 / n) * (X.T @ 오차)       # ∇w = (2/n)·Xᵀ(ŷ-y),  형상 (특징 수,)
    grad_b = (2 / n) * np.sum(오차)       # ∂L/∂b = (2/n)Σ(ŷ-y)
    return grad_w, grad_b

gw, gb = 그래디언트(X, y, w시험, b시험)
print("∇w (세 가중치의 기울기):", np.round(gw, 4))   # → ∇w (세 가중치의 기울기): [-5.832  -0.3888 -0.0718]
print("∂L/∂b:", round(gb, 4))                        # → ∂L/∂b: -0.084


# ----------------------------------------
# 표준화 없이 그냥 걸어 보면? - 발산 미리보기
# ----------------------------------------

# 여기서 한 번 함정에 빠져 봅니다. 표준화 없이 원래 X 로 바로 걸어 볼게요.
# 온도(수십)와 진동(소수)의 범위가 크게 다른데, 이게 문제를 일으킵니다.

def 원시_경사하강(X, y, lr, epochs):
    w = np.zeros(X.shape[1])              # 특징 수만큼 0으로 출발
    b = 0.0
    for _ in range(epochs):
        gw, gb = 그래디언트(X, y, w, b)
        w = w - lr * gw
        b = b - lr * gb
    return 손실(X, y, w, b)

print("\n[표준화 없이 원래 X 로 경사하강]")
# 일부러 발산시키는 데모라 오버플로우 경고가 뜹니다. 경고만 잠시 끄고 봅니다.
with np.errstate(over="ignore", invalid="ignore"):
    L원시 = 원시_경사하강(X, y, lr=0.001, epochs=200)
print("  lr=0.001, 200 epoch 후 손실:", L원시)   # → lr=0.001, 200 epoch 후 손실: inf

# 손실이 inf(무한대) — 발산했습니다. 왜일까요? 다음 단락이 그 이유입니다.


# ========================================================
#  PART 5 : 특징 스케일 문제 - 표준화 필수
# ========================================================

# ----------------------------------------
# 범위가 다르면 걸음이 휘청인다
# ----------------------------------------

# 세 특징의 범위를 나란히 보면 문제가 보입니다.
print("\n[특징별 범위]")
for 이름, 열 in zip(["온도", "압력", "진동"], X.T):
    print(f"  {이름}: {열.min():.2f} ~ {열.max():.2f}")
# → [특징별 범위]
# →   온도: 65.00 ~ 85.00
# →   압력: 3.50 ~ 5.80
# →   진동: 0.50 ~ 1.30

# 온도는 수십, 진동은 소수입니다. 그래디언트 ∇w=(2/n)Xᵀ(ŷ-y) 에서
# 온도 열의 값이 크니 온도 쪽 기울기만 유독 커집니다.
# 그럼 모든 가중치에 같은 lr 을 곱해 걷는데, 온도 방향으로만 훌쩍 넘어가
# 골짜기를 건너뛰고 튕겨 나갑니다 → 발산(nan). 과정3의 그 발산이 재현된 거죠.
#
# 해결은 과정2에서 배운 표준화입니다. 모든 특징을 '평균 0, 퍼짐 1' 로 맞춰
# 눈금을 통일하면, 어느 방향이든 걸음 크기가 비슷해져 안정적으로 내려갑니다.
#   z = (x - x평균) / x표준편차       (열마다 따로 적용)

# ----------------------------------------
# 표준화 - 열마다 평균 0, 퍼짐 1
# ----------------------------------------

# 각 특징 열의 평균과 표준편차를 구해 빼고 나눕니다. axis=0 = 열 방향(과정9).

def 표준화(X):
    mu = X.mean(axis=0)          # 열별 평균 (3,)
    sd = X.std(axis=0)           # 열별 표준편차 (3,)
    Z = (X - mu) / sd            # 브로드캐스트로 열마다 표준화
    return Z, mu, sd             # 되돌릴 때 쓰려고 mu, sd 도 반환

Z, mu, sd = 표준화(X)
print("\n표준화 후 열별 평균:", np.round(Z.mean(axis=0), 4))   # → 표준화 후 열별 평균: [ 0.  0. -0.]
print("표준화 후 열별 표준편차:", np.round(Z.std(axis=0), 4))  # → 표준화 후 열별 표준편차: [1. 1. 1.]
# 세 특징 모두 평균 0, 퍼짐 1 로 눈금이 통일됐습니다. 이제 안정적으로 걸을 수 있어요.


# ----------------------------------------
# fit - 표준화 공간에서 걸어 찾기
# ----------------------------------------

# 과정3의 fit 을 다변수로 넓힙니다. 하는 일은 그대로예요.
#   1) X 를 표준화(Z)해서 눈금 통일
#   2) w(길이 3), b(하나) 를 0에서 출발
#   3) epochs 번 반복하며 ∇w, ∂L/∂b 로 조금씩 갱신
#   4) 마지막에 z 공간의 (w, b) 를 원래 x 눈금으로 되돌림

def fit(X, y, lr=0.1, epochs=3000, 로그=False):
    Z, mu, sd = 표준화(X)
    w = np.zeros(X.shape[1])              # 특징 수만큼 0
    b = 0.0
    for epoch in range(epochs):
        gw, gb = 그래디언트(Z, y, w, b)   # z 공간에서의 내리막 방향
        w = w - lr * gw                   # w ← w - lr·∇w  (벡터째 갱신)
        b = b - lr * gb
        if 로그 and epoch % 600 == 0:
            print(f"  epoch {epoch:5d}   손실 {손실(Z, y, w, b):.4f}")
    if 로그:
        print(f"  epoch {epochs:5d}   손실 {손실(Z, y, w, b):.4f}")

    # z 공간의 (w, b) 를 원래 x 눈금으로 되돌린다. (과정3의 1변수 복원을 벡터로)
    #   ŷ = Σ wj·(xj - muj)/sdj + b = Σ (wj/sdj)·xj + (b - Σ wj·muj/sdj)
    w실제 = w / sd
    b실제 = b - np.sum(w * mu / sd)
    return w실제, b실제, w         # w(표준화 공간)도 반환 — PART 6 해석에 씀

print("\n[다변수 경사하강 학습 로그 · 표준화 후]")
w_gd, b_gd, w_std = fit(X, y, lr=0.1, epochs=3000, 로그=True)
# → [다변수 경사하강 학습 로그 · 표준화 후]
# →   epoch     0   손실 64.3542
