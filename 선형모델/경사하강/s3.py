# ----------------------------------------
# [실습] 가동시간으로 진동 예측하기
# ----------------------------------------

# 오늘 만든 fit / predict / R² 를 그대로 써서 새 데이터에 직선을 맞춰 보세요.
#
#   케이스 A : 가동시간(x)으로 진동(y) 예측   ← 아래 정답 예시
#   케이스 B : 압력(x)으로 불량(y) 예측       ← 직접 데이터 만들어 해보기
#
#   Step 1) w, b = fit(x, y, lr=0.1, epochs=3000)   경사하강으로 학습
#   Step 2) w, b 출력 — 기울기·절편 확인
#   Step 3) predict(새값, w, b) 으로 안 겪은 x 예측
#   Step 4) R2(x, y, w, b) 로 설명력 확인 (1에 가까울수록 좋음)
#   Step 5) sklearn LinearRegression 과 w, b 가 근접하는지 대조
#
#   완료 기준 : w·b·예측·R² 가 화면에 나오고, sklearn 과 소수 3자리 근접하면 성공.

# (실습 정답 예시 — 케이스 A 가동시간 → 진동)
가동시간 = [10, 20, 30, 40, 50, 60, 70, 80]
진동     = [0.5, 0.7, 0.9, 1.0, 1.3, 1.4, 1.6, 1.8]

w실습, b실습 = fit(가동시간, 진동, lr=0.1, epochs=3000)
print("\n[실습 예시 · 가동시간 → 진동]")
print("  경사하강  w:", round(w실습, 4), "/ b:", round(b실습, 4))
print("  가동 55시간 예측 진동:", round(predict(55, w실습, b실습), 4))
print("  R²:", round(R2(가동시간, 진동, w실습, b실습), 4))

X실습 = np.array(가동시간).reshape(-1, 1)
sk실습 = LinearRegression().fit(X실습, 진동)
print("  sklearn   w:", round(sk실습.coef_[0], 4), "/ b:", round(sk실습.intercept_, 4))
# → [실습 예시 · 가동시간 → 진동]
# →   경사하강  w: 0.0183 / b: 0.325
# →   가동 55시간 예측 진동: 1.3333
# →   R²: 0.9941
# →   sklearn   w: 0.0183 / b: 0.325

# 경사하강이 낸 w(0.0183)·b(0.325) 가 sklearn 과 소수점까지 같습니다.
# 여기서도 '걸어서 도착 = 공식 도착'. 3부작을 관통한 하나의 결론이죠.


# ----------------------------------------
# 3부작 마무리 - 오늘 손에 넣은 것
# ----------------------------------------

#   [경사하강 3부작 한 줄 정리]
#     1편  손실과 그래디언트  → 어느 쪽이 내리막인지 재는 법
#     2편  한 스텝           → 그 방향으로 딱 한 걸음 갱신
#     3편  반복(오늘)        → 한 걸음을 수백 번, 걸어서 바닥에 도착
#
#   [오늘의 fit 3줄 요약]
#     w, b = 0 에서 출발
#     epochs 번:  그래디언트 구해  w ← w - lr·∂L/∂w,  b ← b - lr·∂L/∂b
#     손실이 안 줄면 = 바닥 = 완성
#
#   [기억할 것]
#     · 한 스텝은 조금, 반복하면 바닥에 닿는다
#     · lr 너무 크면 발산 / 너무 작으면 굼벵이 — 실험으로 고른다
#     · 걸어서 찾은 답 ≈ 최소제곱 공식 ≈ sklearn (같은 골짜기 바닥)
#     · 공식이 없거나 비싼 문제(신경망 등)에선 경사하강만이 통한다
#     · 이 걸음이 과정4 신경망 학습(역전파)의 원형이다
