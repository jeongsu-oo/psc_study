"""[한 걸음으로는 못 내려가는데, 그럼 어떻게 바닥에 닿나요?]
경사하강 3부작의 마지막, 클라이맥스입니다.

1편에서 '기울기(그래디언트)가 손실이 가장 빨리 주는 방향' 임을 봤고,
2편에서 그 방향으로 딱 '한 스텝' 내려가는 계산을 손으로 짰습니다.
   w ← w - lr·(∂L/∂w)      한 번 갱신하면 손실이 조금 준다

그런데 한 스텝은 조금 내려갈 뿐입니다. 산 중턱에서 한 발짝 뗀 셈이죠.
오늘 할 일은 단순합니다 — 그 한 스텝을 for 루프로 감싸 수백 번 반복합니다.
한 발 한 발 내려가다 보면 결국 골짜기 바닥(손실 최소)에 닿습니다.
그 바닥의 w, b 가 바로 '가장 잘 맞는 직선' 입니다.

오늘의 성취 하나를 미리 말해 둡니다.
걸어서 도착한 그 w, b 가 —
  · D파트에서 공식으로 단번에 구한 최소제곱 값(w=0.5, b=-7.2) 과
  · 세계 표준 도구 sklearn 값 과
소수점까지 똑같습니다. '빙 둘러 걸어왔지만 같은 곳에 도착' 하는 거죠.

그런데 답이 딱 떨어지는 공식이 이미 있는데, 왜 굳이 걸어서 갈까요?
그 답이 오늘의 진짜 이유입니다. 맨 끝에서 만납니다.

이 파일은 전환 → 반복 루프 → fit 완성 → lr 실험 → 언제 멈추나 →
삼중 대조 → 왜 경사하강 → 실습 순으로 위에서 아래로 쌓아 갑니다.
"""

# 맨 끝에서 '우리가 걸어서 찾은 게 진짜 맞는지' 채점할 때만 씁니다.
# 그전까지는 전부 순수 파이썬입니다.
import math
import numpy as np


# ========================================================
#  PART 1 : 전환 - 한 스텝을 '반복' 하면 바닥에 닿는다
# ========================================================

# ----------------------------------------
# 2편에서 만든 도구들 다시 챙기기
# ----------------------------------------

# 오늘은 2편의 '한 스텝' 을 재료로 씁니다. 그 재료부터 다시 손에 쥡니다.
# 세 가지예요 — 예측, 손실(MSE), 그래디언트.
#
#   예측 :  ŷ = w·x + b
#   손실 :  L = (1/n)Σ(y - ŷ)²                ← MSE, 오차 제곱의 평균
#   그래디언트(2편 결론) :
#           ∂L/∂w = -(2/n)Σ x(y - ŷ)          ← w 를 어느 쪽으로 움직일까
#           ∂L/∂b = -(2/n)Σ (y - ŷ)           ← b 를 어느 쪽으로 움직일까

def 평균(xs):
    return sum(xs) / len(xs)                  # Σx / n

def 예측하기(xs, w, b):
    return [w * x + b for x in xs]            # 각 x 마다 ŷ = w·x + b

def 손실(xs, ys, w, b):
    n = len(xs)
    preds = 예측하기(xs, w, b)
    return sum((y - p) ** 2 for y, p in zip(ys, preds)) / n   # (1/n)Σ(y-ŷ)²

def 그래디언트(xs, ys, w, b):
    n = len(xs)
    preds = 예측하기(xs, w, b)
    gw = -(2 / n) * sum(x * (y - p) for x, y, p in zip(xs, ys, preds))  # ∂L/∂w
    gb = -(2 / n) * sum((y - p) for y, p in zip(ys, preds))            # ∂L/∂b
    return gw, gb

# 여기까지는 2편에서 이미 만든 것과 똑같습니다. 오늘의 새 재료가 아니에요.


# ----------------------------------------
# 한 스텝은 '조금' 내려간다 - 눈으로 확인
# ----------------------------------------

# 2편의 한 스텝(w, b 를 한 번 갱신)을 하면 손실이 정말 주는지 봅니다.
# 작은 데이터로 딱 한 번만 갱신해 보죠.

x맛보기 = [1, 2, 3, 4, 5]
y맛보기 = [2, 4, 5, 4, 5]

w, b = 0.0, 0.0                               # 아무 데서나 출발 (여기선 0)
print("[한 스텝 맛보기]")
print("  출발 손실:", round(손실(x맛보기, y맛보기, w, b), 4))   # → 출발 손실: 17.2

lr = 0.01                                     # 학습률 (한 걸음 크기)
gw, gb = 그래디언트(x맛보기, y맛보기, w, b)
w = w - lr * gw                               # w ← w - lr·∂L/∂w
b = b - lr * gb                               # b ← b - lr·∂L/∂b
print("  한 스텝 후 손실:", round(손실(x맛보기, y맛보기, w, b), 4))  # → 한 스텝 후 손실: 10.4902

# 17.2 → 10.49. 딱 한 걸음 뗐는데 손실이 뚝 줄었습니다.
# '조금' 이 핵심이에요. 한 번에 바닥까지 못 갑니다. 조금 내려갔을 뿐이죠.
#
#   손실
#    ↑  \
#    |   \ ●  ← 출발 (17.2)
#    |    \●  ← 한 스텝 (10.5)   한 걸음에 요만큼 내려감
#    |     \___
#    |         \_____●  ← 바닥 (여기까지 가려면?)
#    +-------------------→  w, b
#
# 그럼 바닥까지 가려면? 답은 뻔합니다. 이 한 걸음을 계속 반복하면 됩니다.


# ----------------------------------------
# 반복 = for 루프로 감싸기
# ----------------------------------------

# 한 스텝을 여러 번 반복하는 건 for 루프 하나면 됩니다.
# '반복 한 번' 을 epoch(에폭) 이라 부릅니다. 전체 데이터를 한 번 보고
# w, b 를 한 번 갱신하는 것 = 1 epoch.

w, b = 0.0, 0.0
for epoch in range(50):                       # 같은 한 스텝을 50번
    gw, gb = 그래디언트(x맛보기, y맛보기, w, b)
    w = w - lr * gw
    b = b - lr * gb
print("  50번 반복 후 손실:", round(손실(x맛보기, y맛보기, w, b), 4))  # → 50번 반복 후 손실: 0.9429

# 17.2 → 10.5 → ... → 0.94. 반복할수록 손실이 계속 줍니다.
# 바로 이겁니다. 한 스텝은 조금, 하지만 수십·수백 번 반복하면 바닥에 닿아요.
# 이 for 루프를 함수로 깔끔하게 묶은 게 다음의 fit 입니다.


# ========================================================
#  PART 2 : fit 완성 - 데이터를 보고 걸어서 w, b 찾기
# ========================================================

# ----------------------------------------
# 표준화 - 걸음을 안정시키는 준비
# ----------------------------------------

# 잠깐 준비물 하나. 온도는 20~38 처럼 큰 값이고 불량은 3~12 입니다.
# x 값이 크면 그래디언트도 커져서, 조금만 걸어도 휘청거려 발산하기 쉽습니다.
# 그래서 x 를 '평균 0, 퍼짐 1' 로 재는 눈금을 바꿔 줍니다 = 표준화.
#
#   z = (x - x평균) / x표준편차      (1편에서 만든 그 표준화 그대로)
#
# 표준화하면 걸음이 안정돼서 같은 lr 로도 훨씬 잘 수렴합니다.
# 나중에 z 로 찾은 직선을 원래 x 눈금으로 되돌리기만 하면 됩니다.

def 표준화(xs):
    m = 평균(xs)
    s = (sum((x - m) ** 2 for x in xs) / len(xs)) ** 0.5   # 표준편차
    zs = [(x - m) / s for x in xs]
    return zs, m, s                           # 되돌릴 때 쓰려고 m, s 도 반환


# ----------------------------------------
# fit(xs, ys, lr, epochs) - 경사하강 본체
# ----------------------------------------

# 드디어 경사하강 함수 본체입니다. 하는 일은 이게 전부예요.
#   1) w, b 를 0 에서 시작 (아무 값이나 상관없음)
#   2) epochs 번 반복하며 매번 그래디언트 구해 w, b 를 조금씩 갱신
#   3) 몇 epoch마다 손실을 print 해서 '점점 주는 것' 을 눈으로 확인
# x 는 표준화해서 z 공간에서 걷고, 마지막에 원래 눈금으로 되돌립니다.

def fit(xs, ys, lr=0.1, epochs=2000, 로그=False):
    zs, m, s = 표준화(xs)                     # z 눈금으로 갈아타고
    w, b = 0.0, 0.0                           # 아무 데서나 출발

    for epoch in range(epochs):
        gw, gb = 그래디언트(zs, ys, w, b)     # 지금 위치의 내리막 방향
        w = w - lr * gw                       # w ← w - lr·∂L/∂w
        b = b - lr * gb                       # b ← b - lr·∂L/∂b
        if 로그 and epoch % 400 == 0:         # 400 epoch마다 손실 찍기
            print(f"  epoch {epoch:5d}   손실 {손실(zs, ys, w, b):.4f}")

    if 로그:
        print(f"  epoch {epochs:5d}   손실 {손실(zs, ys, w, b):.4f}")

    # z 공간에서 찾은 (w, b) 를 원래 x 눈금으로 되돌린다.
    #   ŷ = w·z + b = w·(x - m)/s + b = (w/s)·x + (b - w·m/s)
    w실제 = w / s
    b실제 = b - w * m / s
    return w실제, b실제


# ----------------------------------------
# predict / R² - 찾은 직선 쓰기
# ----------------------------------------

# fit 이 정한 w, b 로 새 x 의 y 를 예측하고, 얼마나 잘 맞나 점수(R²)를 냅니다.
# D파트에서 만든 것과 똑같은 식입니다. 재활용이에요.

def predict(x, w, b):
    return w * x + b                          # ŷ = w·x + b

def R2(xs, ys, w, b):
    ȳ = 평균(ys)
    preds = 예측하기(xs, w, b)
    SSE = sum((y - p) ** 2 for y, p in zip(ys, preds))   # 직선이 못 맞힌 오차
    SST = sum((y - ȳ) ** 2 for y in ys)                  # 평균으로 찍기의 오차
    return 1 - SSE / SST                       # 1에 가까울수록 잘 맞음


# ----------------------------------------
# 제조 데이터로 fit - 손실이 주는 걸 눈으로
# ----------------------------------------

# D파트에서 쓴 그 온도-불량 데이터 그대로입니다. (외부 파일 없이 인라인)
# 온도가 오를수록 불량이 느는 흐름. 공식으로는 w=0.5, b=-7.2 가 나왔었죠.
# 오늘은 경사하강으로 '걸어서' 같은 값에 닿는지 봅니다.

온도 = [20, 22, 24, 26, 28, 30, 32, 34, 36, 38]
불량 = [ 3,  4,  5,  5,  7,  8,  8, 10, 11, 12]

print("\n[제조 데이터 경사하강 학습 로그]")
w, b = fit(온도, 불량, lr=0.1, epochs=2000, 로그=True)
# → [제조 데이터 경사하강 학습 로그]
# →   epoch     0   손실 39.5456
# →   epoch   400   손실 0.1600
# →   epoch   800   손실 0.1600
# →   epoch  1200   손실 0.1600
# →   epoch  1600   손실 0.1600
# →   epoch  2000   손실 0.1600

# 손실이 39.5 에서 시작해 0.16 까지 뚝 떨어지고, 그 뒤로는 안 변합니다.
# 바닥에 닿았다는 뜻이죠. 걸어 내려온 과정을 곡선으로 그리면:
#
#   손실
#    40 |●
#       | \
#    30 |  \
#    20 |   \
#    10 |    \
#     0 |     ●●●●●●●●●●●●●●●●●●●●●●●●   ← 금세 바닥에 붙어 평평
#       +----------------------------→ epoch
#        0   400  800  1200  1600  2000
#
# 초반 몇백 걸음에 확 내려가고, 그 뒤엔 바닥이라 더 안 내려갑니다.

print("경사하강 결과 → w:", round(w, 4), "/ b:", round(b, 4))   # → 경사하강 결과 → w: 0.5 / b: -7.2

# w=0.5, b=-7.2. D파트 공식값과 벌써 똑같습니다! 걸어서 도착했어요.


# ----------------------------------------
# predict / R² 확인
# ----------------------------------------

print("  35도 예측 불량:", round(predict(35, w, b), 4))   # → 35도 예측 불량: 10.3
print("  40도 예측 불량:", round(predict(40, w, b), 4))   # → 40도 예측 불량: 12.8
print("  R² (설명력):", round(R2(온도, 불량, w, b), 4))   # → R² (설명력): 0.981

# 35도는 데이터에 없던 값인데 "약 10.3개" 라고 답합니다.
# R²≈0.98 → 불량이 흩어진 정도의 98%를 이 직선이 설명. 믿고 예측해도 되는 수준.


# ========================================================
#  PART 3 : 학습률(lr) 실험 - 걸음 크기의 감 잡기
# ========================================================

# ----------------------------------------
# lr 이 뭐길래 - 걸음의 보폭
# ----------------------------------------

# lr(learning rate, 학습률)은 '한 걸음을 얼마나 크게 뗄까' 입니다.
#   w ← w - lr·∂L/∂w   에서 lr 이 클수록 한 번에 많이 움직여요.
#
#   너무 작으면 :  보폭이 좁아 굼벵이. 바닥까지 한참 걸림
#   적당하면   :  성큼성큼 잘 내려가 금세 바닥
#   너무 크면   :  한 걸음이 골짜기를 훌쩍 넘어가 반대편 벽으로.
#                 왔다갔다 튕기다 손실이 오히려 커짐 = 발산
#
#   너무 큰 lr →   손실
#                   ↑    ●       ●         ← 골짜기를 건너뛰며
#                   |   / \     / \          점점 위로 튕겨나감
#                   |  ●   \   /   ●
#                   | /     \ /
#                   |●       ●
#                   +--------------→ w

# 세 가지 lr 로 같은 데이터를 200 epoch 씩 돌려 최종 손실을 비교합니다.
# (여기선 발산이 보이게, 표준화한 z 공간의 손실을 그대로 재서 찍습니다.)

def 손실만_구하기(xs, ys, lr, epochs):
    zs, m, s = 표준화(xs)
    w, b = 0.0, 0.0
    for _ in range(epochs):
        gw, gb = 그래디언트(zs, ys, w, b)
        w = w - lr * gw
        b = b - lr * gb
    return 손실(zs, ys, w, b)

print("\n[학습률 실험 · 200 epoch 후 손실]")
for lr시험 in [0.001, 0.1, 1.05]:
    L = 손실만_구하기(온도, 불량, lr시험, 200)
    if math.isnan(L) or L > 1e6:
        판정 = "발산! (걸음이 너무 커 튕겨나감)"      # ← 의도된 발산 데모
    elif L > 1:
        판정 = "굼벵이 (아직 한참 남음)"
    else:
        판정 = "좋음 (거의 바닥)"
    print(f"  lr={lr시험:<6} → 손실 {L:.4f}   {판정}")
# → [학습률 실험 · 200 epoch 후 손실]
# →   lr=0.001  → 손실 27.7896   굼벵이 (아직 한참 남음)
# →   lr=0.1    → 손실 0.1600   좋음 (거의 바닥)
# →   lr=1.05   → 손실 2219379423254027520.0000   발산! (걸음이 너무 커 튕겨나감)

# lr=0.001 : 보폭이 좁아 200걸음 걸어도 손실이 27.8. 굼벵이입니다.
# lr=0.1   : 200걸음이면 이미 바닥(0.16). 딱 좋아요.
# lr=1.05  : 손실이 천문학적 숫자로 폭발. 골짜기를 건너뛰다 발산했습니다.
#            (이 발산은 lr 을 일부러 크게 준 의도된 데모입니다.)
#
# 감 : lr 은 발산 안 하는 선에서 되도록 크게. 보통 0.001~0.1 부근에서
#      몇 개 넣어 보고 손실이 잘 주는 걸 고릅니다. 정답 공식은 없어요, 실험입니다.


# ========================================================
#  PART 4 : 반복 횟수(epochs) - 언제 멈추나
# ========================================================

# ----------------------------------------
# 손실이 거의 안 변하면 = 바닥 = 그만
# ----------------------------------------

# "몇 번 반복해야 하나?" 답 : 손실이 더 안 줄 때까지.
# 바닥에 닿으면 아무리 더 걸어도 손실이 제자리입니다. 그때가 멈출 때죠.
# 초반엔 확 줄다가 어느 순간부터 변화가 미미해지는 걸 눈으로 봅시다.

print("\n[반복 횟수별 손실 변화 · lr=0.1, z 공간]")
zs, _, _ = 표준화(온도)
w, b = 0.0, 0.0
이전손실 = None
for epoch in range(301):
    if epoch in (0, 10, 30, 60, 100, 200, 300):
        L = 손실(zs, 불량, w, b)
        변화 = "" if 이전손실 is None else f"  (직전 확인 대비 {이전손실 - L:+.4f})"
        print(f"  epoch {epoch:4d}   손실 {L:8.4f}{변화}")
        이전손실 = L
    gw, gb = 그래디언트(zs, 불량, w, b)
    w = w - 0.1 * gw          # lr 은 여기서 0.1 로 명시 (앞 실험 루프 변수와 무관)
    b = b - 0.1 * gb
# → [반복 횟수별 손실 변화 · lr=0.1, z 공간]
# →   epoch    0   손실  61.7000
# →   epoch   10   손실   0.8695  (직전 확인 대비 +60.8305)
# →   epoch   30   손실   0.1601  (직전 확인 대비 +0.7094)
# →   epoch   60   손실   0.1600  (직전 확인 대비 +0.0001)
# →   epoch  100   손실   0.1600  (직전 확인 대비 +0.0000)
# →   epoch  200   손실   0.1600  (직전 확인 대비 +0.0000)
# →   epoch  300   손실   0.1600  (직전 확인 대비 +0.0000)

# 처음 10걸음에 61.7 → 0.87 로 확 줍니다. 30걸음이면 0.16 으로 거의 바닥.
# 60걸음부터는 변화가 +0.0001, 그 뒤론 0.0000 — 사실상 안 변합니다.
# 이게 '수렴' 입니다. 손실 변화가 미미해지면 그만 걸어도 됩니다.
# 실무에선 '변화가 어떤 값보다 작으면 멈추기(early stopping)' 를 넣지만,
# 오늘은 넉넉히 2000번 돌려 확실히 바닥에 붙였습니다.


# ========================================================
#  PART 5 : 삼중 대조 - 걸어온 값 ≈ 공식값 ≈ sklearn
# ========================================================

# ----------------------------------------
# 세 길이 같은 곳에서 만난다
# ----------------------------------------

# 오늘의 클라이맥스입니다. 세 가지 방법으로 같은 데이터의 w, b 를 구합니다.
#   ① 경사하강   : 아무 값에서 출발해 조금씩 걸어서 (오늘)
#   ② 최소제곱   : 공식에 값 넣어 단번에 (D파트, w=0.5·b=-7.2)
#   ③ sklearn    : 세계 표준 도구
# 셋이 소수점까지 같으면 — '빙 둘러 걸어왔지만 같은 곳에 도착' 한 겁니다.

# ① 경사하강 (다시 확실히)
w_gd, b_gd = fit(온도, 불량, lr=0.1, epochs=2000)

# ② 최소제곱 공식 (D파트 그대로 — 여기서 직접 계산)
x̄, ȳ = 평균(온도), 평균(불량)
w_공식 = sum((x - x̄) * (y - ȳ) for x, y in zip(온도, 불량)) / sum((x - x̄) ** 2 for x in 온도)
b_공식 = ȳ - w_공식 * x̄

# ③ sklearn
from sklearn.linear_model import LinearRegression
X = np.array(온도).reshape(-1, 1)             # sklearn 은 x 를 세로 표로 받음
sk = LinearRegression().fit(X, 불량)

print("\n[삼중 대조]")
print(f"  ① 경사하강  w: {w_gd:.4f}   b: {b_gd:.4f}")   # → ① 경사하강  w: 0.5000   b: -7.2000
print(f"  ② 최소제곱  w: {w_공식:.4f}   b: {b_공식:.4f}")  # → ② 최소제곱  w: 0.5000   b: -7.2000
print(f"  ③ sklearn   w: {sk.coef_[0]:.4f}   b: {sk.intercept_:.4f}")  # → ③ sklearn   w: 0.5000   b: -7.2000

# 소수 3자리까지 근접하는지 자동 채점 (경사하강은 근사라 완전 일치는 아님)
w근접 = abs(w_gd - w_공식) < 1e-3 and abs(w_gd - sk.coef_[0]) < 1e-3
b근접 = abs(b_gd - b_공식) < 1e-3 and abs(b_gd - sk.intercept_) < 1e-3
print("  세 값 소수 3자리까지 근접?  w:", w근접, "/ b:", b근접)
# → 세 값 소수 3자리까지 근접?  w: True / b: True

# 전부 True. 세 방법이 완전히 다른 길인데 도착점이 같습니다.
#   공식은 지도 보고 직선으로 순간이동, 경사하강은 두 발로 걸어서.
#   길은 달라도 골짜기 바닥은 하나뿐이니 같은 곳에 닿는 게 당연하죠.
# 도구 안(sklearn)에서 벌어지는 일을, 오늘 우리가 손으로 걸어서 재현했습니다.


# ========================================================
#  PART 6 : 왜 굳이 경사하강? - 오늘의 진짜 이유
# ========================================================

# ----------------------------------------
# 공식이 답을 주는데 왜 걸어서 가나
# ----------------------------------------

# 여기서 당연한 의문. "①공식이 단번에 정답을 주는데, 왜 ②경사하강을
# 배웠지? 느리게 걸어가는 게 무슨 소용이야?"
#
# 이유는 이겁니다 — 공식이 통하는 건 오늘 같은 '착한' 문제뿐이에요.
#
#  (1) 변수가 많아지면 공식이 비싸진다.
#      온도 하나면 공식이 딱 떨어지지만, 온도·습도·압력·가동시간…
#      입력이 수백·수천 개면 공식은 거대한 '역행렬' 을 구해야 합니다.
#      그 계산이 변수 수의 세제곱에 비례해 폭발적으로 비싸져요.
#      경사하강은 그냥 걷기라, 변수가 많아도 한 걸음씩 감당됩니다.
#
#  (2) 아예 공식이 없는 문제가 대부분이다.
#      로지스틱 회귀(합격/불량 확률), 신경망 같은 문제는
#      손실이 오늘처럼 예쁜 그릇 모양이 아니라 울퉁불퉁합니다.
#      "정답을 딱 주는 공식" 자체가 존재하지 않아요.
#      이런 문제엔 오직 경사하강 — '걸어서 내려가기' 만이 통합니다.
#
# 그래서 오늘 착한 문제로 경사하강을 연습한 겁니다.
# 답을 아는 문제(w=0.5)로 '걷는 법' 을 몸에 익혀 두면,
# 답을 모르는 문제에서도 같은 걸음으로 찾아갈 수 있으니까요.

# ----------------------------------------
# 다음 예고 - 신경망도 결국 이 걸음이다
# ----------------------------------------

# 과정4에서 만날 MLP(신경망)의 '역전파' 라는 학습법이 있습니다.
# 이름은 거창하지만 심장은 오늘과 똑같아요 —
#   손실을 재고 → 그래디언트(내리막 방향)를 구해 → 조금씩 걷는다.
# 층이 여러 개라 그래디언트를 뒤에서 앞으로 '되짚어(역전파)' 구할 뿐,
# w ← w - lr·∂L/∂w 라는 오늘의 갱신식은 그대로입니다.
#
# 즉 오늘 두 발로 걸어 골짜기를 내려온 이 경험이,
# 신경망을 학습시키는 그 걸음의 원형입니다. 3부작을 끝낸 지금,
# 여러분은 이미 딥러닝 학습의 심장을 손으로 만들어 본 겁니다.


