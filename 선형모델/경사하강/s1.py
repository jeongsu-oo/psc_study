# ----------------------------------------
# 시작 w 를 0.7 로 바꿔 똑같이 한 발
# ----------------------------------------

# 이번엔 정답 0.5 의 '오른쪽' 비탈, w=0.7 에서 출발해 봅시다.
# 방향이 반대로 나와야 맞겠죠? 직접 재서 확인합니다.
#
#   Step 1) 기울기(0.7) 을 재서 부호를 본다 (양수? 음수?)
#   Step 2) 새w = 0.7 - lr · 기울기  로 한 발 옮긴다
#   Step 3) 손실이 이전보다 줄었는지 확인한다
#
# 완료 기준 : 기울기가 양수로 나오고, w 가 '작아지는' 쪽으로 움직이고,
#            손실이 줄면 성공. (0.7 은 바닥의 오른쪽이니 왼쪽으로 가야 맞음)

시작w = 0.7
g2 = 기울기(시작w)
새w2 = 시작w - lr * g2

print("[실습 · w=0.7 에서 한 발]")
print("  기울기:", round(g2, 4))              # → 기울기: 349.6
print("  현재 w:", 시작w, "→ 새 w:", round(새w2, 6))   # → 현재 w: 0.7 → 새 w: 0.59512
print("  손실  이전 (w=0.7    ):", round(손실(시작w), 4))   # → 손실  이전 (w=0.7    ): 35.12
print("  손실  이후 (w=0.59512):", round(손실(새w2), 4))    # → 손실  이후 (w=0.59512): 8.0678

# 이번엔 기울기가 +349.6 양수라, '빼기'가 w 를 줄였습니다: 0.7 → 0.59512.
# 정답 0.5 를 향해 이번엔 왼쪽으로 다가갔죠. 손실도 35.12 → 8.07 로 감소.
#
# 어느 쪽 비탈에서 출발하든, 기울기의 부호가 알아서 방향을 정해 주고
# '기울기 반대로 한 발'이라는 같은 규칙이 우리를 바닥으로 데려갑니다.
# 왼쪽에서 시작하면 오른쪽으로, 오른쪽에서 시작하면 왼쪽으로. 늘 바닥 쪽.


