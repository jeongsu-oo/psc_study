#   방향 찾기   |  좌우로 밟아보기 → 낮은 쪽       |  손실(w+h) vs 손실(w-h)
#   기울기      |  변화의 방향·가파름을 한 숫자로   |  (L(w+h)-L(w-h))/(2h)
#   부호 읽기   |  음수→키움, 양수→줄임, 0→도착    |  기울기(w) 의 부호
#   한 발       |  기울기 반대로 학습률만큼 이동    |  새w = w - lr·기울기
