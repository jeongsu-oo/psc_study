"""[손잡이가 두 개면 어느 쪽을 얼마나 돌려야 하나요?]
경사하강 3부작의 2편입니다.

1편에서는 절편 b 를 고정해 두고 기울기 w '하나만' 움직였습니다.
밥그릇(손실 곡선)의 바닥으로 굴러 내려가는 데 손잡이가 하나뿐이었죠.
w 를 조금 키우면 손실이 어떻게 변하나 — 그 기울기 하나만 보면 됐습니다.

그런데 진짜 직선은 w 와 b '둘 다' 있습니다.
   y = w·x + b
그러니 손실도 사실은 w 하나가 아니라 w 와 b '둘'에 따라 달라져요.
손잡이가 두 개인 셈입니다. 오늘은 이 두 손잡이를 다룹니다.

  1) 손실은 L(w, b) — w 와 b 둘의 함수 (밥그릇이 2차원 바닥에 놓임)
  2) 편미분 — 나머지는 고정하고 손잡이 하나만 살짝 돌려 본 기울기
  3) 그 둘을 묶은 게 그래디언트 = (∂L/∂w, ∂L/∂b)
  4) 수치미분으로 먼저 재고 → 해석적 공식과 대조 (공식이 맞다는 증거)
  5) 한 스텝 동시 갱신 → 손실이 실제로 줄어드는지 확인

전부 순수 파이썬입니다. 개념 → 손계산 → 코드 → 검증 순으로 위에서
아래로 쌓아 갑니다. 어렵게 생각하지 마세요. '각 손잡이별 기울기' 입니다.
"""


# ========================================================
#  PART 1 : 손실은 w'만'이 아니라 w 와 b 둘의 함수다
# ========================================================

# ----------------------------------------
# 1편 복습 - 손잡이가 하나였던 밥그릇
# ----------------------------------------

# 1편의 그림을 떠올려 봅시다. b 를 못 박아 두고 w 만 바꿨죠.
# 가로축이 w, 세로축이 손실 L 인 'U자 밥그릇' 하나가 있었습니다.
#
#   손실 L
#    |  \                 /
#    |    \             /
#    |      \_________/        ← 바닥이 가장 잘 맞는 w
#    +---------------------- w
#
# 손잡이(w)를 왼쪽 오른쪽으로 돌려 가며 바닥을 찾았습니다.
# 그런데 이건 반쪽짜리였어요. b 를 고정했으니까요.


# ----------------------------------------
# 진짜 밥그릇은 2차원 바닥에 놓여 있다
# ----------------------------------------

# 직선은 y = w·x + b 라 정하는 숫자가 '두 개'(w, b)입니다.
# 그러니 손실도 두 숫자에 따라 달라지는 L(w, b) 예요.
# 밥그릇이 이제 (w, b) 두 방향으로 펼쳐진 바닥 위에 놓입니다.
#
#            L (손실, 높이)
#             |        ___
#             |      /     \          그릇 자체가
#             |    /  \___/  \        w 방향으로도,
#             |   |   바닥    |       b 방향으로도
#             |    \  (최소)  /       패인 3차원 그릇
#             |      \______/
#             |_______________________
#            /  b 방향        \  w 방향
#
# 손잡이가 이제 '두 개' 입니다 — w 손잡이, b 손잡이.
# 바닥(손실 최소)으로 가려면 두 손잡이를 각각 얼마나 돌릴지 정해야 해요.
# "어느 손잡이를 얼마나 돌리나"가 오늘의 전부입니다.


# ----------------------------------------
# 손실 함수 L(w, b) 를 코드로
# ----------------------------------------

# 1편과 같은 손실입니다 — 오차제곱의 평균(MSE, 평균제곱오차).
# 다른 점은 이제 w 와 b 를 '둘 다' 인자로 받는다는 것뿐이에요.
#
#   L(w, b) = (1/n) Σ (yᵢ - (w·xᵢ + b))²
#
# 작은 데이터를 하나 두고 시작합니다. 온도(x) → 불량(y) 느낌으로,
# 손계산이 편하도록 숫자를 얌전하게 골랐습니다.
#
# ※ 잠깐 - 1편에서는 진짜 온도-불량 데이터(20~38°C)를 썼는데 여기선 왜 [1,2,3,4]?
#   이번 편은 '편미분·그래디언트가 뭔지' 개념을 잡는 게 목적이라, 정답이 딱
#   떨어지는(w=2, b=1) 깔끔한 숫자가 감 잡기 좋아서예요. 원래 온도 데이터는 값이
#   커서 기울기가 -349 처럼 지저분하게 나오거든요. 진짜 온도-불량으로 끝까지
#   학습시키는 건 다음 편(3편)에서 합니다. 여기선 개념에 집중.

xs = [1, 2, 3, 4]          # 입력 (예: 정규화한 온도)
ys = [3, 5, 7, 9]          # 실제 값 (예: 불량수) — 사실 y = 2x+1 에 딱 맞음

def 손실(w, b):
    n = len(xs)
    return sum((y - (w * x + b)) ** 2 for x, y in zip(xs, ys)) / n

# 아무 데서나 시작해 봅니다. w=0, b=0 이면 전부 0 으로 예측하니 오차가 크죠.
print("L(0, 0) =", 손실(0, 0))   # → L(0, 0) = 41.0
# 참고로 정답은 w=2, b=1 입니다 (y=2x+1 이니까). 거기선 손실이 0 이에요.
print("L(2, 1) =", 손실(2, 1))   # → L(2, 1) = 0.0

# 우리 목표: 아무 (w, b) 에서 출발해 이 손실을 줄이는 쪽으로 걸어 내려가기.
# 그러려면 '지금 자리에서 어느 방향으로 가야 손실이 줄까'를 알아야 합니다.


# ========================================================
#  PART 2 : 편미분 - 손잡이 하나만 살짝 건드려 보기
# ========================================================

# ----------------------------------------
# 편미분이 별게 아니다 - 나머지는 고정
# ----------------------------------------

# '편미분'이라는 말에 겁먹지 마세요. 뜻은 아주 단순합니다.
#
#   편미분 = 나머지는 그대로 두고, 손잡이 하나만 살짝 건드려
#            손실이 얼마나 변하는지 본 '그 손잡이의 기울기'
#
#   ∂L/∂w  →  b 는 '고정'하고, w 만 살짝 움직였을 때 손실의 변화율
#   ∂L/∂b  →  w 는 '고정'하고, b 만 살짝 움직였을 때 손실의 변화율
#
# 1편에서 b 고정하고 w 기울기 하나만 봤던 그 일을,
# 이번엔 'w 고정하고 b' 로도 한 번 더 하는 것뿐입니다.
# ∂ 기호는 그냥 "여럿 중 하나만 건드린 기울기" 라는 표시예요.
#
# 어렵게 생각 말 것: '각 손잡이별 기울기' 두 개. 그게 편미분입니다.


# ----------------------------------------
# 기울기의 부호가 알려 주는 것
# ----------------------------------------

# 기울기(변화율) 하나가 손에 들어오면, 그 '부호'가 방향을 알려 줍니다.
#
#   ∂L/∂w 가 양수  →  w 를 키우면 손실이 는다  →  줄이려면 w 를 '줄여야'
#   ∂L/∂w 가 음수  →  w 를 키우면 손실이 준다  →  줄이려면 w 를 '키워야'
#
# 즉 손실을 줄이려면 기울기의 '반대 방향'으로 가면 됩니다.
# 이게 경사'하강'의 핵심이고, w 든 b 든 규칙이 똑같아요.


# ========================================================
#  PART 3 : 수치미분으로 두 기울기를 먼저 재 본다
# ========================================================

# ----------------------------------------
# 수치미분 - 살짝 밀어 보고 기울기를 재는 법
# ----------------------------------------

# 1편에서 쓴 그 방법입니다. 한 지점의 기울기는, 그 점 양옆을 아주 조금
# (h) 밀어 손실을 재고, 그 차이를 폭으로 나누면 근사됩니다.
#
#   기울기 ≈ (L(·+h) - L(·-h)) / (2h)     (중앙차분, h 는 아주 작은 수)
#
# '편'미분이니 밀 때 '하나만' 밉니다.
#   ∂L/∂w 는 w 만 ±h 하고 b 는 그대로,
#   ∂L/∂b 는 b 만 ±h 하고 w 는 그대로.

h = 1e-5   # 아주 작은 밀기 폭

def 수치_dw(w, b):
    # w 만 살짝 밀고 b 는 고정 → w 방향 기울기
    return (손실(w + h, b) - 손실(w - h, b)) / (2 * h)

def 수치_db(w, b):
    # b 만 살짝 밀고 w 는 고정 → b 방향 기울기
    return (손실(w, b + h) - 손실(w, b - h)) / (2 * h)

# w=0, b=0 자리에서 두 방향 기울기를 재 봅니다.
print("수치 ∂L/∂w (0,0):", round(수치_dw(0, 0), 4))   # → 수치 ∂L/∂w (0,0): -35.0
print("수치 ∂L/∂b (0,0):", round(수치_db(0, 0), 4))   # → 수치 ∂L/∂b (0,0): -12.0

# 둘 다 음수죠. 부호 규칙대로면 "w 도 키우고 b 도 키워야 손실이 준다"는
# 뜻입니다. 실제로 정답이 w=2, b=1 로 지금(0,0)보다 크니 방향이 맞네요.


# ----------------------------------------
# 두 기울기를 한 쌍으로 묶으면 = 그래디언트
# ----------------------------------------

# w 방향 기울기와 b 방향 기울기, 이 둘을 한 쌍(튜플)으로 묶은 것이
# 바로 그래디언트(gradient) 입니다.
#
#   그래디언트 = (∂L/∂w, ∂L/∂b)
#
# 이 한 쌍은 방향을 가리키는 화살표예요.
#   → '손실이 가장 가파르게 오르는 방향'을 가리킵니다.
# 그러니 우리가 갈 곳은 그 '정반대' 방향 — 가장 빨리 내려가는 쪽입니다.

def 수치_그래디언트(w, b):
    return (수치_dw(w, b), 수치_db(w, b))

g = 수치_그래디언트(0, 0)
print("수치 그래디언트 (0,0):", (round(g[0], 4), round(g[1], 4)))
# → 수치 그래디언트 (0,0): (-35.0, -12.0)

# 화살표 (-35, -12) 는 '손실이 가장 빨리 오르는 방향'.
# 우리는 반대인 (+35, +12) 쪽으로 조금 가면 손실이 가장 빨리 줄어요.
# 즉 w 를 늘리고 b 를 늘리는 쪽. 정답(2,1)으로 가는 방향과 일치합니다.


# ========================================================
#  PART 4 : 해석적 공식 - 손으로 준 것과 대조한다
# ========================================================

# ----------------------------------------
# 밀어 보지 않아도 되는 공식이 있다
# ----------------------------------------

# 수치미분은 매번 손실을 두 번씩 계산해 '밀어 봐야' 합니다. 느리고,
# h 때문에 아주 미세한 오차도 있어요. 다행히 이 손실은 기울기를 딱
# 떨어지게 주는 공식이 있습니다. (유도·연쇄법칙은 4과정 역전파에서 다뤄요.
#  지금은 "공식은 이렇고, 수치미분과 맞는다"로 납득하면 충분합니다.)
#
#   ∂L/∂w = -(2/n) Σ xᵢ · (yᵢ - (w·xᵢ + b))
#   ∂L/∂b = -(2/n) Σ      (yᵢ - (w·xᵢ + b))
#
# 안쪽 (yᵢ - (w·xᵢ+b)) 는 그 점의 '오차(실제-예측)' 입니다.
#   ∂L/∂w 는 그 오차에 xᵢ 를 곱해 더한 것,
#   ∂L/∂b 는 그 오차를 그냥 더한 것.
# 둘 다 앞에 -(2/n) 이 붙습니다. 코드로 그대로 옮겨 봅니다.

def 해석_그래디언트(w, b):
    n = len(xs)
    오차 = [y - (w * x + b) for x, y in zip(xs, ys)]      # yᵢ - (w·xᵢ+b)
    dw = -(2 / n) * sum(x * e for x, e in zip(xs, 오차))   # -(2/n) Σ xᵢ·오차
    db = -(2 / n) * sum(오차)                              # -(2/n) Σ 오차
    return (dw, db)

gw, gb = 해석_그래디언트(0, 0)
print("해석 그래디언트 (0,0):", (round(gw, 4), round(gb, 4)))
# → 해석 그래디언트 (0,0): (-35.0, -12.0)


# ----------------------------------------
# ★검증★ 수치미분 ≈ 해석 공식
# ----------------------------------------

# 공식이 맞다는 증거: 힘들게 '밀어서' 잰 수치미분과, 공식으로 '단번에'
# 낸 값이 같아야 합니다. 여러 지점에서 나란히 재 대조해 봅니다.

print("\n[수치미분  vs  해석공식  그래디언트 대조]")
for (w, b) in [(0, 0), (1, 0), (2, 1), (1.5, 0.5)]:
    nw, nb = 수치_그래디언트(w, b)
    aw, ab = 해석_그래디언트(w, b)
    같나 = abs(nw - aw) < 1e-4 and abs(nb - ab) < 1e-4
    print(f"  (w={w}, b={b})  수치=({round(nw,4)}, {round(nb,4)})"
          f"  해석=({round(aw,4)}, {round(ab,4)})  일치? {같나}")
# → [수치미분  vs  해석공식  그래디언트 대조]
# →   (w=0, b=0)  수치=(-35.0, -12.0)  해석=(-35.0, -12.0)  일치? True
# →   (w=1, b=0)  수치=(-20.0, -7.0)  해석=(-20.0, -7.0)  일치? True
# →   (w=2, b=1)  수치=(0.0, 0.0)  해석=(-0.0, -0.0)  일치? True
# →   (w=1.5, b=0.5)  수치=(-10.0, -3.5)  해석=(-10.0, -3.5)  일치? True

# 모든 지점에서 소수점까지 같습니다. 두 가지가 확인됐어요.
#   1) 정답 (w=2, b=1) 에서는 그래디언트가 (0, 0) — 바닥이라 기울기가 없죠.
#   2) 손으로 준 공식이 수치미분과 일치 → 공식이 맞다는 증거.
#
# 그럼 왜 공식을 쓰나요? 밀어 볼 필요 없이(빠름), h 오차도 없이(정확함)
# 곧장 답이 나오기 때문입니다. 이제부터는 공식 그래디언트를 씁니다.


# ========================================================
#  PART 5 : 한 스텝 - 두 손잡이를 '동시에' 돌린다
# ========================================================

# ----------------------------------------
# 갱신식 - 기울기의 반대로, lr 만큼
# ----------------------------------------

# 방향(그래디언트)을 알았으니 한 걸음 내딛습니다. 가장 빨리 내려가는
# 쪽 = 그래디언트의 반대. 얼마나? 학습률(lr) 만큼만 조금.
#
#   w ← w - lr · ∂L/∂w
#   b ← b - lr · ∂L/∂b
#
# ★주의 - 반드시 '동시에' 갱신★
#   먼저 그래디언트 (dw, db) 를 '둘 다' 구해 놓고,
#   그다음 w 와 b 를 갱신해야 합니다.
#   w 를 먼저 바꾼 뒤 그 바뀐 w 로 db 를 구하면 순서가 꼬여 엉뚱해져요.
#   그래서 dw, db 를 한 번에 받아 두고 나서 갱신합니다.

def 한스텝(w, b, lr):
    dw, db = 해석_그래디언트(w, b)   # ① 둘 다 '먼저' 구하고 (같은 w,b 기준)
    새w = w - lr * dw               # ② 그다음 동시에 갱신
    새b = b - lr * db
    return 새w, 새b


# ----------------------------------------
# 손계산 먼저 - (0,0) 에서 한 스텝
# ----------------------------------------

# lr = 0.1 로 (0,0) 에서 한 걸음 딛으면 어디로 갈까요? 손으로 먼저.
#
#   그래디언트 (0,0) = (-35, -12)   ← PART 4 에서 구함
#   새 w = 0 - 0.1 · (-35) = 0 + 3.5 = 3.5
#   새 b = 0 - 0.1 · (-12) = 0 + 1.2 = 1.2
#
# 기울기가 음수라 빼기(-lr·음수)가 더하기가 되어 둘 다 커졌습니다.
# 정답 (2, 1) 쪽으로 움직인 거죠 (다만 lr 이 커서 w 는 살짝 지나침).

새w, 새b = 한스텝(0, 0, lr=0.1)
