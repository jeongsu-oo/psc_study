# ----------------------------------------
# 오늘 만든 것 - 한 장 요약
# ----------------------------------------

#   개념          |  뜻                              |  식 / 코드
#  --------------+---------------------------------+---------------------------
#   손실 L(w,b)   |  w,b 두 손잡이의 함수            |  (1/n)Σ(yᵢ-(w·xᵢ+b))²
#   편미분 ∂L/∂w  |  b 고정, w 만 건드린 기울기       |  -(2/n)Σ xᵢ·오차
#   편미분 ∂L/∂b  |  w 고정, b 만 건드린 기울기       |  -(2/n)Σ 오차
#   그래디언트    |  두 편미분을 묶은 화살표          |  (∂L/∂w, ∂L/∂b)
#                |  가장 가파르게 '오르는' 방향       |
#   한 스텝       |  기울기 반대로 lr 만큼 '동시에'   |  w←w-lr·dw, b←b-lr·db
#
# 이어지는 흐름:
#   1편  손잡이 하나(w) → 밥그릇 바닥 굴러가기 맛보기
#   2편  손잡이 둘(w,b) → 편미분·그래디언트로 한 스텝 딛기   ← 오늘
#   3편  그 한 스텝을 여러 번 반복 → 바닥까지 완주(학습 루프)


# ----------------------------------------
# [실습] 다른 시작점에서 그래디언트·한 스텝
# ----------------------------------------

# 시작점을 바꿔도 규칙은 똑같습니다. 아래 흐름을 그대로 따라 해 보세요.
#
#   Step 1) 시작점 (w, b) 정하기
#   Step 2) 해석_그래디언트(w, b) 로 (∂L/∂w, ∂L/∂b) 구하기
#           → 수치_그래디언트 와 같은지 대조하면 확신이 든다
#   Step 3) 한스텝(w, b, lr) 로 한 걸음
#   Step 4) 손실이 걷기 전보다 줄었는지 확인 (줄면 성공)
#
# 완료 기준: 그래디언트가 화면에 나오고, 한 스텝 뒤 손실이 줄면 성공.

print("\n[실습 예시 · 시작점 (1, 0), lr=0.1]")
w0, b0 = 1, 0

nw, nb = 수치_그래디언트(w0, b0)
aw, ab = 해석_그래디언트(w0, b0)
print("  수치 그래디언트:", (round(nw, 4), round(nb, 4)))   # → 수치 그래디언트: (-20.0, -7.0)
print("  해석 그래디언트:", (round(aw, 4), round(ab, 4)))   # → 해석 그래디언트: (-20.0, -7.0)
print("  두 방식 일치?:", abs(nw - aw) < 1e-4 and abs(nb - ab) < 1e-4)  # → 두 방식 일치?: True

nw1, nb1 = 한스텝(w0, b0, lr=0.1)
print("  한 스텝 후 (w,b):", (round(nw1, 4), round(nb1, 4)))   # → 한 스텝 후 (w,b): (3.0, 0.7)
print("  손실:", round(손실(w0, b0), 4), "→", round(손실(nw1, nb1), 4),
      "/ 줄었나?", 손실(nw1, nb1) < 손실(w0, b0))
# → 손실: 13.5 → 6.09 / 줄었나? True
