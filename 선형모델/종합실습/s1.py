# ----------------------------------------
# 로지스틱 회귀 - 확률로 바꿔 판정
# ----------------------------------------

# 같은 특징으로, 이번엔 '불량 배치냐(1) 아니냐(0)' 를 맞힙니다.
# 회귀와 딱 두 군데만 다릅니다(분류·평가 편에서 배운 그대로).
#   · 예측 : 직선값을 sigmoid 로 눌러 0~1 확률로       p = sigmoid(Zw + b)
#   · 손실 : MSE 대신 로그손실, 그래디언트는 (p - y)    ∂L/∂w = (1/n) Zᵀ(p - y)
# 걷는 방식(w ← w - lr·gw)은 회귀와 완전히 같습니다.

def sigmoid(z):
    return 1 / (1 + np.exp(-z))          # 아무 값이나 0~1 로 눌러 주는 S자

def 분류학습(Z, y, lr=0.2, epochs=4000):
    n, d = Z.shape
    w = np.zeros(d)
    b = 0.0
    for _ in range(epochs):
        오차 = sigmoid(Z @ w + b) - y     # p - y  (회귀의 ŷ-y 자리)
        gw = (Z.T @ 오차) / n             # ∂L/∂w = (1/n)Zᵀ(p-y)
        gb = 오차.sum() / n
        w = w - lr * gw
        b = b - lr * gb
    return w, b

def 확률(Z, w, b):
    return sigmoid(Z @ w + b)            # 각 배치의 불량 확률

w_clf, b_clf = 분류학습(Z_train, 불량여부_train)
p_test = 확률(Z_test, w_clf, b_clf)

print("[분류 · 학습 결과]")
print("  가중치 [온도 압력 진동 속도]:", np.round(w_clf, 3))
print("  절편 b:", round(b_clf, 3))
