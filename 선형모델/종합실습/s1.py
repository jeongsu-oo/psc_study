# ========================================================
#  PART 4 : 회귀 트랙 - 다변수 선형회귀로 불량'수' 예측
# ========================================================

# ----------------------------------------
# 다변수 선형회귀 - 특징 4개를 한 줄로
# ----------------------------------------

# 경사하강 3부작에선 온도 하나로 직선을 맞췄죠. 오늘은 특징이 4개입니다.
# 식이 조금 길어질 뿐, 뼈대는 똑같아요.
#
#   예측 :  ŷ = w1·온도 + w2·압력 + w3·진동 + w4·속도 + b
#          = (특징 · 가중치) + b        ← 벡터 내적 한 방
#   손실 :  MSE = (1/n) Σ (y - ŷ)²      (오차 제곱의 평균, 3부작 그대로)
#   그래디언트(3부작 결과) :
#          ∂L/∂w = (2/n) Zᵀ(ŷ - y)      ← 특징별 기울기 한 번에
#          ∂L/∂b = (2/n) Σ (ŷ - y)
#
# 특징이 하나든 넷이든 코드가 거의 안 변합니다. 이게 벡터 연산의 힘이에요.
# lam(정규화 세기)도 미리 넣어 둡니다 — PART 6 에서 이걸로 과적합을 처방합니다.
# (lam=0 이면 정규화 없음 = 순수 회귀. 지금은 0 으로 씁니다.)

def 회귀학습(Z, y, lr=0.1, epochs=3000, lam=0.0):
    n, d = Z.shape
    w = np.zeros(d)                      # 가중치 4개, 0 에서 출발
    b = 0.0
    for _ in range(epochs):
        오차 = Z @ w + b - y             # ŷ - y (전체 배치 한 번에)
        gw = (2 / n) * (Z.T @ 오차) + 2 * lam * w   # 정규화 항 2·lam·w
        gb = (2 / n) * 오차.sum()
        w = w - lr * gw                  # w ← w - lr·∂L/∂w
        b = b - lr * gb
    return w, b

def 회귀예측(Z, w, b):
    return Z @ w + b                     # ŷ = Zw + b

def R2(y, yhat):
    SSE = ((y - yhat) ** 2).sum()        # 모델이 못 맞힌 오차
    SST = ((y - y.mean()) ** 2).sum()    # '평균으로 찍기' 의 오차
    return 1 - SSE / SST                 # 1 에 가까울수록 잘 맞음

def MSE(y, yhat):
    return ((y - yhat) ** 2).mean()


