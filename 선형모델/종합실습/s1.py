#   Step 2) 각 임계값에서 지표()로 정밀도·재현율을 뽑아 표로 본다
#   Step 3) 재현율↑ 이면 정밀도↓ 인 트레이드오프를 눈으로 확인
#   완료 기준 : 임계값을 낮출수록 재현율이 오르고 정밀도가 내려가면 성공.

# (실습 정답 예시 — 임계값 트레이드오프 표)
