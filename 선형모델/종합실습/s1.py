"""[지금까지 배운 걸 다 합치면, 진짜 현장 문제 하나를 풀 수 있을까요?]
과정3을 여기까지 오느라 고생 많으셨습니다. 우리는 조각조각 배웠어요.
  · 선형회귀     : 온도로 불량 '개수' 를 예측 (직선 맞추기)
  · 경사하강     : 걸어서 가장 잘 맞는 w, b 를 찾기
  · 다변수·정규화: 특징이 여러 개일 때, 과적합을 정규화로 누르기
  · 로지스틱     : 불량 '이냐 아니냐' 를 확률로 판정
  · 평가지표     : 혼동행렬·정밀도·재현율·F1, 임계값 조정

오늘은 이 조각들을 하나로 잇습니다. 제조 현장에 데이터가 딱 떨어졌다고
치고, 문제 정의부터 결과 해석까지 '처음부터 끝까지(end-to-end)' 를
한 번에 관통합니다. 새 이론은 없어요. 배운 걸 순서대로 꿰는 게 오늘의 전부.

중요한 약속 하나. 오늘은 강사가 먼저 시범을 보이고,
중간중간 [실습 지점] 에서 "이제 여러분 차례" 하고 넘깁니다.
그 자리엔 정답 예시도 실행되게 넣어 뒀으니, 먼저 스스로 해보고 비교하세요.

  [오늘의 흐름]
    1. 문제 정의   - 뭘 풀 건가 (회귀 트랙 + 분류 트랙)
    2. 데이터 이해 - 센서 데이터 살펴보기 (요약·불량비율=불균형 점검)
    3. 전처리      - 결측·이상값·표준화·train/test 분리 (누출 방지)   [실습]
    4. 회귀 트랙   - 다변수 선형회귀로 불량수 예측, R²·MSE           [실습]
    5. 분류 트랙   - 로지스틱으로 불량여부, 혼동행렬·임계값 조정      [실습]
    6. 과적합 점검 - train/test 격차 확인, 정규화로 처방
    7. 결과 해석   - 지표를 '현장 언어' 로 번역
    8. 마무리      - 과정4(신경망) 예고

과정3 범위는 '선형모델' 까지입니다. 그래서 오늘도 회귀·로지스틱만 씁니다.
(더 복잡한 신경망은 과정4에서 같은 문제를 더 잘 풀어 봅니다.)
"""

# 오늘은 numpy 밑바닥으로 갑니다. 경사하강도 우리 손으로 짠 것 그대로예요.
# 데이터는 외부 파일 없이 '시드 고정' 으로 이 안에서 만듭니다(자족).
# 맨 끝 선택 파트에서만, 우리가 구한 값이 맞는지 sklearn 으로 대조합니다.
import numpy as np


# ========================================================
#  PART 1 : 문제 정의 - 무엇을 풀 것인가
# ========================================================

# ----------------------------------------
# 한 데이터, 두 질문 - 회귀와 분류
# ----------------------------------------

# 제조 라인에서 센서가 온도·압력·진동·속도를 계속 찍고 있습니다.
# 현장이 이 데이터로 알고 싶은 건 크게 두 가지예요. 둘 다 오늘 풉니다.
#
#   (a) 불량이 몇 개나 날까?     → '개수' 예측 = 회귀      (선형회귀)
#   (b) 이 배치, 불량 배치야?    → '이냐 아니냐' = 분류    (로지스틱)
#
# 같은 센서 데이터를 놓고 타깃만 둘로 두는 겁니다.
#   회귀 타깃 : 불량수    (0, 1, 2, ... 개)
#   분류 타깃 : 불량여부  (불량수가 기준을 넘으면 1, 아니면 0)
#
#   [오늘의 end-to-end 흐름도]
#
#     센서 데이터(온도·압력·진동·속도)
#            │
#      ┌─────┴─────┐
#      ▼           ▼
#   회귀 트랙     분류 트랙
#   불량'수'      불량'여부'
#   예측          판정
#      │           │
#   R²·MSE      정밀도·재현율·F1
#      │           │
#      └─────┬─────┘
#            ▼
#      현장 언어로 해석 → 조치
#
# 왼쪽(회귀)은 "얼마나" 를, 오른쪽(분류)은 "그러냐 아니냐" 를 답합니다.
# 현장에선 둘 다 필요해요 — 생산량 계획엔 개수가, 배치 합격판정엔 여부가.


# ========================================================
#  PART 2 : 데이터 이해 - 센서 데이터를 살펴본다
# ========================================================

# ----------------------------------------
# 데이터 만들기 - 인라인, 시드 고정
# ----------------------------------------

# 외부 csv 없이 이 안에서 데이터를 만듭니다(자족 원칙). 시드를 고정해서
# 몇 번을 돌려도 똑같은 데이터가 나오게 합니다 — 그래야 결과가 재현됩니다.
# 실제 라인에서는 pd.read_csv 로 파일을 읽겠지만, 그 뒤 과정은 오늘과 똑같아요.

SEED = 42
rng = np.random.RandomState(SEED)       # 시드 고정 = 항상 같은 난수

N = 200                                  # 제조 배치 200건
온도 = rng.uniform(180, 240, N)          # 성형 온도 (도)
압력 = rng.uniform(90, 135, N)           # 주입 압력 (bar)
진동 = rng.uniform(0.5, 3.0, N)          # 설비 진동 (mm/s)
속도 = rng.uniform(45, 80, N)            # 라인 속도 (개/분)

# 불량수(회귀 타깃)를 '숨은 규칙 + 약간의 잡음' 으로 만듭니다.
# 온도·압력·진동이 높으면 불량↑, 속도가 빠르면 살짝 불량↓ 이라고 둡니다.
# (이 규칙은 데이터 생성용일 뿐. 모델은 이걸 모른 채 데이터만 보고 배웁니다.)
잡음 = rng.normal(0, 1.2, N)             # 현실의 들쭉날쭉함
불량수_연속 = (0.08 * (온도 - 200)
             + 0.10 * (압력 - 105)
             + 3.2 * (진동 - 1.5)
             - 0.03 * (속도 - 62)
             + 6 + 잡음)
불량수 = np.clip(np.round(불량수_연속), 0, None)   # 개수니까 반올림하고 음수는 0으로

# 분류 타깃(불량여부) : 불량수가 12개 이상이면 '불량 배치(1)', 아니면 '양품 배치(0)'
불량여부 = (불량수 >= 12).astype(int)


# ----------------------------------------
# 살펴보기 - 요약통계 (과정2 회수)
# ----------------------------------------

# 데이터를 받으면 제일 먼저 '어떻게 생겼나' 를 봅니다. 최소·최대·평균.
# 과정2 numpy 에서 배운 .min() .max() .mean() 을 그대로 씁니다.

print("[센서 데이터 요약 · 배치", N, "건]")
for 이름, 열 in [("온도", 온도), ("압력", 압력), ("진동", 진동), ("속도", 속도)]:
    print(f"  {이름}: 최소 {열.min():6.1f}   최대 {열.max():6.1f}   평균 {열.mean():6.1f}")
print(f"  불량수: 최소 {불량수.min():.0f}   최대 {불량수.max():.0f}   평균 {불량수.mean():.2f}")
# → [센서 데이터 요약 · 배치 200 건]
# →   온도: 최소  180.3   최대  239.2   평균  209.0
# →   압력: 최소   90.2   최대  134.6   평균  112.7
# →   진동: 최소    0.5   최대    3.0   평균    1.8
# →   속도: 최소   45.6   최대   79.6   평균   61.8
# →   불량수: 최소 2   최대 17   평균 8.45

# 온도 180~240, 진동 0.5~3.0 … 열마다 값의 크기(스케일)가 제각각이죠?
# 이게 나중에 표준화가 필요한 이유입니다. 지금은 눈도장만 찍어 둡니다.


# ----------------------------------------
# 불량 비율 - 클래스 불균형 점검 (분류 전 필수)
# ----------------------------------------

# 분류를 하기 전, 반드시 볼 게 하나 있어요 — '불량이 전체의 몇 %냐'.
# 대부분의 제조 라인은 양품이 많고 불량은 소수입니다(불균형).
# 이걸 모르고 정확도만 보면 나중에 크게 속습니다(과정3 평가지표 편의 그 함정).

불량건수 = int(불량여부.sum())
불량비율 = 불량여부.mean()
print("\n[클래스 불균형 점검]")
print(f"  양품 배치: {N - 불량건수}건 / 불량 배치: {불량건수}건")
print(f"  불량 비율: {불량비율:.3f}  (전체의 약 {불량비율*100:.0f}%)")
# → [클래스 불균형 점검]
# →   양품 배치: 161건 / 불량 배치: 39건
# →   불량 비율: 0.195  (전체의 약 20%)

# 불량이 약 20%. "전부 양품이라 찍기만 해도 정확도 80%" 가 나오는 판이에요.
# 그러니 오늘 분류에서는 정확도만 믿지 말고 재현율·F1 을 꼭 함께 봐야 합니다.
# (이 불균형 점검을 습관으로 만드세요. 분류 시작 전 항상 이걸 먼저 봅니다.)


# ========================================================
#  PART 3 : 전처리 - 모델에 넣기 전에 데이터를 다듬는다
# ========================================================

# ----------------------------------------
# 결측·이상값 - 현실 데이터엔 반드시 있다
# ----------------------------------------

# 방금 만든 데이터는 깨끗하지만, 현실 센서 데이터엔 꼭 구멍이 있습니다.
#   · 결측(빠진 값)  : 센서가 잠깐 먹통이라 값이 안 찍힘
#   · 이상값         : 센서 오작동으로 온도가 9999 같은 말도 안 되는 값
# 이런 걸 그대로 모델에 넣으면 학습이 망가집니다. 다뤄 보게 일부러 심어 봅니다.

온도_더러움 = 온도.copy()
온도_더러움[3] = np.nan          # 3번 배치: 온도가 안 찍힘(결측)
온도_더러움[7] = 9999.0          # 7번 배치: 센서 오작동(이상값)

# 처리 방침(가장 단순하고 안전한 기본):
#   · 결측 → 그 열의 '중앙값' 으로 메움 (평균은 이상값에 휘둘려서 중앙값이 안전)
#   · 이상값 → 물리적으로 불가능한 값이면 결측으로 취급해 같이 메움
# ★ 규칙(누출 방지): 메울 때 쓰는 중앙값은 '학습 데이터' 것만 써야 합니다.
#    지금은 원리를 보여주려 전체로 계산하지만, 아래 분리 후엔 train 기준으로 씁니다.

def 청소(열, 하한, 상한):
    열 = 열.copy()
    말이안됨 = (열 < 하한) | (열 > 상한)          # 물리적으로 불가능한 범위
    열[말이안됨] = np.nan                          # 이상값도 일단 결측 취급
    중앙값 = np.nanmedian(열)                       # nan 무시하고 중앙값
    열[np.isnan(열)] = 중앙값                       # 결측·이상값 자리를 메움
    return 열, 중앙값

온도_청소, 온도중앙 = 청소(온도_더러움, 150, 260)   # 온도는 150~260 밖이면 오류
print("[전처리 · 결측·이상값 메우기]")
print(f"  3번(결측) 처리 후: {온도_청소[3]:.1f}   ← 중앙값 {온도중앙:.1f} 로 메움")
print(f"  7번(9999 이상값) 처리 후: {온도_청소[7]:.1f}   ← 중앙값으로 교체")
# → [전처리 · 결측·이상값 메우기]
# →   3번(결측) 처리 후: 209.5   ← 중앙값 209.5 로 메움
# →   7번(9999 이상값) 처리 후: 209.5   ← 중앙값으로 교체

# 원본으로 되돌려 이후 파트는 깨끗한 온도로 진행합니다(시연은 끝).
온도 = 온도.copy()


# ----------------------------------------
# [실습 지점] 압력 열도 청소해 보세요
# ----------------------------------------

# 강사가 방금 '온도' 를 청소했습니다. 이제 여러분 차례.
# 압력에도 결측·이상값을 심어 두었으니, 위 청소() 함수를 그대로 써서
# 처리해 보세요. 압력의 물리적 범위는 대략 70~160 bar 로 봅니다.
#
#   Step 1) 압력_더러움 을 복사해 한 칸은 np.nan(결측), 한 칸은 -50(이상값)으로
#   Step 2) 청소(압력_더러움, 70, 160) 을 호출
#   Step 3) 그 두 칸이 중앙값으로 메워졌는지 확인
#   완료 기준 : 결측 칸과 이상값(-50) 칸이 둘 다 압력 중앙값으로 바뀌면 성공.

# (실습 정답 예시)
압력_더러움 = 압력.copy()
압력_더러움[2] = np.nan            # 결측
압력_더러움[5] = -50.0            # 이상값(음수 압력은 불가능)
압력_청소, 압력중앙 = 청소(압력_더러움, 70, 160)
print("\n[실습 · 압력 청소]")
print(f"  2번(결측)   → {압력_청소[2]:.1f}  (중앙값 {압력중앙:.1f})")
print(f"  5번(-50)    → {압력_청소[5]:.1f}  (중앙값으로 교체)")
# → [실습 · 압력 청소]
# →   2번(결측)   → 114.5  (중앙값 114.5)
# →   5번(-50)    → 114.5  (중앙값으로 교체)


# ----------------------------------------
# train/test 분리 - 시험 문제 미리 안 보기 (누출 방지)
# ----------------------------------------

# 모델을 만들면 "잘 맞나?" 를 채점해야 합니다. 그런데 학습에 쓴 데이터로
# 채점하면 반칙이에요 — 시험 문제를 미리 보고 시험 치는 격.
# 그래서 데이터를 둘로 나눕니다.
#   train(학습용) : 이걸로 w, b 를 배운다   (70%)
#   test(시험용)  : 학습엔 절대 안 쓰고, 마지막 채점에만 쓴다  (30%)
#
#   ★ 데이터 누출(leakage) 방지 : test 는 학습 어디에도 스며들면 안 됩니다.
#     표준화에 쓰는 평균·표준편차도 'train 것만' 으로 계산해야 해요.
#     test 의 평균까지 끌어다 쓰면, 시험지를 미리 훔쳐본 셈이 됩니다.

idx = np.arange(N)
np.random.RandomState(0).shuffle(idx)    # 순서 섞기(시드 고정) — 편향 방지
n_train = 140                            # 200건 중 140 학습 / 60 시험
tr, te = idx[:n_train], idx[n_train:]

특징 = np.column_stack([온도, 압력, 진동, 속도])   # (200, 4) 특징 행렬
X_train, X_test = 특징[tr], 특징[te]
불량수_train, 불량수_test = 불량수[tr], 불량수[te]     # 회귀 타깃
불량여부_train, 불량여부_test = 불량여부[tr], 불량여부[te]  # 분류 타깃

print("\n[train/test 분리]")
print(f"  train {len(tr)}건  (불량비율 {불량여부_train.mean():.3f})")
print(f"  test  {len(te)}건  (불량비율 {불량여부_test.mean():.3f})")
# → [train/test 분리]
