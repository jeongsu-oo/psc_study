# 위 회귀는 train R²(0.885)와 test R²(0.755)가 크게 안 벌어졌습니다 — 건강해요.
# 그런데 데이터가 적고 쓸데없는 특징이 많으면, 모델이 train 을 '통째로 외워'
# 버립니다. train 은 완벽한데 test 는 엉망 — 이게 과적합입니다.
# 벼락치기로 기출은 다 맞는데 새 문제는 못 푸는 학생과 똑같아요.
#
# 일부러 과적합을 만들어 봅시다 : 학습 데이터를 16건으로 확 줄이고,
# 불량과 아무 상관없는 '잡음 특징' 3개를 끼워 넣습니다(센서 노이즈라 치고).

잡음특징 = np.random.RandomState(7).normal(0, 1, (N, 3))   # 의미 없는 특징 3개
특징_확장 = np.column_stack([특징, 잡음특징])               # 4개 + 잡음 3개 = 7개

작은train = tr[:16]                                        # 학습을 16건으로 줄임
Xs = 특징_확장[작은train]
ys = 불량수[작은train]
mu_s, sd_s = Xs.mean(axis=0), Xs.std(axis=0)
Zs = (Xs - mu_s) / sd_s
Zt = (특징_확장[te] - mu_s) / sd_s                          # test 는 train 기준 표준화


# ----------------------------------------
# 정규화로 처방 - 가중치를 눌러 외우기 방지
# ----------------------------------------

# 처방은 정규화(다변수·정규화 편에서 배운 그거)입니다. 손실에 '가중치가 크면
# 벌점' 을 더해, 모델이 특정 특징(특히 잡음)에 과하게 매달리지 못하게 눌러요.
# lam(정규화 세기)을 0 → 키우면서 train·test R² 가 어떻게 갈리는지 봅시다.

print("[과적합 점검 · 학습 16건 + 잡음 특징 3개]")
print("  lam(정규화)   train R²   test R²   가중치최대")
for lam in [0.0, 0.2, 0.5, 1.0]:
    ws, bs = 회귀학습(Zs, ys, lr=0.1, epochs=3000, lam=lam)
    r2_tr = R2(ys, 회귀예측(Zs, ws, bs))
    r2_te = R2(불량수_test, 회귀예측(Zt, ws, bs))
    print(f"   {lam:.1f}          {r2_tr:.4f}     {r2_te:.4f}    {np.abs(ws).max():.3f}")
# → [과적합 점검 · 학습 16건 + 잡음 특징 3개]
# →   lam(정규화)   train R²   test R²   가중치최대
# →    0.0          0.9803     0.6272    2.309
# →    0.2          0.9157     0.7204    1.679
# →    0.5          0.7809     0.6271    1.209
# →    1.0          0.6158     0.4634    0.835

# lam=0 (정규화 없음) : train R² 0.98 로 거의 완벽한데 test 는 0.63 — 큰 격차.
#                       train 을 외운 겁니다. 이게 과적합의 전형적 신호예요.
# lam=0.2 (약간 정규화): train 은 0.92 로 조금 내려갔지만 test 가 0.72 로 올랐습니다!
#                        가중치 최대도 2.31 → 1.68 로 눌렸죠. 처방이 통한 겁니다.
# lam=1.0 (너무 셈)    : 너무 눌러서 train·test 둘 다 떨어짐(과소적합).
# → 교훈 : train/test 격차가 크면 과적합. 정규화를 '적당히' 걸면 격차가 줄고
#          진짜 실력(test)이 오릅니다. 세게 걸수록 좋은 게 아니라 딱 알맞게.


