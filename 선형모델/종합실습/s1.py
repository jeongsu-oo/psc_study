print("  절편 b:", round(b_reg, 3))
print(f"  train  R² {R2(불량수_train, train_pred):.4f}   MSE {MSE(불량수_train, train_pred):.3f}")
print(f"  test   R² {R2(불량수_test, test_pred):.4f}   MSE {MSE(불량수_test, test_pred):.3f}")
