# 같은 걸 배웠습니다. 이제 이 확률을 0.5 기준으로 판정해 채점해 봅시다.


# ----------------------------------------
# 혼동행렬과 4대 지표 - 손으로 세기 (평가지표 편 회수)
# ----------------------------------------

# 불량=1 을 '잡아내야 할 양성' 으로 둡니다(제조 관점 — 불량을 놓치면 큰일).
#   TP: 불량을 불량이라 맞힘   FP: 양품을 불량이라 오판(헛경보)
#   FN: 불량을 양품이라 놓침!  TN: 양품을 양품이라 맞힘
# 지표 : 정확도=(TP+TN)/전체, 정밀도=TP/(TP+FP), 재현율=TP/(TP+FN),
#        F1=2·정밀도·재현율/(정밀도+재현율)

def 혼동행렬(y, pred):
    tp = int(((y == 1) & (pred == 1)).sum())
    fp = int(((y == 0) & (pred == 1)).sum())
    fn = int(((y == 1) & (pred == 0)).sum())
    tn = int(((y == 0) & (pred == 0)).sum())
    return tp, fp, fn, tn

def 지표(y, p, 임계값=0.5):
    pred = (p >= 임계값).astype(int)     # 확률이 임계값 넘으면 불량(1)
    tp, fp, fn, tn = 혼동행렬(y, pred)
    정확도 = (tp + tn) / len(y)
    정밀도 = tp / (tp + fp) if (tp + fp) else 0.0   # 0 나눗셈 보호
    재현율 = tp / (tp + fn) if (tp + fn) else 0.0
    F1 = 2 * 정밀도 * 재현율 / (정밀도 + 재현율) if (정밀도 + 재현율) else 0.0
    return tp, fp, fn, tn, 정확도, 정밀도, 재현율, F1

tp, fp, fn, tn, acc, prec, rec, f1 = 지표(불량여부_test, p_test, 0.5)
